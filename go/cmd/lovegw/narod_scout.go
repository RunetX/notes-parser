package main

// lovegw narod scout — подбор доноров под состав.
//
// Первый шаг конвейера производства жителя, и он же ответ на замер 28.08.2026:
// разговор между жителями заводится от их ЧИСЛА, а не от настройки кубика.
// Добирать состав «покрупнее корпусом» бесполезно — нужен СОСЕД по тредам, то
// есть тот, кто на самом деле сидел рядом и отвечал тем же людям.
//
// Выбирает всё равно владелец: команда только показывает числа, по которым
// выбор можно сделать. Ни в сеть, ни в Postgres не ходит — читается archive.db.

import (
	"context"
	"fmt"
	"os"
	"strconv"
	"strings"

	"lovegw/internal/archive"
)

// scoutOpts — параметры подбора.
type scoutOpts struct {
	dbPath      string
	with        string // состав, вокруг которого ищем: u<id> через запятую
	threads     int    // сколько последних тредов состава просмотреть
	minComments int    // корпус кандидата, ниже которого слепок не снять
	limit       int
}

// scoutMinComments — минимальный корпус донора.
//
// Полторы тысячи, потому что слепок меряет не только манеру: полоса голоса
// набирается ПАЧКАМИ по 600 знаков (двести отложенных реплик), кривая отклика
// считается по последним тремстам тредам, а характерные ошибки — сравнением с
// нормой корпуса. У человека с полутора сотнями реплик всё это выйдет числами,
// которые нельзя отличить от шума.
const scoutMinComments = 1500

func narodScout(ctx context.Context, o scoutOpts) error {
	ids, err := parseActorIDs(o.with)
	if err != nil {
		return err
	}
	if len(ids) == 0 {
		return fmt.Errorf("narod scout: нужен состав, вокруг которого искать: -with u123,u456")
	}
	ar, err := archive.Open(ctx, o.dbPath)
	if err != nil {
		return err
	}
	defer ar.Close()

	list, err := ar.MineCoParticipants(ctx, ids, o.threads, o.minComments, o.limit)
	if err != nil {
		return err
	}
	if len(list) == 0 {
		return fmt.Errorf("narod scout: соседей с корпусом от %d реплик не нашлось — "+
			"опустите -min-comments", o.minComments)
	}

	fmt.Fprintf(os.Stderr, "соседей по последним %d тредам состава: %d\n", o.threads, len(list))

	// Готовность влезть в чужой разговор спрашивается у КАЖДОГО кандидата, и
	// это самый важный столбец таблицы, хотя стоит он не первым.
	//
	// Зажигание треда — «сколько ответов соберёт ПЕРВАЯ реплика» — равно числу
	// соседей, помноженному на эту вероятность, и больше в нём не участвует
	// ничто: у первой реплики нет ни знакомства, ни сцепившейся пары, ни накала
	// (замер 29.08.2026). У наших двенадцати она разнится ВПЯТЕРО — 4.10 % у
	// Lady in red против 0.75 % у ДВ, — поэтому роспись из разговорчивых зажигает
	// тред вдвое меньшим составом, и это единственный рычаг, которым нужное
	// число жителей уменьшается вовсе.
	//
	// Замер идёт по сотне тредов на кандидата, а не по тремстам, как у слепка:
	// здесь нужен ПОРЯДОК величины для выбора, а не число для карточки.
	rate := make(map[int64]float64, len(list))
	for _, p := range list {
		r, err := ar.MineReplyRate(ctx, []int64{p.UserID}, scoutRateThreads)
		if err != nil {
			return err
		}
		if v, ok := r.Rate(1, false); ok {
			rate[p.UserID] = v
		}
	}
	var sum float64
	for _, v := range rate {
		sum += v
	}
	fmt.Fprintf(os.Stderr, "средняя готовность влезть: %.2f %%; на таком составе первая реплика "+
		"соберёт одну только при %.0f жителях\n\n", sum/float64(max(len(rate), 1))*100,
		1/max(sum/float64(max(len(rate), 1)), 0.001)+1)
	fmt.Printf("| анкета | ник | пол | ВЛЕЗЕТ | корпус | тредов рядом | сказал | ответов друг другу | на сайте |\n")
	fmt.Printf("|---|---|---|---:|---:|---:|---:|---:|---|\n")
	for _, p := range list {
		v := "—"
		if r, ok := rate[p.UserID]; ok {
			v = fmt.Sprintf("%.2f %%", r*100)
		}
		fmt.Printf("| u%d | %s | %s | %s | %d | %d | %d | %d | %s — %s |\n",
			p.UserID, p.Nick, orDash(genderRu(p.Gender)), v, p.Comments, p.Threads, p.Said,
			p.Replies, orDash(dateOnly(p.First)), orDash(dateOnly(p.Last)))
	}
	fmt.Fprintf(os.Stderr, "\nСтолбцы отвечают на РАЗНЫЕ вопросы, и порядок строк остался по "+
		"ответам друг другу: ВЛЕЗЕТ говорит, сколько жителей нужно вообще (разговор "+
		"зажигается числом соседей, помноженным на него), а ответы друг другу — будет ли "+
		"этот человек говорить именно с составом; сосед по треду бывает случайным, "+
		"собеседник нет. Разговорчивый, не пересекающийся с составом, зажжёт тред и "+
		"уйдёт говорить в сторону. Эпоху смотреть обязательно: замолчавший до прихода "+
		"состава не встретится с ним ни в одном треде.\nСлепок снимается `narod card u<id>`.\n")
	return nil
}

// scoutRateThreads — сколько последних тредов кандидата смотреть на готовность
// влезть. Сотня, потому что кандидатов десятки, а решает здесь порядок
// величины: половина процента и четыре процента различаются и на сотне тредов.
const scoutRateThreads = 100

// parseActorIDs — список анкет u<id> через запятую.
func parseActorIDs(s string) ([]int64, error) {
	var out []int64
	for _, t := range splitTokens(s) {
		id, err := strconv.ParseInt(strings.TrimPrefix(t, "u"), 10, 64)
		if err != nil {
			return nil, fmt.Errorf("анкеты задаются как u<id>, а не %q", t)
		}
		out = append(out, id)
	}
	return out, nil
}
