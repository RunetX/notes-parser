// corpusOf — корпус из n одинаковых реплик, чтобы знаменатель был известен.
func corpusOf(n int, text string) []string {
	out := make([]string, n)
	for i := range out {
		out[i] = text
	}
	return out
}

// СЛОВО ОДНОГО ТРЕДА — ЭТО ТЕМА, А НЕ ПОЧЕРК.
//
// В треде про ночные смены «ночь» стоит у тридцати пяти жителей из сорока
// девяти, и без этого правила свод объявил бы почерком тему разговора.
func TestСловоОдногоТредаНеПопадаетВСвод(t *testing.T) {
	тема := strings.Repeat("гараж ", 20)
	общее := strings.Repeat("складно ", 20)
	threads := [][]string{
		{тема + общее},
		{общее},
	}
	res := Sweep(threads, corpusOf(500, "обычная реплика про жизнь и работу"))
	for _, w := range append(res.Words, res.Rare...) {
		if w.Word == "гараж" {
			t.Fatal("слово одного треда попало в свод — это тема, а не почерк")
		}
	}
}

// ОТСУТСТВУЮЩЕЕ В КОРПУСЕ СЛОВО ПОПАДАЕТ В ОТДЕЛЬНЫЙ РАЗДЕЛ, А НЕ ПРОПАДАЕТ.
//
// Первый прогон свода не увидел «складно» — самый сильный штамп — ровно потому,
// что в корпусе оно реже порога, а отрыв на таком знаменателе не считается.
// Пропасть оно при этом не имеет права: это сильнейшее свидетельство из всех.
func TestРедкоеВКорпусеСловоНеТеряется(t *testing.T) {
	наше := strings.Repeat("складно ", 15)
	res := Sweep([][]string{{наше}, {наше}}, corpusOf(500, "обычная реплика про жизнь"))
	var found bool
	for _, w := range res.Rare {
		if w.Word == "складно" {
			found = true
			if w.Count < 20 {
				t.Errorf("сосчитано %d вхождений, а их тридцать", w.Count)
			}
		}
	}
	if !found {
		t.Fatal("слово, которого нет в корпусе, потерялось вовсе")
	}
	for _, w := range res.Words {
		if w.Word == "складно" {
			t.Error("слово без знаменателя попало в список с отрывом — отрыв там случайное число")
		}
	}
}

// ЧАСТОТА СЧИТАЕТСЯ НА СЛОВО, А НЕ ДОЛЕЙ РЕПЛИК.
//
// Наши реплики в полтора раза длиннее корпусных, и на долях завышенным выходило
// ВСЁ подряд впятеро. Проверка прямая: если у нас и в корпусе слово стоит с
// ОДИНАКОВОЙ частотой на слово, отрыва быть не должно, как бы ни различалась
// длина реплик.
func TestДлинаРепликиНеСоздаётОтрыва(t *testing.T) {
	// У нас одна длинная реплика, в корпусе — короткие; доля слова одна и та же.
	наше := strings.Repeat("работа дом ", 10)
	res := Sweep([][]string{{наше}, {наше}}, corpusOf(600, "работа дом"))
	for _, w := range res.Words {
		if w.Word == "работа" {
			t.Errorf("длина реплики создала отрыв %.1fx на ровном месте", w.Times)
		}
	}
}

// КОНТРОЛЬ НЕПУСТ, КОГДА СРАВНЕНИЕ ЧЕСТНОЕ. Пустой контроль означает, что
// завышено всё подряд, — и отчёт обязан это показывать, а не молчать.
func TestКонтрольНаполняется(t *testing.T) {
	// У нас слова поровну, в корпусе «работа» втрое чаще «дома»: значит по нашей
	// частоте на слово мы этим словом НЕДОигрываем, и место ему в контроле.
	наше := strings.Repeat("работа ", 10) + strings.Repeat("дом ", 10)
	corpus := corpusOf(600, "работа работа работа дом")
	res := Sweep([][]string{{наше}, {наше}}, corpus)
	if len(res.Control) == 0 {
		t.Fatal("контроль пуст: слово, которого у нас меньше, чем в корпусе, не показано")
	}
}

// ДОЛЯ РЕПЛИК СО ШТАМПОМ СЧИТАЕТСЯ У ОБОИХ — иначе мерить, сработал ли евал,
// нечем: одиночная доля невода не значит ничего.
func TestДоляШтампаСчитаетсяУОбоих(t *testing.T) {
	res := Sweep([][]string{{"складно у вас выходит"}, {"будто мне неясно"}},
		[]string{"складно всё это", "обычная реплика", "обычная реплика", "обычная реплика"})
	if res.OurStamp != 1 {
		t.Errorf("наша доля %.2f, а штамп в обеих репликах", res.OurStamp)
	}
	if res.HumanStamp <= 0 {
		t.Error("человеческая доля не посчитана — сравнивать не с чем")
	}
}
