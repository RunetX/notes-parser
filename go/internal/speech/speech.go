// Пакет speech — меры СОДЕРЖАНИЯ реплики: говорит человек СЛУЧАЕМ или МНЕНИЕМ.
//
// Заведён 30.08.2026 по жалобе владельца на первую живую песочницу: «реплики
// какие-то абстрактные, большинство людей так не общается». Механику письма
// (длину, ритм, знаки, регистр) архив мерил с самого начала, и калибровка её
// выправила — а мерки на то, ЧЕМ реплика наполнена, не было вовсе, и потому
// разрыв нечем было ни назвать числом, ни проверить после правки.
//
// ЛИСТОВОЙ ПАКЕТ И БЕЗ ЗАВИСИМОСТЕЙ — по доводу `profanity`: меры нужны ТРОИМ, у
// которых общего пакета нет и быть не может. Архиву — снять портрет живого
// донора; калибровке — сравнить с ним слепок; команде замера — померить наши
// боевые реплики, лежащие в Postgres, куда ни архив, ни ядро не ходят. Три копии
// одного невода разошлись бы молча, а сравнение двух чисел, снятых разными
// неводами, не значит ничего.
//
// ГРАНИЦА МЕТОДА НАЗВАНА ЗАРАНЕЕ, как у generalizeLine: невод ловит ФОРМУ, а не
// поведение. «Свой случай» он видит по местоимению и глаголу прошедшего времени
// в одном предложении, а не по смыслу, — значит и промахивается в обе стороны:
// «у меня школа рядом была» засчитается, «сам вчера чинил кран» без «я»
// пропустится.
//
// Отсюда правило применения: числа этого пакета читаются ТОЛЬКО В СРАВНЕНИИ.
// Донор и житель меряются одним и тем же неводом, поэтому его систематическая
// ошибка стоит в обоих числах и в разнице сокращается; поодиночке же ни одно из
// них не означает ничего, и печатать их порознь нельзя.
package speech

import (
	"strings"
	"unicode"
)

// Marks — портрет содержания по НАБОРУ текстов: доли реплик, в которых примета
// нашлась. Доли, а не «сколько раз на сто слов», потому что вопрос стоит про
// РЕПЛИКУ: рассказал человек случай или не рассказал.
type Marks struct {
	Texts int `json:"texts"`

	// OwnStory — свой случай: первое лицо и прошедшее время в одном предложении
	// («вчера сам менял, намучился»). Главная мера пакета: её и недостаёт
	// машинному тексту, который рассуждает о предмете вообще.
	OwnStory float64 `json:"own_story"`
	// TimeMark — привязка ко времени: вчера, утром, в пятницу, год назад. У
	// случая время есть почти всегда, у мнения — никогда.
	TimeMark float64 `json:"time_mark"`
	// Digits — числа: цена, срок, возраст, расстояние. Та же мера, что
	// VoiceShape.HasDigits, повторена здесь, чтобы портрет содержания снимался с
	// любых текстов, не поднимая архива.
	Digits float64 `json:"digits"`
	// General — обобщение: все, всегда, никто, вообще, обычно, люди. Оборотная
	// сторона случая, и мера тут не «плохо», а «сколько»: у живых это редкий
	// приём, у модели — способ говорить по умолчанию.
	General float64 `json:"general"`
	// Advice — поучение: надо, нужно, должен, стоит. Первую реплику амвона сняли
	// с сайта именно за этот тон, и с тех пор он стоит отдельной мерой.
	Advice float64 `json:"advice"`
	// Stamp — ШТАМП МАШИНЫ: слово, которым модель говорит куда чаще живых.
	//
	// Замер 01.09.2026 по 849 боевым репликам жителей в ПЯТИ тредах разных тем
	// против 400 тыс. реплик корпуса, частотой НА СЛОВО (доля реплик врёт: наши
	// реплики длиннее корпусных в полтора раза по числу слов, и всё подряд
	// выходило впятеро завышенным). Разброс: складно ×730, вслух ×50, ровно ×27,
	// будто ×20, верно ×11, легко ×10, нечего ×5,6, потому ×6,0 — при том что
	// «просто», «тоже», «надо», «вообще», «люди» легли в 0,4–1,0× и служат
	// внутренним контролем: систематического пола у сравнения нет.
	//
	// Слово в список берётся, только если живёт во ВСЕХ пяти тредах: слово одной
	// темы — это тема, а не почерк.
	Stamp float64 `json:"stamp"`
}

// Measure снимает портрет с набора текстов.
func Measure(texts []string) Marks {
	m := Marks{Texts: len(texts)}
	if len(texts) == 0 {
		return m
	}
	var own, tm, dg, gen, adv, stp int
	for _, t := range texts {
		f := Of(t)
		if f.OwnStory {
			own++
		}
		if f.TimeMark {
			tm++
		}
		if f.Digits {
			dg++
		}
		if f.General {
			gen++
		}
		if f.Advice {
			adv++
		}
		if f.Stamp {
			stp++
		}
	}
	n := float64(len(texts))
	m.OwnStory = round4(float64(own) / n)
	m.TimeMark = round4(float64(tm) / n)
	m.Digits = round4(float64(dg) / n)
	m.General = round4(float64(gen) / n)
	m.Advice = round4(float64(adv) / n)
	m.Stamp = round4(float64(stp) / n)
	return m
}

// Flags — приметы одного текста.
type Flags struct {
	OwnStory bool
	TimeMark bool
	Digits   bool
	General  bool
	Advice   bool
	Stamp    bool
}

// GeneralHit — ПЕРВОЕ слово-обобщение в тексте; пусто — обобщения нет.
//
// Заведена 01.09.2026 вместе с евалом обобщения в народе. Тот же невод, что у
// Of, но отдаёт СЛОВО, а не флаг, и довод ровно один: брак, названный словом,
// модель исправляет с первой попытки, а брак, названный правилом, — переписывая
// реплику наугад. Цена евала считается в лишних вызовах, поэтому качество
// обратной связи здесь не удобство, а деньги.
func GeneralHit(text string) string {
	for _, s := range sentences(strings.ToLower(text)) {
		for _, w := range wordsOf(s) {
			if generalWords[w] {
				return w
			}
		}
	}
	return ""
}

// StampHit — ПЕРВЫЙ штамп машины в тексте; пусто — штампа нет.
//
// Устроена как GeneralHit и по тому же доводу: брак, названный словом, модель
// исправляет с первой попытки. Сравнение идёт ПО СЛОВУ, а не по подстроке, —
// иначе «верно» ловилось бы в «наверное», а «сама» в «самая», и невод врал бы
// в ту же сторону, в какую его завели.
func StampHit(text string) string {
	for _, s := range sentences(strings.ToLower(text)) {
		for _, w := range wordsOf(s) {
			if stampWords[w] {
				return w
			}
		}
	}
	return ""
}

// Of разбирает один текст.
func Of(text string) Flags {
	var f Flags
	low := strings.ToLower(text)
	for _, s := range sentences(low) {
		words := wordsOf(s)
		if !f.OwnStory && hasFirstPerson(words) && hasPast(words) {
			f.OwnStory = true
		}
		for _, w := range words {
			switch {
			case timeWords[w]:
				f.TimeMark = true
			case generalWords[w]:
				f.General = true
			case adviceWords[w]:
				f.Advice = true
			}
			if stampWords[w] {
				f.Stamp = true
			}
		}
		if !f.TimeMark && hasTimePhrase(s) {
			f.TimeMark = true
		}
	}
	for _, r := range text {
		if unicode.IsDigit(r) {
			f.Digits = true
			break
		}
	}
	return f
}

// hasFirstPerson — говорит ли предложение о себе.
func hasFirstPerson(words []string) bool {
	for _, w := range words {
		if firstPerson[w] {
			return true
		}
	}
	return false
}

// hasPast — есть ли в предложении глагол прошедшего времени.
//
// Морфологии у нас нет, поэтому глагол опознаётся по хвосту: -л, -ла, -ло, -ли
// плюс возвратные -лся, -лась, -лись. Хвост этот носят и существительные
// (школа, сила, дело, число), поэтому самые частые вычтены списком — полным он
// не будет никогда, и это ровно та систематическая ошибка, которая сокращается
// при сравнении двух портретов одним неводом.
func hasPast(words []string) bool {
	for _, w := range words {
		if len([]rune(w)) < 4 || notPast[w] {
			continue
		}
		for _, suf := range pastSuffixes {
			if strings.HasSuffix(w, suf) {
				return true
			}
		}
	}
	return false
}

var pastSuffixes = []string{"лся", "лась", "лись", "л", "ла", "ло", "ли"}

// firstPerson — местоимения первого лица. «Мы» здесь наравне с «я»: свой случай
// человек рассказывает и от лица семьи («ездили, стояли в пробке»).
var firstPerson = set(
	"я", "мне", "меня", "мной", "мною",
	"мы", "нам", "нас", "нами",
	"мой", "моя", "моё", "мои", "моего", "моей", "моих", "моим",
	"наш", "наша", "наше", "наши", "нашего", "нашей", "наших",
)

// notPast — частые слова с глагольным хвостом, глаголами не являющиеся. Список
// короткий намеренно: он снимает самые шумные, а не притворяется полным.
var notPast = set(
	"школа", "сила", "дело", "число", "тепло", "мало", "село", "стекло",
	"весло", "пила", "скала", "метла", "игла", "стрела", "смола", "зола",
	"крыло", "масло", "сало", "зеркало", "одеяло", "покрывало", "начало",
	"правило", "мыло", "люди", "цели", "щели", "или", "они", "боль",
	"роль", "соль", "жаль", "даль", "пыль", "цель", "щель", "мель",
	"тело", "тела", "дела", "мила", "мила", "вилы", "село",
)

// timeWords — привязка ко времени одним словом.
var timeWords = set(
	"вчера", "позавчера", "сегодня", "утром", "днём", "днем", "вечером",
	"ночью", "недавно", "давеча", "намедни", "накануне",
	"понедельник", "вторник", "среду", "четверг", "пятницу", "субботу",
	"воскресенье", "летом", "зимой", "весной", "осенью",
)

// timePhrases — привязка ко времени оборотом. Ищется подстрокой: «на той
// неделе», «года назад» — то, что одним словом не ловится.
var timePhrases = []string{
	"на той неделе", "на прошлой неделе", "на этой неделе", "в прошлом году",
	"в этом году", "года назад", "лет назад", "дня назад", "месяц назад",
	"месяца назад", "недели назад", "неделю назад", "час назад",
	"в прошлый раз", "на днях", "с утра", "под вечер", "в тот день",
}

func hasTimePhrase(s string) bool {
	for _, p := range timePhrases {
		if strings.Contains(s, p) {
			return true
		}
	}
	return false
}

// stampWords — ШТАМПЫ МАШИНЫ: слова, которыми модель говорит в разы чаще живых.
//
// Список ЗАМЕРЕН, а не собран на слух (см. Marks.Stamp), и держится тремя
// правилами. Слово обязано жить во всех тредах замера — иначе это тема. Слово
// обязано отрываться от корпуса в разы, а не в проценты, — рядом с контролем в
// 0,4–1,0×. И слова, уже судимого другим неводом, здесь быть не должно:
// «никто» лежит в generalWords, и два невода, судящие одно слово, однажды
// разойдутся между собой — обобщение выпало разрешённым, а штамп запрещённым.
//
// Список ПОЛ, а не потолок: он ловит те слова, которыми модель выдала себя на
// первых девятистах репликах, и после каждой правки промпта его надо снимать
// заново — почерк уедет в другие слова.
var stampWords = set(
	"складно", "вслух", "ровно", "будто", "верно", "легко", "нечего", "потому",
)

// generalWords — вынесение сказанного на всех.
var generalWords = set(
	"все", "всё", "всегда", "никогда", "вообще", "обычно", "каждый", "каждая",
	"каждому", "любой", "любая", "никто", "никому", "всех", "всем", "всеми",
	"люди", "людей", "людям", "мужики", "мужчины", "женщины", "бабы",
	"большинство",
)

// adviceWords — поучение. Тон, за который сняли первую реплику амвона.
var adviceWords = set(
	"надо", "нужно", "должен", "должна", "должны", "стоит", "следует",
	"обязан", "обязана", "необходимо", "правильнее",
)

// sentences — грубое деление на предложения: точка, вопрос, восклицание,
// перевод строки, точка с запятой. Точности здесь не нужно — примета ищется В
// ПРЕДЕЛАХ фразы, чтобы «я» и глагол стояли рядом, а не в разных концах реплики.
func sentences(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool {
		return r == '.' || r == '!' || r == '?' || r == '\n' || r == ';'
	})
}

// wordsOf — слова предложения без знаков.
func wordsOf(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && r != '-'
	})
}

func set(words ...string) map[string]bool {
	m := make(map[string]bool, len(words))
	for _, w := range words {
		m[w] = true
	}
	return m
}

func round4(x float64) float64 { return float64(int(x*10000+0.5)) / 10000 }
