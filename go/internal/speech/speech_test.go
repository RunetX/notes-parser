package speech

// Меры содержания. Тесты здесь короткие и назывные: каждый показывает ОДНУ
// примету на живой фразе и на её противоположности — иначе невод, ловящий всё
// подряд, выглядел бы работающим.

import "testing"

// Свой случай — это первое лицо И прошедшее время в одной фразе. Порознь ни то,
// ни другое случаем не является: «я думаю» — мнение, «он приехал» — чужая жизнь.
func TestСвойСлучайЭтоПервоеЛицоИПрошедшее(t *testing.T) {
	cases := []struct {
		text string
		want bool
	}{
		{"вчера сам менял, намучился с этой резьбой", false}, // нет «я»/«мы»
		{"я вчера менял, намучился", true},
		{"мы с ней ездили на дачу, вернулись затемно", true},
		{"у меня кран протекал всю неделю", true},
		// СЛЕПОЕ МЕСТО НЕВОДА, названное здесь нарочно: у мужского прошедшего
		// без -л (тёк, нёс, мог, лёг) хвоста нет вовсе, и такой случай невод
		// пропускает. Ловить его добавочными хвостами -г/-с/-к нельзя — под них
		// попадут луг, лес, сок и бег, то есть шума станет больше, чем находок.
		{"у меня кран тёк всю неделю", false},
		{"я думаю, что тут дело в другом", false}, // первое лицо без прошедшего
		{"он приехал и сразу начал учить", false}, // прошедшее без первого лица
		{"мужики всегда так делают", false},       // ни того, ни другого
		{"у меня школа рядом", false},             // «школа» вычтена из глаголов
	}
	for _, c := range cases {
		if got := Of(c.text).OwnStory; got != c.want {
			t.Errorf("%q: свой случай %v, ожидалось %v", c.text, got, c.want)
		}
	}
}

// Время — то, что у случая есть почти всегда, а у мнения не бывает.
func TestВремяСловомИОборотом(t *testing.T) {
	for _, s := range []string{"вчера заходил", "на той неделе привезли",
		"года назад такое было", "с утра не заводится"} {
		if !Of(s).TimeMark {
			t.Errorf("%q: время не найдено", s)
		}
	}
	if Of("мужчины вообще не перезванивают").TimeMark {
		t.Error("у обобщения нашлось время")
	}
}

// Обобщение и поучение — две приметы мнения, и они разные: первое выносит
// сказанное на всех, второе указывает собеседнику, как ему быть.
func TestОбобщениеИПоучениеРазныеПриметы(t *testing.T) {
	gen := Of("все мужики так делают")
	if !gen.General || gen.Advice {
		t.Errorf("обобщение разобрано как %+v", gen)
	}
	adv := Of("тебе надо было сразу спросить")
	if !adv.Advice || adv.General {
		t.Errorf("поучение разобрано как %+v", adv)
	}
}

// Портрет — доли реплик, а не сумма примет: вопрос стоит про реплику, а не про
// то, сколько раз в ней помянули «всех».
func TestПортретСчитаетДолиРеплик(t *testing.T) {
	m := Measure([]string{
		"я вчера сам менял",          // случай + время
		"все всегда всё знают лучше", // обобщение
		"дождь",              // ничего
		"взял за 300 рублей", // цифры
	})
	if m.Texts != 4 {
		t.Fatalf("текстов %d", m.Texts)
	}
	if m.OwnStory != 0.25 {
		t.Errorf("свой случай %.2f, ожидалось 0.25", m.OwnStory)
	}
	if m.General != 0.25 {
		t.Errorf("обобщение %.2f, ожидалось 0.25", m.General)
	}
	if m.Digits != 0.25 {
		t.Errorf("цифры %.2f, ожидалось 0.25", m.Digits)
	}
	if Measure(nil).Texts != 0 {
		t.Error("пустой набор дал непустой портрет")
	}
}
