package speech

import "testing"

// Слово, которое говорят все и всегда, каноном быть не может: без этого
// знаменателя «выдуманный факт» находился бы в каждом треде.
func TestЧастыеСловаНеИдутВКанон(t *testing.T) {
	for _, w := range []string{"вообще", "женщины", "человек", "поэтому", "наверное"} {
		if !CommonWord(w) {
			t.Errorf("слово %q замер назвал частым, а список его не знает", w)
		}
	}
	for _, w := range []string{"свадьба", "прокладка", "аквариум", "полка"} {
		if CommonWord(w) {
			t.Errorf("слово %q не из частых, а список его прячет", w)
		}
	}
}

func TestСловаСодержанияБезКоротких(t *testing.T) {
	got := ContentWords("Чужая свадьба и год ожидания, вообще свадьба тут ни при чём")
	seen := map[string]bool{}
	for _, w := range got {
		if seen[w] {
			t.Fatalf("повтор в разборе: %q", w)
		}
		seen[w] = true
	}
	if !seen["свадьба"] {
		t.Error("слово содержания потеряно")
	}
	if seen["год"] || seen["вообще"] {
		t.Error("в разбор попало короткое либо частое слово")
	}
}
