// КАНОН РАЗГОВОРА — слова, которых в заметке не было, а в треде они уже у всех.
//
// Заведено 01.09.2026 по разбору первого треда с панчем в каждой реплике: там
// жители сговорились о «четырёх годах» и «чужой свадьбе», которых в исходной
// заметке нет вовсе. Один сказал — остальные приняли за известное, и через
// двадцать реплик выдуманный факт стал общим прошлым. У живых так не бывает:
// подхватывают двое-трое, а дальше разговор идёт своей дорогой.
//
// Ловится это словами, а не смыслом, и потому нужен ЗНАМЕНАТЕЛЬ: без него
// «канон» находился бы в каждом треде, потому что слова «вообще» и «женщины»
// в двадцати репликах подряд встретятся всегда.
//
// commonWords — ЗАМЕР: три сотни самых частых слов корпуса длиной от пяти букв
// (10,8 млн реплик, 1,69 млн разных слов). Выброшена из него только латиница —
// коды смайлов вроде crazy и agree по частоте стоят рядом с «конечно».
//
// НИКИ ИЗ СПИСКА НЕ ВЫЧИЩАЮТСЯ, и это решение, а не небрежность. Первая
// редакция вычищала: ники участников архива (13 683 токена из users.name и
// nick_history) вычитались из частотного списка, — и вместе с «ягодой» и
// «мрачным» из него выпало слово «человек», потому что кто-то когда-то взял его
// ником. Знаменатель дороже опрятности: несколько ников в списке значат лишь,
// что эти слова не считаются каноном, а они им и не бывают — участники треда
// исключаются из канона отдельно и по имени (canonWords).
//
// Со списком штампов (stampWords) он не спорит и спорить не может: тот СУДИТ
// слово, а этот лишь снимает с него подозрение. Двух приговоров на одно слово
// здесь не возникает — возникает приговор и его отсутствие.
var commonWords = map[string]bool{}

