func init() {
	for _, w := range commonList {
		commonWords[w] = true
	}
}

// CommonWord — говорят ли это слово все и всегда.
func CommonWord(w string) bool { return commonWords[strings.ToLower(w)] }

// contentRe — слово, годное в канон: от пяти букв. Короткие в счёт не идут
// вовсе — на них знаменатель кончается раньше, чем начинается смысл.
var contentRe = regexp.MustCompile(`[а-яёА-ЯЁa-zA-Z][а-яёА-ЯЁa-zA-Z-]{4,}`)

// ContentWords — слова текста, годные в канон: не короче пяти букв и не из
// числа тех, что говорят все. Возвращаются в нижнем регистре и без повторов.
func ContentWords(text string) []string {
	seen := map[string]bool{}
	var out []string
	for _, w := range contentRe.FindAllString(text, -1) {
		w = strings.ToLower(w)
		if commonWords[w] || seen[w] {
			continue
		}
		seen[w] = true
		out = append(out, w)
	}
	return out
}
