package speech

import "testing"

// РОЛЕВОЙ ЗАЧИН — то, чем машина выдала себя в первом же треде с панчем.
// Обе строки взяты с боевой страницы 01.09.2026.
func TestРолевойЗачинЛовитсяТам(t *testing.T) {
	for _, s := range []string{
		"как пожарный скажу: горело четыре года, а вызвали соседи...",
		"Как автослесарь спрошу: она четыре года стук слушала?",
		"как мать двоих заявляю - так не бывает",
		"Как бухгалтер, скажу вам прямо",
	} {
		if got := RoleLead(s); got == "" {
			t.Errorf("зачин не пойман: %q", s)
		}
	}
}

// А вот это живая речь, и ловить её нельзя. Шесть таких стояло в замере
// (10,8 млн реплик): «как я скажу, так и будет» — оборот, а не должность.
func TestРолевойЗачинНеЛовитЖивогоОборота(t *testing.T) {
	for _, s := range []string{
		"как я скажу, так и будет",
		"как ты скажешь, так и сделаем",
		"как обычно, всё через одно место",
		"как только приедет - позвоню",
		"а он мне: как хочешь скажу, а я не пойду",
		"потом уже как врач скажу, но это в конце реплики",
	} {
		if got := RoleLead(s); got != "" {
			t.Errorf("живой оборот принят за зачин: %q → %q", s, got)
		}
	}
}

// САМОНАЗВАННОЕ РЕМЕСЛО. Невод грубый по устройству (ловит форму, а не смысл),
// и цена ошибки несимметрична: лишний брак стоит одного платного круга, а
// житель, побывавший в одном треде ветеринаром и сантехником, ломает характер.
func TestСамоназванноеРемесло(t *testing.T) {
	cases := []struct{ text, want string }{
		{"как сантехник говорю - там прокладка", "сантехник"},
		{"я сварщик, мне это видно", "сварщик"},
		{"ну я работаю кладовщиком, у нас так же", "кладовщиком"},
		{"как бывший строитель, скажу", "строитель"},
		{"как человек посторонний, промолчу", ""},
		{"я думаю, что это ерунда", ""},
		{"как женщина вам говорю", ""},
		{"он у меня молодец, всё сам", ""},
	}
	for _, c := range cases {
		if got := SelfRole(c.text); got != c.want {
			t.Errorf("%q: ремесло %q, ожидалось %q", c.text, got, c.want)
		}
	}
}

// Корень в пять букв: «сантехник» сходится со «сантехником» из биографии и
// расходится со «сварщиком».
func TestКореньРемесла(t *testing.T) {
	if TradeRoot("сантехник") != TradeRoot("сантехником") {
		t.Error("одно и то же ремесло разошлось по корню")
	}
	if TradeRoot("сварщик") == TradeRoot("сантехник") {
		t.Error("разные ремёсла сошлись по корню")
	}
}
