package speech

// РОЛЕВОЙ ЗАЧИН — «как пожарный скажу:», «как автослесарь спрошу:».
//
// Заведён 01.09.2026 по жалобе владельца на первый тред с панчем в каждой
// реплике: две реплики подряд открывались этой рамкой, а по разбору прогона ею
// было построено около 80 % треда.
//
// ЗАМЕР по 10,8 млн реплик архива: зачин «как <кто-то> скажу/спрошу» стоит в 46
// репликах, из них 6 — это «как я скажу» и прочие местоимения, то есть
// НАСТОЯЩИХ ролевых сорок. Доля — 0,0004 %, одна реплика на двести тридцать
// тысяч; в полосе длины наших реплик (5–25 слов) ровно та же. Для сравнения:
// «как <слово>» в начале реплики вообще, без глагола говорения, — 0,238 %, то
// есть на три порядка чаще, и запрещать эту форму целиком нельзя.
//
// ОТКУДА ОНА У НАС ВЗЯЛАСЬ, видно точно, и это не догадка: в 849 боевых
// репликах ДО панча (пять тредов, замер того же дня) зачина нет НИ ОДНОГО. Он
// пришёл вместе с образцом приёма «не тот эксперт» — «Как кладовщик скажу:
// недостачу так не закрывают», — и модель скопировала не приём, а ФОРМУ
// образца. Тот же урок, что с jabsLine и списком приёмов пассивной агрессии,
// только теперь оплаченный образцом, а не списком.
//
// ГРАНИЦА НЕВОДА названа, как у соседей: он ловит ФОРМУ. «Как пожарный скажу»
// поймает, «я вообще-то пожарный, и скажу» — пропустит. Числа его читаются
// только в сравнении: донор и житель меряются одним неводом.

import (
	"regexp"
	"strings"
)

// roleLeadRe — «как <одно-два слова> скажу/спрошу/…» в самом начале реплики.
//
// Глаголы взяты ЗАКРЫТЫМ списком и только первого лица: именно они делают рамку
// заявлением о себе. «Как сказала бы моя бабушка» — не про говорящего.
//
// Конец слова назван КЛАССОМ, а не \b: граница слова в Go считается по ASCII, и
// после «скажу» перед двоеточием её нет вовсе — русская буква для неё не буква.
// Замер, снятый питоновской регуляркой, здесь молча разошёлся бы с судом, и
// евал не поймал бы ровно тех двух реплик, из-за которых заведён.
var roleLeadRe = regexp.MustCompile(`(?i)^[\s"«(]*как\s+([а-яёa-z-]+)(?:\s+([а-яёa-z-]+))?\s*,?\s*(скажу|спрошу|добавлю|замечу|отвечу|отвечаю|говорю|заявляю|заявлю)(?:[^а-яёА-ЯЁa-zA-Z]|$)`)

// roleLeadPronouns — то, что стоит на месте роли, но ролью не является. Шесть
// таких нашлось в замере («как я скажу, так и будет»), и всё это живая речь:
// запретив её, мы ловили бы не машину, а оборот.
var roleLeadPronouns = map[string]bool{
	"я": true, "ты": true, "он": true, "она": true, "оно": true,
	"мы": true, "вы": true, "они": true, "мне": true, "тебе": true,
	"вам": true, "нам": true, "только": true, "раз": true, "уж": true,
	"тут": true, "там": true, "же": true, "бы": true, "хочешь": true,
	"хотите": true, "знаешь": true, "знаете": true,
}

// RoleLead — ролевой зачин реплики; пусто, если его нет. Возвращается сам кусок
// текста: он идёт и в брак модели, и в журнал, — по нему видно, за что реплику
// завернули.
func RoleLead(text string) string {
	m := roleLeadRe.FindStringSubmatch(text)
	if m == nil {
		return ""
	}
	if roleLeadPronouns[strings.ToLower(m[1])] {
		return ""
	}
	return strings.TrimSpace(strings.TrimLeft(m[0], " \t\"«("))
}

// tradeSuffixes — по каким окончаниям слово опознаётся ремеслом.
//
// Список НАРОЧНО грубый, и цена ошибки несимметрична — тот же довод, что у
// strangeName в narod: лишний брак стоит одного платного круга, а житель,
// назвавшийся чужим ремеслом, ломает характер, который собирали неделю (в
// прогоне 01.09.2026 Тонкая рябина побывала в одном треде ветеринаром и
// сантехником, Фельдшер Оля — кладовщиком).
var tradeSuffixes = []string{
	"ник", "щик", "чик", "тель", "ист", "лог", "ер", "ёр", "ор", "арь",
	"ант", "ент", "ач", "ец", "ица", "иха", "ша", "вод", "граф", "ург", "мен",
	"ником", "щиком", "телем", "истом", "логом", "ером", "ором", "арем",
}

// notTrades — слова, попадающие под окончание, но ремеслом не являющиеся.
// Список короткий и пополняется по находкам: длинного и не нужно — проверка
// идёт только по словам от шести букв.
var notTrades = map[string]bool{
	"молодец": true, "наконец": true, "конец": true, "палец": true,
	"человек": true, "мужчина": true, "женщина": true, "старик": true,
	"близнец": true, "любимец": true, "жилец": true, "уроженец": true,
	"иностранец": true, "сибиряк": true, "покойник": true, "должник": true,
	"родитель": true, "зритель": true, "читатель": true, "обыватель": true,
	"мечтатель": true, "одиночка": true, "мамаша": true, "женщиной": true,
	"мужчиной": true, "человеком": true,
}

// selfRoleRe — где житель называет своё ремесло.
//
// Форм две, и якоря у них РАЗНЫЕ. «Как сантехник» берётся только с начала
// фразы: в середине этот оборот сплошь и рядом про третьего («он у меня как
// слесарь шарит»), и, судя его, мы браковали бы разговор о постороннем.
// «Я сварщик» берётся где угодно на границе слова — это заявление о себе в
// любом месте реплики, а «меня» и «моя» под границу не подпадают.
var selfRoleRe = []*regexp.Regexp{
	regexp.MustCompile(`(?i)(?:^|[.!?…]\s+)как\s+(?:бывш(?:ий|ая)\s+|потомственн(?:ый|ая)\s+)?([а-яё-]{6,})`),
	regexp.MustCompile(`(?i)(?:^|[^а-яёА-ЯЁa-zA-Z])я\s+(?:бывш(?:ий|ая)\s+|потомственн(?:ый|ая)\s+|работаю\s+)?([а-яё-]{6,})`),
}

// SelfRole — ремесло, которым житель назвался в этой реплике; пусто, если
// такого в тексте нет.
//
// Судит ФОРМУ, а не смысл: «как сантехник» поймает, «чиню трубы двадцать лет»
// пропустит. Годится же оно ровно для одного вопроса — совпадает ли названное с
// карточкой, — а на него формы достаточно.
func SelfRole(text string) string {
	for _, re := range selfRoleRe {
		for _, m := range re.FindAllStringSubmatch(text, -1) {
			w := strings.Trim(strings.ToLower(m[1]), ",-")
			if notTrades[w] || roleLeadPronouns[w] {
				continue
			}
			for _, suf := range tradeSuffixes {
				if strings.HasSuffix(w, suf) {
					return w
				}
			}
		}
	}
	return ""
}

// TradeRoot — корень названия ремесла для сверки с карточкой. Пять букв: этого
// хватает, чтобы «сантехник» сошёлся с «сантехником» из биографии и разошёлся
// со «сварщиком», и не хватает, чтобы «печник» сошёлся с «пекарем».
func TradeRoot(word string) string {
	r := []rune(strings.ToLower(strings.TrimSpace(word)))
	if len(r) > 5 {
		r = r[:5]
	}
	return string(r)
}
