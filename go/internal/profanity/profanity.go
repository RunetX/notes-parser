// Пакет profanity — словарь канонического мата, общий на весь проект.
//
// ЛИСТОВОЙ и без зависимостей, и это не оформление. Список нужен ДВОИМ, у
// которых нет и не может быть общего пакета:
//
//   - автомату модерации (platmod) — чтобы СУДИТЬ чужую реплику: право машины
//     убрать чужие слова обязано держаться на словаре, а не на мнении модели;
//   - народу (narod) — чтобы НЕ ПИСАТЬ: житель, написавший мат, тут же получит
//     от автомата скрытие, то есть оплаченную генерацию, снятую со страницы, и
//     дыру в треде на её месте.
//
// Ядро народа не импортирует ни platform, ни archive (см. шапку narod), а
// platmod знает про площадку всё — значит второй словарь рядом с первым завёлся
// бы неизбежно. А два словаря мата, расходящиеся молча, — это площадка, на
// которой запрещено писать не то, что она гасит.

package profanity

// Мат считает КОД, а не модель — по той же причине, по какой код считает шторм
// (см. isFlood): это лексический факт, а не суждение. Отсюда три свойства,
// которых у модели не бывает: решение воспроизводимо, стоит ноль и не зависит
// от того, какая модель сегодня в конфиге.
//
// Правило 11 площадки запрещает брань «в любом виде, включая завуалированные —
// маскировку буквами, цифрами и цитированием», поэтому перед проверкой слово
// нормализуется: латиница и цифры-двойники возвращаются в кириллицу, символы
// выбрасываются, удвоенные буквы схлопываются. Так «разосрРала» становится
// «разосрала», а «Х-У-Й» — «хуй».
//
// **Разбор идёт ПОСЛОВНО, и это не мелочь.** Выброси разделители на всей
// строке — и соседние слова склеятся: «мыс раком» дало бы «мысраком», то есть
// мат из двух невинных слов. Поэтому границей служит пробел, а внутри слова
// маскировка разрешена любая.
//
// Список корней намеренно КОРОТКИЙ: только канонический мат. Ругательства
// помягче (мудак, пидор, говно, сука) сюда не входят — их отличает от резкости
// не написание, а адрес и намерение, и это работа модели по категории insult.
// Каждый корень здесь — это право пометить чужую реплику, и растить список
// молча нельзя.

import (
	"regexp"
	"strings"
	"unicode"
)

// homoglyphs — чем заменяют кириллицу, чтобы обойти фильтр. Цифры тоже: пункт 11
// называет их прямо.
var homoglyphs = map[rune]rune{
	'a': 'а', 'b': 'в', 'c': 'с', 'e': 'е', 'h': 'н', 'k': 'к', 'm': 'м',
	'o': 'о', 'p': 'р', 't': 'т', 'x': 'х', 'y': 'у', 'u': 'и', 'n': 'п',
	'3': 'е', '0': 'о', '4': 'ч', '6': 'б', '9': 'д', '1': 'и', '5': 'ѕ',
}

// matRoots — канонический мат. Проверяются по НОРМАЛИЗОВАННОМУ слову целиком,
// поэтому `^` и `$` здесь — границы слова, а не строки.
var matRoots = []*regexp.Regexp{
	// ху* — «хуй», «хуя», «нахуя», «похую». Тоже С НАЧАЛА слова или после
	// приставки: свободной подстрокой корень забирает «застрахуй», «страхует»,
	// «перестрахуйся» и весь винительный падеж прилагательных на «-хую» —
	// «плохую», «сухую», «тихую», «глухую».
	regexp.MustCompile(`^(вы|за|на|по|при|про|разо|раз|рас|подо|подъ|под|съ|со|с|у|ото|отъ|от|до|объ|об|недо|не|ни|пере|о|а)?ху[йеяию]`),
	// пизд* — во всех видах.
	regexp.MustCompile(`пизд`),
	// бля* — С НАЧАЛА слова или после приставки, как и «еб». Свободной
	// подстрокой этот корень брать НЕЛЬЗЯ: «блят» живёт в середине совершенно
	// невинных слов — «уподобляться», «углубляться», «употребляться»,
	// «ослабляться». Прогон по живой очереди 23.08.2026 поймал ровно это: под
	// нож без человека уходила реплика «не следует уподобляться тому, что для
	// тебя неприемлемо», и цитатой автору предъявлялось слово «уподобляться».
	// Двадцать четыре проверки на ложные срабатывания эту дыру не увидели —
	// среди них не было ни одного слова с «бля» внутри.
	regexp.MustCompile(`^(вы|за|на|по|при|про|разо|раз|подо|подъ|съ|со|у|ото|отъ|от|до|объ|об|недо|пере)?бля(д|т|$)`),
	// еб* — ТОЛЬКО в начале слова или после приставки. Без этого «себе»,
	// «требовать» и «хлебать» стали бы матом: «еб» живёт у них в середине.
	// Голой приставки «с» в списке нет намеренно — она даёт ровно «себе».
	regexp.MustCompile(`^(вы|за|на|по|при|про|разо|раз|подо|подъ|съ|со|у|ото|отъ|от|до|объ|об|недо|пере)?еб([аеиоуыя]|$)`),
}

// Чего в списке НЕТ и почему. «Сра*» стояло здесь до 23.08.2026 и было снято
// прогоном по живой очереди: из восьми срабатываний profanity семь пришлись на
// вульгаризмы — «Сраца на нгсе», «пересрались», «разосрРала», — а рядом
// модель добавляла «хрен» и «херню». Мат это четыре обсценных корня, всё
// остальное — грубость, то есть ЖАНР раздела; автоскрытие грубости выкосило бы
// саму площадку. Кто считает иначе, вернёт строку сюда — но правкой, которую
// видно в diff, как и всё остальное про право машины убирать чужие слова.

// maskedRoots — корни, у которых буква ЗАМЕНЕНА символом, а не разделена им.
// Отдельный список и отдельная форма слова, потому что случаи разной природы:
// «х-у-й» лечится выбрасыванием символов, а «х*й» от этого становится «хй» и
// не совпадает ни с чем. Здесь только три несомненных корня: подстановка
// расширяет совпадение, а значит и цену ошибки.
var maskedRoots = []*regexp.Regexp{
	regexp.MustCompile(`х\*([йеяию]|$)`),
	regexp.MustCompile(`п\*зд|пи\*д|пиз\*`),
	regexp.MustCompile(`бл\*[дт]|^бл\*$`),
}

// normalizeWord приводит слово к виду, в котором его сравнивают с корнями:
// латиница и цифры-двойники — в кириллицу, удвоения схлопнуты, символы
// выброшены.
func normalizeWord(w string) string { return normalize(w, false) }

// maskWord — то же, но ВНУТРЕННИЕ символы заменяются одной звёздочкой, а не
// выбрасываются: так «х*й» остаётся трёхбуквенным следом слова, а не «хй».
// Символы по краям выбрасываются всегда — это кавычки и знаки препинания.
func maskWord(w string) string { return normalize(w, true) }

func normalize(w string, keepGaps bool) string {
	var b strings.Builder
	var prev rune
	gap := false
	for _, r := range strings.ToLower(w) {
		if r == 'ё' {
			r = 'е'
		}
		if h, ok := homoglyphs[r]; ok {
			r = h
		}
		if !unicode.Is(unicode.Cyrillic, r) {
			// Пропуск помечаем, но ставим звёздочку только когда за ним
			// придёт буква: иначе край слова дал бы ложную «замену».
			gap = gap || b.Len() > 0
			continue
		}
		if gap && keepGaps {
			b.WriteRune('*')
			prev = '*'
		}
		gap = false
		if r == prev {
			continue // «ррр» → «р»: удвоение тоже маскировка
		}
		b.WriteRune(r)
		prev = r
	}
	return b.String()
}

// FindMat возвращает первое матерное слово исходного текста — оно же цитата для
// карточки проверки. Пустая строка означает «не нашлось».
//
// Возвращается слово ОРИГИНАЛА, а не нормализованное: человеку в очереди нужно
// видеть, что именно написал автор, а не что из этого получилось у детектора.
func FindMat(text string) string {
	for _, w := range strings.Fields(text) {
		norm, masked := normalizeWord(w), maskWord(w)
		// Порог считается по ФОРМЕ С ПРОПУСКАМИ: у «х*й» выброс символов даёт
		// «хй», и порог в три буквы отсекал бы слово раньше, чем до него дойдёт
		// проверка на замену. Из одной-двух букв мата не выходит, а ложных
		// срабатываний да.
		if len([]rune(masked)) < 3 {
			continue
		}
		for _, re := range matRoots {
			if re.MatchString(norm) {
				return strings.Trim(w, ".,;:!?()«»\"'…")
			}
		}
		for _, re := range maskedRoots {
			if re.MatchString(masked) {
				return strings.Trim(w, ".,;:!?()«»\"'…")
			}
		}
	}
	return ""
}
