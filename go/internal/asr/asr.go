// Пакет asr — автораспознавание голосовых, попавших в тред заметки: бот
// отвечает реплаем расшифровкой, а что с ней делать (скопировать,
// отредактировать, отправить комментарием), решает автор. Фича без состояния:
// ни кнопок, ни подтверждений, ни переписки в ЛС.
//
// Пакет не знает про мессенджеры: транспорт приходит замыканиями Fetch/Reply в
// Job, поэтому гейт MAX подключится к тому же сервису без дублирования.
package asr

import (
	"context"
	"io"
)

// Transcriber — распознавание речи: WAV 16 кГц моно → текст. За интерфейсом
// прячется облачный провайдер (сейчас Nexara), чтобы сменить сервис или
// подключить локальную модель, не трогая вызывающий код.
type Transcriber interface {
	Transcribe(ctx context.Context, wav io.Reader) (string, error)
}

// Converter приводит присланное аудио/видео к формату, который ждёт
// Transcriber. За интерфейсом — ffmpeg; в тестах подменяется.
type Converter interface {
	ToWAV(ctx context.Context, in []byte) ([]byte, error)
}
