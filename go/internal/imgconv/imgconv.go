// Пакет imgconv — приведение присланной участником картинки к тому, что площадка
// готова хранить и показывать: одна сторона не длиннее MaxSide, данные съёмки
// сняты, формат WebP (а где сборка ffmpeg без libwebp — JPEG).
//
// Отдельный пакет, а не файл в web, по той же причине, по какой отдельным пакетом
// живёт asr: здесь нет ни строки про HTTP и ни строки про шаблоны — это разбор
// байтов и запуск чужого процесса. Работа идёт ЧУЖИМ ПРОЦЕССОМ намеренно:
// декодирование присланного файла — самое опасное место всей затеи, и память на
// него тратит ffmpeg, а не мы.
package imgconv

import (
	"context"
	"errors"
)

const (
	// MaxSide — потолок длинной стороны. Константой, а не настройкой: 1600 это
	// ширина колонки заметки, умноженная на двойную плотность экрана телефона,
	// — число, которое меняется вместе с вёрсткой, а не по вкусу.
	MaxSide = 1600

	// MaxPixels — потолок ВХОДА, считанный по худшему случаю: PNG декодируется
	// в RGBA, четыре байта на точку, и двадцать четыре миллиона точек — это
	// 96 МБ у ffmpeg. А ffmpeg живёт в ТОМ ЖЕ контейнере, что и морда
	// (mem_limit 320m), значит его память — это наша память, и GOMEMLIMIT про
	// неё не знает вовсе. Двадцать четыре миллиона при этом больше любого
	// телефонного снимка: у 48-мегапиксельной камеры кадр выходит 12 Мп.
	MaxPixels = 24_000_000

	// MaxBytes — потолок исходника (решение владельца 26.08.2026).
	MaxBytes = 10 << 20

	// Quality — качество WebP. Восемьдесят это тот порог, за которым разница с
	// оригиналом перестаёт быть видна, а файл ещё не начал расти вдвое.
	Quality = 80
)

// Ошибки — значениями, а не текстом: морда переводит их в слова для человека,
// и разбирать для этого строки она не должна (тот же приём, что у writeProblem).
var (
	ErrNotImage  = errors.New("это не картинка")
	ErrTooBig    = errors.New("картинка больше потолка")
	ErrTooManyPx = errors.New("в картинке слишком много точек")
	ErrConvert   = errors.New("картинка не перекодировалась")
)

// Source — что нам дали. Заполняется БЕЗ декодирования: заголовок формата и, у
// JPEG, тег ориентации. В этом весь смысл разделения: решение «принимать или
// нет» принимается по сотне прочитанных байт, а не по распакованному растру.
type Source struct {
	MIME        string // image/jpeg | image/png | image/gif | image/webp
	Width       int
	Height      int
	Orientation int // 1..8 из EXIF; 0 — тега нет
}

// Result — что получилось. Размеры здесь ТОЧНЫЕ, а не угаданные: их задали мы
// сами, литералом в командной строке, поэтому декодировать выход ради двух
// чисел, которые уже лежат в переменной, незачем.
type Result struct {
	Data   []byte
	MIME   string
	Width  int
	Height int
}

// Converter — перекодировщик. За интерфейсом ffmpeg; в тестах морды подменяется
// целиком — тот же приём и та же причина, что у asr.Converter.
type Converter interface {
	Convert(ctx context.Context, in []byte) (Result, error)
	// ConvertTo — то же со своим потолком длинной стороны: у аватара она своя
	// (квадрат на странице), и меняться вместе с шириной колонки заметки не
	// должна.
	ConvertTo(ctx context.Context, in []byte, maxSide int) (Result, error)
	// Codec — что умеет эта сборка: "webp", "jpeg" или "" (не умеет ничего).
	// Спрашивается один раз, при поднятии морды.
	Codec() string
}

// Swapped — поворот меняет стороны местами (ориентации 5..8).
func Swapped(orientation int) bool { return orientation >= 5 && orientation <= 8 }

// Fit — во что вписать: размеры ПОСЛЕ поворота, уменьшенные до MaxSide.
//
// Увеличения не бывает никогда: растянутая картинка хуже маленькой, а место
// занимает большее.
func Fit(src Source) (w, h int) { return FitTo(src, MaxSide) }

// FitTo — то же со своим потолком. Нужен аватару: у фото человека своя мера
// (квадрат 100×100 на странице), и она не обязана меняться вместе с шириной
// колонки заметки.
func FitTo(src Source, maxSide int) (w, h int) {
	if maxSide <= 0 {
		maxSide = MaxSide
	}
	w, h = src.Width, src.Height
	if Swapped(src.Orientation) {
		w, h = h, w
	}
	if w <= 0 || h <= 0 {
		return 0, 0
	}
	long := w
	if h > long {
		long = h
	}
	if long <= maxSide {
		return w, h
	}
	// Считаем от длинной стороны, а не по двум независимым отношениям: так
	// пропорция сохраняется точно, а длинная сторона выходит ровно MaxSide.
	if w >= h {
		h = h * maxSide / w
		w = maxSide
	} else {
		w = w * maxSide / h
		h = maxSide
	}
	if w < 1 {
		w = 1
	}
	if h < 1 {
		h = 1
	}
	return w, h
}
