package platmod

// Промпт классификатора и — важнее — ГРАНИЦА между тем, что решает модель, и
// тем, что решаем мы.
//
// Модель отвечает на один вопрос: «попадает ли этот текст в одну из перечисленных
// категорий и уверена ли ты». Что делать с ответом — скрыть, позвать человека
// или ничего — решает код (platform.AutoHideable). Так сделано потому, что
// промпт это текст, который однажды поправят между делом, а право машины убрать
// чужие слова из разговора обязано меняться правкой, которую видно в diff.
//
// Второе правило, ради которого всё и написано так осторожно: ССОРА ЗДЕСЬ
// ЖАНР. Раздел «Заметки» тринадцать лет живёт на перепалках, колкостях и
// переходах на личности; модель, настроенная на «токсичность», выкосила бы саму
// площадку и первыми — самых заметных её людей. Поэтому в промпте не список
// «что такое хорошо», а закрытый перечень, и к каждому пункту приписано, чем он
// НЕ является.

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"strings"

	"lovegw/internal/platform"
)

// maxBodyRunes — сколько текста показываем модели. Заметки бывают на двадцать
// тысяч знаков, а решение про спам или чужой телефон принимается по первым
// строкам; платить за остальное незачем. Обрезка честно отмечается в тексте,
// чтобы модель не приняла обрыв за оборванную мысль автора.
const maxBodyRunes = 1500

// systemPrompt — правила, по которым выносится мнение.
//
// Контекста разговора модели НЕ дают, и это осознанно: закрытый перечень —
// про сам текст (реклама, чужой телефон, угроза, порнография), а не про то,
// уместен ли он в этой ветке. Уместность — вопрос вкуса, а вкус мы не судим.
const systemPrompt = `Ты — фильтр публикаций на площадке «Заметки»: это переехавшее сообщество
русскоязычного сайта знакомств, живущее с 2004 года. Люди здесь ссорятся,
язвят, переходят на личности и обсуждают личную жизнь — это НОРМА раздела и
НЕ повод для отметки.

Твоя работа — заметить ровно те публикации, которые попадают в закрытый список
ниже. Ничего сверх него ты не оцениваешь.

Список категорий:
- spam — реклама, продажа, рассылка, зазывание на сторонние сайты и в каналы.
  НЕ спам: упоминание фильма, книги, магазина или заведения в разговоре.
- pii — контакты и данные ТРЕТЬЕГО лица без его ведома: телефон, адрес, место
  работы, номер машины, ссылка на чужую страницу с намерением навредить.
  НЕ pii: свои собственные данные, имя или ник участника разговора.
- threat — угроза насилием, расправой, «найду и изобью», призыв к нападению.
  НЕ threat: брань, оскорбление, «да пошёл ты», злая шутка, угроза пожаловаться.
- drugs — продажа, поиск, реклама наркотиков, инструкция по изготовлению.
  НЕ drugs: рассказ о чьём-то пьянстве, осуждение, разговор о лечении.
- suicide — подталкивание к самоубийству, инструкция, «сделай это».
  НЕ suicide: рассказ о собственном отчаянии, разговор о чужой смерти, чёрный юмор.
- extremism — призывы к насилию по признаку национальности, религии, пола;
  оправдание терроризма; пропаганда запрещённых организаций.
  НЕ extremism: резкое мнение о политике, стране, начальстве или соседях.
- porn — порнографическое описание или ссылка на порнографию.
  НЕ porn: разговор о сексе, флирт, откровенность о своей личной жизни.
- other — есть что-то, чего нет в списке, но человеку стоит взглянуть.
  Ставь редко: это очередь живого модератора, а не корзина сомнений.
- clean — ничего из перечисленного. Это ОБЫЧНЫЙ ответ; ссора, грубость,
  бессмыслица, бессвязный набор слов и обида на весь свет — всё это clean.

Поле certain ставь true только если нарушение видно прямо в тексте и ты
процитируешь его дословно. Сомневаешься — certain=false, решит человек.

quote — дословный кусок исходного текста (до 200 знаков), на котором основано
решение. Для clean оставляй пустым. Ничего не сочиняй: если процитировать
нечего, это clean.

reason — одна короткая фраза по-русски, которую увидит автор публикации.`

// verdictSchema — форма ответа. Structured outputs, поэтому разбирать свободный
// текст не приходится, а «n» связывает ответ с номером в пачке.
func verdictSchema() map[string]any {
	cats := append(platform.AutoCategories(), catClean)
	return map[string]any{
		"type":                 "object",
		"additionalProperties": false,
		"required":             []string{"items"},
		"properties": map[string]any{
			"items": map[string]any{
				"type": "array",
				"items": map[string]any{
					"type":                 "object",
					"additionalProperties": false,
					"required":             []string{"n", "category", "certain", "quote", "reason"},
					"properties": map[string]any{
						"n":        map[string]any{"type": "integer"},
						"category": map[string]any{"type": "string", "enum": cats},
						"certain":  map[string]any{"type": "boolean"},
						"quote":    map[string]any{"type": "string"},
						"reason":   map[string]any{"type": "string"},
					},
				},
			},
		},
	}
}

// catClean — ответ «ничего из списка». Отдельным значением, а не пустой
// строкой: пустая строка в enum читается как забытое поле.
const catClean = "clean"

// answer — то, что вернула модель.
type answer struct {
	Items []answerItem `json:"items"`
}

type answerItem struct {
	N        int    `json:"n"`
	Category string `json:"category"`
	Certain  bool   `json:"certain"`
	Quote    string `json:"quote"`
	Reason   string `json:"reason"`
}

// buildPrompt собирает пачку. Нумерация с единицы — так модель реже путает
// порядок, чем с нуля.
func buildPrompt(items []platform.Pending) string {
	var b strings.Builder
	b.WriteString("Оцени каждую публикацию отдельно. Верни по одному ответу на каждый номер.\n")
	for i, it := range items {
		fmt.Fprintf(&b, "\n=== %d ===\n%s\n", i+1, trimBody(it.Body))
	}
	return b.String()
}

func trimBody(s string) string {
	r := []rune(strings.TrimSpace(s))
	if len(r) <= maxBodyRunes {
		return string(r)
	}
	return string(r[:maxBodyRunes]) + "\n[текст обрезан для проверки]"
}

// promptSHA — отпечаток правил, по которым вынесено мнение. Кладётся в карточку
// проверки: без него решение невоспроизводимо — через месяц не понять, тот же
// это был промпт или уже другой.
var promptSHA = func() []byte {
	schema, _ := json.Marshal(verdictSchema()) //nolint:errcheck // схема наша, сериализуется всегда
	sum := sha256.Sum256(append([]byte(systemPrompt), schema...))
	return sum[:]
}()

// decide переводит ответ модели в вердикт площадки.
//
// ВСЯ политика — здесь, и она нарочно скупа:
//   - категории нет в закрытом списке (модель придумала своё) → человеку;
//   - категория из списка «гасим сами» и модель уверена → скрыть;
//   - всё остальное, кроме чистого → человеку.
//
// «Не уверена» никогда не даёт скрытия. Это и есть та цена, которую платит
// автомат за право работать без надзора.
func decide(a answerItem) platform.VerdictRecord {
	rec := platform.VerdictRecord{
		Category: a.Category,
		Reason:   strings.TrimSpace(a.Reason),
		Quote:    strings.TrimSpace(a.Quote),
	}
	switch {
	case a.Category == catClean:
		rec.Verdict, rec.Category, rec.Quote, rec.Reason = platform.VerdictClean, "", "", ""
	case !platform.KnownCategory(a.Category):
		// Модель ответила чем-то своим. Схема такого не пропускает, но
		// полагаться на это нельзя: незнакомая категория — это ровно тот
		// случай, когда решать должен человек.
		rec.Verdict, rec.Category = platform.VerdictReview, platform.CatOther
	case platform.AutoHideable(a.Category) && a.Certain && rec.Quote != "":
		rec.Verdict = platform.VerdictHidden
	default:
		rec.Verdict = platform.VerdictReview
	}
	return rec
}
