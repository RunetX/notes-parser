package platmod

import "testing"

// Мат опознаётся, в том числе замаскированный: пункт 11 правил запрещает его
// «в любом виде, включая завуалированные — маскировку буквами, цифрами».
func TestFindMatCatchesMasked(t *testing.T) {
	for _, tc := range []struct{ name, text string }{
		{"прямой", "Нахуя банить за флуд"},
		{"начало слова", "ебал я эти правила"},
		{"с приставкой", "да заебали уже"},
		{"пизд", "полная пиздец история"},
		{"бля отдельным словом", "ну бля вы даёте"},
		{"удвоение букв", "ну ты и ХУЙЙЛО"},
		{"латиница-двойник", "ну ты и xyйло"},
		{"дефисы внутри слова", "х-у-й им всем"},
		{"символ вместо буквы", "иди на х*й"},
		{"звёздочки внутри", "п*здец какой-то"},
		{"заглавные", "ЗАЕБИСЬ просто"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := FindMat(tc.text); got == "" {
				t.Errorf("мат не найден в %q", tc.text)
			}
		})
	}
}

// Ложные срабатывания — то, ради чего этот тест написан. Каждая строка здесь
// живое русское слово, в котором корень лежит внутри: ошибка тут означает
// помеченную ни за что реплику, а у площадки таких слов миллионы.
func TestFindMatLeavesInnocentAlone(t *testing.T) {
	for _, tc := range []struct{ name, text string }{
		{"себе", "он оставил это себе"},
		{"себя", "веди себя прилично"},
		{"требовать", "не надо требовать невозможного"},
		{"хлебать", "будешь хлебать эту кашу"},
		{"победа", "победа была за нами"},
		{"потребность", "это базовая потребность"},
		{"перебор", "по-моему это перебор"},
		{"добежать", "успел добежать до угла"},
		{"сразу", "сразу видно человека"},
		{"сражение", "целое сражение развернулось"},
		{"сработать", "должно сработать"},
		{"сравнить", "если сравнить с прошлым годом"},
		{"срам", "один срам да и только"},
		// Вульгаризмы — грубость, а не мат: ссора здесь жанр раздела, и
		// автоскрытие за «хрен» выкосило бы саму площадку (замер 23.08.2026).
		{"хрен", "хрен вас разберешь"},
		{"херня", "психологическая херня какая-то"},
		{"жопа", "вжопувашнгс"},
		{"пересрались", "пока я спала опять все пересрались"},
		{"сраца", "сраца на нгсе выходит интереснее"},
		{"мудрость", "мудрость приходит с годами"},
		{"скука", "какая же скука"},
		{"страна", "страна большая"},
		{"красный", "красный шарф"},
		{"пиджак", "надел пиджак"},
		{"похудеть", "хочу похудеть к лету"},
		{"два слова рядом", "мыс раком выдаётся в море"},
		{"убегать", "хватит убегать от разговора"},
		{"уехал", "он уехал вчера"},
		{"небо", "небо затянуло"},
		{"особый", "особый случай"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := FindMat(tc.text); got != "" {
				t.Errorf("ложное срабатывание на %q: поймано %q", tc.text, got)
			}
		})
	}
}

// Цитата — слово ОРИГИНАЛА: модератору в очереди нужно видеть написанное
// автором, а не то, что из него сделал детектор.
func TestFindMatQuotesOriginal(t *testing.T) {
	got := FindMat("Ну наХУЙня, бывает")
	if got != "наХУЙня" {
		t.Errorf("цитата %q, ожидалось %q", got, "наХУЙня")
	}
}

// Склейка соседних слов — та ошибка, ради которой разбор пословный.
func TestNormalizeKeepsWordsApart(t *testing.T) {
	if got := normalizeWord("мыс"); got != "мыс" {
		t.Errorf("нормализация слова: %q", got)
	}
	if got := normalizeWord("разосрРала"); got != "разосрала" {
		t.Errorf("схлопывание удвоения: %q", got)
	}
	if got := normalizeWord("х-у-й"); got != "хуй" {
		t.Errorf("маскировка дефисами: %q", got)
	}
}
