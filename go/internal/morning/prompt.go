// buildPunchPrompt — что видит редактор: свой черновик и тот же список поводов.
// Список нужен не для новых фактов (их брать запрещено), а чтобы номера в used
// остались теми же: заметку после правки проверяет ТОТ ЖЕ валидатор.
func buildPunchPrompt(text string, in promptInput) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## Сегодня\n\n%s, %s.\n\n", capitalize(in.Weekday), in.DateWord)
	b.WriteString("## Черновик\n\n" + text + "\n\n")
	if len(in.Facts) > 0 {
		b.WriteString("## Поводы дня (номера для used)\n\n")
		for i, f := range in.Facts {
			b.WriteString(strconv.Itoa(i+1) + ". " + factLine(f) + "\n")
		}
	}
	return b.String()
}
