// retryNote — хвост переспроса. Слепой повтор повторил бы и брак, поэтому
// причина едет в промпт (как у амвона и у редактуры дайджеста).
const retryNote = `

## Переспрос

Предыдущий ответ забракован: %v. Напиши заметку заново — с учётом этой причины.`

// promptInput — всё волатильное, что видит модель.
type promptInput struct {
	Nick     string
	Weekday  string
	DateWord string // «24 августа 2026 года»
	Facts    []holidays.Occasion
	History  []string // свои заметки прошлых дней: «так уже было»
	MinRunes int
	MaxRunes int
	MaxLines int
}

// weekdays / months — по-русски и в том падеже, в котором это пойдёт в текст.
var weekdays = [...]string{
	"воскресенье", "понедельник", "вторник", "среда",
	"четверг", "пятница", "суббота",
}

var months = [...]string{
	"января", "февраля", "марта", "апреля", "мая", "июня",
	"июля", "августа", "сентября", "октября", "ноября", "декабря",
}

// buildPrompt собирает промпт от стабильного к волатильному: у Claude
// кэшируется префикс, и держать меняющееся (поводы дня) в конце дешевле.
func buildPrompt(in promptInput) string {
	var b strings.Builder
	if in.Nick != "" {
		fmt.Fprintf(&b, "## Кто пишет\n\nЗаметка выходит от имени участника по имени %s.\n\n", in.Nick)
	}
	fmt.Fprintf(&b, "## Размер\n\nОт %d до %d знаков, не больше %d строк.\n\n",
		in.MinRunes, in.MaxRunes, in.MaxLines)
	if len(in.History) > 0 {
		b.WriteString("## Так уже было\n\nТвои заметки прошлых дней. Не повторяйся ни шуткой, ни заходом:\n\n")
		for _, h := range in.History {
			b.WriteString("- " + collapse(h) + "\n")
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "## Сегодня\n\n%s, %s.\n\n", capitalize(in.Weekday), in.DateWord)
	b.WriteString("## Поводы дня\n\n")
	if len(in.Facts) == 0 {
		b.WriteString("Сегодня поводов нет: календари ничего не дали. Напиши просто" +
			" приветствие про этот день недели и время года и закончи вопросом.\n")
		return b.String()
	}
	for i, f := range in.Facts {
		b.WriteString(strconv.Itoa(i+1) + ". " + factLine(f) + "\n")
	}
	return b.String()
}

// factLine — как повод выглядит в промпте. Число назвавших календарей стоит
// рядом намеренно: это подсказка, чему верить больше, и модель ей пользуется
// ровно так же, как пользовались бы мы.
func factLine(f holidays.Occasion) string {
	var b strings.Builder
	switch f.Kind {
	case holidays.KindHistory:
		fmt.Fprintf(&b, "[событие %d года] %s", f.Year, f.Title)
	case holidays.KindFolk:
		b.WriteString("[народный календарь] " + f.Title)
	case holidays.KindName:
		b.WriteString("[именины] " + f.Title)
	default:
		b.WriteString("[праздник] " + f.Title)
	}
	if len(f.Sources) > 1 {
		fmt.Fprintf(&b, " (подтверждают %d календаря)", len(f.Sources))
	}
	return b.String()
}

// collapse — своя прошлая заметка одной строкой: модели нужен её ЗАХОД, а не
// текст целиком.
func collapse(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	r := []rune(s)
	if len(r) > 160 {
		return string(r[:160]) + "…"
	}
	return s
}

func capitalize(s string) string {
	r := []rune(s)
	if len(r) == 0 {
		return s
	}
	return strings.ToUpper(string(r[0])) + string(r[1:])
}

