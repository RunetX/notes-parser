package sitetext_test

import (
	"strings"
	"testing"

	"lovegw/internal/sitetext"
)

// Сайт не возвращает текст побайтово: схлопывает пробелы, делает nl2br,
// подменяет эмодзи картинками. Отпечаток обязан пережить всё это — иначе своя
// реплика не опознается и встанет в тред вторым экземпляром.
func TestFingerprintSurvivesWhatTheSiteDoesToText(t *testing.T) {
	ours := "Полку  прибил, а ровно ли — иди смотри.\n\nСам вчера чинил."
	theirs := "Полку прибил, а ровно ли — иди смотри. Сам вчера чинил."
	if !sitetext.SameText(ours, theirs) {
		t.Fatalf("отпечатки разошлись:\n%q\n%q",
			sitetext.Fingerprint(ours), sitetext.Fingerprint(theirs))
	}
}

// Границу метода надо знать: невод ловит БУКВЫ И ЦИФРЫ, значит две реплики,
// различающиеся одной пунктуацией, для него одинаковы. Это осознанный размен —
// ложное совпадение стоит одной непринесённой реплики, а ложное расхождение
// дубля в чужом треде.
func TestFingerprintIgnoresPunctuation(t *testing.T) {
	if !sitetext.SameText("да, конечно", "Да! Конечно?") {
		t.Fatal("пунктуация не должна разводить отпечатки")
	}
	if sitetext.SameText("да, конечно", "да, конечно же") {
		t.Fatal("лишнее слово обязано разводить: длины разные, а до порога начала не дотянуть")
	}
}

// Пустое не совпадает ни с чем: у реплики из одних смайлов сайт не оставит ни
// буквы, и «совпало с пустым» опознало бы своей любую такую реплику подряд.
func TestEmptyFingerprintMatchesNothing(t *testing.T) {
	if sitetext.SameText(":::popcorn:::", "!!!") {
		t.Fatal("две пустышки не должны считаться одним текстом")
	}
	if sitetext.Fingerprint("... )))") != "" {
		t.Fatal("из знаков препинания отпечатка не выходит")
	}
}

// Лента отдаёт длинную заметку НАЧАЛОМ, и допуск на это даёт ОТДЕЛЬНОЕ правило:
// у реплики такого обрыва не бывает, а у заметки бывает всегда.
func TestFeedExcerptIsRecognisedForNotesOnly(t *testing.T) {
	long := strings.Repeat("длинная заметка про огурцы и рассаду 1234 ", 6)
	cut := long[:220] + "…"
	if !sitetext.SameStart(long, cut) {
		t.Error("срез ленты обязан опознаваться у заметки")
	}
	if sitetext.SameText(long, cut) {
		t.Error("у реплики обрыва не бывает — допуск ей не положен")
	}
	if sitetext.SameStart("да", "да, и вот почему всё вышло именно так, а не иначе") {
		t.Error("короткий текст не смеет опознать себя в длинном")
	}
}

// СЛУЧАЙ ИЗ БОЯ (01.09.2026, заметка 313146): сайт подменил `:D` эмодзи, и
// первая редакция сверки — строка целиком плюс общее начало — реплику не
// опознала. В треде и в обоих каналах вышло по дублю.
func TestSiteSubstitutesEmoticonWithEmoji(t *testing.T) {
	ours := `В профиле появилась опция "Отправлять на НГС" :D`
	theirs := `В профиле появилась опция "Отправлять на НГС" 😃`
	if !sitetext.SameText(ours, theirs) {
		t.Fatal("подстановка смайлика буквами развела тексты — ровно этот дубль и вышел в бою")
	}
	// Живой эмодзи ломать ничего и не должен был: он выпадает с обеих сторон
	// одинаково, и соседняя реплика того же прогона опозналась верно.
	same := "Молодцы сибиряки и сибирячки, надо же как-то согреваться 💪"
	if !sitetext.SameText(same, same) {
		t.Fatal("реплика с живым эмодзи не опозналась сама с собой")
	}
}

// Допуск даётся только там, где слов достаточно. У короткой реплики разница в
// одном выброшенном слове — это разные слова, а не артефакт сайта.
func TestShortRepliesCompareWholly(t *testing.T) {
	if sitetext.SameText("я не пойду", "я пойду") {
		t.Error("отрицание потеряно: реплики склеены")
	}
	if !sitetext.SameText("я не пойду", "я  не  пойду!") {
		t.Error("та же реплика с другими пробелами не опозналась")
	}
	if sitetext.SameText("спасибо", "пожалуйста") {
		t.Error("разные короткие реплики склеены")
	}
}

// Огрызки подстановки выпадают, а предложение разницы — нет: иначе сверка
// съела бы соседнюю реплику того же человека в том же треде.
func TestSentenceOfDifferenceIsNotTolerated(t *testing.T) {
	a := "Поехал на дачу копать картошку, вернусь поздно вечером"
	b := "Поехал на дачу копать картошку, вернусь поздно вечером, а завтра снова туда же и опять с лопатой"
	if sitetext.SameText(a, b) {
		t.Error("реплика, дописанная целым предложением, принята за ту же")
	}
}

// Граница правила для заметок названа вслух: началом опознаётся и продолжение,
// а не только срез. Обе такие заметки наши, обе ушли на сайт, и перепутанные
// строки очереди дают тот же итог — оба эха погашены.
func TestNoteRuleAcceptsContinuationToo(t *testing.T) {
	a := "Поехал на дачу копать картошку, вернусь поздно вечером"
	b := a + ", а завтра снова туда же и опять с лопатой наперевес"
	if !sitetext.SameStart(b, a) {
		t.Error("правило заметки обязано принимать начало — на этом держится срез ленты")
	}
}
