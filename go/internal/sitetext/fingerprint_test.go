package sitetext_test

import (
	"strings"
	"testing"

	"lovegw/internal/sitetext"
)

// Сайт не возвращает текст побайтово: схлопывает пробелы, делает nl2br,
// подменяет эмодзи картинками. Отпечаток обязан пережить всё это — иначе своя
// реплика не опознается и встанет в тред вторым экземпляром.
func TestFingerprintSurvivesWhatTheSiteDoesToText(t *testing.T) {
	ours := "Полку  прибил, а ровно ли — иди смотри.\n\nСам вчера чинил."
	theirs := "Полку прибил, а ровно ли — иди смотри. Сам вчера чинил."
	if !sitetext.SameText(ours, theirs) {
		t.Fatalf("отпечатки разошлись:\n%q\n%q",
			sitetext.Fingerprint(ours), sitetext.Fingerprint(theirs))
	}
}

// Границу метода надо знать: невод ловит БУКВЫ И ЦИФРЫ, значит две реплики,
// различающиеся одной пунктуацией, для него одинаковы. Это осознанный размен —
// ложное совпадение стоит одной непринесённой реплики, а ложное расхождение
// дубля в чужом треде.
func TestFingerprintIgnoresPunctuation(t *testing.T) {
	if !sitetext.SameText("да, конечно", "Да! Конечно?") {
		t.Fatal("пунктуация не должна разводить отпечатки")
	}
	if sitetext.SameText("да, конечно", "да, конечно же") {
		t.Fatal("лишнее слово обязано разводить: длины разные, а до порога начала не дотянуть")
	}
}

// Пустое не совпадает ни с чем: у реплики из одних смайлов сайт не оставит ни
// буквы, и «совпало с пустым» опознало бы своей любую такую реплику подряд.
func TestEmptyFingerprintMatchesNothing(t *testing.T) {
	if sitetext.SameText(":::popcorn:::", "!!!") {
		t.Fatal("две пустышки не должны считаться одним текстом")
	}
	if sitetext.Fingerprint("... )))") != "" {
		t.Fatal("из знаков препинания отпечатка не выходит")
	}
}

// Лента отдаёт длинную заметку НАЧАЛОМ, поэтому сверяется общее начало. Но не
// любой длины: «да» не смеет опознать себя в «да, и вот почему…».
func TestPrefixMatchNeedsEnoughLetters(t *testing.T) {
	long := strings.Repeat("буквы и цифры 1234 ", 20)
	if !sitetext.SameText(long, long[:220]+"…") {
		t.Fatal("срез ленты обязан опознаваться началом")
	}
	if sitetext.SameText("да", "да, и вот почему всё вышло именно так, а не иначе") {
		t.Fatal("короткое начало опознавать нельзя")
	}
}
