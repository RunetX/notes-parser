// buildPunchupPrompt — что редактор видит: заметку, черновик и его форму.
func buildPunchupPrompt(note, draft, form string, maxRunes int) string {
	var b strings.Builder
	b.WriteString("## Заметка\n\n" + note + "\n\n")
	fmt.Fprintf(&b, "## Черновик реплики (форма: %s)\n\n%s\n\n", form, draft)
	fmt.Fprintf(&b, "## Размер\n\nПотолок %d знаков. Короче черновика - хорошо, "+
		"длиннее - только если добавилась добивка.\n", maxRunes)
	return b.String()
}

