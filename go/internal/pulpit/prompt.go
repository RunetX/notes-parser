// promptInput — всё волатильное одного запроса.
type promptInput struct {
	Note       string   // текст заметки
	AuthorName string   // имя автора ("" — анонимная заметка)
	Anonymous  bool     // заметка анонимная: автор скрыт даже от сайта
	Forms      []string // формы, разрешённые в этот раз
	History    []string // свои последние реплики
	Samples    []string // собственные комментарии владельца — образец манеры
	TargetRune int      // ориентир длины
	MaxRunes   int
	MaxLines   int
	AllowEmoji bool
}

// targetRunes — ориентир длины. Медиана собственных реплик владельца 79 рун, и
// шутка тем более не терпит длины: длинная — это уже рассказ, а в рассказе
// удар приходится ждать.
const targetRunes = 90

// buildQuipPrompt собирает промпт. Порядок частей — от стабильного к
// волатильному: манера, потом своя история, потом сама заметка. Так голова
// запроса не меняется от такта к такту и кэшируется на стороне API.
func buildQuipPrompt(in promptInput) string {
	var b strings.Builder
	if len(in.Samples) > 0 {
		b.WriteString("## Манера\n\nТак пишет тот, чьим голосом ты говоришь. " +
			"Перенимай длину фразы, пунктуацию и интонацию, но не тему и не повод:\n\n")
		for _, s := range in.Samples {
			fmt.Fprintf(&b, "- %s\n", oneLine(s))
		}
		b.WriteString("\n")
	}
	if len(in.History) > 0 {
		b.WriteString("## Так уже было\n\nТвои последние реплики. Не повторяйся " +
			"ни шуткой, ни поворотом, ни концовкой:\n\n")
		for _, h := range in.History {
			fmt.Fprintf(&b, "- %s\n", oneLine(h))
		}
		b.WriteString("\n")
	}
	b.WriteString("## Форма\n\n" + formsHelp + "\n\n")
	fmt.Fprintf(&b, "В этот раз возьми одну из форм: %s.\n\n", strings.Join(in.Forms, ", "))

	fmt.Fprintf(&b, "## Размер\n\nОриентир — около %d знаков, потолок %d знаков и %d строк. "+
		"Короткая реплика смешнее длинной: лишняя фраза после удара его и гасит.\n\n",
		in.TargetRune, in.MaxRunes, in.MaxLines)
	if !in.AllowEmoji {
		b.WriteString("Эмодзи в этот раз не ставь.\n\n")
	}

	b.WriteString("## Заметка\n\n")
	if in.Anonymous {
		b.WriteString("Автор скрыл имя (анонимная заметка) — по имени к нему не обращайся.\n\n")
	} else if in.AuthorName != "" {
		fmt.Fprintf(&b, "Автор: %s.\n\n", in.AuthorName)
	}
	b.WriteString(in.Note)
	return b.String()
}

