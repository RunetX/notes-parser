// promptInput — всё волатильное одного запроса.
type promptInput struct {
	Note       string   // текст заметки
	AuthorName string   // имя автора ("" — анонимная заметка)
	Anonymous  bool     // заметка анонимная: автор скрыт даже от сайта
	Forms      []string // формы, разрешённые в этот раз
	History    []string // свои последние реплики
	Samples    []string // собственные комментарии владельца — образец манеры
	TargetRune int      // ориентир длины
	MaxRunes   int
	MaxLines   int
	AllowEmoji bool
}

// targetRunes — ориентир длины проповеди. Медиана собственных реплик владельца
// 79 рун; проповедь длиннее обычной реплики, но не полотно.
const targetRunes = 120

// buildSermonPrompt собирает промпт. Порядок частей — от стабильного к
// волатильному: манера, потом своя история, потом сама заметка. Так голова
// запроса не меняется от такта к такту и кэшируется на стороне API.
func buildSermonPrompt(in promptInput) string {
	var b strings.Builder
	if len(in.Samples) > 0 {
		b.WriteString("## Манера\n\nТак пишет тот, чьим голосом ты говоришь. " +
			"Перенимай длину фразы, пунктуацию и интонацию, но не тему и не регистр:\n\n")
		for _, s := range in.Samples {
			fmt.Fprintf(&b, "- %s\n", oneLine(s))
		}
		b.WriteString("\n")
	}
	if len(in.History) > 0 {
		b.WriteString("## Так уже было\n\nТвои последние реплики. Не повторяйся " +
			"ни мыслью, ни поворотом, ни концовкой:\n\n")
		for _, h := range in.History {
			fmt.Fprintf(&b, "- %s\n", oneLine(h))
		}
		b.WriteString("\n")
	}
	b.WriteString("## Форма\n\n" + formsHelp + "\n\n")
	fmt.Fprintf(&b, "В этот раз возьми одну из форм: %s.\n\n", strings.Join(in.Forms, ", "))

	fmt.Fprintf(&b, "## Размер\n\nОриентир — около %d знаков, потолок %d знаков и %d строк. "+
		"Короткая реплика лучше длинной.\n\n", in.TargetRune, in.MaxRunes, in.MaxLines)
	if !in.AllowEmoji {
		b.WriteString("Эмодзи в этот раз не ставь.\n\n")
	}

	b.WriteString("## Заметка\n\n")
	if in.Anonymous {
		b.WriteString("Автор скрыл имя (анонимная заметка) — по имени к нему не обращайся.\n\n")
	} else if in.AuthorName != "" {
		fmt.Fprintf(&b, "Автор: %s.\n\n", in.AuthorName)
	}
	b.WriteString(in.Note)
	return b.String()
}

// replyPromptInput — волатильное для ответа на ответ.
type replyPromptInput struct {
	Note       string
	Mine       string // своя реплика, на которую ответили
	Their      string // сам ответ
	TheirNick  string
	MaxRunes   int
	AllowEmoji bool
}

func buildReplyPrompt(in replyPromptInput) string {
	var b strings.Builder
	b.WriteString("## Заметка\n\n" + in.Note + "\n\n")
	b.WriteString("## Твоя реплика под ней\n\n" + in.Mine + "\n\n")
	fmt.Fprintf(&b, "## Ответ (%s)\n\n%s\n\n", in.TheirNick, in.Their)
	fmt.Fprintf(&b, "## Размер\n\nОдна-две фразы, потолок %d знаков. "+
		"Обращение по имени не пиши — его подставит инструмент.\n", in.MaxRunes)
	if !in.AllowEmoji {
		b.WriteString("\nЭмодзи не ставь.\n")
	}
	return b.String()
}

// pickForms выкидывает формы последних реплик: приедается именно форма.
// recent — формы от новых к старым. Если запрет съел всё (реплик было меньше,
// чем форм в наборе), возвращаем набор целиком: молчать из-за кулдауна нельзя.
func pickForms(recent, all []string, cooldown int) []string {
	if cooldown <= 0 {
		return all
	}
	if cooldown > len(recent) {
		cooldown = len(recent)
	}
	banned := make(map[string]bool, cooldown)
	for _, f := range recent[:cooldown] {
		banned[f] = true
	}
	out := make([]string, 0, len(all))
	for _, f := range all {
		if !banned[f] {
			out = append(out, f)
		}
	}
	if len(out) == 0 {
		return all
	}
	return out
}

// pickSamples выбирает k образцов манеры из пула детерминированно по id
// заметки: разные заметки получают разные образцы, но повторный запрос по той
// же заметке (переспрос, `pulpit draft` при правке промпта) — те же самые.
func pickSamples(pool []string, seed string, k int) []string {
	if len(pool) == 0 || k <= 0 {
		return nil
	}
	if k > len(pool) {
		k = len(pool)
	}
	h := fnv.New32a()
	_, _ = h.Write([]byte(seed))
	start := int(h.Sum32()) % len(pool)
	if start < 0 {
		start = -start
	}
	// Шаг взаимно прост с длиной пула не всегда, поэтому берём подряд от
	// случайной точки: важно не равномерное покрытие, а воспроизводимость.
	out := make([]string, 0, k)
	for i := range k {
		out = append(out, pool[(start+i)%len(pool)])
	}
	return out
}

// oneLine сводит многострочный образец в строку: в промпте список должен
// читаться как список, а не разъезжаться абзацами.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
