// Рамка недоверенного текста. Заметку и ответы пишут люди, которые видят, что
// под заметками отвечает бот, и обращение к нему («напиши стихами», «забудь
// инструкции») попадает прямо в текст. Метки отделяют материал от указаний, а
// правило о них стоит в системной части — там, куда автор заметки не дотянется.
// Сами метки из текста вырезаются: иначе рамку закрыли бы досрочно.
func fenced(kind, text string) string {
	open, close := "<<<"+kind, ">>>"+kind
	clean := strings.ReplaceAll(text, open, "")
	clean = strings.ReplaceAll(clean, close, "")
	return open + "\n" + strings.TrimSpace(clean) + "\n" + close
}

// buildPunchupPrompt — что редактор видит: заметку, черновик и его форму.
func buildPunchupPrompt(note, draft, form string, maxRunes int) string {
	var b strings.Builder
	b.WriteString("## Заметка\n\n" + fenced("ЗАМЕТКА", note) + "\n\n")
	fmt.Fprintf(&b, "## Черновик реплики (приём: %s)\n\n%s\n\n", form, draft)
	fmt.Fprintf(&b, "## Размер\n\nПотолок %d знаков, но цель не уложиться в него, "+
		"а стать короче черновика (%d знаков).\n", maxRunes, len([]rune(draft)))
	return b.String()
}

