// pickForms выкидывает формы последних реплик: приедается именно форма.
// recent — формы от новых к старым. Если запрет съел всё (реплик было меньше,
// чем форм в наборе), возвращаем набор целиком: молчать из-за кулдауна нельзя.
func pickForms(recent, all []string, cooldown int) []string {
	if cooldown <= 0 {
		return all
	}
	if cooldown > len(recent) {
		cooldown = len(recent)
	}
	banned := make(map[string]bool, cooldown)
	for _, f := range recent[:cooldown] {
		banned[formKey(f)] = true
	}
	out := make([]string, 0, len(all))
	for _, f := range all {
		if !banned[formKey(f)] {
			out = append(out, f)
		}
	}
	if len(out) == 0 {
		return all
	}
	return out
}

// formKey — форма для сравнения: регистр и «ё» не в счёт. Модель возвращает
// название формы своей строкой, и «ложная серьезность» вместо «ложной
// серьёзности» стоила бы переспроса — то есть тех самых 10–30 секунд, ради
// которых вся спешка.
func formKey(form string) string {
	return strings.ReplaceAll(strings.ToLower(strings.TrimSpace(form)), "ё", "е")
}

// pickSamples выбирает k образцов манеры из пула детерминированно по id
// заметки: разные заметки получают разные образцы, но повторный запрос по той
// же заметке (переспрос, `pulpit draft` при правке промпта) — те же самые.
func pickSamples(pool []string, seed string, k int) []string {
	if len(pool) == 0 || k <= 0 {
		return nil
	}
	if k > len(pool) {
		k = len(pool)
	}
	h := fnv.New32a()
	_, _ = h.Write([]byte(seed))
	start := int(h.Sum32()) % len(pool)
	if start < 0 {
		start = -start
	}
	// Шаг взаимно прост с длиной пула не всегда, поэтому берём подряд от
	// случайной точки: важно не равномерное покрытие, а воспроизводимость.
	out := make([]string, 0, k)
	for i := range k {
		out = append(out, pool[(start+i)%len(pool)])
	}
	return out
}

// minFunnyPool — с какого размера отбор смешных образцов имеет смысл. Меньше —
// берём пул целиком: четыре образца из десятка это уже не выбор манеры, а
// заучивание конкретных шуток.
const minFunnyPool = 20

// preferFunny оставляет в пуле те свои комментарии, где владелец смеялся.
// Отметка смеха на этой площадке — незакрытая скобка (см. память
// punctuation-fingerprint-sweep), и считается она именно так: закрывающих
// больше, чем открывающих. Обычные скобки «(вот так)» баланс не рушат, а
// «смешно)» и «))» — рушат.
func preferFunny(pool []string) []string {
	funny := make([]string, 0, len(pool))
	for _, s := range pool {
		if strings.Count(s, ")") > strings.Count(s, "(") {
			funny = append(funny, s)
		}
	}
	if len(funny) < minFunnyPool {
		return pool
	}
	return funny
}

// oneLine сводит многострочный образец в строку: в промпте список должен
// читаться как список, а не разъезжаться абзацами.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
