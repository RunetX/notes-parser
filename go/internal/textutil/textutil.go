// Пакет textutil — обрезка и нормализация пользовательского текста для
// показа: подписи кнопок, выдержки в уведомлениях, однострочные упоминания
// заметок. Листовой (ничего из проекта не импортирует), поэтому доступен и
// транспортам, и диалоговому ядру, и CLI.
//
// Функций обрезки три, и это не дубли: у них разные контракты по итоговой
// длине, и подменять одну другой нельзя.
package textutil

import "strings"

// OneLine сводит текст в одну строку: в заметке бывают абзацы, а упоминают её
// одной строкой.
func OneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// Truncate режет по границе руны, добавляя многоточие. Итог — до limit+1 рун:
// многоточие сверх лимита. Годится там, где лимит приблизительный (выдержка
// текста в уведомлении).
func Truncate(s string, limit int) string {
	r := []rune(s)
	if len(r) <= limit {
		return s
	}
	return string(r[:limit]) + "…"
}

// TruncateTrim — то же, но без висящего пробела перед многоточием. Отдельная
// функция, а не флаг: у обрезки по границе слова другой типичный вызывающий
// (композиция сообщений), и лишний параметр читался бы хуже.
func TruncateTrim(s string, limit int) string {
	r := []rune(s)
	if len(r) <= limit {
		return s
	}
	return strings.TrimSpace(string(r[:limit])) + "…"
}

// Fit укорачивает так, чтобы итог был НЕ ДЛИННЕЕ limit рун вместе с
// многоточием. Нужен там, где предел жёсткий, — подписи кнопок мессенджера.
func Fit(s string, limit int) string {
	r := []rune(s)
	if len(r) <= limit {
		return s
	}
	if limit <= 1 {
		return "…"
	}
	return string(r[:limit-1]) + "…"
}
