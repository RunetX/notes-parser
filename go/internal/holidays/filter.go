package holidays

// Что годится в «доброе утро», а что нет.
//
// Список ЗАКРЫТЫЙ и живёт В КОДЕ, а не в промпте — по тому же доводу, по
// которому в ядре площадки закрыт список категорий модерации
// (`platform.AutoHideable`): промпт однажды поправят между делом, а правило
// «о чём мы не шутим утром» обязано меняться правкой, которую видно в diff.
//
// Повод для проверки дал первый же разобранный день, 24.08.2026: у обоих
// календарей первым праздником идёт День независимости Украины, а Википедия
// в тот же день предлагает Варфоломеевскую ночь и падение Западной Римской
// империи. Ни одно из этого не годится в утреннее приветствие на сайте
// знакомств — и не потому, что это плохие даты, а потому, что разговор о них
// начинается не со слов «доброе утро».
//
// Модель — второй рубеж, а не первый: ей тоже сказано не брать беду, но
// решение, что показывать, принимает код.

import "strings"

// stopRoots — корни, по которым повод отсеивается. Корень, а не слово: русский
// склоняет, и «войны», «войне», «войну» это одно и то же. Подстрокой, а не
// словом целиком — по той же причине.
//
// Список правится ЗАМЕРОМ, а не вкусом, в обе стороны. Из него исключены
// «оруж» (убил бы День оружейника), «пожар» (День пожарной охраны) и «авари»
// (День спасателя) — все три светлые профессиональные даты. И наоборот,
// первый же прогон по настоящему дню (24.08.2026) показал промахи, которых не
// придумать за столом: «погибли» мимо корня «погибш», «сожгли Белый дом»,
// «сгорел парусник», «отравился поэт». Корни добавлены по этим находкам.
//
// Второй прогон, 26.08.2026, дал вторую партию — и все четыре промаха были
// «почти пойманы»: «террористический акт» мимо корня «теракт», «сжег Москву»
// мимо «сожг», «заложил бомбу» мимо «бомбардировк», а самоубийство управделами
// ЦК не описывалось ни одним словом из списка вовсе. Отсюда правило: корень
// брать КОРОЧЕ того слова, на котором его заметили («бомб», а не
// «бомбардировк»), — русский приставками и суффиксами уводит дальше, чем
// кажется за столом.
//
// Список не претендует на полноту: он гарантирует, что в утро не попадёт
// НАЗВАННАЯ здесь беда, а не что всякая беда названа. Второй рубеж — модель,
// которой сказано не брать мрачное; третий — человек, читающий стенд.
var stopRoots = []string{
	// Скорбь и утраты.
	"траур", "скорб", "жертв", "погиб", "гибел", "отрави",
	"геноцид", "холокост", "репресс", "депортац", "концлагер", "узник",
	// Война и насилие.
	"войн", "вооружённ", "вооруженн", "битв", "сражени", "бомб", "террорист",
	"блокад", "капитуляц", "оккупац", "теракт", "казн", "расстрел",
	"резня", "резни", "покушени", "убийств", "мятеж", "восстани",
	"расправ", "погром", "взяти", "взял", "нашестви", "штурм", "разгром",
	// Беда без войны.
	"катастроф", "трагед", "эпидеми", "крушени", "извержени", "уничтож",
	"сожг", "сожж", "сжег", "сжёг", "сгоре", "ураган", "разруш", "ущерб",
	// Смерть человека, названная любым словом, и памятные даты о ней.
	"самоубий", "суицид", "выбросил", "увековеч", "путч",
	// Оружие и взрывы. Корень «ядерн» закрывает и «термоядерное»,
	// а «оруж» в списке нет намеренно (см. выше про День оружейника).
	"взрыв", "ядерн", "десант", "диверс",
	// Государственная политика чужих стран доезжает и без метки страны.
	"независимост", "суверенитет", "аннекс",
}

// Reject возвращает причину, по которой повод не годится ("" — годится).
// Причину, а не bool: её печатает стенд `morning sources`, и по ней видно,
// какое правило сработало, — иначе список правится вслепую.
func Reject(o Occasion) string {
	switch o.Scope {
	case ScopeForeign:
		return "чужой государственный праздник"
	case ScopeReligious:
		return "церковная дата"
	}
	lower := strings.ToLower(o.Title)
	for _, root := range stopRoots {
		if strings.Contains(lower, root) {
			return "стоп-слово «" + root + "»"
		}
	}
	return ""
}

// Filter оставляет только годные поводы, сохраняя порядок.
func Filter(list []Occasion) []Occasion {
	out := make([]Occasion, 0, len(list))
	for _, o := range list {
		if Reject(o) == "" {
			out = append(out, o)
		}
	}
	return out
}
