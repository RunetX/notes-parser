package narodsim

// Кубик харнесс не заводит свой, а берёт ЯДЕРНЫЙ (narod/decide.go).
//
// Псевдонимами, а не обёртками, и это существенно: калибровка меряет ровно ту
// формулу, которая потом работает в бою. Разойдись они — и весь смысл замера
// исчез бы, потому что мерили бы мы не то, что играет; а так расхождение
// невозможно физически, тип один и тот же.
//
// Здесь же кубик и вырос — до 29.08.2026 он лежал в этом пакете. Переехал он
// вместе со службой народа: боевой оркестратор не вправе импортировать реплей
// (тот тянет за собой архив), а формула нужна обоим.

import "lovegw/internal/narod"

type (
	// DecisionPoint — момент, когда житель мог бы заговорить.
	DecisionPoint = narod.DecisionPoint
	// Decision — что он решил.
	Decision = narod.Decision
	// Decider — кто это решает.
	Decider = narod.Decider
	// CardDecider — решение по карточке.
	CardDecider = narod.CardDecider
)

// quantileAt — восстановление квантиля по четырём числам замера. Им же берётся
// длина реплики (speaker.go): у задержки и у длины содержание в хвосте, а не в
// середине, и восстанавливать их обязано одно и то же.
func quantileAt(d narod.Dist, u float64) float64 { return narod.QuantileAt(d, u) }

// noteSalt — соль заметки в ключе монетки; вакууму она нужна, чтобы считать
// СВОИ ключи событий тем же способом, что и кубик.
const noteSalt = narod.NoteSalt
