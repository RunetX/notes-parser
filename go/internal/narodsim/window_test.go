package narodsim

// ОКНО НАКАЛА — одно на три мира.
//
// Величина эта живёт в трёх местах сразу: в ЗАМЕРЕ (archive снимает кривую
// отклика по накалу за десять минут), в БОЮ (narod.Service считает накал по
// треду тем же окном) и в КАЛИБРОВКЕ (этот пакет). Разойдись они — множитель
// прикладывался бы к накалу, которого в замере не было, и заметить это было бы
// нечем: кубик молча стал бы звать не тех.
//
// Своей копии числа здесь поэтому нет вовсе, а стережёт равенство ЭТОТ тест —
// единственное место, которое видит и архив, и ядро народа (ядру архив
// импортировать нельзя, deps_test). Тот же довод, по которому словарь мата
// вынесен в общий листовой пакет profanity: два молча разошедшихся списка дали
// бы площадку, где запрещено не то, что гасится.

import (
	"testing"

	"lovegw/internal/archive"
	"lovegw/internal/narod"
)

func TestОкноНакалаОдноНаЗамерИБой(t *testing.T) {
	if narod.TempoWindow != archive.TempoWindow {
		t.Errorf("окно накала разошлось: в бою %v, в замере %v — "+
			"значит множитель прикладывается к величине, которой не мерили",
			narod.TempoWindow, archive.TempoWindow)
	}
}
