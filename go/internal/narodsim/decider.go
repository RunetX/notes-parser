package narodsim

// Базовый кубик — БАЗЛАЙН этапа 2, а не окончательное правило.
//
// Он смотрит ровно на три вещи: обратились ли к жителю, сколько он уже сказал в
// этом треде и что говорит его карточка о частоте. Ни темы, ни отношений, ни
// часа суток здесь нет намеренно — они появятся на этапе 3 вместе с миром, и
// смысл базлайна в том, чтобы к их появлению уже было ЧИСЛО, которое они обязаны
// улучшить. Пороги калибровки, придуманные раньше первого прогона, были бы
// выдумкой.
//
// Бросок выводится из (зерно, анкета, реплика), а не из последовательного
// генератора. Разница существенная: последовательный даёт разный результат,
// стоит поменяться порядку или числу точек решения — например, если завтра
// добавится ещё один источник событий, — и два прогона перестанут сравниваться.
// Здесь же монетка на конкретной реплике одна и та же всегда.

import (
	"context"
	"math/rand/v2"
	"time"

	"lovegw/internal/narod"
)

// CardDecider — «прийти или смолчать» по карточке.
type CardDecider struct {
	Card narod.Card
	Seed uint64
}

// MaxChance — потолок вероятности отклика. Единицы здесь быть не может:
// человек, отвечающий ВСЕГДА, — это не характер, а автоответчик, и на любом
// сочетании множителей такое должно оставаться невозможным.
const MaxChance = 0.9

// Decide бросает монетку на одной точке.
func (d *CardDecider) Decide(_ context.Context, p DecisionPoint) (Decision, error) {
	dice := d.Card.Dice
	// Потолок реплик на тред — часть характера, а не защита: человек, у которого
	// в замере полтора десятка реплик за тред, на шестидесяти выглядел бы
	// одержимым.
	if dice.MaxPerThread > 0 && p.Said >= dice.MaxPerThread {
		return Decision{}, nil
	}

	prob, dist := chanceOf(d.Card, p)
	rng := rand.New(rand.NewPCG(pointSeed(d.Seed, p), uint64(p.TriggerID)+1))
	// Задержка тянется ПЕРВОЙ, потому что от неё зависит сама вероятность: час
	// суток решает не в момент публикации заметки, а в момент, когда житель до
	// неё дошёл бы. Иначе заметка, вышедшая в три ночи, не собрала бы никого —
	// хотя на деле её читают утром, и утренние люди в ней и окажутся.
	after := sampleDist(dist, rng.Float64())
	if p.TriggerID == 0 {
		prob = min(prob*d.Card.Rhythm.HourWeight(p.Now.Add(after)), MaxChance)
	}
	if rng.Float64() >= prob {
		return Decision{}, nil
	}
	return Decision{Speak: true, After: after}, nil
}

// pointSeed — ключ монетки: «кто и где» первым словом, «на что» вторым.
//
// ЗАМЕТКА в ключе обязательна, и стоило это первого же прогона в вакууме
// 28.08.2026: у точки решения на САМОЙ заметке номера реплики нет вовсе (ноль),
// и без номера заметки бросок выходил один и тот же во всех тредах серии.
// Житель, которому на первой заметке выпало смолчать, молчал дальше везде — а
// трое таких дали десять пустых заметок подряд и отчёт, в котором нечего мерить.
// В solo дефект был тем же и виден не был: там точка на заметке одна из сотен, и
// её вечное «не приходить» терялось в матрице. В вакууме то же верно и для
// реплик: номера там свои у каждого треда и начинаются с единицы.
//
// Номера реплик в треде идут почти подряд, то есть PCG получает соседние
// зёрна, — и это проверено, а не принято на веру (28.08.2026, 200 тыс. точек):
// ни частота бросков, ни связь соседних от этого не страдают (корреляция
// −0,002 при шуме ±0,002). Перемешивать зёрна не понадобилось, а частоту
// стережёт тест на подряд идущих номерах.
const noteSalt = 0x9E3779B97F4A7C15

func pointSeed(seed uint64, p DecisionPoint) uint64 {
	return seed ^ uint64(p.Actor) ^ uint64(p.NoteID)*noteSalt
}

// chanceOf — вероятность заговорить и распределение задержки для точки.
//
// Вероятность ОТВЕТА берётся из замера (card.Rate) и зависит от того, как далеко
// зашёл разговор. Числа карточки остаются запасным путём — на случай, когда
// корзина замера пуста, — и оба довода за это записаны замером 28.08.2026:
// придуманное «влезть в чужой разговор = 0.15» оказалось завышено в 20–40 раз
// (настоящее — от 0.4 % у ДВ до 3.7 % у Полынь-Травы), а придуманное «ответить,
// когда обратились = 0.7» попало почти точно (настоящее 39–91 %). То есть на
// глаз угадывается то, что человек делает часто, и не угадывается то, что редко,
// — а из редкого и состоит поведение в людном треде.
//
// Затухание при этом настоящее, но скромное: мимо-разговорная вероятность падает
// вдвое-вчетверо от начала треда к трёхсотой реплике, а обращённая к нему — едва
// на четверть. Человек уходит не из разговора вообще, а из ЧУЖОГО разговора.
//
// А вот «прийти в новую заметку» замерить нельзя и незачем притворяться: в
// архиве видно, в какие треды человек пришёл, и не видно, какие он пролистал.
func chanceOf(card narod.Card, p DecisionPoint) (float64, narod.Dist) {
	dice, lat := card.Dice, card.Latency
	if p.TriggerID == 0 {
		// Заметка: «прийти в новую» — и задержка меряется от её публикации.
		//
		// Сама вероятность неизмерима (в архиве видно, куда человек пришёл, и не
		// видно, что он пролистал), а вот ПЕРЕКОС по теме измерим и вносится
		// множителем: доля темы среди заметок, где он говорил, против доли той же
		// темы среди всех заметок его времени. Без него кубик про заметку не
		// знает ничего, кроме того, что она новая, — и выбор «кто придёт именно
		// сюда» выходил случайным (замер 28.08.2026: состав заговоривших сходился
		// с настоящим ровно настолько, насколько сошёлся бы жребий).
		p0 := dice.ComeToNote
		if lift, ok := card.TopicLift(p.Topics); ok {
			p0 *= lift
		}
		// Тот же рычаг отношения, что и у ответа, и с тем же потолком: в чью
		// заметку зайти — вопрос ровно про то же, про что «влезать ли в его
		// разговор». Полоса при этом замерена на репликах, а не на заметках, и
		// это заимствование; но взять её оттуда честнее, чем выдумать сюда
		// второе число, у которого замера не будет вовсе.
		p0 *= relationLift(card, p)
		return min(p0, MaxChance), lat.ToThreadSec
	}
	if r, ok := card.Rate.Rate(p.Seen, p.Addressed); ok {
		// Знакомство накладывается МНОЖИТЕЛЕМ поверх позиции: вопросы разные —
		// «докуда дошёл разговор» и «кто говорит», — и обе готовые вероятности
		// содержат общую базу, которая учлась бы дважды.
		if lift, ok := card.Rate.FamiliarLift(p.Familiarity, p.Addressed); ok {
			r *= lift
		}
		// Накал: без него вероятность постоянна и в мёртвом треде, и в
		// разгоревшемся. Замер говорит, что горячий тред РАЗВОДИТ людей по парам —
		// в чужой разговор влезают втрое реже, своему собеседнику отвечают вдвое
		// надёжнее, — и перепалка растёт именно отсюда. Множитель поэтому
		// разнонаправленный, и разделяет его тот же признак Addressed, что у
		// знакомства: одна средняя величина между этими двумя не значит ничего.
		if lift, ok := card.Rate.TempoLift(p.Tempo, p.Addressed); ok {
			r *= lift
		}
		r *= relationLift(card, p)
		return min(r, MaxChance), lat.ToReplySec
	}
	if p.Addressed {
		return dice.ReplyMention, lat.ToReplySec
	}
	return dice.ReplyOther, lat.ToReplySec
}

// relationLift — во сколько раз ОТНОШЕНИЕ меняет готовность откликнуться.
//
// Единственный рычаг кубика, у которого нет собственного замера, и это сказано
// прямо, потому что скрыть тут нечего: в архиве видно, ЧТО человек написал, и
// не видно, как он к собеседнику относился. Симпатию нельзя добыть счётом — её
// называет модель, читая закончившийся разговор (narod.Chronicle).
//
// Поэтому придумано здесь ровно одно — ЗНАК, а размах взят из замера. Потолок
// рычага равен потолку ЗНАКОМСТВА (FamiliarSpan): знакомство — это тот же след
// отношения, только доступный счёту («мы уже разговаривали, и я вернулся»), и
// сказать «отношение решает не больше, чем решает знакомство» можно, не гадая.
// Тон в ±1 двигает вероятность до края замеренной полосы, и ни на шаг дальше.
//
// Работает он ТОЛЬКО мимо прямого обращения — по тому же замеру, по которому
// туда же поставлено знакомство: когда обратились лично, человек отвечает и
// нелюбимому, а вот влезать в чужой разговор ради него не станет. Наложить
// рычаг на оба случая значило бы выдумывать там, где выдумка видна.
func relationLift(card narod.Card, p DecisionPoint) float64 {
	if p.Addressed || p.Tone == 0 {
		return 1
	}
	span, ok := card.Rate.FamiliarSpan(false)
	if !ok || span <= 1 {
		return 1 // полосы не замерили — рычага нет вовсе
	}
	tone := min(max(p.Tone, -1), 1)
	if tone > 0 {
		return 1 + tone*(span-1)
	}
	// Вниз — тем же множителем, обращённым: иначе неприязнь била бы слабее
	// симпатии просто потому, что у вероятности снизу ноль, а сверху потолок.
	return 1 / (1 - tone*(span-1))
}

// sampleDist — задержка по квантилям замера.
//
// Распределение задано четырьмя числами (P10, медиана, P90, максимум), и
// восстанавливается оно кусочно-линейно между ними. Это заведомо грубее правды,
// но честнее любого красивого закона: показательное или логнормальное
// распределение подогнало бы хвост под формулу, а хвост здесь и есть содержание —
// человек отвечает то через минуту, то через три часа.
func sampleDist(d narod.Dist, u float64) time.Duration {
	return time.Duration(quantileAt(d, u) * float64(time.Second))
}

// quantileAt — само восстановление квантиля, без единиц измерения. Отдельно от
// задержки, потому что тем же жребием берётся ДЛИНА реплики: у обеих величин
// содержание в хвосте, а не в середине.
func quantileAt(d narod.Dist, u float64) float64 {
	switch {
	case d.Median <= 0:
		return 0
	case u < 0.1:
		return lerp(0, float64(d.P10), u/0.1)
	case u < 0.5:
		return lerp(float64(d.P10), float64(d.Median), (u-0.1)/0.4)
	case u < 0.9:
		return lerp(float64(d.Median), float64(d.P90), (u-0.5)/0.4)
	default:
		top := float64(d.Max)
		if top < float64(d.P90) {
			top = float64(d.P90)
		}
		return lerp(float64(d.P90), top, (u-0.9)/0.1)
	}
}

func lerp(a, b, t float64) float64 { return a + (b-a)*t }
