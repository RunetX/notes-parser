-- Выпуск дайджеста считается по площадке: индексы по ВРЕМЕНИ комментария.
--
-- До 22.08.2026 сводку недели считали по SQLite зеркала, где комментариев
-- десятки тысяч и любой запрос дёшев. Теперь она считается здесь, а здесь их
-- 10,7 миллиона, и ни одного индекса по published_at у comments не было:
-- дерево (note_id, path), лента треда (note_id, id) и реплики автора
-- (author_id, id) отвечают на другие вопросы. Недельное окно без такого
-- индекса — это seq scan по таблице на 3 ГБ, то есть выпуск раз в неделю
-- вымывал бы кэш всей площадке.
--
-- Почему id вместо времени не годится, хотя id и растут по времени: полоса
-- восстановленного [2e11..3e11) — это август 2010 года с САМЫМИ БОЛЬШИМИ
-- идентификаторами, и «свежие по id» дали бы там пятнадцатилетние реплики.
--
-- Оба индекса частичные по status = 0: выпуск считает то, что видно читателю,
-- а скрытое модератором или автором в сводку не идёт ни числом, ни цитатой.
--
-- ВНИМАНИЕ, время постройки. На боевых 10,7 млн строк это единицы минут, и всё
-- это время CREATE INDEX держит на comments блокировку, при которой запись в
-- таблицу ждёт (чтение — нет). Накатывать вместе с остальными миграциями, в
-- известный момент, как и заведено: приём зеркала на эти минуты встанет и
-- нагонит сам.
CREATE INDEX comments_time ON comments (published_at) WHERE status = 0;

-- Второй отвечает на вопрос «когда этот человек писал в последний раз ДО
-- окна» — им живут рубрики «новые лица» и «возвращение недели». Индекс
-- (author_id, id DESC) на него не отвечает по причине из абзаца про полосы:
-- у человека с репликами 2010 года первой же строкой идёт именно она.
CREATE INDEX comments_author_time ON comments (author_id, published_at DESC)
    WHERE status = 0;
