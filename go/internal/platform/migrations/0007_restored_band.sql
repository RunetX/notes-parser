-- Третья полоса идентификаторов: ВОССТАНОВЛЕННОЕ из чужих зеркал.
--
-- Полос было две (см. шапку 0001_init.sql): записи НГС, где id строки равен id
-- на сайте, и нативные с 1e11. Между ними не помещается то, ради чего эта
-- миграция и написана, — 11 577 комментариев августа 2010 года из дампа
-- theloser.ru (WordPress-зеркало «Заметок», работавшее в 2010–2012). Сам НГС
-- комментарии до конца 2013 стёр: страница треда заметки 2010 года отдаёт ноль
-- реплик, то есть эпоху не достать уже ничем, кроме чужих копий. Идентификатора
-- сайта у этих строк нет и никогда не было — грабер выдал им отрицательные, и
-- первая раскатка архива их поэтому честно пропустила.
--
-- Почему полоса, а не колонка `source`. Ровно по той же причине, по какой её нет
-- у первых двух: дискриминатор, закодированный в ключе, нельзя рассинхронизировать
-- с содержимым, а колонку можно забыть проставить ровно один раз. Полоса при этом
-- НЕ отменяет обещание первой («id строки равен id на сайте»), а называет строки,
-- к которым оно неприменимо.
--
-- Почему это не «нативная» полоса, хотя id выдаём мы. Нативное — это написанное
-- ЗДЕСЬ, и оно уходит в каналы мессенджеров (internal/platout читает всё, что
-- больше 1e11). Реплика 2010 года, попавшая в нативную полосу, была бы через
-- пятнадцать секунд запощена в канал — одиннадцать тысяч сообщений из позапрошлой
-- эпохи. Разделяющая полоса делает это невозможным по устройству, а не по
-- внимательности.
--
--   [1 .. 1e11)      записи НГС: id строки РАВЕН id на сайте
--   [1e11 .. 2e11)   нативные: из последовательностей *_native_seq
--   [2e11 .. 3e11)   восстановленное: id сайта нет, ключ выведен из ключа архива
--   [3e11 .. )       резерв
--
-- Последовательности у третьей полосы нет намеренно: ключ считается из ключа
-- архива (id = 2e11 + |id архива|), а детерминированное отображение — это и есть
-- идемпотентность добора, без таблицы соответствий и без второго источника правды.
--
-- NOT VALID — не отложенная проверка, а точное знание. Новая граница ШИРЕ прежней,
-- поэтому каждая строка, прошедшая старую (id < 2e11), проходит и новую. Полный
-- проход по 10,8 млн строк `comments` под ACCESS EXCLUSIVE не купил бы ни одного
-- нового факта, зато уложил бы страницы треда на минуту.

ALTER TABLE users    DROP CONSTRAINT users_id_band;
ALTER TABLE users    ADD  CONSTRAINT users_id_band
    CHECK (id > 0 AND id < 300000000000) NOT VALID;

ALTER TABLE notes    DROP CONSTRAINT notes_id_band;
ALTER TABLE notes    ADD  CONSTRAINT notes_id_band
    CHECK (id > 0 AND id < 300000000000) NOT VALID;

ALTER TABLE comments DROP CONSTRAINT comments_id_band;
ALTER TABLE comments ADD  CONSTRAINT comments_id_band
    CHECK (id > 0 AND id < 300000000000) NOT VALID;

COMMENT ON CONSTRAINT users_id_band ON users IS
    'полосы: [1,1e11) НГС, [1e11,2e11) нативные, [2e11,3e11) восстановленные';
COMMENT ON CONSTRAINT notes_id_band ON notes IS
    'полосы: [1,1e11) НГС, [1e11,2e11) нативные, [2e11,3e11) восстановленные';
COMMENT ON CONSTRAINT comments_id_band ON comments IS
    'полосы: [1,1e11) НГС, [1e11,2e11) нативные, [2e11,3e11) восстановленные';
