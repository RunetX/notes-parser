-- Ш7, модерация: очередь, решения, аудит и права субъекта.
--
-- Схема под это лежала с v1 (`reports`, `audit_log`, `users.role`,
-- `users.banned_until`, статусы публикаций), а v5 добавила `moderation_queue`
-- крючком: строка заводится ТОЙ ЖЕ транзакцией, что и публикация. Здесь
-- дописывается ровно то, чего не хватило самой модерации, — и ни одной колонки
-- «на будущее».

-- 1. ЖИЗНЬ КАРТОЧКИ ПРОВЕРКИ.
--
-- До сих пор в очереди хранилось только мнение автомата (verdict, category,
-- quote). Мнения мало: у решения обязан быть автор и момент, иначе через месяц
-- «за что скрыли» отвечается догадкой. Решение человека пишется рядом с
-- мнением автомата, а не вместо него, — расхождение этих двух полей и есть
-- статистика ложных срабатываний, ради которой автомат вообще можно держать.
ALTER TABLE moderation_queue
    ADD COLUMN note_id    bigint,                          -- куда вести из очереди
    ADD COLUMN attempts   smallint NOT NULL DEFAULT 0,     -- сколько раз автомат брался
    ADD COLUMN decided_at timestamptz,
    ADD COLUMN decided_by bigint REFERENCES users(id),
    ADD COLUMN decision   smallint;                        -- 0 оставить, 1 скрыть

COMMENT ON COLUMN moderation_queue.note_id IS
    'заметка, к которой относится строка (у самой заметки — она же): очередь обязана уметь дать ссылку, не читая comments';
COMMENT ON COLUMN moderation_queue.attempts IS
    'сколько раз автомат брал строку: битый ответ модели не должен крутиться вечно';
COMMENT ON COLUMN moderation_queue.decision IS
    '0 оставить видимым, 1 скрыть; NULL — человек ещё не смотрел';

-- Уже лежащим строкам заметку проставляем ровно один раз, здесь: заметка у
-- комментария не меняется никогда, поэтому это не денормализация «на удачу».
UPDATE moderation_queue q SET note_id = q.subject_id WHERE q.subject_kind = 'note';
UPDATE moderation_queue q SET note_id = c.note_id
  FROM comments c WHERE q.subject_kind = 'comment' AND c.id = q.subject_id;

-- Очередь ЧЕЛОВЕКА — это «автомат передал» плюс «автор обжаловал» плюс
-- «пожаловались», и всё это до решения. Индекс частичный, потому что цель
-- владельца — единицы строк в сутки: полный индекс по таблице, куда падает
-- КАЖДАЯ публикация, стоил бы дороже самой очереди.
CREATE INDEX moderation_review ON moderation_queue (queued_at)
    WHERE decided_at IS NULL AND (verdict = 1 OR appealed_at IS NOT NULL);

-- «Мои скрытые публикации» на своей странице спрашиваются ОТСЮДА, а не обходом
-- comments по автору: у участника с 138 тыс. реплик такой обход стоит 53 с
-- (замер 18.08.2026), то есть не влезает в срок веб-запроса вовсе. В очереди же
-- лежит только нативное и то, на что пожаловались.
CREATE INDEX moderation_author ON moderation_queue (author_id, queued_at DESC);

-- 2. ЗА ЧТО ЗАПРЕТ.
--
-- Забаненному показывается срок и причина: «публикации вам сейчас запрещены»
-- без объяснения — это то же молча исчезнувшее сообщение, только про человека
-- целиком. Кто поставил — в audit_log, но здесь оно нужно на чтении, а лезть
-- за ним в журнал на каждый показ страницы незачем.
ALTER TABLE users
    ADD COLUMN ban_reason text NOT NULL DEFAULT '',
    ADD COLUMN banned_by  bigint REFERENCES users(id);

-- 3. ЖАЛОБА — единственный вход в модерацию для СТАРЫХ строк.
--
-- Кнопки «пожаловаться» с НГС мы не переносили (решение эпика E по виду
-- страницы), но своя жалоба нужна по другой причине: классификатор по архиву не
-- гоняется — 10,8 млн комментариев это тысячи долларов даже на дешёвой модели,
-- — значит историю модерировать больше нечем.
--
-- Одна открытая жалоба на человека на объект: повторные нажатия не должны
-- превращать очередь в счётчик недовольства. После решения модератора
-- пожаловаться на тот же объект снова можно — обстоятельства меняются.
CREATE UNIQUE INDEX reports_once ON reports (reporter_id, subject_kind, subject_id)
    WHERE resolved_at IS NULL;

-- 4. ОТЛОЖЕННЫЙ ПРОХОД ПО АВТОРУ.
--
-- Отзыв согласия на распространение и обезличивание обязаны пройти по ВСЕМ
-- публикациям человека, а такой проход стоит десятки секунд (замер выше) — в
-- срок веб-запроса (5 с у пула морды) он не влезает. Поэтому форма делает
-- столько, сколько успевает, и поднимает флаг; остальное доводит фоновая
-- служба демона.
--
-- Флаг, а не таблица задач: состояние «строки статусов разошлись с рубильником»
-- полностью выводится из самой базы, поэтому очередь заданий здесь была бы
-- вторым источником правды, который умеет расходиться с первым. Флаг
-- самозалечивается — служба гасит его, лишь когда проход не нашёл ни строки.
ALTER TABLE users ADD COLUMN visibility_dirty boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN users.visibility_dirty IS
    'публикации ещё не приведены к hide_all: проход не уложился в срок запроса, доводит фоновая служба';
CREATE INDEX users_visibility_dirty ON users (id) WHERE visibility_dirty;
