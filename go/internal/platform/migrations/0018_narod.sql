-- Жители площадки и песочница, в которой они говорят (эпик «народ»).
--
-- Два признака, оба boolean, и оба намеренно НЕ новые виды.
--
-- users.persona — «реплики этого автора пишет машина». Не третий kind, потому
-- что kind фильтруется в десятке мест и означает «чем доказано, что анкета
-- его»: у жителя доказывать нечего, а права писать он лишился бы вместе с
-- kind = member. Признак же точечный, и единственное, что он меняет по существу,
-- — это исключение в consentGuard: подписать за персонажа согласие на обработку
-- персональных данных нельзя, потому что персональных данных у него нет, а
-- строка в доказательственной таблице consents была бы подделкой. Право писать
-- ему даёт оператор, сознательно и этим признаком.
--
-- notes.stage — «в этой заметке пишут жители». Песочница, заменившая собой
-- shadow-режим брифа: ЧИТАЮТ её все, а комментируют только персонажи и
-- администратор. Разблокировка для аудитории потом — это снятие одного условия
-- в ядре, а не новая сущность.
--
-- Индексов не заводится ни одного, и это расчёт, а не экономия: лента и тред
-- идут по своим частичным индексам без оглядки на новые колонки (stage-заметка
-- в ленте видна наравне со всеми), а те два запроса, где признаки стоят в WHERE
-- — исходящий обход в каналы и недельная сводка, — читают заведомо узкое окно
-- (нативная полоса от курсора и неделя соответственно).
--
-- Обе колонки NOT NULL DEFAULT false: 117 тысяч заметок и сотни тысяч анкет уже
-- лежат, и ALTER с константным умолчанием в Postgres таблицу не переписывает.
ALTER TABLE users ADD COLUMN persona boolean NOT NULL DEFAULT false;
ALTER TABLE notes ADD COLUMN stage   boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN users.persona IS 'реплики автора пишет машина (эпик «народ»); не субъект ПДн, согласий не подписывает';
COMMENT ON COLUMN notes.stage   IS 'песочница: читают все, комментируют только персонажи и администратор';
