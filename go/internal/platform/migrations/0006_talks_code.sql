-- Второй канал доставки кода входа: личное сообщение на НГС.
--
-- Основным был код в поле «о себе», и он забуксовал по причине, которой не было
-- в замерах: правка «о себе» уходит на МОДЕРАЦИЮ, и одобрят её не наверняка и не
-- сразу. Личка модерации не проходит, приходит мгновенно и вдобавок доказывает
-- больше: код в публичной анкете видит кто угодно (мы сами читаем её анонимно),
-- а код в личке читает только владелец ящика — поэтому там нужна была вторая
-- половина доказательства (кука), а здесь достаточно того, что человек назвал
-- код обратно.
--
-- Оба канала живут рядом и различаются видом челленджа (kind), потому что
-- различается СПОСОБ ПРОВЕРКИ. Перепутать их нельзя: если код, показанный на
-- экране, начать принимать введённым обратно, то войти под чужой анкетой можно
-- будет в одно нажатие — запросил код на чужой номер, увидел его у себя,
-- переписал в поле.
--
-- sends считает отправки: начатый кем угодно вход шлёт сообщение НАСТОЯЩЕМУ
-- владельцу анкеты, то есть служебный аккаунт можно превратить в рассыльщик
-- спама чужими руками. Потолок отправок на анкету — единственное, что этому
-- мешает, и стоит он в той же строке, что и сам код.
ALTER TABLE auth_challenges ADD COLUMN sends smallint NOT NULL DEFAULT 0;
COMMENT ON COLUMN auth_challenges.sends IS 'сколько раз код отправляли (для talks-канала: потолок против рассылки чужими руками)';
COMMENT ON COLUMN auth_challenges.kind IS 'ngs_profile — код в «о себе» (проверка двусторонняя); ngs_talks — код в личку (проверка вводом)';
