-- СМЕЖНОЕ обсуждение: синтетический тред рядом с настоящим (эпик «народ»).
--
-- Понадобилось потому, что прежний способ пустить жителей в существующую
-- заметку был ОДИН — перевести её в песочницу (notes.stage), а перевод возможен,
-- только пока в заметке никто не сказал ни слова, и после него заметка достаётся
-- жителям целиком. Владелец назвал это решение поспешным, и он прав: заметка с
-- живым тредом — самый интересный материал для симуляции, а её-то и нельзя было
-- взять вовсе.
--
-- ДВОЙНИК решает это, ничего не отнимая: у заметки заводится СМЕЖНАЯ запись со
-- своим тредом, признаком песочницы и ссылкой сюда. Оригинал не трогается
-- вовсе — ни текст, ни автор, ни его настоящее обсуждение, — а жители говорят у
-- себя, и два разговора не смешиваются по построению, а не по дисциплине.
--
-- Почему ссылкой, а не копией текста: скопировать чужую заметку в новую запись
-- значит поставить чужие слова под другим именем — ровно то, что запрещено
-- правкой чужого текста (ErrNotNative). Двойник держит НОМЕР оригинала, текст
-- для жителей приёмник берёт по этой ссылке (platnarod), а читателю двойник
-- показывает, чьё обсуждение он читает.
--
-- Колонка nullable и без умолчания: 117 тысяч заметок уже лежат, ALTER без
-- дефолта таблицу не переписывает вовсе.
ALTER TABLE notes ADD COLUMN synth_of bigint REFERENCES notes(id);

-- Индекс УНИКАЛЬНЫЙ и частичный, и оба свойства работают.
--
-- Уникальность — правило «у заметки один двойник», и держит его база, а не
-- проверка в коде: двух администраторов, нажавших кнопку разом, проверка не
-- разводит, а уникальный индекс разводит.
--
-- Частичность делает его почти невесомым (двойников единицы из 117 тысяч) и
-- заодно даёт тот единственный запрос, ради которого он нужен: «есть ли у этой
-- заметки смежное обсуждение» на каждой странице заметки.
CREATE UNIQUE INDEX IF NOT EXISTS notes_synth_of ON notes (synth_of) WHERE synth_of IS NOT NULL;

COMMENT ON COLUMN notes.synth_of IS 'двойник: номер заметки, чьё смежное синтетическое обсуждение здесь ведут жители';
COMMENT ON INDEX notes_synth_of IS 'у заметки не больше одного двойника; он же вход «есть ли смежное обсуждение»';
