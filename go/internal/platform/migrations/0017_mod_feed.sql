-- Скрытая заметка ЗАТЕНЯЕТСЯ модератору, а не исчезает у него вместе со всеми.
--
-- Жалоба владельца 26.08.2026: скрыв заметку, он терял её из виду вовсе. В
-- ленте её больше нет ни у кого, включая того, кто её скрыл, а на её страницу
-- надо помнить адрес — то есть вернуть скрытое можно было только из очереди
-- `/mod`, по цитате, без разговора вокруг. Ровно того, чего избегает правило
-- «модератор работает там, где читает».
--
-- В ТРЕДЕ это устроено с самого начала (threadModQuery: `status IN (0, 2)`), а
-- лента не могла: её индекс ЧАСТИЧНЫЙ по `status = 0`, и запрос с двумя
-- статусами ушёл бы в полный перебор 117 тысяч строк на каждый показ — то есть
-- редкая роль оплачивалась бы самым горячим запросом площадки. Отсюда второй
-- индекс: зеркало notes_feed с расширенным условием. Он не ЗАМЕНЯЕТ первый —
-- лента читателя обязана остаться на самом узком.
--
-- Тот же случай у закреплённых, и без второго индекса он оборачивался дырой:
-- notes_pinned частичен по `status = 0`, а лента отсекает закреплённые по
-- pinned_at, — значит скрытая закреплённая заметка не показывалась бы модератору
-- НИГДЕ, ни наверху, ни в хронологии.
--
-- Время постройки: в notes 117 тысяч строк, это секунды, а не минуты 0014/0015
-- на comments. Накатывать всё равно ДО подъёма нового образа — морда при
-- расхождении версии схемы стартовать отказывается намеренно.
CREATE INDEX notes_feed_mod ON notes (published_at DESC, id DESC)
    WHERE status IN (0, 2);

CREATE INDEX notes_pinned_mod ON notes (pinned_at DESC, id DESC)
    WHERE pinned_at IS NOT NULL AND status IN (0, 2);
