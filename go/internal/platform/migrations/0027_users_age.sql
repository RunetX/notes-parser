-- Возраст рядом с ником — как в мобильной версии НГС (06.09.2026, решение
-- владельца).
--
-- НОВЫХ ДАННЫХ ЭТО НЕ ЗАВОДИТ. Возраст зеркало читает с первого дня: он стоит в
-- alt аватара на странице комментариев («Ник, 43 года»), разбирается
-- love.splitNameAge, хранится в SQLite колонкой comments.author_age и с тех же
-- пор печатается шапкой каждой реплики в Telegram и MAX (tgx.commentHead,
-- maxx.ComposeCommentMessage). Не было его ровно в одном месте — на страницах
-- самой площадки, и эта колонка чинит именно это.
--
-- У ЖИВОГО ЧЕЛОВЕКА ОН ЕСТЬ, ТОЛЬКО ПОКА ТОТ ТЕНЬ, и правило держится не
-- условием, а тем, КТО пишет колонку: пишет её один лишь ensureShadow, а он и
-- без того ограничен `WHERE users.kind = KindShadow` — той же оговоркой, которая
-- не даёт зеркалу переписать ник вошедшему участнику. Значит участнику возраст
-- здесь не заводится вовсе, и обещание подписанных им согласий («поля анкеты
-- НГС, кроме ника, аватара и пола, не показываются») остаётся исполненным БЕЗ
-- ЕДИНОЙ НОВОЙ ПОДПИСИ. Обратный ход тоже нужен и стоит в auth.go и botlogin.go:
-- тень, вошедшая на площадку, становится участником — и возраст с неё снимается
-- той же транзакцией, что и сам вход.
--
-- Исключение одно — ЖИТЕЛИ (users.persona): им возраст ставит `narod enroll` из
-- рецепта (SetPersonaAge). Персональных данных у персонажа нет вовсе, скрывать
-- нечего и не от кого, а житель без возраста рядом с тенями, у которых он есть,
-- выглядел бы дырой в разметке.
--
-- Число, а не строка. Сайт отдаёт «43 года», и соблазн сохранить как есть велик,
-- но тогда в базе оседает ЧУЖАЯ формулировка: у нас склонение считает plural, и
-- две записи одного и того же («43 года» строкой и 43 числом) разошлись бы на
-- первом же переносе. Пусто — «не знаем»: возраст не обязателен и на самом НГС.
ALTER TABLE users ADD COLUMN age smallint;

COMMENT ON COLUMN users.age IS 'возраст: у теней из alt аватара НГС, у жителей из рецепта; у вошедшего участника не заводится вовсе';
