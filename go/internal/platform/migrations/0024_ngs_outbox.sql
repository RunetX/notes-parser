-- Отправка написанного здесь на love.ngs.ru (01.09.2026, решение владельца).
--
-- Направление обратное зеркалу: зеркало приносит НГС сюда, а это уносит наше
-- туда. Нужно оно потому, что сообщество расколото — часть людей осталась на
-- сайте и сюда не переехала, — и человек, написавший на площадке, хочет быть
-- прочитанным обеими половинами.
--
-- ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО, и это не осторожность, а согласие: публикуя здесь,
-- человек соглашался на публикацию ЗДЕСЬ. Унести его слова на чужой сайт от его
-- имени можно только по отдельной, осознанно нажатой галочке.
ALTER TABLE users ADD COLUMN ngs_send boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN users.ngs_send IS 'уносить ли написанное этим человеком на love.ngs.ru (галочка на /me, по умолчанию выключена)';

-- Очередь, а не отправка на месте. Причина не в скорости: КЛЮЧ ШИФРОВАНИЯ КУК
-- есть только у демона, и это записано в docker-compose прямо — конфиг веб-морды
-- отдельный, потому что она смотрит в интернет. Морда поэтому лишь ставит
-- строку, а ходит на сайт демон, ровно как platout носит заметки в мессенджеры.
--
-- Строка ставится ТОЙ ЖЕ транзакцией, что и сама публикация: «опубликовано, но в
-- очередь не попало» не должно существовать — тем же доводом, по которому в той
-- же транзакции пишется moderation_queue.
CREATE TABLE ngs_outbox (
    id          bigserial PRIMARY KEY,
    -- Что уносим. Заметка уходит новой заметкой НГС, комментарий — репликой в
    -- тред уже зеркальной заметки; вида ровно два, и третьего быть не может.
    kind        text   NOT NULL CHECK (kind IN ('note', 'comment')),
    -- Наш id заметки или комментария. Внешнего ключа НЕТ намеренно: строка
    -- очереди переживает скрытие и правку объекта, а решение «нести или нет»
    -- принимается в момент отправки, глядя на объект живьём.
    object_id   bigint NOT NULL,
    -- От чьего имени. Сессия НГС лежит в SQLite демона и ищется по номеру
    -- анкеты, который РАВЕН этому id.
    author_id   bigint NOT NULL REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    -- Состояние: queued → sent | failed | skipped. Отдельного 'sending' нет
    -- намеренно: сайт отвечает 500 и на принятый комментарий (замер 17.08.2026),
    -- то есть «отправляется» неотличимо от «отправлено», и отметка врала бы.
    -- Взятое в работу помечается сразу attempts + 1, и повтор виден по счётчику.
    state       text   NOT NULL DEFAULT 'queued'
                CHECK (state IN ('queued', 'sent', 'failed', 'skipped')),
    attempts    smallint NOT NULL DEFAULT 0,
    last_error  text   NOT NULL DEFAULT '',
    sent_at     timestamptz,
    -- id реплики на НГС, если сайт его вернул. Пусто — обычное дело: PostNote
    -- не возвращает id вовсе.
    ngs_id      text   NOT NULL DEFAULT ''
);

-- Очередь берётся по времени и только ждущая. Частичный индекс, потому что
-- отправленное копится навсегда, а разбирают всегда голову очереди.
CREATE INDEX ngs_outbox_queued ON ngs_outbox (created_at, id) WHERE state = 'queued';
-- Одна строка на объект: повторная публикация одного и того же комментария на
-- НГС — это дубль в чужом треде, который потом не убрать.
CREATE UNIQUE INDEX ngs_outbox_object ON ngs_outbox (kind, object_id);
