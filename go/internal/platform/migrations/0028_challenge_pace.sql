-- Темп проверок кода входа вместо их числа (10.09.2026).
--
-- ЗАМЕР, из-за которого это делается. С 19.08.2026 вход по коду в «о себе»
-- начали десять человек — и НИ ОДИН не дошёл до конца. Не потому, что не
-- поняли: трое жали «Проверить» по 8, 16 и 20 раз. Двадцать — это ровно
-- прежний challengeMaxAttempts, то есть площадка переставала разговаривать с
-- человеком, который делал всё правильно.
--
-- Причина в паре чисел, противоречивших друг другу три недели. ChallengeTTL
-- стоял ЧАС с доводом «человеку нужно открыть НГС, отредактировать анкету и
-- вернуться» — срок, посчитанный на правку, которая появляется СРАЗУ. А правка
-- поля «о себе» уходит на модерацию НГС и одобряется не сразу и не наверняка,
-- и это записано и в CLAUDE.md с 18.08, и на самом экране кода соседней
-- фразой. Пока жил канал лички, код в «о себе» был запасным путём, которым не
-- пользовались; 01.09 личку убрали, он стал единственным — и оказался
-- непроходим.
--
-- Абсолютный потолок здесь и есть замок: он защёлкивается именно на том, кто
-- ЖДЁТ одобрения и потому проверяет много раз. Заводили его не против подбора
-- (40 бит по сети не подбирают), а против долбёжа по НГС — а темп защищает
-- ровно это и никого не запирает. Отсюда колонка: считаем, КОГДА проверяли
-- последний раз, а не СКОЛЬКО раз всего.
--
-- Колонка attempts остаётся: она больше ничего не запрещает, но отвечает на
-- вопрос «сколько человек бился», а именно он и показал этот дефект. Ценой
-- одной колонки в таблице на десяток строк — не жалко.
ALTER TABLE auth_challenges ADD COLUMN last_attempt_at timestamptz;

COMMENT ON COLUMN auth_challenges.last_attempt_at IS 'когда проверяли в последний раз: потолок здесь про темп, а не про число попыток';
COMMENT ON COLUMN auth_challenges.attempts IS 'сколько раз проверяли: счётчик наблюдения, ничего не запрещает с 10.09.2026';
