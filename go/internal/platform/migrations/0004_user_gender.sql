-- мужской #448dc8). Не украшение — в треде на четыре сотни реплик цвет первым
-- отделяет собеседников друг от друга.
--
-- Эпик E запрещал заводить анкетные поля («спецкатегории заводятся сами, если
-- сделать поля»), и запрет остаётся в силе: пол — единственное исключение, и
-- сделано оно осознанно. Пол НЕ относится к специальным категориям ст. 10
-- 152-ФЗ (там раса, национальность, взгляды, убеждения, здоровье, интимная
-- жизнь), он публично напечатан на самом НГС рядом с ником, и приезжает даром
-- вместе с обходом тредов — отдельного сбора данных о людях не заводится.
--
-- 0 — неизвестен: у безанкетных комментаторов зеркала его взять неоткуда.
