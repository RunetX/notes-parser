-- Биография ЖИТЕЛЯ (эпик «народ») и страница участника.
--
-- Одна колонка, и она нужна ровно потому, что страницу рисует ВЕБ-МОРДА, а
-- карточка жителя лежит файлом рядом с демоном (data/narod/cards/*.json).
-- Морда до этих файлов не дотягивается и дотягиваться не должна: `web` не знает
-- про эпик «народ» ничего, кроме признака `users.persona`, — иначе показ
-- страницы начал бы зависеть от того, разложены ли рядом карточки.
--
-- Заполняет её `narod enroll` вместе с самой анкетой: там, где житель
-- заводится, и лежит его карточка.
--
-- Живому человеку поля «о себе» это НЕ заводит, и запрет держит не колонка, а
-- проверка в ядре (SetPersonaBio требует persona = true). Свободный текст от
-- участника — это и персональные данные, и вторая поверхность модерации, и
-- площадка их не заводила нигде: у события шины нет колонки под текст ровно по
-- этому доводу. У персонажа персональных данных нет, а сочинил биографию
-- оператор, и отвечает за неё он же.
--
-- В биографию не идёт `frustration` из карточки — то, чем житель уязвлён. Это
-- рычаг кубика, а не факт о человеке: напечатанный на странице, он превратил бы
-- характер в приложенную к нему инструкцию.
--
-- NOT NULL DEFAULT '' — сотни тысяч анкет уже лежат, и ALTER с константным
-- умолчанием в Postgres таблицу не переписывает. Индекса нет: колонку читают по
-- первичному ключу, на одной странице одного человека.
ALTER TABLE users ADD COLUMN bio text NOT NULL DEFAULT '';

COMMENT ON COLUMN users.bio IS 'биография ЖИТЕЛЯ (users.persona); у людей всегда пусто — поля «о себе» площадка не заводит';
