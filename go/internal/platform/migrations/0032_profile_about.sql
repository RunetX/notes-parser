-- Эпик M: «о себе» и фотографии участника (12.09.2026, решение владельца).
--
-- Повод двойной. Страница /u/<id> есть с 30.08.2026, но заводилась она ЖИТЕЛЯМ —
-- у персонажа есть биография, и показать её было негде; живому человеку
-- рассказать о себе на площадке негде до сих пор, а на НГС эту роль играла
-- анкета с фотоальбомом, и именно её люди считали своим местом на сайте
-- знакомств. Вторая половина повода сильнее первой: АВАТАР СЮДА БОЛЬШЕ НЕ
-- ПРИЕЗЖАЕТ САМ — его приносило зеркало вместе с комментарием, а комментариев
-- НГС не принимает с 17.08.2026; анкеты же удаляются вместе с фотографией.
-- Свои фотографии снимают эту зависимость.
--
-- ПЕРЕПОДПИСКИ ЭТО НЕ СТОИЛО, и в этом весь замысел. Действующие согласия
-- перечисляют обрабатываемое ЗАКРЫТЫМ списком, и ни «о себе», ни фотографий
-- профиля в нём нет; но переподписывать ВСЕХ ради того, чем воспользуется
-- меньшинство, — это ровно та частая переподписка, на которую люди уже
-- жаловались. Поэтому берётся рычаг, придуманный 11.09.2026 для привязки
-- мессенджера: маленький НЕОБЯЗАТЕЛЬНЫЙ документ подписывает только тот, кто
-- сюда что-то кладёт (consents/profile.v1.txt), а обязательное ядро
-- заморожено. Оговорка, которую нельзя потерять: базовый перечень после этого
-- перестаёт быть исчерпывающим, поэтому дополнение ссылается на него словами
-- «в дополнение к» — молча изменённое обещание обесценивает и все остальные.
--
-- Состав УЗКИЙ намеренно: город, занятие, свободный текст и до трёх
-- фотографий. Возраст рукой сюда не входит — маленький документ дёшево
-- расширить (его новая редакция переподпишет только тех, кто им пользовался),
-- а поле, оказавшееся лишним, назад не выпишешь. «Ищет» и «пишет» из макета не
-- заводятся вовсе: эпик делает МЕСТО, где человек рассказывает о себе, а не
-- сервис знакомств.

-- Город и занятие — своими колонками, а не строкой в bio: их читает
-- справочная колонка страницы СТРОКАМИ «что — какое», и вынимать их обратно из
-- абзаца пришлось бы разбором, то есть догадкой.
--
-- Свободный текст кладётся в СУЩЕСТВУЮЩУЮ users.bio (0019). Второго хранилища
-- под то же самое не заводится, а дверей к колонке становится две, и у каждой
-- своё основание: житель — оператор из консоли, без согласия, потому что
-- субъекта за персонажем нет (SetPersonaBio, WHERE persona); человек — форма
-- плюс подписанный документ (SetAbout). Комментарий колонки поэтому переписан.
ALTER TABLE users
    ADD COLUMN city text NOT NULL DEFAULT '',
    ADD COLUMN job  text NOT NULL DEFAULT '',
    ADD COLUMN about_status smallint NOT NULL DEFAULT 0;

COMMENT ON COLUMN users.city IS 'город, названный самим человеком; у жителя не заполняется';
COMMENT ON COLUMN users.job IS 'занятие, названное самим человеком';
COMMENT ON COLUMN users.about_status IS '0 видно, 2 скрыто модератором — те же значения, что у notes.status';
COMMENT ON COLUMN users.bio IS 'рассказ о себе: у жителя его пишет narod enroll, у человека — он сам';

-- Фотографии профиля.
--
-- ТРИ — решение владельца, и второй довод к нему арифметический: каждая
-- фотография это строка в очередь модерации, а картинки у нас судит ЧЕЛОВЕК
-- (автомат текстовый и в изображения не смотрит вовсе). Три на участника —
-- очередь, которую видно глазами; двадцать — альбом, который не посмотрит
-- никто, то есть модерация только на бумаге.
--
-- Потолок держит БАЗА (CHECK и UNIQUE), а не счёт в Go: двух одновременных
-- загрузок проверка в коде не разводит — тем же приёмом держатся единственность
-- двойника заметки и единственность служебной анкеты.
--
-- У строки СВОЙ номер, хотя пара (user_id, position) её уже определяет: на неё
-- показывает subject_id очереди модерации и жалоба читателя, а там одно число.
-- Полос идентификаторов это не касается вовсе — полоса правило про записи НГС и
-- нативные публикации, а фотография не публикация.
--
-- status, а не удаление: у модератора площадки нет права стирать — он скрывает,
-- и решение его обратимо нажатием. Здесь это важнее обычного, потому что вернуть
-- удалённую фотографию человеку неоткуда.
CREATE TABLE user_photos (
    id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id  bigint   NOT NULL REFERENCES users(id),
    position smallint NOT NULL CHECK (position BETWEEN 1 AND 3),
    sha256   bytea    NOT NULL REFERENCES media(sha256),
    status   smallint NOT NULL DEFAULT 0,
    added_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, position)
);

COMMENT ON TABLE user_photos IS 'фотографии профиля, до трёх на человека; байты лежат в media';
COMMENT ON COLUMN user_photos.status IS '0 видно, 2 скрыто модератором';

-- Индекс по содержимому — не украшение, на нём стоит УБОРКА. Снятая фотография
-- обязана унести за собой и байты (единственное место проекта, где хранилище
-- чистится), а решить это можно, только спросив, не ссылается ли на них кто-то
-- ещё: имя файла есть его содержимое, и двое вправе поставить одну картинку.
-- Без индекса такой вопрос — обход всех альбомов.
CREATE INDEX user_photos_sha ON user_photos (sha256);

