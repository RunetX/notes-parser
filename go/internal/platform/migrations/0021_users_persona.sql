-- Индекс под мордоленту: жители площадки.
--
-- Мордолента (полоса лиц над лентой заметок, web/faces.go) спрашивает всех
-- жителей на КАЖДОМ показе первой страницы — то есть на самом частом запросе
-- площадки. Жителей десятки, а `users` после раскатки архива насчитывает
-- сотни тысяч строк: без индекса каждый заход в ленту перебирал бы их целиком
-- ради трёх десятков. Перебор идёт на том же одном ядре, где живёт зеркало, и
-- цена ему та же, что у `notes_stage`, — отобранное у обхода НГС.
--
-- Индекс ЧАСТИЧНЫЙ и потому почти невесом: `persona` стоит у единиц из сотен
-- тысяч, строится он мгновенно и не держит запись сколько-нибудь заметно (в
-- отличие от индексов по `comments`, где то же действие стоит минут).
--
-- Порядок по `id` в нём тот же, что у списка жителей в администрировании
-- (`Personas`), — этому запросу он достаётся даром. Мордолента сортирует иначе
-- (по тому, кто говорил последним), но тридцать строк сортируются в памяти, а
-- «когда говорил» лежит в своём индексе `comments_author_time`.
CREATE INDEX IF NOT EXISTS users_persona ON users (id) WHERE persona;

COMMENT ON INDEX users_persona IS 'жители площадки: мордолента на каждой первой странице ленты';
