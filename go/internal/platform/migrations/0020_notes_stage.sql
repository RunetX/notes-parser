-- Индекс под службу народа: заметки-песочницы.
--
-- Запрос `WHERE stage AND status = 0 ORDER BY id` крутится КАЖДЫЕ ТРИДЦАТЬ
-- СЕКУНД — это такт смотра, — а `notes` уже 117 тысяч строк, и без индекса
-- каждый такт перебирал их целиком. Заметно это не было, пока песочница
-- заводилась раз в неделю руками, но перебор идёт на том же одном ядре, где
-- живёт зеркало: всё, что отберёт служба, отбирается у обхода НГС.
--
-- Индекс ЧАСТИЧНЫЙ и потому почти невесом: песочниц единицы из 117 тысяч
-- заметок, и строится он мгновенно — в отличие от индексов по `comments`, где
-- то же действие стоит минут и держит запись. Порядок по `id` в нём тот же, что
-- в запросе, поэтому сортировки не остаётся вовсе.
--
-- `status = 0` внутри условия, а не в списке колонок: скрытая песочница службе
-- не видна вовсе (для пишущего скрытая заметка просто отсутствует), значит она
-- и не должна попадать в индекс.
CREATE INDEX IF NOT EXISTS notes_stage ON notes (id) WHERE stage AND status = 0;

COMMENT ON INDEX notes_stage IS 'песочницы для службы народа: такт смотра раз в 30 с';
