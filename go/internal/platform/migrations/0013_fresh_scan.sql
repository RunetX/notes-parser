-- Живой тред обходится по мобильной версии, а не только историю.
--
-- Живое зеркало знает адресата лишь по обращению «Ник, …» и разрешает его сам
-- (love.Addressees) — это догадка, и она ошибается: 23.08.2026 ответ уехал в
-- чужую ветку, потому что адресат последний раз высказался там. Настоящее ребро
-- отдаёт мобильная страница, и до сих пор её обходила только очередь добора
-- истории — «сперва не смотренные, дальше по давности». Заметку из этой очереди
-- смотрят ОДИН раз, и дописанные после реплики остаются с угаданными рёбрами
-- навсегда: до второго круга по 117 тысячам заметок дело не дойдёт никогда.
--
-- Отсюда вторая очередь — «у кого появились реплики после последнего обхода».
-- Ей нужен вход по времени последнего комментария; без индекса это seq scan по
-- всем заметкам раз в минуту.
--
-- Индекс частичный по тем же двум условиям, что стоят в запросе: обходить можно
-- только записи НГС (у нативной заметки нет страницы на сайте) и только с
-- комментариями. На 117 тысячах строк он строится мгновенно и весит десятки
-- килобайт — это не comments, где та же операция идёт минуты.
CREATE INDEX notes_fresh_scan ON notes (last_comment_at DESC)
    WHERE id < 100000000000 AND comment_count > 0;
