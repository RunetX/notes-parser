-- Закреплённая заметка: одна-две наверху ленты, поверх хронологии.
--
-- Просьба владельца 18.08.2026. Переносом это не является — на НГС закрепления
-- не было, и лента там строго по времени. Заводится оно ради того, чего у НГС
-- и не могло быть: площадка живёт своими объявлениями (правила, переезд, сбои),
-- а лента в 117 тысяч заметок топит их за час. Новость в канале мессенджера
-- этого не решает: читают-то здесь.
--
-- Колонка — МОМЕНТ, а не флаг, и это не запас на будущее: закреплённых бывает
-- несколько, и порядок между ними обязан быть определён, иначе две заметки
-- меняются местами от перезапуска планировщика. Момент же отвечает на вопрос
-- «давно ли висит» — а закрепление, о котором забыли, ровно так и выглядит.
ALTER TABLE notes ADD COLUMN pinned_at timestamptz;

COMMENT ON COLUMN notes.pinned_at IS
    'когда заметку закрепили наверху ленты (NULL — обычная); кто и зачем — в audit_log';

-- Индекс частичный по той же причине, по которой частичен notes_feed:
-- закреплённых единицы, а таблица — 117 тысяч строк. Условие повторяет условие
-- ленты (status = 0), чтобы скрытая заметка не всплыла наверх из-за того, что
-- её когда-то закрепили.
CREATE INDEX notes_pinned ON notes (pinned_at DESC, id DESC)
    WHERE pinned_at IS NOT NULL AND status = 0;
