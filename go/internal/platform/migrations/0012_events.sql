-- Шина событий: журнал ФАКТОВ и ПОВОДЫ, по которым человеку о них говорят.
--
-- Раньше площадка не умела сказать человеку ничего. Подписки, которые есть,
-- живут в SQLite у ботов и знают только заметки НГС (store.subscriptions,
-- mirror.SubNotify); тому, кому ответили ЗДЕСЬ, не приходило ничего и никуда — а
-- с тех пор, как писать можно только здесь, это основной способ разговора.
--
-- Таблиц две, и делятся они по вопросу, а не по удобству:
--
--   events        — ЧТО случилось. Один раз на событие, append-only.
--   notifications — КОМУ это повод. Ноль, одна или несколько строк на событие.
--
-- Слить их в одну было бы соблазнительно ровно до первого правила адресации,
-- дающего двух получателей: пришлось бы либо дублировать факт, либо хранить
-- список людей в колонке. А раздельно факт остаётся фактом даже тогда, когда
-- повода не нашлось никому, — и именно он служит курсором живой странице,
-- которой адресаты не нужны вовсе.
--
-- ГЛАВНОЕ ПРАВИЛО, которое держит здесь устройство, а не дисциплина: в events
-- НЕТ НИ ОДНОЙ КОЛОНКИ СО СВОБОДНЫМ ТЕКСТОМ ОТ УЧАСТНИКА. Событие несёт ссылку
-- на публикацию, открытую всем и так, и наш собственный служебный текст в
-- details. Причина не в экономии места: обмен произвольными сообщениями между
-- людьми — это 149-ФЗ и реестр организаторов распространения информации
-- (хранение сообщений полгода, метаданных год, взаимодействие с органами), то
-- есть тяжелее всего 152-ФЗ вместе взятого. Одна новая колонка «текст» превратит
-- уведомления в личные сообщения незаметно для всех, включая того, кто её
-- добавит; отсутствие такой колонки делает это правкой, которую видно в diff.
CREATE TABLE events (
    id              bigserial PRIMARY KEY,
    kind            smallint NOT NULL,
    at              timestamptz NOT NULL DEFAULT now(),

    -- actor_id — кто сделал. NULL у машины (автоскрытие), у реакций и у
    -- анонимной заметки. Последние два — не забывчивость, а та же граница
    -- показа, что и в остальном ядре: класть настоящего автора туда, откуда его
    -- нельзя показывать, значит однажды его показать.
    actor_id        bigint REFERENCES users(id),
    -- subject_user_id — О КОМ факт: забаненный, автор скрытой реплики. У
    -- тредовых событий пусто, адресата там считают правила раздачи.
    subject_user_id bigint REFERENCES users(id),

    note_id         bigint REFERENCES notes(id)    ON DELETE CASCADE,
    comment_id      bigint REFERENCES comments(id) ON DELETE CASCADE,

    -- details — служебное и только наше: код реакции и их число, категория
    -- скрытия, срок запрета. См. правило в шапке.
    details         jsonb NOT NULL DEFAULT '{}',

    -- fanned_at — поводы разосланы. Отметкой на строке, а не отдельным
    -- курсором, по образцу moderation_queue.checked_at: так «сколько осталось»
    -- читается запросом, а не выводится из состояния чужого процесса.
    fanned_at       timestamptz
);

COMMENT ON TABLE events IS
    'журнал фактов площадки; поводы для людей — в notifications, аудит модератора — в audit_log';

-- Очередь раздачи. Частичный индекс, потому что нераздано всегда единицы строк,
-- а таблица растёт со скоростью разговора.
CREATE INDEX events_pending ON events (id) WHERE fanned_at IS NULL;

-- Поводы. Ключ (человек, факт) — он же идемпотентность раздачи: повторный
-- проход после обрыва не удвоит ни одной строки, и отдельная отметка
-- «разослано» для этого не нужна.
--
-- Отдельного id у строки нет намеренно. Порядок показа задаёт event_id, он
-- монотонный, и PK уже даёт индекс (user_id, event_id) — то есть страница
-- событий читается range-scan'ом по ключу, без единого лишнего индекса.
CREATE TABLE notifications (
    user_id    bigint NOT NULL REFERENCES users(id),
    event_id   bigint NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    -- reason — ПОЧЕМУ это его повод. Один факт бывает поводом по-разному
    -- («ответили лично» против «упомянули»), и человеку разница видна.
    reason     smallint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at    timestamptz,
    PRIMARY KEY (user_id, event_id)
);

COMMENT ON TABLE notifications IS
    'кому и по какому поводу; одна строка на человека и факт, порядок — по event_id';

-- Второй индекс поводов — по факту. Нужен дважды и оба раза обязателен: живой
-- странице (кому только что стало о чём сказать) и РЕТЕНЦИИ — внешний ключ сам
-- по себе индекса не заводит, и удаление старого события искало бы своих
-- потомков перебором всей таблицы.
CREATE INDEX notifications_event ON notifications (event_id);

-- Счётчик в шапке спрашивается на КАЖДОЙ странице вошедшего, поэтому у него
-- свой частичный индекс: непрочитанного у человека единицы, прочитанного за
-- месяц — тысячи, и count по всей его истории ради значка был бы платой на
-- ровном месте.
CREATE INDEX notifications_unread ON notifications (user_id) WHERE read_at IS NULL;

-- Реакции: отметка «о ней уже сказали».
--
-- Курсора у прохода по реакциям взять было неоткуда — ключ таблицы
-- (note_id, comment_id, user_id), монотонной колонки нет, а окно по created_at
-- пришлось бы делать идемпотентным вручную. Отметка на строке решает это тем же
-- способом, что и events.fanned_at, и заодно честно отвечает на вопрос «о чём
-- ещё не сказали». Снятая реакция (строку удаляют) до отметки не доживает — и
-- это правильно: говорить о том, что уже передумали, незачем.
ALTER TABLE reactions ADD COLUMN noticed_at timestamptz;

CREATE INDEX reactions_unnoticed ON reactions (note_id, comment_id) WHERE noticed_at IS NULL;

-- Уже стоящие реакции (их поставили до появления шины) отмечаем сразу: иначе
-- первый же проход разослал бы людям уведомления обо всём, что накопилось за
-- время, когда сказать было нечем. Это то же правило, что и `run -seed` у
-- зеркала — включение шины не должно начинаться со шквала.
UPDATE reactions SET noticed_at = now();
