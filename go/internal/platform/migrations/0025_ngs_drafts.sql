-- Заметка человека с галочкой «Отправлять на НГС» не заводится здесь вовсе
-- (02.09.2026, решение владельца: «если галка отправки стоит, то свою не
-- создаём, отправляем на НГС, а с НГС забираем как обычно»).
--
-- ЗАЧЕМ. До этого дня такая заметка выходила ДВАЖДЫ: нативной строкой здесь и
-- копией там, — и обе половины приходилось разводить руками. Эхо гасило
-- вернувшуюся копию, чтобы она не встала в ленту второй раз, а платой за это
-- был оборванный разговор: заметки для зеркала не существовало, значит и тред
-- её на сайте никто не опрашивал. Человек, ответивший на НГС, отвечал в пустоту.
--
-- Теперь копия ровно одна и живёт она на НГС, а сюда приезжает обычным зеркалом
-- — со своим тредом, со своими репликами, со своей дорогой в каналы. Ничего
-- нового для этого не нужно: так с первого дня работает `/add_note` у РюмкинЪа,
-- и веб-форма просто перестала быть исключением.
--
-- Следствие, названное вслух: заметка появляется здесь НЕ СРАЗУ. Такт очереди
-- выноса полминуты, обход ленты минуту — значит от «Опубликовать» до строки в
-- ленте проходит около полутора минут. Это цена, а не сбой.
CREATE TABLE ngs_drafts (
    id         bigserial PRIMARY KEY,
    author_id  bigint  NOT NULL REFERENCES users(id),
    -- Тело лежит ЗДЕСЬ, а не в notes: заметки ещё нет и может не быть вовсе.
    -- Строка эта — единственное место, где текст живёт между нажатием кнопки и
    -- появлением на сайте, поэтому терять её нельзя ни при каком отказе.
    body       text    NOT NULL,
    anonymous  boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- queued → sent | local. Третьего исхода нет намеренно: черновик обязан
    -- где-то опубликоваться. Не пустил сайт — публикуем здесь (local), и текст
    -- человека не пропадает. «Отказ» как конечное состояние означал бы заметку,
    -- которую написали, а её нигде нет.
    state      text    NOT NULL DEFAULT 'queued'
               CHECK (state IN ('queued', 'sent', 'local')),
    attempts   smallint NOT NULL DEFAULT 0,
    last_error text    NOT NULL DEFAULT '',
    -- Куда легло, если ушло сюда: id нативной заметки. У ушедшего на НГС пусто —
    -- номер там мы не знаем и знать не обязаны, заметку принесёт зеркало.
    note_id    bigint,
    sent_at    timestamptz
);

-- Очередь берут по времени и только ждущую — тот же приём и та же причина, что
-- у ngs_outbox: разобранное копится навсегда, а разбирают всегда голову.
CREATE INDEX ngs_drafts_queued ON ngs_drafts (created_at, id) WHERE state = 'queued';

-- По автору спрашивают ДВОЕ: потолок частоты (у такого человека нативных
-- заметок не бывает вовсе, и считать его темп больше не по чему) и страница
-- «Моя страница», где показывают ещё не доехавшие. Индекс поэтому не роскошь.
CREATE INDEX ngs_drafts_author ON ngs_drafts (author_id, created_at DESC);

COMMENT ON TABLE ngs_drafts IS 'заметки, которые публикуются НА НГС вместо площадки: у автора стоит галочка ngs_send, а сюда их приносит зеркало';
