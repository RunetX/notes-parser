-- Потолок вложенности: 12 УРОВНЕЙ, то есть depth <= 12.
--
-- В v1 ограничение было записано как depth < 12, а это одиннадцать уровней:
-- глубина считается от единицы (корневой комментарий — 1), и строгая граница
-- срезала ровно тот уровень, который ClampParent считает последним разрешённым.
-- Расхождение поймал интеграционный тест на ветке глубже потолка — из живого
-- зеркала оно вылезло бы отказом приёма единственного комментария в редком
-- глубоком треде, то есть тихой дырой в архиве.
--
-- 12 уровней выбраны не наугад: на НГС наблюдалось максимум 7, а 12 сегментов
-- по 13 знаков с разделителями — это 167 байт пути, потолок для индекса.

ALTER TABLE comments DROP CONSTRAINT comments_depth;
ALTER TABLE comments ADD CONSTRAINT comments_depth CHECK (depth >= 0 AND depth <= 12);
