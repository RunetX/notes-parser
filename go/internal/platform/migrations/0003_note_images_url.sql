-- Иллюстрация заметки опознаётся по ССЫЛКЕ, а не по позиции.
--
-- Причина в том, что писателей у note_images двое и позиции они считают
-- по-разному: живое зеркало отдаёт картинки по одной и порядкового номера не
-- знает вовсе (в mirror.Sink его нет), а сверка приходит со своим номером из
-- lovegw.db. Без этого индекса одна и та же картинка ложилась бы дважды —
-- сначала под номером сверки, потом под следующим свободным.
--
-- position при этом остаётся: он задаёт порядок показа, а ключ — ссылка.
CREATE UNIQUE INDEX note_images_url ON note_images (note_id, url);
