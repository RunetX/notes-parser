-- Ш5, запись: участник пишет у нас, и написанное здесь живёт в ОДНОМ треде с
-- зеркальным. Разделяет их полоса id, а не колонка (см. шапку 0001_init.sql),
-- поэтому ни `source`, ни `external_id` тут не появляется и теперь.
--
-- Схеме для записи не хватало трёх вещей.

-- 1. СВОЙ замок треда.
--
-- Зеркальный comments_closed — это ЧУЖАЯ отметка «не актуальна», и запирать ею
-- разговор у нас нельзя. Замер 18.08.2026 по боевому зеркалу: отметка стоит у
-- 177 заметок из 285, и в них лежат 45 695 комментариев из 61 177 — гейт по ней
-- открыл бы площадку в режиме чтения ровно там, где идёт разговор. Вдобавок сайт
-- ставит её через минуты после публикации, пока реплики продолжают приходить
-- (это же правило запрещает ей управлять архивацией зеркала), то есть как
-- признак «тред закончился» она недостоверна и на самом НГС.
--
-- Поэтому отметка остаётся НАДПИСЬЮ на странице — она перенесена с сайта и
-- часть узнаваемости, — а запрет писать живёт отдельным полем, и ставит его наш
-- модератор.
ALTER TABLE notes ADD COLUMN locked boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN notes.locked IS
    'тред закрыт НАШИМ модератором; comments_closed — чужая отметка НГС «не актуальна», писать она не запрещает';

-- 2. Ник, выбранный У НАС.
--
-- Опубликованный текст согласия обещает «ник вы меняете сами», и обещание надо
-- чем-то удержать: вход по анкете переписывает ник из НГС при каждом заходе, и
-- без этого флага выбранное здесь имя затиралось бы молча. Зеркала это не
-- касается — ensureShadow правит только тени, — а вот входа касается.
ALTER TABLE users ADD COLUMN nick_custom boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN users.nick_custom IS
    'ник выбран на площадке: вход по анкете НГС его больше не переписывает';

-- 3. Очередь проверки публикаций.
--
-- Классификатор — это Ш7, здесь только крючок, и он ставится сейчас по одной
-- причине: задача заводится В ТОЙ ЖЕ транзакции, что и сама публикация. Значит
-- «опубликовано, но в очередь не попало» — состояние, которого не бывает, а не
-- редкая гонка, которую потом чинят бэкфиллом.
--
-- verdict NULL означает «ещё не смотрели». Причина и цитата хранятся вместе с
-- моделью и версией промпта: через месяц «за что скрыли» должно быть ответимо,
-- а без версии промпта решение невоспроизводимо.
CREATE TABLE moderation_queue (
    subject_kind text   NOT NULL,          -- 'note' | 'comment'
    subject_id   bigint NOT NULL,
    author_id    bigint REFERENCES users(id),
    queued_at    timestamptz NOT NULL DEFAULT now(),
    checked_at   timestamptz,
    verdict      smallint,                 -- 0 чисто, 1 человеку, 2 скрыто автоматом
    category     text NOT NULL DEFAULT '',
    model        text NOT NULL DEFAULT '',
    prompt_sha   bytea,
    reason       text NOT NULL DEFAULT '',
    quote        text NOT NULL DEFAULT '',
    appealed_at  timestamptz,              -- автор попросил пересмотра
    PRIMARY KEY (subject_kind, subject_id)
);
COMMENT ON TABLE moderation_queue IS
    'очередь проверки публикаций; строка заводится в одной транзакции с самой публикацией';
COMMENT ON COLUMN moderation_queue.verdict IS '0 чисто, 1 в очередь человеку, 2 скрыто автоматом; NULL — не проверялось';

CREATE INDEX moderation_pending ON moderation_queue (queued_at) WHERE checked_at IS NULL;
CREATE INDEX moderation_appeals ON moderation_queue (appealed_at) WHERE appealed_at IS NOT NULL;

-- Ограничение частоты считает НАТИВНЫЕ публикации автора за окно. Индекс
-- notes_author для этого не годится: он частичный (WHERE status = 0), то есть
-- скрытая заметка из счёта выпала бы — и «скрой свою и пиши заново» обходило бы
-- лимит. У комментариев такой индекс уже есть полным (comments_author).
CREATE INDEX notes_author_all ON notes (author_id, id DESC);
