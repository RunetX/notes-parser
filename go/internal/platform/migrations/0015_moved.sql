-- Переехавшая реплика: страница обязана узнать, что дерево перестроили.
--
-- Живой канал умеет только ДОПИСЫВАТЬ: курсор идёт по id, и реплика, у которой
-- id не изменился, назад не приезжает никогда. А дерево под открытой страницей
-- перестраивается регулярно — зеркало знает адресата лишь по обращению «Ник, …»
-- и угадывает его примерно с половинной точностью, настоящее ребро приносит
-- обход мобильной версии (platsink.ReplyScanner, такт минуту).
--
-- Замер 23.08.2026, заметка 313058: Kowalski 63238879 был нарисован страницей на
-- глубине 4 (угаданный адресат — последняя реплика Аматы), обход переставил его
-- на глубину 2, и следующая же строка треда, его собственный ответ 63238886,
-- приехала с глубиной 3 — то есть МЕНЬШЕ, чем у родителя строкой выше. Читатель
-- видит разорванную ветку, а обновление страницы показывает правильную.
--
-- Отсюда отметка на строке: «эта реплика переехала или её тело переписано
-- приёмом». По ней добор досылает такую строку второй раз, а страница ставит её
-- на новое место. Время, а не счётчик: пара «время, id» упорядочивает переезды
-- однозначно (одна транзакция обхода штампует все свои строки одним now()), и
-- в psql её видно глазами — при разборе жалобы это дороже экономии восьми байт.
--
-- Индекс ЧАСТИЧНЫЙ, и это тот редкий случай, когда экономия настоящая: переезды
-- случаются у долей процента строк, а спрашивает их каждое открытое окно на
-- каждый такт. Порядок колонок — вход запроса: заметка, потом пара курсора.
--
-- ВНИМАНИЕ, время постройки: сама колонка добавляется мгновенно (NULL по
-- умолчанию — правка метаданных), а вот CREATE INDEX обязан прочитать всю
-- таблицу, чтобы убедиться, что подходящих строк нет. На боевых 10,7 млн строк
-- это единицы минут с блокировкой записи, как у 0011 и 0014: накатывать в
-- известный момент и ДО подъёма нового образа.
ALTER TABLE comments ADD COLUMN moved_at timestamptz;

CREATE INDEX comments_moved ON comments (note_id, moved_at, id)
    WHERE moved_at IS NOT NULL;
