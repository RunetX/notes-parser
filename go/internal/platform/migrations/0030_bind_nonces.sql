-- Привязка мессенджера как способ вернуть вход (11.09.2026).
--
-- ПОВОД. Дверей на площадку три, и две из них доказывают право одним и тем же —
-- живой анкетой на love.ngs.ru: код в поле «о себе» читает её страницу, ссылка
-- из бота держится на сессии сайта, которую бот хранит. Анкету можно удалить,
-- потерять или лишиться её вместе с самим сайтом — и тогда у человека остаётся
-- одно приглашение, которое выдаёт администратор. Владелец площадки в этом
-- положении уже находится: своей анкеты у него нет с 10.09.2026, сессия
-- площадки живёт до середины ноября и не продлевается.
--
-- Мессенджер такой зависимости не имеет: бот узнаёт собеседника в ЛИЧНОМ
-- разговоре, и это доказательство не зависит от чужого сайта вовсе.
--
-- Колонка purpose нужна ровно затем, чтобы два ключа не ходили по одной дороге.
-- В таблице теперь живут две разные вещи:
--
--   login — ключ ВХОДА. Рождается у бота (БОТ → ЧЕЛОВЕК → ПЛОЩАДКА), потому что
--           назначает, КОГО впустить, и подсунуть его нечего: он рождается в
--           разговоре с тем, кто его получит.
--   bind  — ключ ПРИВЯЗКИ. Рождается НАОБОРОТ, в живой сессии на площадке
--           (ПЛОЩАДКА → ЧЕЛОВЕК → БОТ), потому что назначает, К КАКОЙ УЧЁТНОЙ
--           ЗАПИСИ прицепить мессенджер. Родись он у бота — злоумышленник
--           подсунул бы жертве ключ со своим messenger_user_id, и его
--           мессенджер стал бы вечной отмычкой к её записи.
--
-- Правило у обоих одно и то же, просто читать его надо точно: ключ рождается
-- там, где сидит тот, кого он назначает.
--
-- Без этой колонки они мешали бы друг другу на ровном месте: StartBotLogin
-- гасит прежние ключи человека одним DELETE по user_id, и начатая привязка
-- умирала бы от того, что человек тем временем попросил ссылку входа.
ALTER TABLE login_nonces ADD COLUMN purpose text NOT NULL DEFAULT 'login';

COMMENT ON COLUMN login_nonces.purpose IS 'login — ключ входа (рождается у бота); bind — ключ привязки (рождается в сессии на площадке)';
COMMENT ON COLUMN login_nonces.messenger_user_id IS 'у ключа входа — кому его выдали; у ключа привязки пусто до тех пор, пока бот его не погасит';

-- Способ доказательства у привязки свой, и список в комментарии схемы (0001)
-- про него не знал: там перечислены 'profile_code' | 'talks_code' |
-- 'bot_deeplink' | 'admin_invite'. Схема обязана описывать себя сама — иначе
-- через полгода значение в колонке придётся опознавать по коду.
COMMENT ON COLUMN identities.method IS 'profile_code | bot_deeplink | admin_invite | messenger_bind (talks_code умер вместе с каналом лички 01.09.2026)';
COMMENT ON COLUMN identities.kind IS 'ngs_profile | invite | telegram | max — последние две заводит привязка мессенджера (11.09.2026)';

-- ЧЕМ ДОКАЗАНО ПРАВО — вторая колонка, и она не про породу ключа, а про его
-- происхождение. Ключ ВХОДА рождается двумя разными дорогами, и завершать его
-- надо по-разному:
--
--   bot_deeplink   — право доказано ЖИВОЙ СЕССИЕЙ НГС, которую держит бот.
--                    Это и есть обряд анкеты: тень становится участником,
--                    возраст снимается, в identities встаёт ngs_profile.
--   messenger_bind — право доказано ПРИВЯЗКОЙ. Обряда анкеты здесь быть не
--                    должно вовсе: анкеты у человека может не быть никогда (он
--                    пришёл по приглашению), а записать ему ngs_profile значило
--                    бы засвидетельствовать владение тем, чего он не показывал.
--
-- Различать это ПОЛОСОЙ идентификатора нельзя, хотя соблазнительно: полоса
-- отвечает на вопрос «откуда запись», а не «чем доказано право», и проект уже
-- четырежды обжигался на выводах из неё (см. id-band-order-breaks-cursors).
-- Вдобавок по привязке входит и человек С номером НГС — владелец площадки
-- ровно таков, — и полоса назвала бы его дорогу анкетной.
ALTER TABLE login_nonces ADD COLUMN method text NOT NULL DEFAULT 'bot_deeplink';

COMMENT ON COLUMN login_nonces.method IS 'bot_deeplink — право доказано сессией НГС у бота; messenger_bind — привязанным мессенджером. У ключа привязки (purpose=bind) не читается вовсе';
