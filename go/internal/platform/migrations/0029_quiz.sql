-- Пятничный вопрос: комментарий, у которого есть варианты ответа.
--
-- Рубрика площадки (эпик J): вечером в пятницу под вступительной заметкой
-- появляются вопросы из архива — «в каком году это написано», «сколько реплик
-- собрала заметка», «что ответили на эту реплику», — а люди жмут вариант и
-- спорят репликами тут же. Смысл рубрики не в игре как таковой: под площадкой
-- лежит 117 тысяч заметок и 10,7 млн реплик, до середины ленты идти пять тысяч
-- страниц, и в архив не заходит никто. Вопрос — способ доставать оттуда по
-- горсти и возвращать людям их же разговоры.
--
-- ВОПРОС — ЭТО НАДСТРОЙКА НАД ОБЫЧНЫМ КОММЕНТАРИЕМ, а не новый вид записи, и
-- это главное решение схемы. Текст вопроса живёт в `comments.body` как у всех,
-- а здесь лежит только то, чего у обычной реплики нет: варианты, правильный и
-- разгадка. Отсюда три вещи достаются даром, и все три пришлось бы иначе
-- писать заново: `platout` унесёт в канал читаемый текст, живой добор нарисует
-- строку тем же `parts/comment.gohtml`, а дерево, модерация и обезличивание
-- работают с ней как с любой другой репликой. Второго пути рендера не
-- заводится — то самое правило, которым держится `fresh.go`.

CREATE TABLE quiz_questions (
    -- Ключ — сам комментарий: вопрос не существует отдельно от реплики, в
    -- которой он задан, и своего идентификатора ему не нужно.
    comment_id  bigint      PRIMARY KEY REFERENCES comments(id) ON DELETE CASCADE,
    -- note_id стоит ВСЕГДА, по тому же доводу, что у реакций (0008): страница
    -- треда собирает все вопросы одним range-scan, а не запросом на реплику.
    note_id     bigint      NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    -- Варианты массивом, а не своей таблицей: их два-пять, они неизменны после
    -- публикации, и join ради трёх строк — это join на каждой странице треда.
    options     text[]      NOT NULL,
    right_idx   smallint    NOT NULL,
    -- reveal — что сказать после ответа: дата, число реплик, чем дело
    -- кончилось. Хранится ЗДЕСЬ, а не в теле комментария, ровно потому, что до
    -- ответа его показывать нельзя, а тело показывается всегда и всем.
    reveal      text        NOT NULL DEFAULT '',
    -- source_note — заметка архива, из которой взят материал: ссылка «дочитать
    -- разговор целиком» и есть половина смысла рубрики. Без REFERENCES
    -- намеренно: заметку может снести модерация, и вопрос от этого не портится,
    -- он просто теряет ссылку.
    source_note bigint,
    created_at  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT quiz_options_sane CHECK (array_length(options, 1) BETWEEN 2 AND 5),
    CONSTRAINT quiz_right_in_range CHECK (right_idx >= 0 AND right_idx < array_length(options, 1))
);

COMMENT ON TABLE quiz_questions IS
    'пятничный вопрос: варианты и разгадка для комментария, который их задаёт';

CREATE INDEX quiz_questions_note ON quiz_questions (note_id);

-- Голоса. Устройство списано с реакций (0008) вплоть до формы ограничения, и
-- различие ровно одно: реакцию МЕНЯЮТ и СНИМАЮТ, а ответ на вопрос — нет.
-- Ответил — ответил; иначе после разгадки каждый оказался бы прав, а проценты
-- под вопросом перестали бы что-либо значить.
CREATE TABLE quiz_votes (
    comment_id bigint      NOT NULL REFERENCES quiz_questions(comment_id) ON DELETE CASCADE,
    -- note_id денормализован по тому же доводу, что и в quiz_questions: счёт
    -- для всей страницы берётся одним запросом.
    note_id    bigint      NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    user_id    bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    choice     smallint    NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT quiz_votes_one UNIQUE (comment_id, user_id)
);

COMMENT ON TABLE quiz_votes IS
    'ответы на пятничные вопросы; кто как ответил — наружу не показывается, только счётчик';

-- Всё, что нужно странице треда: ответы на все вопросы заметки разом.
CREATE INDEX quiz_votes_note ON quiz_votes (note_id);

-- Выпуск недели: вступительная заметка рубрики.
--
-- Ключ — НЕДЕЛЯ, и в этом вся однократность, ровно как у `morning_notes` с его
-- ключом-днём: строка заводится через ON CONFLICT DO NOTHING, поэтому ни второй
-- проход службы, ни рестарт, ни ручной прогон команды второй заметки не дадут.
-- Отдельной проверки «а не публиковали ли уже» не нужно вовсе.
--
-- Сколько вопросов уже задано, здесь НЕ хранится: это считается по
-- quiz_questions той же заметки. Счётчик рядом с фактом разошёлся бы с ним на
-- первом же откате транзакции.
CREATE TABLE friday_issues (
    week       text        PRIMARY KEY,
    note_id    bigint      NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE friday_issues IS
    'вступительные заметки пятничной рубрики; ключ-неделя и есть её однократность';
