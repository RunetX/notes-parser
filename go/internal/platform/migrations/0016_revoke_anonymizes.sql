-- Отзыв согласия обезличивает заметки, а не прячет публикации.
--
-- До 25.08.2026 отзыв согласия на распространение поднимал рубильник
-- users.hide_all и уводил ВСЕ публикации человека в статус 1 («скрыл автор»).
-- Цену этого площадка сама себе запретила в других местах: скрытая заметка
-- уносит со страниц весь тред, то есть чужие ответы на чужие слова. Ровно этим
-- доводом обоснованы «модератор скрывает, а не удаляет» и «обезличивание
-- переносит публикации, а не стирает их»; отзыв был единственным исключением.
--
-- Решение владельца: уходит не текст, а ИМЯ. Заметки переезжают на безымянную
-- могилу и остаются на виду (platform.anonymizeOwnNotes), комментарии не
-- трогаются вовсе. Значит рубильника больше нет — ни как поведения, ни как
-- колонки: колонка, которую никто не поднимает, через полгода читается как
-- «фича, про которую забыли», и кто-нибудь честно попробует ею воспользоваться.
--
-- Что делает эта миграция:
--   1. применяет новое правило к тем, кто скрыт ПРЯМО СЕЙЧАС: их заметки — на
--      могилу, а весь материал — обратно на вид;
--   2. снимает обе колонки рубильника.
--
-- Про стоимость. У кого не было ни одного отзыва — а это наиболее вероятное
-- состояние — миграция вырождается в один ALTER и идёт мгновенно. Если отзывы
-- были, объём равен числу публикаций этих людей, и идут они по индексам
-- comments_author и notes_author_all, а не перебором таблицы на 10,7 млн строк.
-- Накатывать, как заведено, в известный момент и ДО подъёма нового образа.

DO $$
DECLARE
    r     record;
    grave bigint;
    ids   bigint[];
BEGIN
    -- Оба флага, а не один: hide_all — «сейчас скрыт», visibility_dirty —
    -- «проход не доведён». У второго направление могло быть и обратным
    -- (человек вернул согласие, а хвост не успел подняться), и заметки такому
    -- обезличивать нельзя — согласие у него действует.
    FOR r IN SELECT id, hide_all FROM users WHERE hide_all OR visibility_dirty LOOP
        -- Комментарии возвращаются на вид ВСЕГДА и остаются за автором:
        -- обезличивание их не касается. Счётчик правится той же командой —
        -- разойдясь, он показал бы под заметкой «Комментарии 40» при сорока
        -- двух видимых (тот же приём, что был у sweepComments).
        WITH back AS (
            UPDATE comments SET status = 0
             WHERE author_id = r.id AND status = 1
            RETURNING note_id
        ), touched AS (
            SELECT note_id, count(*) AS n FROM back GROUP BY note_id
        )
        UPDATE notes n SET comment_count = n.comment_count + t.n
          FROM touched t WHERE n.id = t.note_id;

        IF NOT r.hide_all THEN
            -- Возврат, не доведённый до конца: просто поднимаем заметки.
            UPDATE notes SET status = 0 WHERE author_id = r.id AND status = 1;
            CONTINUE;
        END IF;
        IF NOT EXISTS (SELECT 1 FROM notes WHERE author_id = r.id) THEN
            CONTINUE; -- отзывать нечего, пустую могилу не заводим
        END IF;

        -- Могила — то же, что делает platform.newGrave: нативный id, ник
        -- GraveNick, время огрублено до суток (точное now() совпало бы с
        -- consents.revoked_at и записало бы соответствие «кто → какая могила»
        -- метками времени). Ник здесь написан буквой: SQL до констант Go не
        -- дотягивается, а миграция разовая.
        INSERT INTO users (id, nick, kind, created_at, anonymized_at)
        VALUES (nextval('users_native_seq'), 'Удалённый участник', 0,
                date_trunc('day', now()), date_trunc('day', now()))
        RETURNING id INTO grave;

        -- Переезд и возврат на вид одной командой: порознь второй запрос уже
        -- не нашёл бы этих строк — автор у них к тому моменту другой.
        WITH moved AS (
            UPDATE notes
               SET author_id = grave,
                   status = CASE WHEN status = 1 THEN 0 ELSE status END
             WHERE author_id = r.id
            RETURNING id
        )
        SELECT coalesce(array_agg(id), '{}') INTO ids FROM moved;

        -- Карточки проверки едут следом, иначе очередь модератора продолжала бы
        -- показывать, чья это заметка. Комментарии в очереди остаются его.
        UPDATE moderation_queue SET author_id = grave
         WHERE author_id = r.id AND subject_kind = 'note';

        -- Шина: чистится ровно то, что связывает ЕГО с этими заметками.
        -- comment_id IS NULL обязательно — события про реплики в его теме
        -- принадлежат другим людям и их поводам.
        DELETE FROM notifications
         WHERE user_id = r.id
           AND event_id IN (SELECT id FROM events WHERE note_id = ANY(ids));
        DELETE FROM events
         WHERE note_id = ANY(ids) AND comment_id IS NULL
           AND (actor_id = r.id OR subject_user_id = r.id);
    END LOOP;

    -- Проверка перед сносом рубильника: под ним не должно остаться ни одной
    -- строки, иначе она станет невидимой навсегда — рычага возврата больше нет.
    --
    -- Спрашиваем только notes (117 тыс. строк, доли секунды). Комментарии не
    -- спрашиваем не из лени: статус 1 ставил ИМ только проход по автору с
    -- поднятым рубильником, а проход помечал автора флагом в той же транзакции,
    -- что и сам отзыв, и снимал флаг лишь дойдя до конца. Значит всех таких
    -- авторов мы только что обошли, а перебор таблицы на 10,7 млн строк ради
    -- перепроверки этого рассуждения стоил бы минут блокировки.
    IF EXISTS (SELECT 1 FROM notes WHERE status = 1) THEN
        RAISE EXCEPTION 'остались заметки в статусе «скрыл автор»: рубильник снимать нельзя';
    END IF;
END $$;

ALTER TABLE users DROP COLUMN hide_all, DROP COLUMN visibility_dirty;
