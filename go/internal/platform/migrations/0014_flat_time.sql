-- Линейный вид треда упорядочивается ПО ВРЕМЕНИ, а не по идентификатору.
--
-- «Сначала новые» на НГС и у нас значило «по убыванию id», и это работало ровно
-- до тех пор, пока в треде жила одна полоса. Своё и зеркальное живут в ОДНОМ
-- разговоре (эпик E), а полосы упорядочены по происхождению, а не по времени:
-- реплика, написанная здесь 18.08, имеет номер больше комментария, пришедшего с
-- НГС сегодня. Линейный вид поэтому показывал сверху все нативные реплики, а
-- самый свежий ответ с сайта уезжал под них — тем сильнее, чем больше здесь
-- пишут.
--
-- Индекс СПЛОШНОЙ, не частичный по status: в отличие от индексов дайджеста
-- (0011), скрытых строк тут доли процента, и экономии бы не вышло, а модератору
-- его же линейный вид (статусы 0 и 2) достался бы сортировкой всего треда.
--
-- id третьей колонкой — ради постранички: у OFFSET порядок обязан быть
-- однозначным, иначе две реплики одной секунды разъезжаются между страницами.
--
-- ВНИМАНИЕ, время постройки — то же, что у 0011: на боевых 10,7 млн строк это
-- единицы минут, и всё это время CREATE INDEX держит на comments блокировку, при
-- которой запись в таблицу ждёт (чтение — нет). Накатывать в известный момент,
-- как и заведено; приём зеркала на эти минуты встанет и нагонит сам. Вес — около
-- полугигабайта: (note_id, published_at, id) на 10,7 млн строк.
CREATE INDEX comments_flat_time ON comments (note_id, published_at, id);
