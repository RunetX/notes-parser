-- Реакции: короткий ответ, на который иначе уходит целая реплика.
--
-- Это НОВАЯ вещь, а не перенос с НГС, и врать себе тут не надо. Замер
-- 18.08.2026 по 1 642 652 комментариям выгрузок: смайл на сайте жил ВНУТРИ
-- реплики (22 948 комментариев со смайлом), а отдельным сообщением почти не
-- бывал — ровно 66 реплик состоят из одного кода и ничего больше. Кнопки
-- «нравится» на сайте не было вовсе, и эпик E её не заводил намеренно.
-- Решение владельца 18.08.2026: в 2026-м отдельное сообщение ради смайла
-- избыточно — значит нужны реакции.
--
-- Показываются они смайлами САМОГО НГС (web/smiles.go): набор перенесён с
-- сайта, узнаётся здешними людьми и не требует заводить ещё один язык знаков.

CREATE TABLE reactions (
    -- note_id стоит ВСЕГДА, даже у реакции на комментарий, и это не
    -- избыточность: страница треда собирает все реакции одним range-scan по
    -- этому индексу, а не запросом на каждую из девятисот реплик.
    note_id    bigint      NOT NULL REFERENCES notes(id)    ON DELETE CASCADE,
    -- NULL — реакция на саму заметку. Отдельной колонки «вид объекта» нет:
    -- у заметки и комментария разные таблицы, и NULL здесь читается однозначно.
    comment_id bigint               REFERENCES comments(id) ON DELETE CASCADE,
    user_id    bigint      NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
    code       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),

    -- Одна реакция на человека на объект: нажатие другой кнопки МЕНЯЕТ её, а не
    -- добавляет вторую. NULLS NOT DISTINCT — потому что comment_id у реакции на
    -- заметку пуст, а по умолчанию Postgres считал бы такие строки разными и
    -- позволил бы поставить их сколько угодно.
    CONSTRAINT reactions_one UNIQUE NULLS NOT DISTINCT (note_id, comment_id, user_id)
);

COMMENT ON TABLE reactions IS
    'реакции участников; comment_id NULL — реакция на саму заметку, note_id стоит всегда';

-- Всё, что нужно странице треда: реакции заметки и всех её комментариев разом.
CREATE INDEX reactions_note ON reactions (note_id);

-- Частота реакций считается по этому индексу (см. platform/reactions.go).
CREATE INDEX reactions_user_time ON reactions (user_id, created_at DESC);
