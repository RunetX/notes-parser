-- Служебная анкета САМОЙ ПЛОЩАДКИ: под ней выходит недельный выпуск.
--
-- До 05.09.2026 выпуск подписывал ВЛАДЕЛЕЦ своей анкетой НГС, и это дало
-- дефект, который настройкой не чинится: у человека стоит галочка «отправлять
-- мои записи на НГС», и сводка про Зазеркалье уехала заметкой на love.ngs.ru
-- (313176, 05.09.2026) под его именем. Дефект не в галочке — она работала ровно
-- как обещано. Дефект в подписи: выпуск пишет не человек, а ПЛОЩАДКА, спрашивать
-- за него надо с оператора, и подпись у него обязана быть своя.
--
-- Саму строку заводит `platform migrate` (EnsureSystemUser), а не эта миграция,
-- и это то же разделение, что у текстов согласий: схему меняет SQL, содержимое
-- кладёт Go. Ник площадки живёт ОДНОЙ константой в коде (web.SiteName), и второе
-- его написание здесь разошлось бы с первым молча.
--
-- Индекс держит ЕДИНСТВЕННОСТЬ, и держит её база, а не порядок вызовов, — как у
-- двойника заметки (notes_synth_of). Два `migrate` подряд, два администратора
-- разом, накат дампа поверх живой базы: во всех трёх случаях вторая служебная
-- анкета получит отказ, а не заведётся тихо, после чего «под кем выходит
-- выпуск» стало бы вопросом с двумя ответами.
--
-- Уникальность по САМОЙ КОЛОНКЕ при частичном условии `kind = 2` и означает «не
-- больше одной такой строки». Индекс частичный, поэтому в нём ровно одна запись
-- из сотен тысяч и стоит он ничего. Число 2 — platform.KindService; словами
-- «служебный» оно названо в комментарии к колонке ещё в 0001.
CREATE UNIQUE INDEX IF NOT EXISTS users_system ON users (kind) WHERE kind = 2;

COMMENT ON INDEX users_system IS 'служебная анкета площадки одна: под ней выходит выпуск дайджеста';
