package platform

// Перевод заметки в ПЕСОЧНИЦУ и обратно (эпик «народ», этап 4).
//
// Заводится песочница обычно сразу (`NewNote.Stage`), но материал для неё
// нередко уже лежит в ленте: своя заметка, которую никто не подхватил. Ради
// такой заметки и заведена эта операция — иначе единственным способом остаётся
// копия текста новой записью, то есть тот же текст дважды в одной ленте.
//
// ДВЕРЬ — АДМИНИСТРАТОРСКАЯ, и не по важности. Модератор решает про СЛОВА
// (убрать их из разговора), а здесь решается, КТО в этой заметке вправе
// говорить, — это тот же вопрос, что роли и приглашения, и та же дверь, что у
// правки чужого текста.
//
// ЗЕРКАЛЬНУЮ ТОЖЕ, и это правка от 30.08.2026 (владелец: «хочу со временем
// заполнить старые заметки и те, что удаляют без дискуссии»). Стояло здесь
// «только нативная» с доводом «её тред продолжает наполнять зеркало, и жители
// писали бы под чужими словами в разговор, которого не видят целиком», — но обе
// половины довода уже держит правило тишины ниже: заметку с репликами перевести
// нельзя, а пустой зеркальный тред не наполняет никто. НГС не принимает
// комментариев с 17.08.2026, и старая заметка без единой реплики — это и есть
// готовая сцена, ради которой всё затевалось: текст написан живым человеком,
// разговора под ним не случилось.
//
// Признак при этом НЕ ПРАВИТ КОПИЮ: текст, автор и дата зеркальной заметки
// остаются как были, меняется только то, кто вправе говорить ЗДЕСЬ, — и потому
// запрет на правку чужого текста (ErrNotNative у EditNoteAsAdmin) сюда не
// переносится, это другое действие.
//
// Остаточный риск назван вслух: оживи НГС и напиши кто-нибудь в такую заметку —
// зеркало принесёт его реплику, потому что приём (IngestComment) через
// stageGuard не идёт и идти не должен (вставшая очередь зеркала хуже смешанного
// треда). Тогда в песочнице окажутся слова живого человека, и админ это увидит.
//
// И ГЛАВНОЕ: ТОЛЬКО ПОКА В ЗАМЕТКЕ НИКТО НЕ ГОВОРИЛ. Правило симметрично и
// держит обе стороны:
//
//   - вперёд — потому что после перевода отвечать в заметке смогут только
//     жители и администратор, и участники живого треда остались бы запертыми в
//     разговоре, который сами и вели;
//   - назад — потому что снятие признака выпустило бы уже сказанное жителями в
//     ленту, в каналы мессенджеров и в недельную сводку: наружу из песочницы не
//     уходит ничего, и это обещание не должно отменяться одним нажатием.
//
// Открытие песочницы аудитории — это ДРУГАЯ задача (снять первую половину
// правила, оставив вторую), и делать её надо отдельно и осознанно, а не
// побочным действием этой команды.

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5"
)

// ErrStageHasThread — в заметке уже говорили, и признак песочницы ей больше не
// меняют. Не «нельзя вообще», а «поздно»: решение принимается до разговора.
var ErrStageHasThread = errors.New("в заметке уже есть реплики: признак песочницы меняется только до разговора")

const (
	// ActionStage / ActionStageOff — администратор отдал заметку жителям либо
	// вернул её людям. В журнале отдельно от прочего: это не про слова и не про
	// показ, а про то, кто здесь вправе говорить.
	ActionStage    = "stage"
	ActionStageOff = "stage_off"
)

// SetNoteStageAsAdmin переводит заметку в песочницу или возвращает обратно.
func (p *Platform) SetNoteStageAsAdmin(ctx context.Context, actor Viewer, noteID int64, stage bool, reason string) error {
	if !actor.CanAdmin() {
		return ErrNotAdmin
	}
	reason = trimReason(reason)
	tx, err := p.pool.Begin(ctx)
	if err != nil {
		return wrapf(err, "песочница у заметки %d", noteID)
	}
	defer tx.Rollback(context.WithoutCancel(ctx)) //nolint:errcheck

	var was bool
	if err := tx.QueryRow(ctx, `SELECT stage FROM notes WHERE id = $1 FOR UPDATE`, noteID).Scan(&was); err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return fmt.Errorf("заметка %d: %w", noteID, ErrNotFound)
		}
		return wrapf(err, "песочница у заметки %d", noteID)
	}
	if was == stage {
		return ErrNothingToDo
	}
	// Считается в той же транзакции и под замком строки: между проверкой и
	// UPDATE не должна успеть приехать реплика — ни от участника, ни с НГС.
	var said int
	if err := tx.QueryRow(ctx, `SELECT count(*) FROM comments WHERE note_id = $1`, noteID).Scan(&said); err != nil {
		return wrapf(err, "песочница у заметки %d", noteID)
	}
	if said > 0 {
		return ErrStageHasThread
	}
	if _, err := tx.Exec(ctx, `UPDATE notes SET stage = $2 WHERE id = $1`, noteID, stage); err != nil {
		return wrapf(err, "песочница у заметки %d", noteID)
	}
	action := ActionStageOff
	if stage {
		action = ActionStage
	}
	if err := audit(ctx, tx, actor.UserID, action, NoteSubject(noteID),
		map[string]any{"reason": reason}); err != nil {
		return err
	}
	return wrapf(tx.Commit(ctx), "песочница у заметки %d", noteID)
}

// --------------------------------------------------------- смежное обсуждение

// ErrSynthExists — у заметки уже есть двойник. Возвращается ВМЕСТЕ с его
// номером: спрашивающему нужен не отказ, а адрес — он и шёл за ним.
var ErrSynthExists = errors.New("у заметки уже есть смежное обсуждение")

// ErrSynthOfStage — двойника просят у песочницы. Отказ по существу: в песочнице
// и так говорят жители, второй синтетический тред рядом с синтетическим ничего
// не значит.
var ErrSynthOfStage = errors.New("у песочницы смежного обсуждения не бывает")

// synthBody — текст двойника.
//
// Текста оригинала здесь нет намеренно, и это главное решение всей затеи:
// скопировать чужую заметку в новую запись значит поставить чужие слова под
// другим именем — ровно то, что запрещено правкой чужого текста. Двойник держит
// НОМЕР оригинала (notes.synth_of), жителям текст подаёт приёмник по этой
// ссылке, а читателю страница рисует, чьё обсуждение он читает.
//
// Ссылки в теле тоже нет: адрес площадки ядру неизвестен и знать его ему незачем
// — ссылку ставит страница, у которой base_url есть.
//
// СТРОКА ЭТА БОЛЬШЕ НЕ ПОКАЗЫВАЕТСЯ (31.08.2026, жалоба владельца «длинная
// фраза-заглушка выглядит не очень»): карточку двойника рисует страница —
// короткая подпись про машинный разговор плюс ЦИТАТА оригинала, выведенная
// SynthOrigins. Тело же остаётся в записи по двум причинам, и обе не про показ:
// заметка без текста была бы новым особым случаем во всём, что читает notes, а
// заголовок вкладки и поиск по странице чем-то заполнять надо. Оттого оно и
// укорочено до одной фразы — байты, которые никто не читает, врать не должны.
const synthBody = "Смежное обсуждение: о заметке говорят жители площадки, их реплики пишет машина."

// SynthOrigin — ОРИГИНАЛ, о котором говорят в двойнике: ровно то, что нужно
// показать цитатой, и ни полем больше.
//
// Копии текста по-прежнему нет нигде: двойник держит НОМЕР оригинала, а слова
// выводятся соединением в момент показа — тем же приёмом, каким их получают
// жители (platnarod.stageNotesQuery). Разойтись цитата с оригиналом не может ни
// правкой, ни обезличиванием, потому что второго хранилища у неё нет.
type SynthOrigin struct {
	ID          int64
	Nick        string // пусто у анонима И у тени без ника — рисует это страница
	Anonymous   bool
	PublishedAt time.Time
	// PublishedExact — то же поле, что у заметки: у зеркальной записи точного
	// времени НГС не отдаёт, и цитата обязана говорить об этом тем же значком,
	// что и сама заметка. Без него дата под цитатой утверждала бы больше, чем
	// известно.
	PublishedExact bool
	Body           string
}

// synthOriginsQuery — оригиналы для показанных двойников, ОДНИМ запросом.
//
// Пачкой, а не по заметке, и не колонкой в noteViewColumns — ни то ни другое не
// вкусовщина. Запрос на строку означал бы двадцать походов в базу на страницу
// ленты, а лишний LEFT JOIN в noteViewColumns платили бы ВСЕ заметки, включая
// те 117 тысяч, у которых synth_of пуст, — и платил бы его самый горячий запрос
// площадки. Здесь же цена ровно по месту: нет двойников на странице — нет и
// запроса.
//
// Скрытый оригинал цитаты не даёт (o.status = 0): показать его текст на
// соседней странице значило бы вернуть на вид то, что модератор убрал. Двойник
// при этом остаётся — он просто говорит о заметке, которой читателю не видно.
const synthOriginsQuery = `
	SELECT t.id, o.id, o.anonymous,
	       CASE WHEN o.anonymous THEN '' ELSE coalesce(u.nick, '') END,
	       o.published_at, o.published_exact, o.body
	  FROM notes t
	  JOIN notes o ON o.id = t.synth_of
	  LEFT JOIN users u ON u.id = o.author_id
	 WHERE t.id = ANY($1) AND o.status = 0`

// SynthOrigins — оригиналы для двойников с этой страницы, по номеру ДВОЙНИКА.
//
// Отказ здесь странице не приговор: без цитаты двойник остаётся собой — подпись
// и ссылка «сама заметка» на месте, — поэтому зовущий волен записать ошибку в
// лог и рисовать дальше, как это сделано с иллюстрациями и мордолентой.
func (p *Platform) SynthOrigins(ctx context.Context, twinIDs []int64) (map[int64]SynthOrigin, error) {
	if len(twinIDs) == 0 {
		return nil, nil
	}
	rows, err := p.pool.Query(ctx, synthOriginsQuery, twinIDs)
	if err != nil {
		return nil, wrapf(err, "оригиналы смежных обсуждений")
	}
	defer rows.Close()
	out := make(map[int64]SynthOrigin, len(twinIDs))
	for rows.Next() {
		var twin int64
		var o SynthOrigin
		if err := rows.Scan(&twin, &o.ID, &o.Anonymous, &o.Nick, &o.PublishedAt, &o.PublishedExact, &o.Body); err != nil {
			return nil, wrapf(err, "оригиналы смежных обсуждений")
		}
		out[twin] = o
	}
	return out, wrapf(rows.Err(), "оригиналы смежных обсуждений")
}

// NoteSynth — смежное обсуждение заметки: номер двойника и сколько в нём сказано.
type NoteSynth struct {
	ID           int64
	CommentCount int
}

// SynthTwin — есть ли у заметки смежное обсуждение.
//
// Отдельным запросом, а не колонкой в noteViewColumns, и это расчёт: колонка
// поехала бы и в ЛЕНТУ, то есть в самый горячий запрос площадки, ради строки,
// которая нужна одной странице из двадцати. Здесь же это одно попадание в
// частичный уникальный индекс notes_synth_of.
func (p *Platform) SynthTwin(ctx context.Context, noteID int64) (NoteSynth, bool, error) {
	var out NoteSynth
	err := p.pool.QueryRow(ctx, `
		SELECT id, comment_count FROM notes
		 WHERE synth_of = $1 AND status = 0`, noteID).Scan(&out.ID, &out.CommentCount)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		return NoteSynth{}, false, nil
	case err != nil:
		return NoteSynth{}, false, wrapf(err, "смежное обсуждение заметки %d", noteID)
	}
	return out, true, nil
}

// CreateSynthThreadAsAdmin заводит рядом с заметкой смежное обсуждение.
//
// Ручка эта появилась 31.08.2026 вместо прежней единственной дороги — перевода
// заметки в песочницу (SetNoteStageAsAdmin). У перевода два свойства, которые
// владелец назвал поспешными: он возможен только пока в заметке никто не сказал
// ни слова, и он отдаёт заметку жителям ЦЕЛИКОМ. Самый интересный материал для
// симуляции — заметка с живым тредом — не брался вовсе, а взятая переставала
// быть местом, где могут говорить люди.
//
// Двойник не отнимает ничего: оригинал остаётся как был — текст, автор, его
// собственное обсуждение, дорога в каналы, — а жители говорят у себя. Два
// разговора не смешиваются ПО ПОСТРОЕНИЮ, а не по дисциплине: это разные
// заметки, и всё, что уже написано про песочницу (гейт, исключение из каналов,
// из выпуска и из поводов), достаётся смежному обсуждению даром.
//
// Идемпотентна: повторный вызов возвращает номер уже заведённого двойника вместе
// с ErrSynthExists — спрашивающему нужен адрес, а не отказ.
func (p *Platform) CreateSynthThreadAsAdmin(ctx context.Context, actor Viewer, noteID int64) (int64, error) {
	if !actor.CanAdmin() {
		return 0, ErrNotAdmin
	}
	var (
		stage   bool
		synthOf *int64
		status  Status
	)
	err := p.pool.QueryRow(ctx, `SELECT stage, synth_of, status FROM notes WHERE id = $1`, noteID).
		Scan(&stage, &synthOf, &status)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		return 0, fmt.Errorf("заметка %d: %w", noteID, ErrNotFound)
	case err != nil:
		return 0, wrapf(err, "смежное обсуждение заметки %d", noteID)
	}
	// Скрытую заметку обсуждать не зовём: для пишущего её просто нет.
	if status != StatusVisible {
		return 0, fmt.Errorf("заметка %d: %w", noteID, ErrNotFound)
	}
	// Ни у песочницы, ни у самого двойника: и то и другое уже синтетика, а
	// синтетика рядом с синтетикой не значит ничего.
	if stage || idOf(synthOf) != 0 {
		return 0, ErrSynthOfStage
	}
	if twin, ok, err := p.SynthTwin(ctx, noteID); err != nil {
		return 0, err
	} else if ok {
		return twin.ID, ErrSynthExists
	}
	// ЧЕРЕЗ ЯДРО, тем же вызовом, что и всякая нативная заметка: право писать,
	// потолок частоты, гейт песочницы, очередь модерации той же транзакцией и
	// событие шины. Двойник — публикация администратора, и никаких поблажек у
	// неё нет; уникальный индекс по synth_of разводит двух нажавших разом.
	// В audit_log двойник НЕ пишется, и это не забывчивость. Журнал заведён для
	// действий, которых со стороны не видно, — скрытия, бана, правки чужого
	// текста; двойник же САМ себе запись: нативная заметка с автором,
	// временем и ссылкой на оригинал, видимая всем. Ровно поэтому и `platform
	// post` в журнал не пишет.
	return p.CreateNote(ctx, NewNote{
		AuthorID: actor.UserID, Body: synthBody, Stage: true, SynthOf: noteID,
	})
}
