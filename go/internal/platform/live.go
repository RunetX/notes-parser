package platform

// Звонок живому каналу: NOTIFY на записи, LISTEN у того, кто показывает.
//
// Зачем он есть. Хаб веб-морды (internal/web/hub.go) узнавал о новом опросом
// журнала раз в две секунды, и это была не оплошность, а осознанный размен:
// опрос стоит одинаково при одном открытом окне и при сотне, переживает разрыв
// соединения без переподписки и не требует ничего от пишущего. Плата — до двух
// секунд задержки, из-за которых чужая реплика появлялась в открытом треде не
// «на глазах», а «через паузу».
//
// Почему НЕ хватило просто позвать хаб из кода, который пишет. Процессов ДВА, и
// это видно из развёртывания: `lovegw web` — свой контейнер со своим пулом
// (WebOpts), `lovegw run` — демон с зеркалом, раздачей поводов и исходящим
// обходом (DaemonOpts). Хаб живёт только в первом, а факты рождаются в обоих:
// нативную реплику пишет морда, зеркальную — приёмник демона, повод — platbus
// там же. Прямой вызов в памяти закрыл бы половину случаев и оставил вторую
// половину на опросе, то есть завёл бы ДВА пути с разной задержкой; звонок
// через базу одинаков для обоих и для любого будущего третьего.
//
// ГЛАВНОЕ ПРАВИЛО: NOTIFY — это ЗВОНОК, А НЕ ДАННЫЕ. Payload пуст намеренно, и
// читать его никто не станет: по звонку хаб идёт в журнал СВОИМИ курсорами,
// ровно как ходил по такту. Отсюда всё остальное:
//
//   - потерянный звонок ничего не теряет — пропущенное доберёт такт-страховка;
//   - двойной звонок ничего не удваивает — курсор не сдвинется дважды;
//   - в звонке нечему быть чужим текстом, то есть он не заводит второй путь
//     содержимого на страницу (см. шапку web/live.go — там за это заплачено
//     отказом от готового HTML на проводе).
//
// Postgres доставляет уведомления ПОСЛЕ фиксации транзакции и схлопывает
// одинаковые внутри неё. Поэтому звонок стоит той же транзакцией, что и запись
// факта: откатились — звонка нет, записали пачку — звонок один.

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5"
)

// LiveChannel — имя канала Postgres. Одно на всё: и на факт, и на повод.
//
// Двух каналов нет намеренно. Хаб на любой звонок делает один и тот же проход
// обоими курсорами, и различить «звонит факт» от «звонит повод» ему нечем и
// незачем: лишний проход стоит двух запросов по индексу, а два канала стоили бы
// второй подписки, второго реконнекта и вопроса «а этот звонок про что».
const LiveChannel = "lovegw_live"

// listenPing — как часто щупаем соединение LISTEN, если по нему тихо.
//
// Нужен из-за самого злого отказа: оборванный молча сокет. Ожидание
// уведомления висит на нём вечно, канал считает себя живым, и площадка тихо
// возвращается к такту, никому об этом не сказав. Поэтому ждём с сроком и на
// каждом истечении спрашиваем базу, жива ли она: тишина в полминуты нормальна,
// молчащий на Ping сокет — нет.
const listenPing = 30 * time.Second

// pingTimeout — сколько ждём ответа на этот вопрос. СВОЙ срок обязателен, и
// оплачен он пробой: замороженный Postgres (`docker pause`, 23.08.2026) держит
// сокет установленным и просто молчит, — Ping на общем контексте висел в нём
// сколько угодно, канал всё это время числился живым, и настоящую тишину было
// не отличить от отсутствия событий. Пять секунд при локальной базе, отвечающей
// за миллисекунды: это «мертво», а не «занято».
const pingTimeout = 5 * time.Second

// ringLive звонит слушателям. Той же транзакцией, что и запись, — см. шапку.
//
// Ошибку не возвращает, и это не небрежность, а отсутствие выбора: внутри
// транзакции любой отказ отравляет её целиком, поэтому неудачный звонок всё
// равно приедет вызывающему отказом COMMIT'а, а вне транзакции звонить нам
// незачем. Своих причин отказать у pg_notify нет — имя канала наше и короткое,
// а очередь уведомлений переполняется только вместе со всей базой.
func ringLive(ctx context.Context, q querier) {
	// pg_notify, а не NOTIFY: имя канала здесь константа, но функция принимает
	// его значением, и SQL остаётся без склейки строк вовсе.
	_, _ = q.Exec(ctx, `SELECT pg_notify($1, '')`, LiveChannel)
}

// ListenLive держит ОДНУ подписку и возвращается, когда она кончилась.
//
// Соединение здесь СВОЁ, вне пула, и это требование, а не аккуратность:
// подписка занимает соединение навсегда, а у морды их четыре на всю площадку —
// пятая часть пула, отданная ожиданию, отбирается у страниц, а через них у
// зеркала на том же ядре.
//
// Одна попытка на вызов. Повтор, бэкофф и переключение режима — дело
// вызывающего (web/hub.go): там же живут остальные правила живого канала, и
// разложить их по двум пакетам значило бы отвечать на вопрос «почему канал
// молчит» в двух местах сразу.
//
// ready зовётся один раз, когда подписка встала: вызывающему это сигнал
// «дальше можно ждать звонков» и повод немедленно перечитать журнал — за время
// без подписки он мог пропустить что угодно. ring зовётся на каждый звонок.
func (p *Platform) ListenLive(ctx context.Context, ready, ring func()) error {
	cfg := p.pool.Config().ConnConfig.Copy()
	conn, err := pgx.ConnectConfig(ctx, cfg)
	if err != nil {
		return fmt.Errorf("подписка на живой канал: %w", err)
	}
	// Закрытие идёт по контексту БЕЗ отмены: отменённый контекст — самая частая
	// причина сюда попасть, а закрывать соединение им же значит не закрыть его
	// вовсе и оставить висеть backend в Postgres.
	defer conn.Close(context.WithoutCancel(ctx)) //nolint:errcheck // соединение всё равно уходит

	if _, err := conn.Exec(ctx, "LISTEN "+LiveChannel); err != nil {
		return fmt.Errorf("подписка на живой канал: %w", err)
	}
	ready()

	for {
		wait, cancel := context.WithTimeout(ctx, listenPing)
		_, err := conn.WaitForNotification(wait)
		cancel()
		switch {
		case err == nil:
			ring()
		case ctx.Err() != nil:
			return nil // нас остановили — это не отказ
		case errors.Is(err, context.DeadlineExceeded):
			// Тишина сама по себе законна: звонков может не быть часами.
			// Проверяем не её, а сокет — см. listenPing.
			ping, done := context.WithTimeout(ctx, pingTimeout)
			err := conn.Ping(ping)
			done()
			if err != nil {
				return fmt.Errorf("живой канал молчит и не отвечает: %w", err)
			}
		default:
			return fmt.Errorf("ожидание звонка: %w", err)
		}
	}
}
