package platform

// Кому отвечает «Ник, …», когда тред СМЕШАННЫЙ.
//
// Зеркало решает этот вопрос своей памятью (love.Addressees поверх SQLite), и
// пока весь разговор шёл на НГС, памяти хватало. С появлением записи на площадке
// она перестала видеть половину треда: нативной реплики на НГС нет вовсе, в
// зеркальной базе её нет тем более, — и ответ «Паноптикум, …», написанный на
// сайте в ответ на реплику, написанную ЗДЕСЬ, приклеивался к последней РЕПЛИКЕ
// ЭТОГО ЧЕЛОВЕКА НА НГС, то есть в чужую ветку и часто на час раньше.
//
// Починить это на стороне зеркала нечем: оно про площадку не знает и знать не
// должно. Зато знает площадка — у неё лежит весь тред обеих полос, поэтому
// вопрос решается здесь, а приёмник (platsink) просто спрашивает.
//
// ПРАВИЛО ТО ЖЕ САМОЕ, что в love.Addressees, и это принципиально: «последняя
// реплика адресата, обращённая к самому отвечающему, иначе просто последняя».
// Второе выражение одного правила заведено не по недосмотру — у площадки другое
// ПРЕДСТАВЛЕНИЕ тех же данных: обращение здесь не текст, а ребро (префикс
// срезается на приёме, иначе ник размазан по чужим телам и обезличивание
// невозможно), поэтому «обращённая к отвечающему» читается не разбором строки, а
// переходом по reply_to_id. Стеречь расхождение оставлено тесту: он гоняет обе
// реализации по одному и тому же разговору и требует одинакового ответа.

import (
	"context"
	"errors"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

// normalizeNick — как ник сравнивается. Ровно то же, что делает love.Addressees
// над своей памятью: обрезка по краям и нижний регистр.
func normalizeNick(s string) string { return strings.ToLower(strings.TrimSpace(s)) }

// authorNick — как зовут автора реплики. Ник участника, а нет его — снимок,
// сохранённый зеркалом (см. author_display). Регистр сводит сам Postgres:
// его lower() знает кириллицу, в отличие от SQLite, где зеркалу приходится
// сводить регистр в Go.
const authorNick = `lower(coalesce(nullif(u.nick, ''), c.author_display, ''))`

// beforeCut — «раньше нынешней реплики». Пара, а не одно время: у зеркальных
// строк время с точностью до секунды, и в людном треде их в одной секунде
// несколько — там порядок задаёт id, и внутри полосы он верен. Для двух реплик
// РАЗНЫХ полос в одну и ту же секунду порядок выходит произвольным, и это
// осознанно: доли секунды между «сказал на сайте» и «сказал здесь» никакой
// разговор не различает.
//
// Номера параметров общие у обеих ступеней, поэтому отвечающий у первой идёт
// ПОСЛЕДНИМ ($5), а не третьим: у второй ступени его нет вовсе, а параметр, на
// который в запросе никто не ссылается, Postgres отвергает — тип его вывести
// неоткуда (SQLSTATE 42P18).
const beforeCut = `(c.published_at < $3 OR (c.published_at = $3 AND c.id < $4))`

// statedNick — к кому обращена реплика ПО ТЕКСТУ: первая строка, всё до первой
// запятой, без пробелов по краям. Ровно то, что делает love.splitAddress.
//
// Нужно потому, что обращение живёт в теле только пока оно НЕ разошлось: приём
// срезает префикс в ребро лишь когда адресат нашёлся (иначе снятое обращение
// исчезло бы совсем). А «X обращался к Y» — это свидетельство и тогда, когда
// обращение никуда не привело: в начале треда, или когда адресуются автору
// заметки, реплики которого в треде ещё нет. Зеркало такие обращения помнит,
// и без этого куска площадка отвечала бы иначе — что и поймал парный тест.
const statedNick = `lower(btrim(split_part(split_part(c.body, chr(10), 1), ',', 1)))`

// addresseeToMeQuery — первая ступень: последняя реплика адресата, ОБРАЩЁННАЯ К
// самому отвечающему. Разговор в треде идёт пинг-понгом, поэтому она и есть
// почти всегда верный ответ.
//
// Обращённость читается двумя способами, и это не два правила, а одно на двух
// видах строк: у разошедшегося обращения адресат — ребро, у неразошедшегося он
// остался текстом (см. statedNick). LEFT JOIN, а не JOIN, ровно поэтому.
const addresseeToMeQuery = `
	SELECT c.id
	  FROM comments c
	  LEFT JOIN users u ON u.id = c.author_id
	  LEFT JOIN comments t ON t.id = c.reply_to_id
	  LEFT JOIN users tu ON tu.id = t.author_id
	 WHERE c.note_id = $1 AND ` + authorNick + ` = $2
	   AND ` + beforeCut + `
	   AND (lower(coalesce(nullif(tu.nick, ''), t.author_display, '')) = $5
	     OR (c.reply_to_id IS NULL
	         AND position(',' in split_part(c.body, chr(10), 1)) > 0
	         AND ` + statedNick + ` = $5))
	 ORDER BY c.published_at DESC, c.id DESC
	 LIMIT 1`

// addresseeLastQuery — вторая ступень: просто последняя реплика адресата.
// Сюда попадают те, кто вступает в чужой разговор или отвечает реплике без
// обращения.
const addresseeLastQuery = `
	SELECT c.id
	  FROM comments c
	  LEFT JOIN users u ON u.id = c.author_id
	 WHERE c.note_id = $1 AND ` + authorNick + ` = $2
	   AND ` + beforeCut + `
	 ORDER BY c.published_at DESC, c.id DESC
	 LIMIT 1`

// AddresseeInNote отвечает, какой реплике заметки адресовано обращение «nick, …»
// от replier, написанное в момент (before, beforeID).
//
// Ноль — адресат не нашёлся: ника в треде нет вовсе (адресуются и автору
// заметки, и тем, чья реплика ещё не доехала). Это рабочий ответ, а не ошибка:
// реплика встанет корнем ветки, как вставала до слоя адресатов.
//
// Ники берутся строками, а не id, намеренно: вопрос «кого в ЭТОМ треде зовут
// так» — про разговор, а не про учётную запись, и одинаково отвечается для
// участника, тени и зеркального комментатора без анкеты.
func (p *Platform) AddresseeInNote(ctx context.Context, noteID int64,
	nick, replier string, before time.Time, beforeID int64) (int64, error) {
	nick = normalizeNick(nick)
	if nick == "" {
		return 0, nil
	}
	args := []any{noteID, nick, before, beforeID}
	if replier := normalizeNick(replier); replier != "" {
		id, err := p.addresseeRow(ctx, addresseeToMeQuery, nick, noteID, append(args, replier))
		if err != nil || id != 0 {
			return id, err
		}
	}
	return p.addresseeRow(ctx, addresseeLastQuery, nick, noteID, args)
}

func (p *Platform) addresseeRow(ctx context.Context, sql, nick string, noteID int64, args []any) (int64, error) {
	var id int64
	err := p.pool.QueryRow(ctx, sql, args...).Scan(&id)
	if errors.Is(err, pgx.ErrNoRows) {
		return 0, nil
	}
	return id, wrapf(err, "адресат «%s» в заметке %d", nick, noteID)
}
