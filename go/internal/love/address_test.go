package love

import "testing"

func TestAddressPrefix(t *testing.T) {
	cases := []struct {
		text, want string
	}{
		{"Ягода, привет", "ягода"},
		{"ЯГОДА, привет", "ягода"},                        // регистр кириллицы
		{"  Noname Noface , ну да", "noname noface"},      // пробелы вокруг ника
		{"Ягода, привет\nвторая строка", "ягода"},         // обращение только в первой строке
		{"Просто текст без обращения", ""},                //
		{"а, ну да", ""},                                  // слишком короткий префикс
		{"Когда я разводилась в 35 лет, было тяжело", ""}, // придаточное, а не ник
		{",", ""},
		{"", ""},
	}
	for _, c := range cases {
		if got := AddressPrefix(c.text); got != c.want {
			t.Errorf("AddressPrefix(%q) = %q, want %q", c.text, got, c.want)
		}
	}
}

// TrimAddressPrefix режет ровно то, что нашёл AddressPrefix, — иначе площадка
// снимала бы обращение в ребро, а в теле оставляла его же.
func TestTrimAddressPrefix(t *testing.T) {
	cases := []struct {
		text, want string
	}{
		{"Ягода, привет", "привет"},
		{"  Noname Noface , ну да", "ну да"},
		{"Ягода, привет\nвторая строка", "привет\nвторая строка"},
		{"Ягода,\nа вот и текст", "а вот и текст"}, // перенос сразу после запятой
		{"Просто текст без обращения", "Просто текст без обращения"},
		{"Когда я разводилась в 35 лет, было тяжело", "Когда я разводилась в 35 лет, было тяжело"},
		{"Ягода,", "Ягода,"}, // одно обращение и больше ничего: пустая реплика хуже
		{"", ""},
	}
	for _, c := range cases {
		if got := TrimAddressPrefix(c.text); got != c.want {
			t.Errorf("TrimAddressPrefix(%q) = %q, want %q", c.text, got, c.want)
		}
	}
}

// Память треда выбирает адресата так, как разговор идёт на самом деле:
// пинг-понгом. Случай из жалобы 23.08.2026 — говорливый собеседник, у которого
// последняя реплика адресована СОВСЕМ ДРУГОМУ человеку.
func TestAddresseesPrefersWhoAnsweredYou(t *testing.T) {
	book := NewAddressees[int64]()
	book.Add(1, "Т 72Б", "чтобы уверенно планировать свидания")
	book.Add(2, "Хатуль мадан", "Есть у меня один знакомец")
	book.Add(3, "Хатуль мадан", "Т 72Б, а хоть одна на второе свидание согласилась?")
	book.Add(4, "Лилит", "мне с машиной Вайлдбэррис")
	book.Add(5, "Хатуль мадан", "Лилит, с газель-будкой что ли?")

	cases := []struct {
		name, nick, replier string
		want                int64
		ok                  bool
	}{
		{"отвечают тому, кто обратился к тебе", "хатуль мадан", "Т 72Б", 3, true},
		{"у другого собеседника своя ветка", "хатуль мадан", "Лилит", 5, true},
		{"вступившему в разговор — последняя", "хатуль мадан", "Прохожий", 5, true},
		{"ник не встречался", "ягода", "Т 72Б", 0, false},
		{"регистр и пробелы не важны", "  ХАТУЛЬ МАДАН ", "т 72б", 3, true},
	}
	for _, c := range cases {
		got, ok := book.Resolve(c.nick, c.replier)
		if got != c.want || ok != c.ok {
			t.Errorf("%s: получили (%d, %v), ожидалось (%d, %v)", c.name, got, ok, c.want, c.ok)
		}
	}
}
