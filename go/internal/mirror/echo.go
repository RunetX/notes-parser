package mirror

// Своё эхо: записи НГС, которые зеркало не несёт никуда, потому что это наши же
// слова, ушедшие туда из Зазеркалья (пакет platngs).
//
// Устройство в двух словах: спрашиваем площадку ОДИН раз на запись, ответ «да»
// записываем в lovegw.db и дальше решаем по id. Сверка стоит запроса в Postgres
// с чтением тела публикации, а спрашивают про одну и ту же реплику десятки раз
// подряд: страница треда отдаёт последние тридцать, и наша провисит среди них
// часами.
//
// Отдельный файл, а не десять строк в mirror.go, потому что случаев ДВА и они не
// симметричны: заметку из ленты надо ВЫБРОСИТЬ (иначе она уедет и в канал, и на
// площадку), а реплику треда — наоборот, числить ИЗВЕСТНОЙ, не сохраняя: над
// saveComments стои́т сверка с серверным счётчиком треда, и «пропала одна» она
// лечит добором страниц.
//
// НЕРЕШЁННОЕ РАВНО НЕСОХРАНЁННОМУ. Отказ площадки (лежит Postgres) не читается
// как «не наше»: сохранив запись, зеркало отдаст её всем приёмникам и дубль
// станет неотменимым, а отложив — просто спросит на следующем такте, благо
// запись висит на странице часами. Правило то же, по которому приёмник имеет
// право честно отказать, а догоняет сверка.

import (
	"context"
	"strconv"
	"time"

	"lovegw/internal/love"
	"lovegw/internal/store"
)

// dropNoteEcho убирает из свежих ленты наши собственные заметки, уехавшие на
// НГС. Полная копия такой заметки уже лежит на площадке, а в каналы её отнёс
// platout, — пропусти мы это, и в ленте площадки заметка встала бы дважды, а в
// канале вышла бы вторым постом.
//
// Заметка, про которую площадка не ответила, тоже уходит из обхода — но НЕ
// помечается известной, поэтому вернётся следующим циклом ленты.
//
// Цена решения названа и здесь, и на /me: НГС-обсуждение такой заметки сюда не
// приедет. Заметки для зеркала не существует, значит и тред опрашивать некому —
// разговор на сайте останется на сайте.
func (m *Mirror) dropNoteEcho(ctx context.Context, fresh []love.Note, known map[string]bool) []love.Note {
	if m.echo == nil || len(fresh) == 0 {
		return fresh
	}
	out := fresh[:0]
	for _, n := range fresh {
		own, err := m.ownEcho(ctx, store.EchoNote, n.ID, "", n.AuthorID, n.Text, n.PublishedAt)
		switch {
		case err != nil:
			m.log.Warn("заметка отложена до следующего обхода: своё это или нет, неизвестно",
				"note", n.ID, "err", err)
		case own:
			known[n.ID] = true
			m.log.Info("своя заметка вернулась с НГС — в зеркало не берём", "note", n.ID)
		default:
			out = append(out, n)
		}
	}
	return out
}

// markCommentEcho помечает известными свои реплики, вернувшиеся с НГС.
// saveComments известные пропускает сам, поэтому выбрасывать их из страницы не
// нужно — а числить нужно: иначе len(known) не сойдётся со счётчиком треда и
// каждая наша отправка стоила бы добора страниц.
//
// Ошибка возвращается наружу и обрывает такт целиком: сохранить страницу, не
// решив про одну её реплику, — это и есть дубль.
func (m *Mirror) markCommentEcho(ctx context.Context, n store.Note, comments []love.Comment,
	known map[int64]bool) error {
	if m.echo == nil {
		return nil
	}
	for _, c := range comments {
		if known[c.ID] {
			continue
		}
		id := strconv.FormatInt(c.ID, 10)
		own, err := m.ownEcho(ctx, store.EchoComment, id, n.ID, c.AuthorID, c.Text, c.PublishedAt)
		if err != nil {
			return err
		}
		if !own {
			continue
		}
		known[c.ID] = true
		m.log.Info("своя реплика вернулась с НГС — в зеркало не берём",
			"note", n.ID, "comment", c.ID)
	}
	return nil
}

// ownEcho — один вопрос площадке плюс запись ответа в память зеркала.
//
// Память эта — оптимизация, а не условие правильности: не записавшись, она
// стоит лишнего запроса на следующем такте, но не дубля. Держится это тем, что
// опознание ИДЕМПОТЕНТНО по id записи (platform.ClaimNGSEcho): строка очереди,
// уже закреплённая за этой записью, узнаёт её снова.
func (m *Mirror) ownEcho(ctx context.Context, kind, siteID, noteID, authorID, body string,
	at time.Time) (bool, error) {
	if at.IsZero() {
		// Времени у записи может не быть (лента даты не даёт вовсе), а окно
		// опознания считается от него. «Сейчас» — самое верное приближение:
		// запись мы видим в тот же обход, в который сайт её показал.
		at = time.Now()
	}
	own, err := m.echo.OwnEcho(ctx, kind, siteID, noteID, authorID, body, at)
	if err != nil || !own {
		return false, err
	}
	if err := m.st.MarkNGSEcho(ctx, kind, siteID, noteID, time.Now()); err != nil {
		m.log.Error("отметка своего эха не записалась", "вид", kind, "запись", siteID, "err", err)
	}
	return true, nil
}
