package narod

// Промпт боевой реплики.
//
// Собирается он из четырёх блоков, и порядок у них не случайный, а повторяет то,
// как в разговор входит человек:
//
//	КТО ТЫ (карточка)      — с этим он приходит всегда;
//	ЧТО ТЫ ПОМНИШЬ (мир)   — сквозь это он читает чужие слова;
//	РАЗГОВОР (тред)        — то, что сказано;
//	С КАКИМ ЧУВСТВОМ (тон) — складывается уже из прочитанного, поэтому ПОСЛЕ треда;
//	ЗАДАНИЕ                — что именно написать.
//
// Подай настроение до треда — и оно превратится в заданный тон, не зависящий от
// того, что там сказали; подай память после — и она станет заданием «а теперь
// вспомни». Тот же порядок стоит в archive.buildVoicePrompt, и разойтись им
// нельзя: калибровка мерила бы голос при одном контексте, а бой шёл бы при
// другом.

import (
	"fmt"
	"strings"
)

// writeSchema — structured outputs. Ограничений массива здесь нет и быть не
// может: Claude API отвечает на minItems/maxItems ошибкой 400, а Go SDK, в
// отличие от питоновского, не вырезает такие ключи молча.
var writeSchema = map[string]any{
	"type": "object",
	"properties": map[string]any{
		"action": map[string]any{
			"type": "string",
			"enum": []string{"post", "skip"},
		},
		"reason": map[string]any{"type": "string"},
		"text":   map[string]any{"type": "string"},
	},
	"required":             []string{"action", "reason", "text"},
	"additionalProperties": false,
}

// writeSystemBase — рамка мира.
//
// Отличается от калибровочной (archive.voiceSystemBase) одним, но существенным:
// там текст «никуда не публикуется и уходит в атрибутор», здесь он ПОЯВИТСЯ НА
// СТРАНИЦЕ, которую читают люди. Врать модели про это нельзя — и незачем: всё,
// что ей запрещено, запрещено ровно потому, что публикуется.
const writeSystemBase = `Ты пишешь реплику за жителя небольшого сайта заметок — человека со своим
характером, своей жизнью и своей манерой писать. Реплика появится на странице,
которую читают люди.

Жёсткие правила:
- Никаких новых фактов о себе: ни имён, ни городов, ни родни, ни событий, которых
  нет в задании. Про себя ты знаешь ровно то, что там написано.
- Измерения письма — это ЦЕЛИ, а не пожелания: длина, длина предложений,
  пунктуация, регистр.
- РИТМ важнее среднего. Ровный поток предложений одной длины — главная примета
  машинного текста, даже когда среднее совпало.
- Не приглаживай себя. Если человек груб, коряв и рубит фразу — так и пиши;
  гладкий текст с симметричной шуткой в конце не похож ни на кого.
- Ошибок и опечаток НЕ ИЗОБРАЖАЙ: их внесёт за тебя инструмент, с той самой
  частотой, что у тебя замерена. Написанные руками, они выходят карикатурой.
- Разметка сайта — только его: [b]…[/b], [i]…[/i], смайлы :::код:::. Markdown
  (**, ##, ---, обратные кавычки, списки дефисом) запрещён.
- Пиши обычным текстом, без HTML и без экранирования.
- Пол собеседников указан рядом с ником. Глаголы прошедшего времени, обращения и
  «сам / сама» обязаны ему отвечать; по нику пол не угадывается.
- Не пересказывай то, что уже сказано в треде, и не подводи итогов разговора.
- Ты не знаешь, что ты машина, и никогда об этом не пишешь.

Ответ строго по схеме. action = "skip" — законный и частый ответ: «мне здесь
нечего сказать». Выбирай его всякий раз, когда реплика вышла бы пустой
вежливостью, пересказом сказанного или согласием ни о чём. Молчание живого
человека выглядит именно так.`

// writeSystemReply / writeSystemTop — два жанра, как у калибровки.
const (
	writeSystemReply = writeSystemBase + `

Ты отвечаешь КОНКРЕТНОЙ реплике — той, что помечена «← отвечаешь на эту».
Обращение «Ник,» в начале не пиши: его подставит сам сайт по тому, кому ты
отвечаешь.`

	writeSystemTop = writeSystemBase + `

Ты пишешь реплику САМОЙ ЗАМЕТКЕ, а не кому-то из уже написавших. Обращений по
нику в начале не пиши вовсе: адресата здесь нет.`
)

// writeSystem — рамка под жанр этой реплики.
func writeSystem(p WritePoint) string {
	if p.ReplyTo.ID == 0 {
		return writeSystemTop
	}
	return writeSystemReply
}

// threadLimit — сколько реплик треда показывать. Двадцать: столько же берёт
// калибровка (narodsim.branchLimit), и расходиться нельзя — иначе голос мерился
// бы при одном объёме контекста, а писался при другом.
const threadLimit = 20

// writePrompt собирает задание.
func writePrompt(p WritePoint, feedback string) string {
	var b strings.Builder
	_ = WriteCardBrief(&b, *p.Card)
	if s := strings.TrimSpace(p.Memory); s != "" {
		b.WriteString(p.Memory)
	}

	b.WriteString("\n=== РАЗГОВОР ===\n")
	fmt.Fprintf(&b, "Заметка «%s»:\n%s\n", who(p.Note.AuthorNick, p.Note.AuthorGender), p.Note.Body)
	if shown := tailOfThread(p.Thread, threadLimit); len(shown) > 0 {
		b.WriteString("\nЧто уже сказано:\n")
		for _, c := range shown {
			mark := ""
			switch {
			case c.ID == p.ReplyTo.ID:
				mark = "   ← отвечаешь на эту"
			case c.AuthorID == p.Note.AuthorID && p.Note.AuthorID != 0:
				mark = "   ← это автор заметки"
			}
			fmt.Fprintf(&b, "[%s] %s%s\n", who(c.AuthorNick, c.Gender), c.Body, mark)
		}
	}

	if s := strings.TrimSpace(p.Mood); s != "" {
		b.WriteString(p.Mood)
	}

	b.WriteString("\n=== ЗАДАНИЕ ===\n")
	// ЯКОРЬ ТЕМЫ. Без него разговор уползает от людей к предметам, и это замерено
	// на первой боевой песочнице (29.08.2026): 43 % реплик треда оказались про
	// гараж, случайно помянутый в заметке, а про людей и отношения говорили 11 %
	// против 15,9 % в архиве. Механика ухода простая и потому неизбежная: в промпт
	// идут последние двадцать реплик, у каждого жителя своё ремесло, и первый же,
	// кто подхватил предмет из заметки своим ремеслом, задаёт тему всем
	// следующим — окно само себя подкрепляет.
	//
	// ВТОРАЯ ПОЛОВИНА ЯКОРЯ ДОПИСАНА 30.08.2026, и дописана по замеру: первая
	// редакция выгнала из разговора вещи, а вместе с ними ушла и конкретика —
	// обобщений у нас стало 34,3 % против 11,6–18,7 % у доноров, чисел 1,0 %
	// против 5,8–17,7 %. «Про людей» без «про ЭТОТ случай» модель понимает как
	// «про людей вообще», то есть ровно как приглашение к рассуждению.
	b.WriteString("Разговор идёт про ЛЮДЕЙ из заметки и про то, что между ними, — а не про вещи и обстоятельства, попавшие в неё к слову. Говори про ЭТОТ случай и этих людей, а не про то, как бывает вообще. Свой опыт и своё ремесло приводи ДОВОДОМ в этом разговоре, а не как новую тему.\n")

	if p.ReplyTo.ID == 0 {
		b.WriteString("Напиши реплику к самой заметке — не ответ кому-то из написавших.\n")
	} else {
		fmt.Fprintf(&b, "Ответь на реплику %s, помеченную стрелкой.\n",
			who(p.ReplyTo.AuthorNick, p.ReplyTo.Gender))
	}
	// Длина называется НА КАЖДУЮ реплику отдельно, а не разбросом: разброс живёт
	// между репликами, и модель, прочитавшая «обычно 58 знаков», пишет 58 всегда
	// (замер 28.08.2026 — медиана на треть выше донорской при p90 на четверть
	// ниже, у всех трёх слепков).
	// Жребий ДВУСТОРОННИЙ по той же причине, что и односложность.
	if p.Asks {
		b.WriteString("В этой реплике СПРОСИ — обратись с вопросом, а не с утверждением.\n")
	} else {
		b.WriteString("В этой реплике вопросов не задавай — говори утвердительно.\n")
	}
	// Жребий ДВУСТОРОННИЙ. Односторонний («пиши одной фразой», иначе молчим) дал
	// 97 % однофразовых при замеренных 76 %: где инструкции нет, модель
	// продолжает делать то же самое, и умолчание оказывается сильнее жребия.
	if p.OneThought {
		b.WriteString("Эту реплику пиши ОДНОЙ фразой — одна мысль, без второго предложения и без добивки после неё.\n")
	} else {
		b.WriteString("Эту реплику разверни в две-три фразы — не в одну строку.\n")
	}
	if p.TargetRunes > 0 {
		fmt.Fprintf(&b, "Длина ИМЕННО ЭТОЙ реплики: около %d знаков — целься в это число, а не в привычную середину.\n",
			p.TargetRunes)
	}
	if p.Emoji != nil {
		if *p.Emoji {
			b.WriteString("В этой реплике поставь эмодзи — из тех, что перечислены у тебя в карточке.\n")
		} else {
			b.WriteString("В этой реплике эмодзи не ставь.\n")
		}
	}
	// ЧИСЛО. Одностороннее указание: умолчание модели здесь почти ноль (1,0 % у
	// нас против 11,2 % по корпусу), и запрещать в остальных репликах нечего.
	if p.Digit {
		b.WriteString("В ЭТОЙ реплике назови ЧИСЛО — цену, срок, год, возраст, расстояние, — то, что человек помнит точно.\n")
	}
	// ОБОБЩЕНИЕ. Двустороннее: умолчание модели ВЫШЕ замера (34,3 % против
	// 11,6–18,7 %), и там, где инструкции нет, она продолжает делать то же
	// самое, — урок оплачен односложностью 30.08.2026.
	if p.Broad != nil {
		if *p.Broad {
			b.WriteString("В ЭТОЙ реплике вынеси сказанное на всех — так, мол, оно и бывает вообще.\n")
		} else {
			b.WriteString("В этой реплике на всех не выноси: никаких «все», «всегда», «люди вообще» — говори про этот случай и этих людей.\n")
		}
	}
	if feedback != "" {
		// Причина брака подаётся ТА ЖЕ, что уедет в журнал дропов: второй
		// формулировки не заводится, иначе однажды в gen_runs встанет причина,
		// которой модель не видела.
		fmt.Fprintf(&b, "\nПрошлый черновик не прошёл проверку: %s\nИсправь ровно это, содержание оставь новым.\n", feedback)
	}
	return b.String()
}

// who — как называется участник разговора: ник и пол.
//
// Пол приписывается КАЖДОМУ упоминанию, а не объявляется списком в начале, и
// довод тот же, по которому длина и эмодзи назначаются жребием на реплику:
// сведения, поданные отдельно от места, где ими надо воспользоваться, модель
// читает, но не применяет. Здесь применить их надо в глаголе — а он стои́т в той
// же строке, что и ник.
//
// Неизвестный пол не называется никак: ни «пол неизвестен», ни «неизвестно» —
// названное вслух отсутствие модель обязательно чем-нибудь заполнит, а угадывать
// по нику она уже пробовала.
func who(nick, gender string) string {
	switch gender {
	case "male":
		return nick + ", мужчина"
	case "female":
		return nick + ", женщина"
	}
	return nick
}

// tailOfThread — последние n реплик. Хвост, а не начало: разговор идёт вперёд, и
// то, на что отвечают, лежит в конце.
func tailOfThread(all []StageReply, n int) []StageReply {
	if len(all) <= n {
		return all
	}
	return all[len(all)-n:]
}
