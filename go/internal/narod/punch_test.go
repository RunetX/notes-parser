package narod

// ШТАМП МАШИНЫ И ПАНЧ — ПРОВЕРКАМИ, А НЕ ПРОСЬБОЙ.
//
// Тесты написаны 01.09.2026 по замеру 849 боевых реплик в пяти тредах разных
// тем: слово, которым модель говорит в разы чаще живых, стояло в 23,0 % реплик
// против 2,94 % у живых той же длины. Отбирались слова частотой НА СЛОВО, а не
// долей реплик, — наши реплики в полтора раза длиннее корпусных по числу слов,
// и доля завышала всё подряд впятеро.
//
// Тесты идут ПАРАМИ «запрещено — разрешено»: односторонний евал, проверенный
// только с одной стороны, не отличить от евала, который бракует всегда.

import (
	"context"
	"math/rand/v2"
	"strings"
	"testing"
)

// stamped — точка письма с заданным жребием на штамп.
func stamped(allow bool) WritePoint {
	c := testCard()
	return WritePoint{Card: &c, Stamp: &allow}
}

// ЗАПРЕЩЁННЫЙ ШТАМП БРАКУЕТСЯ, И БРАК НАЗЫВАЕТ СЛОВО. Слово в причине — не
// удобство: брак, названный словом, модель исправляет с первой попытки, а брак,
// названный правилом, — переписывая реплику наугад. Цена евала считается в
// лишних платных вызовах, поэтому качество обратной связи здесь это деньги.
func TestЗапрещённыйШтампБракуется(t *testing.T) {
	got := checkDraft("складно у вас выходит, только жить этим нельзя", stamped(false))
	if got == "" {
		t.Fatal("штамп прошёл проверку, хотя жребий его запретил")
	}
	if !strings.Contains(got, "складно") {
		t.Errorf("брак %q не называет слова, за которое забракован", got)
	}
}

// РАЗРЕШЁННЫЙ ШТАМП ПРОХОДИТ. Вторая половина пары: живые эти слова говорят,
// просто редко, и запрет дал бы речь без «потому что» — вторую примету машины
// взамен первой.
func TestРазрешённыйШтампПроходит(t *testing.T) {
	if got := checkDraft("складно у вас выходит, только жить этим нельзя", stamped(true)); got != "" {
		t.Errorf("разрешённый штамп забракован: %s", got)
	}
}

// БЕЗ ЖРЕБИЯ ЕВАЛ НЕ СУДИТ ВОВСЕ: nil означает «не бросали», и выдумывать за
// него решение нельзя — та же ошибка, из-за которой неизвестный пол однажды
// заполнялся догадкой.
func TestБезЖребияШтампНеСудится(t *testing.T) {
	c := testCard()
	if got := checkDraft("будто вам виднее", WritePoint{Card: &c}); got != "" {
		t.Errorf("штамп забракован без жребия: %s", got)
	}
}

// ЧИСТАЯ РЕПЛИКА ПРОХОДИТ ПРИ ЗАПРЕТЕ — иначе евал, бракующий всё подряд, был
// бы неотличим от работающего.
func TestРепликаБезШтампаПроходит(t *testing.T) {
	if got := checkDraft("я вчера сам менял, 40 минут провозился", stamped(false)); got != "" {
		t.Errorf("чистая реплика забракована: %s", got)
	}
}

// СЛОВО СУДИТСЯ ЦЕЛИКОМ, А НЕ ПОДСТРОКОЙ. «Наверное» содержит «верно», «самая»
// содержит «сама», — невод по подстроке врал бы ровно в ту сторону, в какую его
// завели, и бракование пошло бы на ровном месте.
func TestШтампНеЛовитсяВнутриСлова(t *testing.T) {
	if got := checkDraft("наверное, она просто устала", stamped(false)); got != "" {
		t.Errorf("«верно» внутри «наверное» принято за штамп: %s", got)
	}
}

// ПРИЁМ ШУТКИ ВЫПАДАЕТ ВСЕГДА. Пустая строка означала бы реплику без панча, а
// решение владельца 01.09.2026 — панч в каждой.
func TestПриёмШуткиВыпадаетВсегда(t *testing.T) {
	rng := rand.New(rand.NewPCG(1, 2))
	for i := 0; i < 200; i++ {
		if pickPunch(rng, i%2 == 0) == "" {
			t.Fatal("жребий не выбрал приёма")
		}
	}
}

// ВСТРЕЧНЫЙ ВОПРОС НЕ ВЫПАДАЕТ ТАМ, ГДЕ ВОПРОС ЗАПРЕЩЁН.
//
// Иначе две инструкции столкнулись бы лбами — «вопросов не задавай» и «приём:
// встречный вопрос», — и какая из них победит, решал бы порядок строк в
// промпте, то есть жребий вопроса перестал бы что-либо значить.
func TestВстречныйВопросНеВыпадаетБезВопроса(t *testing.T) {
	rng := rand.New(rand.NewPCG(3, 4))
	for i := 0; i < 500; i++ {
		if got := pickPunch(rng, false); got == "встречный вопрос" {
			t.Fatal("встречный вопрос выпал в реплике, где вопросы запрещены")
		}
	}
	seen := false
	for i := 0; i < 500 && !seen; i++ {
		seen = pickPunch(rng, true) == "встречный вопрос"
	}
	if !seen {
		t.Error("встречный вопрос не выпал ни разу там, где вопрос разрешён")
	}
}

// ПРИЁМ ДОЕЗЖАЕТ ДО ПРОМПТА ВМЕСТЕ С ОБРАЗЦОМ. Тест НА ПУТИ ДАННЫХ: формула
// может быть верна, а поле не заполнено, — так 31.08.2026 молчали четыре
// множителя кубика, и тесты на формулы этого не поймали.
func TestПанчДоезжаетДоПромпта(t *testing.T) {
	c := testCard()
	p := WritePoint{Card: &c, Punch: "правило трёх"}
	got := writePrompt(p, "")
	if !strings.Contains(got, "правило трёх") {
		t.Error("приём не назван в задании")
	}
	if !strings.Contains(got, "Спокойный, надёжный, женатый") {
		t.Error("образец приёма не подан рядом с ним")
	}
	if !strings.Contains(got, "ПОСЛЕ панча не пиши ничего") {
		t.Error("правило «после панча ничего» не доехало")
	}
	// Приёмы подаются ПО ОДНОМУ: список модель читает как рецепт и исполняет
	// весь — оплачено jabsLine 30.08.2026.
	for _, f := range punchForms {
		if f.Name != "правило трёх" && strings.Contains(got, f.Name) {
			t.Errorf("в задании назван и чужой приём %q — приёмы подаются по одному", f.Name)
		}
	}
}

// БЕЗ ПРИЁМА БЛОКА ПАНЧА НЕТ ВОВСЕ — иначе «не шутить» было бы невыразимо.
func TestБезПриёмаПанчаНетВЗадании(t *testing.T) {
	c := testCard()
	if got := writePrompt(WritePoint{Card: &c}, ""); strings.Contains(got, "должна быть СМЕШНОЙ") {
		t.Error("панч попал в задание, хотя приём не выпал")
	}
}

// ЗАПРЕТ ШТАМПА ДОЕЗЖАЕТ ДО ПРОМПТА СЛОВАМИ. Правило «не пиши книжно» модель
// читает и не исполняет — это оплачено поверхностью речи 30.08.2026, где замер
// лежал в карточке, а в промпт уходил описанием.
func TestЗапретШтампаДоезжаетСловами(t *testing.T) {
	no, yes := false, true
	c := testCard()
	got := writePrompt(WritePoint{Card: &c, Stamp: &no}, "")
	if !strings.Contains(got, "складно") {
		t.Error("запрещённые слова не названы в задании")
	}
	if got := writePrompt(WritePoint{Card: &c, Stamp: &yes}, ""); strings.Contains(got, "не пиши слов") {
		t.Error("запрет попал в задание, хотя жребий штамп разрешил")
	}
}

// ЖРЕБИИ ДОЕЗЖАЮТ ДО ТОЧКИ ПИСЬМА — тест НА ПУТИ ДАННЫХ, а не на формуле.
//
// Написан по уроку 31.08.2026: четыре множителя кубика были верно посчитаны и
// ни разу не заполнены, а все тесты на формулы проходили. Здесь ровно та же
// опасность: pickPunch может быть безупречен, а строка `point.Punch = …`
// отсутствовать, и разницы не увидит никто, кроме счёта из облака.
func TestЖребииПанчаИШтампаДоезжаютДоТочки(t *testing.T) {
	ctx := context.Background()
	svc, _, _ := retryService(t, &busyStage{}, nil)
	p := svc.players[0]
	pl := Plan{ActorID: p.Card.ID, NoteID: wiringNote.ID, EventID: "reply:100"}
	point, err := svc.compose(ctx, p, pl, wiringNote, nil)
	if err != nil {
		t.Fatal(err)
	}
	if point.Punch == "" {
		t.Error("приём шутки не доехал до точки письма")
	}
	if point.Stamp == nil {
		t.Error("жребий штампа не доехал до точки письма")
	}
}
