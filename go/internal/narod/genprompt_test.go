// СОДЕРЖАНИЕ реплики: число против обобщения.
//
// Замер 30.08.2026 (internal/speech, 300 наших реплик против четырёх доноров и
// 100 тыс. реплик корпуса) назвал «абстрактность» двумя числами: чисел у нас
// 1,0 % против 5,8–17,7 % у доноров, обобщений 34,3 % против 11,6–18,7 %. Оба
// рычага — жребии на реплику, и оба обязаны быть видны в задании.

import (
	"strings"
	"testing"
)

func promptCard() *Card {
	c := testCard()
	c.ID = "test-content"
	c.Persona.Gender = "male"
	return &c
}

func promptOf(p WritePoint) string { return writePrompt(p, "") }

// Число просят ОДНОСТОРОННЕ: выпало — сказали, не выпало — молчим. Умолчание
// модели здесь почти ноль, и запрещать в остальных репликах нечего.
func TestЧислоПросятЖребиемИТолькоОдносторонне(t *testing.T) {
	p := WritePoint{Card: promptCard(), Note: StageNote{ID: 1, Body: "текст"}}
	p.Digit = true
	if !strings.Contains(promptOf(p), "назови ЧИСЛО") {
		t.Error("выпало число, а в задании его не просят")
	}
	p.Digit = false
	if got := promptOf(p); strings.Contains(got, "ЧИСЛО") || strings.Contains(got, "чисел не") {
		t.Error("не выпало — в задании появился запрет, которого замер не требует")
	}
}

// Обобщение называет ОБА исхода. Односторонний жребий здесь не работает: у
// модели своё умолчание втрое выше замера, и там, где инструкции нет, она
// продолжает делать то же самое (урок оплачен односложностью — 97 % при
// замеренных 76 %).
func TestОбобщениеНазываетОбаИсхода(t *testing.T) {
	p := WritePoint{Card: promptCard(), Note: StageNote{ID: 1, Body: "текст"}}
	yes, no := true, false

	p.Broad = &yes
	if !strings.Contains(promptOf(p), "вынеси сказанное на всех") {
		t.Error("выпало обобщение, а задание молчит")
	}
	p.Broad = &no
	if !strings.Contains(promptOf(p), "на всех не выноси") {
		t.Error("не выпало — запрета в задании нет, и модель напишет как обычно")
	}
	// Замера нет (карточка снята до 30.08.2026) — молчим в обе стороны: запрет
	// без замера был бы выдумкой, а не мерой.
	p.Broad = nil
	if got := promptOf(p); strings.Contains(got, "на всех") {
		t.Error("без замера появилось указание про обобщение")
	}
}

// Якорь темы держит РАЗГОВОР ПРО ЛЮДЕЙ и одновременно про ЭТОТ случай. Первая
// его половина заведена по замеру гаража (43 % реплик про предмет), вторая — по
// замеру обобщений: «про людей» без «про этот случай» модель понимает как
// приглашение рассуждать о людях вообще.
func TestЯкорьТребуетЭтогоСлучаяАНеЛюдейВообще(t *testing.T) {
	got := promptOf(WritePoint{Card: promptCard(), Note: StageNote{ID: 1, Body: "текст"}})
	for _, want := range []string{"про ЛЮДЕЙ", "ЭТОТ случай", "как бывает вообще"} {
		if !strings.Contains(got, want) {
			t.Errorf("в якоре нет %q", want)
		}
	}
}
