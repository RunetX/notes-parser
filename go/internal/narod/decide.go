package narod

// Кубик: «прийти или смолчать». Формула, а не модель, — и потому решение
// меряется в КАЖДОЙ точке, а не в выборочных, и не стоит ни цента.
//
// Живёт он в ЯДРЕ, а не в калибровочном харнессе, хотя вырос именно там (этап 2).
// Довод простой: на калибровке и в бою обязана играть ровно одна формула. Стоило
// бы им разойтись — и весь смысл калибровки исчез бы, потому что мерили бы мы не
// то, что потом работает. Харнесс (narodsim) берёт её отсюда же.
//
// Он смотрит ровно на три вещи: обратились ли к жителю, сколько он уже сказал в
// этом треде и что говорит его карточка о частоте. Ни темы, ни отношений, ни
// часа суток здесь нет намеренно — они появятся на этапе 3 вместе с миром, и
// смысл базлайна в том, чтобы к их появлению уже было ЧИСЛО, которое они обязаны
// улучшить. Пороги калибровки, придуманные раньше первого прогона, были бы
// выдумкой.
//
// Бросок выводится из (зерно, анкета, реплика), а не из последовательного
// генератора. Разница существенная: последовательный даёт разный результат,
// стоит поменяться порядку или числу точек решения — например, если завтра
// добавится ещё один источник событий, — и два прогона перестанут сравниваться.
// Здесь же монетка на конкретной реплике одна и та же всегда.

import (
	"context"
	"math"
	"math/rand/v2"
	"time"
)

// DecisionPoint — момент, когда житель мог бы заговорить.
type DecisionPoint struct {
	Now   time.Time
	Actor int64 // чья очередь думать
	// NoteID — заметка, в которой всё происходит. Часть ключа монетки, а не
	// справка: у точки решения на самой заметке номера реплики нет, и без этого
	// поля бросок выходил бы одинаковым во всех тредах (см. pointSeed).
	NoteID int64
	// Topics — темы САМОЙ ЗАМЕТКИ, ключами лексикона. Разбирает их зовущий, а не
	// решение: разбор живёт в архиве, а кубик обязан работать и там, где архива
	// нет вовсе. Пустой список законен — у заметки может не быть ни одной темы
	// из закрытого набора, и это не то же самое, что «тема не подошла».
	Topics    []string
	TriggerID int64 // реплика, на которую реагируем; 0 — сама заметка
	Trigger   string
	Author    int64 // кто её сказал; у заметки — её автор
	Nick      string
	// Addressed — обратились к самому жителю. Отдельным полем, а не разбором
	// текста: обращение уже срезано в ребро, и второй разбор рядом с первым
	// однажды разошёлся бы с ним.
	Addressed bool
	Seen      int // сколько реплик уже прозвучало
	Said      int // сколько раз житель уже говорил в этом треде
	// Familiarity — сколько раз житель УЖЕ отвечал этому говорящему. Та самая
	// величина, которую копит граф мира (narod.Edge.Familiarity), и та самая, по
	// которой снят замер: знакомство поднимает готовность влезть в чужой
	// разговор втрое-впятеро и почти не трогает ответ на прямое обращение.
	Familiarity int
	// Tempo — НАКАЛ треда: сколько реплик прилетело за последние минуты перед
	// этой точкой. Считает его зовущий, потому что окно у накала своё и живёт
	// оно в замере (archive.tempoWindow), а кубик обязан работать и там, где
	// архива нет вовсе, — тот же приём, что у тем заметки.
	Tempo int
	// Gender — пол того, кто сказал реплику ("male"/"female"; пусто — неизвестен).
	// Подаёт его зовущий, как темы и накал: пол живёт в анкете, а кубик обязан
	// работать и там, где ни архива, ни площадки нет вовсе.
	Gender string
	// Tone — как житель относится к говорящему: [-1..+1] из графа мира
	// (narod.Edge.Tone). Ноль значит и «безразличен», и «незнаком» — для
	// решения это одно и то же, а различает их соседнее поле.
	Tone float64
}

// Decision — что решил житель.
type Decision struct {
	Speak bool
	After time.Duration // через сколько ответил бы
	// Root — заговорил В САМУ ЗАМЕТКУ, а не в ответ тому, кто его сюда позвал.
	//
	// Второй поступок, а не оттенок первого: у живых 40 % всех корней — это
	// человек, который в треде уже говорил и вернулся начать новую ветку
	// (замер `archive.MineRootRate`). Без этого поля кубик бросал «прийти в
	// заметку» РОВНО ОДИН РАЗ за её жизнь, и тридцать жителей не могли дать
	// больше двадцати девяти корней ни при какой вероятности.
	Root bool

	// P и Roll — вероятность, по которой решалась эта точка, и сам бросок.
	// Решению они не нужны вовсе: это ЖУРНАЛ. Колонки `dice.p` и `dice.roll`
	// стоя́т в схеме мира с первого дня и всё это время заполнялись нулями,
	// отчего «никто не пришёл, потому что не повезло» и «никто не пришёл,
	// потому что вероятность нулевая» были в журнале неразличимы — а чинят их
	// по-разному. Цена слепоты названа боем: 02.09.2026 на пустой песочнице по
	// этой самой колонке вышло «ожидание 0,00 корня, вероятность нуля 100 %», и
	// чинить чуть не пошли кубик вместо журнала.
	//
	// Пишется тот бросок, который ТОЧКУ И РЕШИЛ: у вернувшегося в заметку это
	// корневой, у всех остальных основной. Второго броска в журнале нет
	// намеренно — строка отвечает на вопрос «с какой вероятностью вышло то, что
	// вышло», а не пересказывает ход вычисления.
	P, Roll float64

	// Why — почему броска не было ВОВСЕ. Пусто значит «бросали»: без этого
	// различения нулевая вероятность в журнале снова читалась бы двояко, только
	// теперь как «не бросали».
	Why string
}

// WhyThreadCap — единственная причина, по которой точка остаётся без броска:
// личный потолок реплик на тред. Список закрытый и лежит в коде, как
// `EpisodeKinds`: свободная строка через месяц даст десяток формулировок одного
// и того же, и сравнивать прогоны станет нечем.
const WhyThreadCap = "потолок реплик на тред"

// Decider — «прийти или смолчать». Модель здесь не участвует: это формула, и
// потому решение меряется в каждой точке, а не в выборочных.
type Decider interface {
	Decide(ctx context.Context, p DecisionPoint) (Decision, error)
}

// CardDecider — «прийти или смолчать» по карточке.
type CardDecider struct {
	Card Card
	Seed uint64
}

// MaxChance — потолок вероятности отклика. Единицы здесь быть не может:
// человек, отвечающий ВСЕГДА, — это не характер, а автоответчик, и на любом
// сочетании множителей такое должно оставаться невозможным.
const MaxChance = 0.9

// Decide бросает монетку на одной точке.
func (d *CardDecider) Decide(_ context.Context, p DecisionPoint) (Decision, error) {
	dice := d.Card.Dice
	// Потолок реплик на тред — часть характера, а не защита: человек, у которого
	// в замере полтора десятка реплик за тред, на шестидесяти выглядел бы
	// одержимым.
	if dice.MaxPerThread > 0 && p.Said >= dice.MaxPerThread {
		return Decision{Why: WhyThreadCap}, nil
	}

	prob, dist := chanceOf(d.Card, p)
	rng := rand.New(rand.NewPCG(pointSeed(d.Seed, p), uint64(p.TriggerID)+1))
	// Задержка тянется ПЕРВОЙ, потому что от неё зависит сама вероятность: час
	// суток решает не в момент публикации заметки, а в момент, когда житель до
	// неё дошёл бы. Иначе заметка, вышедшая в три ночи, не собрала бы никого —
	// хотя на деле её читают утром, и утренние люди в ней и окажутся.
	after := sampleDist(dist, rng.Float64())
	if p.TriggerID == 0 {
		prob = min(prob*d.Card.Rhythm.HourWeight(p.Now.Add(after)), MaxChance)
	}
	roll := rng.Float64()
	if roll < prob {
		return Decision{Speak: true, After: after, P: prob, Roll: roll}, nil
	}
	got, err := d.rootAgain(p)
	if err != nil || got.Speak {
		return got, err
	}
	// Корневой бросок не выпал (или его не на чем было делать) — точку решил
	// основной, его и записываем.
	return Decision{P: prob, Roll: roll}, nil
}

// rootAgain — второй бросок той же возможности: ВЕРНУТЬСЯ В ЗАМЕТКУ и начать
// новую ветку вместо ответа тому, кто эту возможность создал.
//
// Бросается ПОСЛЕ отказа отвечать, а не рядом с ним, и это осознанный недосчёт.
// У живых один и тот же человек умеет за один заход и ответить, и начать ветку,
// но точка решения здесь рождает РОВНО ОДНУ реплику, и раздваивать её значило бы
// переписывать очередь ради случая, который замер числом не выделяет. Недосчёт
// идёт в безопасную сторону — корней выходит меньше, а не больше.
//
// Условий два, и оба существенные. Житель обязан УЖЕ говорить в треде: первый
// заход этой мерой не покрыт, у него нет знаменателя (в архиве видно, куда
// человек пришёл, и не видно, что он пролистал), и подставлять сюда чужую
// вероятность значило бы выдать за замер то, чего не мерили. И вероятность
// берётся ТОЛЬКО из замера: пустая корзина означает «мерить было не на чем», а
// не «ноль», — запасного числа у этой величины нет намеренно, иначе рядом с
// замером немедленно завелась бы вторая выдумка вроде прежнего 0.15.
func (d *CardDecider) rootAgain(p DecisionPoint) (Decision, error) {
	if p.TriggerID == 0 || p.Said == 0 {
		return Decision{}, nil
	}
	prob, ok := d.Card.Roots.Rate(p.Seen)
	if !ok {
		return Decision{}, nil
	}
	// Накал двигает и этот поступок, и двигает по-своему: в замере он
	// спрашивается тем же вопросом, что у отклика, и ответ у него может выйти
	// обратным. Множителем, а не готовой долей, — позиция и накал описывают
	// разное, а обе готовые доли содержат общую базу, которая учлась бы дважды.
	if lift, ok := d.Card.Roots.TempoLift(p.Tempo); ok {
		prob *= lift
	}
	// Ключ монетки свой: тот же ключ дал бы «кто не ответил, тот и не вернулся»
	// — связь, которой в замере нет.
	rng := rand.New(rand.NewPCG(pointSeed(d.Seed, p)^rootSalt, uint64(p.TriggerID)+1))
	after := sampleDist(d.Card.Latency.ToReplySec, rng.Float64())
	prob = min(prob, MaxChance)
	roll := rng.Float64()
	if roll >= prob {
		return Decision{}, nil
	}
	return Decision{Speak: true, Root: true, After: after, P: prob, Roll: roll}, nil
}

// rootSalt разводит две монетки одной возможности. Час суток здесь не
// применяется намеренно: житель уже в треде, а HourWeight отвечает на вопрос
// «дошёл ли он до заметки вообще».
const rootSalt = 0xC2B2AE3D27D4EB4F

// pointSeed — ключ монетки: «кто и где» первым словом, «на что» вторым.
//
// ЗАМЕТКА в ключе обязательна, и стоило это первого же прогона в вакууме
// 28.08.2026: у точки решения на САМОЙ заметке номера реплики нет вовсе (ноль),
// и без номера заметки бросок выходил один и тот же во всех тредах серии.
// Житель, которому на первой заметке выпало смолчать, молчал дальше везде — а
// трое таких дали десять пустых заметок подряд и отчёт, в котором нечего мерить.
// В solo дефект был тем же и виден не был: там точка на заметке одна из сотен, и
// её вечное «не приходить» терялось в матрице. В вакууме то же верно и для
// реплик: номера там свои у каждого треда и начинаются с единицы.
//
// Номера реплик в треде идут почти подряд, то есть PCG получает соседние
// зёрна, — и это проверено, а не принято на веру (28.08.2026, 200 тыс. точек):
// ни частота бросков, ни связь соседних от этого не страдают (корреляция
// −0,002 при шуме ±0,002). Перемешивать зёрна не понадобилось, а частоту
// стережёт тест на подряд идущих номерах.
// NoteSalt открыт наружу: харнесс считает по нему ключи своих событий, и
// разойтись эти два способа не вправе.
const NoteSalt = 0x9E3779B97F4A7C15

func pointSeed(seed uint64, p DecisionPoint) uint64 {
	return seed ^ uint64(p.Actor) ^ uint64(p.NoteID)*NoteSalt
}

// chanceOf — вероятность заговорить и распределение задержки для точки.
//
// Вероятность ОТВЕТА берётся из замера (card.Rate) и зависит от того, как далеко
// зашёл разговор. Числа карточки остаются запасным путём — на случай, когда
// корзина замера пуста, — и оба довода за это записаны замером 28.08.2026:
// придуманное «влезть в чужой разговор = 0.15» оказалось завышено в 20–40 раз
// (настоящее — от 0.4 % у ДВ до 3.7 % у Полынь-Травы), а придуманное «ответить,
// когда обратились = 0.7» попало почти точно (настоящее 39–91 %). То есть на
// глаз угадывается то, что человек делает часто, и не угадывается то, что редко,
// — а из редкого и состоит поведение в людном треде.
//
// Затухание при этом настоящее, но скромное: мимо-разговорная вероятность падает
// вдвое-вчетверо от начала треда к трёхсотой реплике, а обращённая к нему — едва
// на четверть. Человек уходит не из разговора вообще, а из ЧУЖОГО разговора.
//
// «Прийти в новую заметку» числилось неизмеримым, и это оказалось неверно
// (29.08.2026, `archive.MineComeRate`): знаменатель есть, если спросить иначе —
// присутствие человека на сайте доказывает его собственная реплика ГДЕ УГОДНО,
// значит «был в тот день и в эту заметку не зашёл» есть наблюдаемый промах.
// Величина карточки осталась запасным путём на случай тощего замера.
func chanceOf(card Card, p DecisionPoint) (float64, Dist) {
	dice, lat := card.Dice, card.Latency
	if p.TriggerID == 0 {
		// Заметка: «прийти в новую» — и задержка меряется от её публикации.
		//
		// Сама вероятность неизмерима (в архиве видно, куда человек пришёл, и не
		// видно, что он пролистал), а вот ПЕРЕКОС по теме измерим и вносится
		// множителем: доля темы среди заметок, где он говорил, против доли той же
		// темы среди всех заметок его времени. Без него кубик про заметку не
		// знает ничего, кроме того, что она новая, — и выбор «кто придёт именно
		// сюда» выходил случайным (замер 28.08.2026: состав заговоривших сходился
		// с настоящим ровно настолько, насколько сошёлся бы жребий).
		// Готовность зайти БЕРЁТСЯ ИЗ ЗАМЕРА, а число карточки остаётся запасным
		// путём — тот же порядок, что у отклика. Замер 29.08.2026 показал, что
		// придуманное 0.35 попало почти точно (живые заходят в 32 % заметок
		// своего дня), но личный разброс он же и открыл: у одного это каждая
		// вторая заметка, у другого одна из двадцати.
		p0 := dice.ComeToNote
		if r, ok := card.Come.Rate(); ok {
			p0 = r
		}
		if lift, ok := card.TopicLift(p.Topics); ok {
			p0 *= lift
		}
		// Тот же рычаг отношения, что и у ответа, и с тем же потолком: в чью
		// заметку зайти — вопрос ровно про то же, про что «влезать ли в его
		// разговор». Полоса при этом замерена на репликах, а не на заметках, и
		// это заимствование; но взять её оттуда честнее, чем выдумать сюда
		// второе число, у которого замера не будет вовсе.
		p0 *= relationLift(card, p)
		return min(p0, MaxChance), lat.ToThreadSec
	}
	if r, ok := card.Rate.Rate(p.Seen, p.Addressed); ok {
		// Знакомство накладывается МНОЖИТЕЛЕМ поверх позиции: вопросы разные —
		// «докуда дошёл разговор» и «кто говорит», — и обе готовые вероятности
		// содержат общую базу, которая учлась бы дважды.
		if lift, ok := card.Rate.FamiliarLift(p.Familiarity, p.Addressed); ok {
			r *= lift
		}
		// Накал: без него вероятность постоянна и в мёртвом треде, и в
		// разгоревшемся. Замер говорит, что горячий тред РАЗВОДИТ людей по парам —
		// в чужой разговор влезают втрое реже, своему собеседнику отвечают вдвое
		// надёжнее, — и перепалка растёт именно отсюда. Множитель поэтому
		// разнонаправленный, и разделяет его тот же признак Addressed, что у
		// знакомства: одна средняя величина между этими двумя не значит ничего.
		if lift, ok := card.Rate.TempoLift(p.Tempo, p.Addressed); ok {
			r *= lift
		}
		// Пол собеседника: разговор у живых структурно РАЗНОПОЛЫЙ — мужчина
		// отвечает мужчине вдвое реже случайного и почти втрое реже, чем женщине.
		// Множитель по замеру, а не по вкусу; неизвестный пол рычага не даёт.
		if lift, ok := card.Rate.GenderLift(p.Gender, p.Addressed); ok {
			r *= lift
		}
		r *= relationLift(card, p)
		return min(r, MaxChance), lat.ToReplySec
	}
	if p.Addressed {
		return dice.ReplyMention, lat.ToReplySec
	}
	return dice.ReplyOther, lat.ToReplySec
}

// relationLift — во сколько раз ОТНОШЕНИЕ меняет готовность откликнуться.
//
// Единственный рычаг кубика, у которого нет собственного замера, и это сказано
// прямо, потому что скрыть тут нечего: в архиве видно, ЧТО человек написал, и
// не видно, как он к собеседнику относился. Симпатию нельзя добыть счётом — её
// называет модель, читая закончившийся разговор (narod.Chronicle).
//
// РЫЧАГ ПОДНИМАЕТ ОБЕ СТОРОНЫ, а минимум у него посередине — у равнодушия
// (решение владельца 29.08.2026, авторское, а не измеренное). До этого дня он
// был устроен обратно: при отрицательном тоне житель влезал в разговор
// неприятного ему человека РЕЖЕ, — то есть в кубике стояла машина, гасящая
// ссоры, и мир выходил рафинированным при любом промпте. У живых наоборот:
// в чужую перепалку влезают охотнее, чем в чужое согласие, и «терпеть не могу,
// но читаю каждое слово» — обычное состояние сидящего на сайте годами.
//
// Асимметрия тоже решение владельца: неприязнь тянет СИЛЬНЕЕ симпатии. Размах
// при этом по-прежнему заимствован у ЗНАКОМСТВА (FamiliarSpan) — знакомство есть
// тот же след отношения, только доступный счёту, — и полного размаха достигает
// вражда, а приязнь берёт его корень, то есть ровно половину в логарифме. Второго
// придуманного числа рядом с первым не заводится: асимметрия выражена
// извлечением корня, а не новым коэффициентом.
//
// Работает он ТОЛЬКО мимо прямого обращения — по тому же замеру, по которому
// туда же поставлено знакомство: когда обратились лично, человек отвечает и
// нелюбимому, а вот влезать в чужой разговор — вопрос как раз про отношение.
func relationLift(card Card, p DecisionPoint) float64 {
	if p.Addressed || p.Tone == 0 {
		return 1
	}
	span, ok := card.Rate.FamiliarSpan(false)
	if !ok || span <= 1 {
		return 1 // полосы не замерили — рычага нет вовсе
	}
	tone := min(max(p.Tone, -1), 1)
	if tone < 0 {
		return 1 - tone*(span-1)
	}
	return 1 + tone*(math.Sqrt(span)-1)
}

// sampleDist — задержка по квантилям замера.
//
// Распределение задано четырьмя числами (P10, медиана, P90, максимум), и
// восстанавливается оно кусочно-линейно между ними. Это заведомо грубее правды,
// но честнее любого красивого закона: показательное или логнормальное
// распределение подогнало бы хвост под формулу, а хвост здесь и есть содержание —
// человек отвечает то через минуту, то через три часа.
func sampleDist(d Dist, u float64) time.Duration {
	return time.Duration(QuantileAt(d, u) * float64(time.Second))
}

// quantileAt — само восстановление квантиля, без единиц измерения. Отдельно от
// задержки, потому что тем же жребием берётся ДЛИНА реплики: у обеих величин
// содержание в хвосте, а не в середине.
func QuantileAt(d Dist, u float64) float64 {
	switch {
	case d.Median <= 0:
		return 0
	case u < 0.1:
		return lerp(0, float64(d.P10), u/0.1)
	case u < 0.5:
		return lerp(float64(d.P10), float64(d.Median), (u-0.1)/0.4)
	case u < 0.9:
		return lerp(float64(d.Median), float64(d.P90), (u-0.5)/0.4)
	default:
		top := float64(d.Max)
		if top < float64(d.P90) {
			top = float64(d.P90)
		}
		return lerp(float64(d.P90), top, (u-0.9)/0.1)
	}
}

func lerp(a, b, t float64) float64 { return a + (b-a)*t }
