package narod

// СОДЕРЖАНИЕ РЕПЛИКИ — ПРОВЕРКОЙ, А НЕ ПРОСЬБОЙ.
//
// Тесты написаны 01.09.2026 по замеру боевых реплик и по двум отзывам живых
// читателей НГС («такая чушь отборная», «печально и унизительно»). Замер назвал
// одну строку: обобщение стояло в 32,5 % реплик при личных долях карточек
// 15–21 % и 19,5 % по корпусу, — при том что жребий до промпта доезжал и
// формулировка была двусторонняя. Разница с эмодзи, которые в цель попадают, в
// том, что за эмодзи стоит евал, а за содержанием стояла просьба.
//
// Тесты идут ПАРАМИ «запрещено — разрешено»: односторонний евал, проверенный
// только с одной стороны, не отличить от евала, который бракует всегда.

import "testing"

// broad — точка письма с заданным жребием на обобщение.
func broad(allow bool) WritePoint {
	c := testCard()
	return WritePoint{Card: &c, Broad: &allow}
}

// ЗАПРЕЩЁННОЕ ОБОБЩЕНИЕ БРАКУЕТСЯ, И БРАК НАЗЫВАЕТ СЛОВО.
//
// Слово в причине — не удобство: брак, названный словом, модель исправляет с
// первой попытки, а брак, названный правилом, — переписывая реплику наугад.
// Цена евала считается в лишних вызовах, поэтому качество обратной связи здесь
// прямо переводится в деньги.
func TestЗапрещённоеОбобщениеБракуется(t *testing.T) {
	got := checkDraft("да все они так делают, сам видел", broad(false))
	if got == "" {
		t.Fatal("обобщение прошло проверку, хотя жребий его запретил")
	}
	if !contains(got, "все") {
		t.Errorf("брак %q не называет слова, за которое забракован", got)
	}
}

// РАЗРЕШЁННОЕ ОБОБЩЕНИЕ ПРОХОДИТ. Вторая половина пары: евал обязан молчать
// там, где жребий выпал в другую сторону.
func TestРазрешённоеОбобщениеПроходит(t *testing.T) {
	if got := checkDraft("да все они так делают, сам видел", broad(true)); got != "" {
		t.Errorf("разрешённое обобщение забраковано: %s", got)
	}
}

// БЕЗ ЖРЕБИЯ ЕВАЛ НЕ СУДИТ ВОВСЕ. Broad = nil означает «не бросали» (у карточки
// нет замера доли), и выдумывать за неё решение нельзя — это ровно та ошибка,
// из-за которой неизвестный пол однажды заполнялся догадкой.
func TestБезЖребияОбобщениеНеСудится(t *testing.T) {
	c := testCard()
	if got := checkDraft("все всегда так говорят", WritePoint{Card: &c}); got != "" {
		t.Errorf("обобщение забраковано без жребия: %s", got)
	}
}

// ТРЕБУЕМОЕ ЧИСЛО БРАКУЕТСЯ, ЕСЛИ ЕГО НЕТ.
//
// Жребий на число ОДНОСТОРОННИЙ по устройству: модель цифр по умолчанию не
// ставит (замер 30.08.2026 — 1,0 % против 11,2 % по корпусу), поэтому править
// её надо там, где она промахивается, а запрещать нечего.
func TestТребуемоеЧислоБракуется(t *testing.T) {
	c := testCard()
	p := WritePoint{Card: &c, Digit: true}
	if got := checkDraft("я вчера сам менял, намучился", p); got == "" {
		t.Fatal("реплика без числа прошла, хотя жребий число потребовал")
	}
	if got := checkDraft("я вчера сам менял, 40 минут провозился", p); got != "" {
		t.Errorf("реплика с числом забракована: %s", got)
	}
}

// ЧИСЛО БЕЗ ЖРЕБИЯ НЕ ТРЕБУЕТСЯ — и не запрещается: односторонность работает в
// обе стороны только у обобщения.
func TestЧислоБезЖребияНеТребуется(t *testing.T) {
	c := testCard()
	p := WritePoint{Card: &c}
	if got := checkDraft("я вчера сам менял, намучился", p); got != "" {
		t.Errorf("реплика без числа забракована без жребия: %s", got)
	}
}

func contains(s, sub string) bool {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}
