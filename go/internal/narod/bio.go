package narod

// Биография жителя ДЛЯ ЛЮДЕЙ: то, что видно на его странице на площадке.
//
// Карточка — документ для модели, и в промпт она идёт своим порядком (см.
// prompt.go). Здесь другое: короткий абзац, который читает человек, зашедший на
// /u/<id> посмотреть, кто это. Поэтому и собирается он отдельно, а не
// печатанием той же карточки: разъехаться им не страшно — они и не должны
// совпадать.
//
// ЧЕГО ЗДЕСЬ НЕТ. Frustration — то, чем житель уязвлён: это рычаг кубика, а не
// факт о человеке, и напечатанный на странице он превратил бы характер в
// приложенную к нему инструкцию. Ника нет тоже: он стоит заголовком страницы, и
// повторять его первой строкой абзаца незачем.

import (
	"strconv"
	"strings"
	"unicode"
)

// PublicBio — биография жителя одним абзацем.
//
// Куски идут от общего к частному (возраст и город, ремесло, семья, привычки) и
// склеиваются предложениями: перечисление через точку с запятой читается как
// анкета, а житель — не анкета. Каждый кусок доводится до предложения
// механически (заглавная в начале, точка в конце), потому что в рецепте они
// написаны по-разному — где-то с большой буквы, где-то нет.
func PublicBio(b Bio) string {
	parts := make([]string, 0, 4+len(b.Facts))
	if head := ageCity(b); head != "" {
		parts = append(parts, head)
	}
	parts = append(parts, b.Job, b.Family)
	parts = append(parts, b.Facts...)

	out := make([]string, 0, len(parts))
	for _, p := range parts {
		if s := sentence(p); s != "" {
			out = append(out, s)
		}
	}
	return strings.Join(out, " ")
}

// ageCity — «35 лет, Бердск»: две величины, которые человек называет первыми и
// вместе. Порознь они дали бы два огрызка предложения.
func ageCity(b Bio) string {
	var head []string
	if b.Age > 0 {
		head = append(head, strconv.Itoa(b.Age)+" "+yearsWord(b.Age))
	}
	if c := strings.TrimSpace(b.City); c != "" {
		head = append(head, c)
	}
	return strings.Join(head, ", ")
}

// sentence доводит кусок рецепта до предложения. Пустой остаётся пустым — это
// законно: жителя без семьи и без города придумать можно.
func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	switch r[len(r)-1] {
	case '.', '!', '?', '…':
	default:
		r = append(r, '.')
	}
	return string(r)
}
