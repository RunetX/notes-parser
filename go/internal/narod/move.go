package narod

// ХОД — ЧТО житель делает этой репликой: шутит, спрашивает автора, ворчит,
// отписывается двумя словами, рассказывает свой случай, уходит в сторону.
//
// Заведено 01.09.2026 по разбору первого треда с панчем в каждой реплике
// (заметка 313138, 58 реплик): около 80 % из них были построены одинаково —
// «как <ремесло> скажу: <метафора ремесла>». Дефект не в промпте панча, а в
// том, что панч был ОДИН НА ВСЕХ и в КАЖДОЙ реплике: шестьдесят жителей,
// шутящих всегда, различаются между собой меньше, чем шестьдесят человек.
// Цена эта была названа заранее, в тот же день, когда панч вводили, — и
// пришла первым же боевым тредом.
//
// Ход — та же величина, что длина, эмодзи и приём задевания: она живёт МЕЖДУ
// репликами, а модель видит каждую поодиночке. Значит и назначается она так
// же — ЖРЕБИЕМ зовущего, а не просьбой в промпте; список ходов, поданный
// модели, был бы прочитан как рецепт и исполнен целиком (оплачено jabsLine).
//
// ЗАМЕРА У ДОЛЕЙ НЕТ, и это сказано прямо: распределение — авторское решение
// владельца (01.09.2026), а не вывод из корпуса. Соседние доли службы
// (AskRate, OneThoughtRate, StampRate) замерены по архиву, и путать их с этими
// нельзя. Часть ходов замерима — доля вопросов автору и доля коротких реплик
// считаются по архиву тем же способом, что и остальные, — и когда замер будет
// снят, эти числа обязаны уступить ему место.

import (
	"fmt"
	"math/rand/v2"
	"sort"
)

// Move — ход. Слуг латиницей, потому что он же ключ конфига и строка журнала;
// в промпт уходит не он, а описание (moveLine).
type Move string

const (
	// MovePunch — шутка приёмом из punchForms. Прежнее поведение службы, теперь
	// один ход из семи.
	MovePunch Move = "punch"
	// MoveAuthor — вопрос или реплика АВТОРУ заметки. Отдельным ходом, потому
	// что в разборе прогона автора не заметил никто: жители разговаривали друг
	// с другом поверх человека, который всё это написал.
	MoveAuthor Move = "author"
	// MoveGrumble — ворчание, несогласие, придирка к другому комментатору. Он же
	// провоцирующий ход: ссора начинается не с обиды, а с того, что кто-то
	// зацепился за чужие слова.
	MoveGrumble Move = "grumble"
	// MoveShort — короткая малосодержательная реплика («+1», «и не говори»,
	// «бред»). В живом треде таких много, и они не мусор, а фон, на котором
	// видно остальное.
	MoveShort Move = "short"
	// MoveStory — свой случай БЕЗ шутки.
	MoveStory Move = "story"
	// MoveOfftop — то, что не про заметку вовсе.
	MoveOfftop Move = "offtop"
	// MoveOther — уточнение, переспрос, вопрос залу.
	MoveOther Move = "other"
)

// Moves — все ходы в порядке убывания доли. Порядок нужен жребию: он обязан
// быть повторяемым, а обход map в Go нарочно случаен.
var Moves = []Move{MovePunch, MoveAuthor, MoveGrumble, MoveShort, MoveStory, MoveOfftop, MoveOther}

// KnownMove — есть ли такой ход. Нужна конфигу: опечатка в ключе не должна
// молча обнулять целый ход.
func KnownMove(m Move) bool {
	for _, k := range Moves {
		if k == m {
			return true
		}
	}
	return false
}

// DefaultMoveRates — доли ходов. АВТОРСКОЕ РЕШЕНИЕ владельца, не замер.
func DefaultMoveRates() map[Move]float64 {
	return map[Move]float64{
		MovePunch:   0.20,
		MoveAuthor:  0.20,
		MoveGrumble: 0.15,
		MoveShort:   0.15,
		MoveStory:   0.15,
		MoveOfftop:  0.10,
		MoveOther:   0.05,
	}
}

// MoveFit — что известно о точке, в которой ход выбирается.
//
// Ход, не подходящий точке, не выбрасывается в пустоту, а НЕ УЧАСТВУЕТ в
// жребии, и доли остальных пересчитываются. Довод тот же, по которому pickPunch
// не берёт «встречный вопрос» там, где жребий запретил вопросы: два указания,
// столкнувшиеся лбами, решаются порядком строк в промпте, а не жребием.
type MoveFit struct {
	// ToAuthor — дойдёт ли эта реплика до автора заметки: она либо корневая,
	// либо отвечает самому автору.
	ToAuthor bool
	// ToPeer — отвечаем ли мы кому-то из написавших. Придираться к соседу,
	// когда пишешь в саму заметку, не к кому.
	ToPeer bool
}

// PickMove — ход этой реплики. Жребий у зовущего, как у длины и эмодзи.
//
// Пустых долей не бывает: если конфиг обнулил всё, что подходит точке,
// возвращается MoveOther — «уточнение» уместно всегда, и молчание здесь было бы
// хуже, чем ход не той породы.
func PickMove(rng *rand.Rand, rates map[Move]float64, fit MoveFit) Move {
	type slot struct {
		m Move
		w float64
	}
	var slots []slot
	var sum float64
	for _, m := range Moves {
		w := rates[m]
		if w <= 0 || !moveFits(m, fit) {
			continue
		}
		slots = append(slots, slot{m, w})
		sum += w
	}
	if len(slots) == 0 {
		return MoveOther
	}
	sort.Slice(slots, func(i, j int) bool { return slots[i].m < slots[j].m })
	x := rng.Float64() * sum
	for _, s := range slots {
		if x < s.w {
			return s.m
		}
		x -= s.w
	}
	return slots[len(slots)-1].m
}

// moveFits — годится ли ход в этой точке.
func moveFits(m Move, fit MoveFit) bool {
	switch m {
	case MoveAuthor:
		return fit.ToAuthor
	case MoveGrumble:
		return fit.ToPeer
	}
	return true
}

// moveLine — сам ход словами задания. ОДНОЙ строкой и обязательным
// требованием, а не пожеланием: ход выпал жребием, и модель обязана в него
// попасть — ровно как в длину и эмодзи.
//
// Панча здесь нет: у него свой блок в конце задания (там же приём и устройство
// шутки), и поднимать его сюда значило бы утопить приём среди мерок.
func moveLine(m Move) string {
	switch m {
	case MoveAuthor:
		return "Эта реплика — АВТОРУ заметки, а не разбор чужих слов: спроси его о том, чего он не рассказал, или скажи ему самому, что думаешь о его положении.\n"
	case MoveGrumble:
		return "Эта реплика — ПРИДИРКА к тому, кому отвечаешь: не соглашайся, зацепись за одно его слово или за то, как он рассуждает. Шутить тут не надо.\n"
	case MoveShort:
		return "Эта реплика КОРОТКАЯ и почти пустая: отмашка, поддакивание, «и не говори», «бред», «плюсую». Два-три слова, ничего не объясняй и не развивай.\n"
	case MoveStory:
		return "Эта реплика — СВОЙ СЛУЧАЙ без шутки: что было у тебя или у твоих, коротко и по делу. Панча в ней нет, к морали не своди.\n"
	case MoveOfftop:
		return "Эта реплика НЕ ПРО ЗАМЕТКУ: то, что у тебя сейчас в жизни или на уме, — к предмету разговора можешь не возвращаться вовсе.\n"
	case MoveOther:
		return "Эта реплика — уточнение или переспрос: чего-то в сказанном не хватает, и ты спрашиваешь об этом.\n"
	}
	return ""
}

// ValidateMoveRates — проверка долей. Отказ на СБОРКЕ, а не на первом такте:
// служба с опечаткой в ключе выглядит работающей, а один ход из семи молча
// исчезает.
func ValidateMoveRates(rates map[Move]float64) error {
	if len(rates) == 0 {
		return nil // пусто — берутся умолчания
	}
	var sum float64
	for m, w := range rates {
		if !KnownMove(m) {
			return fmt.Errorf("ход %q: такого нет (%v)", m, Moves)
		}
		if w < 0 || w > 1 {
			return fmt.Errorf("доля хода %q равна %v: бывает от нуля до единицы", m, w)
		}
		sum += w
	}
	if sum <= 0 {
		return fmt.Errorf("доли ходов в сумме дают ноль — писать будет нечем")
	}
	// Сумма НЕ обязана равняться единице: часть ходов в точке отсеивается по
	// пригодности, и доли всё равно пересчитываются. Но грубый промах в сумме
	// это опечатка, а не замысел.
	if sum < 0.5 || sum > 1.5 {
		return fmt.Errorf("доли ходов в сумме дают %.2f — похоже на опечатку", sum)
	}
	return nil
}
