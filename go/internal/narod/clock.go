package narod

// Часы эмуляции.
//
// Служба спрашивает «который час» у часов, а не у time.Now(), потому что жить
// ей приходится в двух временах. В бою это настоящее время: житель отвечает
// через сорок минут, и сорок минут действительно проходят. В реплее сорок минут
// проходить не должны — прогон по десяти архивным тредам занял бы столько же,
// сколько занял оригинальный разговор, то есть недели. Там время виртуальное:
// стрелки переводит сама симуляция, скачком к ближайшему событию.
//
// Отсюда узость интерфейса. Соблазн добавить Sleep был и отвергнут: спящая
// горутина в виртуальном времени превращается либо в настоящее ожидание (и
// реплей снова идёт неделю), либо в мгновенный возврат — а тогда десяток
// «спящих» жителей просыпается одновременно и порядок их пробуждения решает
// планировщик Go, то есть прогон перестаёт быть воспроизводимым. Ждать в
// реплее нечем и не нужно: очередь событий берёт самое раннее и переводит на
// него стрелки (narodsim.Queue).

import (
	"sync"
	"time"
)

// Clock — «который час» с точки зрения службы.
type Clock interface {
	Now() time.Time
}

// RealClock — боевые часы.
type RealClock struct{}

// Now — настоящее время.
func (RealClock) Now() time.Time { return time.Now() }

// VirtualClock — часы реплея: идут не сами, их двигает симуляция.
type VirtualClock struct {
	mu  sync.Mutex
	now time.Time
}

// NewVirtualClock заводит виртуальные часы на заданном моменте.
func NewVirtualClock(start time.Time) *VirtualClock {
	return &VirtualClock{now: start}
}

// Now — текущий момент симуляции.
func (c *VirtualClock) Now() time.Time {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.now
}

// Advance переводит стрелки на t. Назад время не идёт: событие, назначенное
// раньше текущего момента, — это не «в прошлое», а «прямо сейчас», и разница
// между этими прочтениями видна на отчёте прогона. Возвращает время после
// перевода.
func (c *VirtualClock) Advance(t time.Time) time.Time {
	c.mu.Lock()
	defer c.mu.Unlock()
	if t.After(c.now) {
		c.now = t
	}
	return c.now
}
