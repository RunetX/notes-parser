package narod

// С каким чувством житель садится писать ЭТУ реплику.
//
// Третий блок промпта рядом с карточкой («как ты пишешь») и памятью («что ты
// помнишь»), и вопрос у него свой: ПОЧЕМУ человек вообще ввязывается. Без него
// разговор выходит рафинированным — жалоба владельца 29.08.2026: люди на сайте
// годами носят своё и находят ему выход в чужой заметке, а у нас все входили в
// тред эмоционально пустыми.
//
// ЗАМЕРА ЗДЕСЬ НЕТ НИ У ЧЕГО, и это сказано вслух, потому что скрывать нечего:
// в архиве видно, ЧТО человек написал, и не видно, чем он задет и как далеко
// зашёл бы. Всё в этом файле — авторское решение владельца (29.08.2026), а не
// вывод из корпуса. Соседние рычаги кубика замерены, и путать их с этим нельзя.
//
// ЧИСЕЛ В БЛОКЕ НЕТ по тому же правилу, что в памяти (recall.go): скажи модели
// «накал 6» — и она напишет про накал. Ступень называется словами, а слова
// описывают ПОСТУПОК («переходишь на самого собеседника»), а не шкалу.
//
// И ещё одна граница, важнее прочих. Приёмы ниже сняты с живого треда площадки,
// но ДОСЛОВНЫХ цитат оттуда здесь нет ни одной, и это не стилистика: живой текст
// участника в промпте к Claude запрещён опубликованным согласием («не вывозим за
// пределы России»). Приём называется описанием — «насмешливый комплимент сразу
// после возражения», — и работает он так же, а согласие остаётся целым.

import (
	"fmt"
	"strings"
)

// MoodPoint — всё, из чего складывается настроение одной реплики.
type MoodPoint struct {
	Card Card
	// Peer — ник того, кому отвечаем; пусто — пишем в саму заметку, и тогда
	// пары нет, а с ней нет ни накала, ни подтекста.
	Peer       string
	PeerGender string  // male | female | "" — неизвестен
	Tone       float64 // [-1..+1] как житель относится к собеседнику
	// Heat — сколько раз пара УЖЕ обменялась репликами в этом треде. Считает
	// его код и даром: у каждой реплики известны автор и адресат, а «сцепились»
	// это ровно длина их непрерывного обмена.
	Heat int
	// Jab — какой приём задевания взят в ЭТОЙ реплике (индекс в jabWays);
	// отрицательное значение означает «ни одного». Бросается снаружи, в compose,
	// вместе с длиной и эмодзи, и по той же причине.
	Jab int
	// Generalize — вынести ли случай на весь пол (см. generalizeLine). Тоже
	// жребий на реплику, и частота у него замеренная.
	Generalize bool
}

// heatRungs — лестница эскалации, снятая с живого треда: тема → обобщение о
// собеседнике → диагноз → категория людей → приказ → угроза уйти.
//
// Ступенями, а не «пиши жёстче», потому что жёсткость модель понимает как
// громкость и отвечает восклицательными знаками. Ссора же движется СОДЕРЖАНИЕМ:
// на каждом шаге разговор уходит от предмета к человеку, и это шаг, который
// можно назвать.
var heatRungs = []string{
	"речь пока о самом предмете — держись предмета",
	"переходишь с предмета на самого собеседника: не «это неверно», а «ты так говоришь, потому что…»",
	"вместо ответа ставишь диагноз — объясняешь, что у него в голове и почему",
	"обобщаешь до категории людей, к которой его относишь",
	"уже не споришь, а требуешь замолчать или обрываешь разговор",
}

// warmRungs — та же лестница у пары, которая сошлась, а не сцепилась. Нужна
// затем, что накал сам по себе знака не имеет: подряд идущий обмен бывает и
// ссорой, и разговором двоих, отошедшим от темы, — направление задаёт отношение.
var warmRungs = []string{
	"речь пока о самом предмете",
	"разговор уже не про заметку, а про вас двоих",
	"поддеваете друг друга по-свойски, остальные тут лишние",
}

// WriteMood собирает блок настроения. Пустая строка законна: у жителя без
// больного места, пишущего в саму заметку, добавить к промпту нечего.
func WriteMood(p MoodPoint) string {
	var b strings.Builder
	if f := frustrationLine(p.Card.Persona.Frustration); f != "" {
		b.WriteString(f)
	}
	if p.Peer != "" {
		// Ник подаётся ОТДЕЛЬНОЙ пометкой, а не внутри фразы: ники не склоняются
		// («разговор с Кедрачъ»), и любая падежная форма вокруг них читается
		// поломкой — той самой, по которой машинный текст и узнают.
		fmt.Fprintf(&b, "Собеседник: %s. Сейчас: %s.\n", p.Peer, rungOf(p.Heat, p.Tone))
		if s := jabsLine(p.Heat, p.Tone, p.Jab); s != "" {
			b.WriteString(s)
		}
		if s := subtextLine(p); s != "" {
			b.WriteString(s)
		}
	}
	// Вброс не требует собеседника: он про людей из заметки, а не про того, кто
	// сейчас напротив, — и в корневой реплике он как раз уместнее всего.
	if p.Generalize {
		b.WriteString(generalizeLine(p.Card.Persona.Gender))
	}
	if b.Len() == 0 {
		return ""
	}
	// Мат запрещён РЕШЕНИЕМ ВЛАДЕЛЬЦА (29.08.2026), и довод у запрета не
	// нравственный, а арифметический: platmod гасит CatProfanity САМ, по словарю
	// корней, — грубость объявлена жанром раздела, а брань нет. То есть реплика с
	// матом это оплаченная генерация, которую тут же снимут со страницы, плюс
	// дыра в треде на её месте. Токсичность держится на язвительности, а не на
	// брани, и запрет ей не мешает.
	b.WriteString("Мата не пишешь вовсе — ни целиком, ни звёздочками, ни заменой букв.\n")
	return "\n=== С КАКИМ ЧУВСТВОМ ПИШЕШЬ ===\n" + b.String()
}

// frustrationLine — больное место словами.
//
// Вид переводится в ПОВЕДЕНИЕ, а не в жалобу: «тебя задевает…» модель отыгрывает
// признанием («мне одиноко»), а человек своё больное место вслух не называет —
// оно проступает в том, за что он цепляется в чужих словах.
func frustrationLine(kind string) string {
	var what string
	switch kind {
	case FrustLonely:
		what = "чужое благополучие в паре и разговоры о том, что «надо просто уметь любить»"
	case FrustUnseen:
		what = "когда тебя не читают, а отмахиваются, и когда твой опыт объявляют неважным"
	case FrustBody:
		what = "разговоры про внешность, возраст и «пока молодая»"
	case FrustMoney:
		what = "чужой достаток напоказ и советы «просто больше зарабатывать»"
	case FrustChildren:
		what = "чужая уверенность в том, как надо растить детей, и упрёки в их сторону"
	case FrustBetrayal:
		what = "лёгкость, с которой другие говорят о верности и прощении"
	case FrustUnwanted:
		what = "когда при тебе делят людей на нужных и лишних"
	default:
		return ""
	}
	return "Больное место: " + what + ". Вслух ты его не называешь и не жалуешься — " +
		"оно видно только по тому, за что ты цепляешься в чужих словах.\n"
}

// rungOf — ступень лестницы. Направление задаёт отношение, высоту — накал.
func rungOf(heat int, tone float64) string {
	rungs := heatRungs
	if tone >= 0.4 {
		rungs = warmRungs
	}
	if heat < 0 {
		heat = 0
	}
	if heat >= len(rungs) {
		heat = len(rungs) - 1
	}
	return rungs[heat]
}

// jabsLine — формы пассивной агрессии, снятые с живого треда описанием.
//
// Подаются НЕ всегда: на первой реплике незнакомцу они превратили бы в склочника
// каждого, а у живых разговор начинается с предмета. Порог — либо уже начавшийся
// обмен, либо неприязнь, названная графом.
// jabWays — приёмы, которыми задевают не бранью, а формой.
//
// СПИСКОМ ИХ ПОДАВАТЬ НЕЛЬЗЯ, и это оплачено первой же боевой песочницей
// (29.08.2026): перечисление читается как рецепт, и модель делает ПЕРВЫЙ пункт
// каждый раз. В треде из 63 реплик «насмешливый комплимент» стоял в конце почти
// каждой — «Умный вы)», «Наблюдательная», «Догадливая вы)», — а вторым пунктом
// шло уменьшительное от имени, и оно было всюду: Севушка, Валечка, Рябинка.
// Два приёма, названные первыми, стали подписью машины.
//
// Поэтому приём выбирается ОДИН на реплику, жребием, — тем же способом, каким
// уже назначаются длина и эмодзи, и по той же причине: величина живёт МЕЖДУ
// репликами, а модель, прочитавшая список, решает за весь прогон разом.
var jabWays = []string{
	"насмешливый комплимент сразу после возражения",
	"уменьшительное от имени рядом с обесцениванием сказанного",
	"диагноз вместо ответа",
	"припоминание того, что собеседник сам про себя рассказывал раньше",
	"согласие с оговоркой, которая отменяет согласие",
	"вопрос, на который у собеседника нет удобного ответа",
}

func jabsLine(heat int, tone float64, way int) string {
	if heat < 1 && tone > -0.1 {
		return ""
	}
	if way < 0 || way >= len(jabWays) {
		return ""
	}
	return "Задеваешь не бранью, а формой, и в ЭТОЙ реплике ОДНИМ приёмом: " +
		jabWays[way] + ". Другие приёмы прибереги.\n"
}

// generalizeLine — ВБРОС: случай из заметки выносится на весь пол.
//
// Ход этот и есть «основная нить» раздела: спорят на сайте знакомств не о
// предметах, а о том, какие мужчины и какие женщины. Он же зажигает тред —
// возразить хочется всем, кого он задевает.
//
// Частота ЗАМЕРЕНА (29.08.2026, 10,8 млн реплик архива): прямое обобщение
// встречается в 0,198 % реплик, то есть в одной из 504; в тредах, где оно
// вообще звучит, — в одной из 208, и таких тредов 30 % от всех длиннее двадцати
// реплик. Это РЕДКИЙ УДАР, а не фон: разговор, где каждый пятый поминает «всех
// баб», не похож ни на один живой.
//
// Граница замера названа честно: невод ловит ЗАУЧЕННУЮ ФОРМУЛУ («все бабы»,
// «женская логика»), а не поведение, поэтому 0,198 % — это ПОЛ, а не потолок.
// Насколько настоящая доля выше, регулярным выражением не узнать.
func generalizeLine(gender string) string {
	who := "женщины"
	if gender == "female" {
		who = "мужчины"
	}
	return "В ЭТОЙ реплике не разбирай случай поодиночке — вынеси его на весь пол: " +
		who + " вообще так себя и ведут, и тебе это давно ясно. Скажи как решённое, " +
		"без оговорок и без «мне кажется». Возражать будут — и хорошо.\n"
}

// subtextLine — сексуальный подтекст.
//
// Даётся ВСЕМ (решение владельца), а мерой служит сама пара: подтекст живёт
// между мужчиной и женщиной, и рычаг ложится ровно на замеренную разнополость
// разговора (ReplyRate.ToMale/ToFemale — мужчина женщине ×1,36 против ×0,47
// мужчина мужчине). У однополой пары и у неизвестного пола строки нет вовсе.
//
// Знак задаёт отношение: у тёплой пары это флирт, у холодной — то же самое,
// повёрнутое в обесценивание собеседника как мужчины или женщины. Второе у живых
// встречается чаще первого и как раз и читается «пассивной агрессией».
func subtextLine(p MoodPoint) string {
	mine := p.Card.Persona.Gender
	if mine == "" || p.PeerGender == "" || mine == p.PeerGender {
		return ""
	}
	who := "как мужчину"
	if p.PeerGender == "female" {
		who = "как женщину"
	}
	if p.Tone < -0.1 {
		return "Разговор разнополый, и это слышно: обесцениваешь собеседника именно " +
			who + " — намёком, а не прямо, и без телесной грубости.\n"
	}
	return "Разговор разнополый, и это слышно: подтекст, двусмысленность, " +
		"полушутка — намёком, а не прямо; ничего откровенного.\n"
}
