package narod

// Сцена — мир, на котором играет народ.
//
// Интерфейсом, а не *platform.Platform, и довод тот же, по которому ядро не
// импортирует ни площадку, ни архив: ТОТ ЖЕ оркестратор гоняется реплеем
// архивных тредов на машине разработчика, где Postgres не поднят вовсе. Заведи
// мы здесь конкретный тип — и калибровка перестала бы проверять то, что потом
// работает в бою.
//
// Узость списка намеренная. Сцена умеет ровно четыре вещи: сказать, какие
// заметки-песочницы завелись, показать заметку, показать её тред и принять
// реплику. Всё остальное, что площадка про эти строки знает, — статусы,
// модерация, реакции, поводы — служба не спрашивает и спрашивать не должна:
// житель ведёт себя как участник, а не как администратор базы.
//
// НОВОЕ СПРАШИВАЕТСЯ ТАКТОМ, а не живым каналом, и это не упрощение впопыхах.
// Живой канал площадки (LISTEN/NOTIFY, web/hub.go) заведён ради ЧЕЛОВЕКА,
// который смотрит на открытую страницу: там разница между «сразу» и «через
// двадцать секунд» видна глазом. У жителя её нет по построению — задержка
// ответа берётся из замера и составляет минуты и часы (Latency.ToReplySec:
// медиана у доноров 2–20 минут), и такт в полминуты теряется внутри неё
// целиком. Заводить ради этого второе долгоживущее соединение к Postgres,
// которое надо переподключать и сторожить, значило бы платить сложностью за
// точность, которой некому воспользоваться.

import (
	"context"
	"errors"
	"time"
)

// StageNote — заметка-песочница глазами жителя.
type StageNote struct {
	ID           int64
	AuthorID     int64
	AuthorNick   string
	AuthorGender string // male | female | "" — площадка пола не знает
	Body         string
	PublishedAt  time.Time
	Locked       bool
}

// StageReply — чужая реплика в треде.
type StageReply struct {
	ID         int64
	NoteID     int64
	AuthorID   int64
	AuthorNick string
	// Gender — пол сказавшего ("male"/"female"; пусто — неизвестен).
	//
	// Поле сцены, а не догадка по нику, и нужно оно ДВОИМ сразу.
	//
	// КУБИКУ: отклик по полу говорящего — замер, и крупный (ReplyRate.ToMale /
	// ToFemale, 300 тыс. рёбер: мужчина женщине ×1,36, мужчина мужчине ×0,47).
	// В калибровке пол приезжает из архива и рычаг работает, а в бою сцена его не
	// отдавала вовсе — значит боевой кубик выбирал собеседника вслепую, ровно как
	// до замера. Расхождение молчаливое: формула одна на оба мира, а входные
	// данные разные, и заметить это по поведению нельзя.
	//
	// МОДЕЛИ: русский глагол прошедшего времени пола не прощает. Урок этот
	// оплачен один раз — 28.08.2026 модель угадывала пол ПЕРСОНАЖА по нику и
	// половину угадывала неверно (см. innerPrompt), — но исправлен был только
	// свой пол. Про собеседника догадка осталась, и 30.08.2026 она вышла на
	// страницу: «Лисёнок в кедах, ты про себя это и сказал» женщине от женщины.
	Gender      string
	Body        string
	ReplyTo     int64 // 0 — реплика самой заметке
	PublishedAt time.Time
}

// Stage — площадка, на которой жители говорят.
type Stage interface {
	// StageNotesSince — заметки-песочницы с номером больше afterID, по возрастанию
	// номера.
	//
	// КУРСОРОМ ЭТОТ НОМЕР БОЛЬШЕ НЕ СЛУЖИТ. Стояло здесь «полоса нативных id
	// монотонна», и это было верно ровно до 30.08.2026, пока песочницей могла
	// стать только нативная заметка. Зеркальная лежит в полосе НГС, то есть
	// ВСЕГДА ниже любой нативной, — и курсор проходил мимо неё навсегда.
	// Виденное помнит теперь МИР (World.KnownThread), а afterID остался входом
	// для точечного вопроса «что за заметка под этим номером».
	StageNotesSince(ctx context.Context, afterID int64, limit int) ([]StageNote, error)
	// StageThread — весь тред заметки, от старых реплик к новым.
	//
	// ЦЕЛИКОМ, а не порциями: тред и так уходит в промпт целиком, кубику нужен
	// номер каждой реплики по порядку, а песочница — не лента НГС с её девятью
	// сотнями реплик. Когда станет — это будет видно по счёту, а не по догадке.
	StageThread(ctx context.Context, noteID int64) ([]StageReply, error)
	// StagePost публикует реплику жителя и возвращает её номер.
	//
	// Отказ бывает двух пород, и различает их ErrStageBusy (см. ниже).
	StagePost(ctx context.Context, userID, noteID, replyTo int64, body string) (int64, error)
}

// ErrStageBusy — сцена отказала ВРЕМЕННО и НИЧЕГО НЕ ЗАПИСАЛА.
//
// Заведена 31.08.2026 по боевому случаю: у площадки свой потолок частоты (одна
// реплика в десять секунд на человека), написанный для ЧЕЛОВЕКА и меряемый
// СТЕННЫМИ часами, — а житель живёт во времени, сжатом LatencyScale, и два его
// намерения ложатся в одну десятисекундную щель. Четыре реплики из ста тридцати
// четырёх были так потеряны: план снимался насовсем, хотя модель уже вызвана и
// текст написан.
//
// РАЗЛИЧАТЬ ПОРОДЫ ОБЯЗАТЕЛЬНО, и вот почему. Общее правило службы — «строка,
// застрявшая в posting, не переотправляется никогда»: сцена могла реплику и
// ПРИНЯТЬ, ответив ошибкой, а вторая копия под тем же именем хуже пропавшей. То
// же правило у амвона, где не дошедший POST не считается промахом. ErrStageBusy —
// единственное исключение, и держится оно на том, что потолок частоты
// проверяется ВНУТРИ транзакции ДО вставки: отказ ДОКАЗЫВАЕТ, что записи нет.
// Возвращать её на любом другом отказе значит подписаться под двойной репликой.
//
// Ядро о площадке не знает, поэтому перевод стоит на ГРАНИЦЕ (platnarod), тем же
// приёмом и по тому же доводу, что genderWord.
var ErrStageBusy = errors.New("сцена сейчас занята")
