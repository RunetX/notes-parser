// Пакет narod — жители площадки: персонажи, реплики которых пишет модель.
//
// Замысел (briefs/brief-ensemble.md) — не генератор комментариев для оживления
// ленты, а эмуляция сообщества: у персонажа есть характер, память и отношения,
// и меняются они от треда к треду. Отсюда главное отличие от амвона (pulpit),
// который приходится здесь концептуальным предком: там служба одиночная и
// детерминированная, а интерес одной реплики и был целью; здесь интерес рождается
// из итераций простых правил над ПЕРСИСТЕНТНЫМ состоянием, а качество отдельной
// реплики — гигиенический минимум.
//
// Границы пакета. Ядро НЕ импортирует ни platform, ни archive, и это не вкус:
//   - без platform — потому что тот же оркестратор гоняется реплеем архивных
//     тредов на машине разработчика, где Postgres не поднят вовсе (площадка
//     приходит интерфейсом Stage);
//   - без archive — потому что карточка персонажа это ДОКУМЕНТ-контракт, а не
//     проекция внутренних структур архива: разъехавшись, они разъехались бы
//     молча. Карточку из архивной карты письма собирает cmd/lovegw, который и
//     так знает оба мира, а полноту переноса стережёт парный тест.
//
// Что здесь чего стоит по деньгам: майнер, кубик, планировщик и постпроцессор
// ошибок не тратят на модель ничего — платная только генерация реплики и разбор
// закончившегося треда.
package narod

import "time"

// Warning — марка машинного артефакта. Карточка слепка выведена из писем живого
// частного человека, поэтому сама она наружу не идёт никогда: наружу идут только
// реплики композита, у которого ни имени донора, ни его биографии нет.
const Warning = "Машинный артефакт эмуляции: карточка выведена из архивных текстов. " +
	"Не публиковать, не отправлять в мессенджеры, не выкладывать на сайт."

// Stamp ставится КОНСТРУКТОРОМ карточки, а не вызывающим: пути, порождающего
// карточку без марки, в пакете нет (приём взят у archive.VoiceStamp — там он
// оплачен тем, что артефакт легко принять за письмо человека).
type Stamp struct {
	Tool         string `json:"tool"`
	Machine      bool   `json:"machine_generated"`
	DoNotPublish bool   `json:"do_not_publish_raw"`
	CreatedAt    string `json:"created_at"`
	Warning      string `json:"warning"`
}

// NewStamp — марка на артефакт, порождённый инструментом tool.
func NewStamp(tool string, now time.Time) Stamp {
	return Stamp{
		Tool: tool, Machine: true, DoNotPublish: true,
		CreatedAt: now.UTC().Format(time.RFC3339), Warning: Warning,
	}
}
