package web

// Иллюстрации заметки на её странице: главная крупно, остальные полосой под ней
// и любая — в просмотрщике во весь экран.
//
// Зачем это понадобилось. У заметки бывает НЕСКОЛЬКО картинок, и накапливаются
// они сами: автор меняет иллюстрацию на НГС, а зеркало видит не замену, а новый
// адрес — ключ у строки её ссылка, — поэтому прежняя остаётся лежать рядом.
// 10.09.2026 у заметки 313234 их собралось четыре: наша, неверная с НГС,
// исправленная там же и снятая с нашей страницы. Прежний показ выкладывал все
// подряд во всю ширину, и страница начиналась с четырёх экранов одного и того
// же сюжета, причём первым стоял НЕВЕРНЫЙ — порядок шёл по времени появления.
//
// Какая главная, решает НЕ показ, а ядро (platform.mainImageFirst): наша, если
// она есть, иначе последняя с НГС. Одно правило на ленту, канал и эту страницу —
// разойдись они, читатель увидел бы в ленте одну картинку, а на странице другую.
// Здесь порядок только принимается как данность: первая в списке и есть главная.
//
// ПРОСМОТРЩИК СДЕЛАН НА `:target`, а не на скрипте, и это не упрямство: без JS
// страница обязана работать, а строгий CSP запрещает inline-стили, то есть
// готовых библиотек тут не бывает в принципе. Нажатие на картинку — обычный
// переход по анкору, показ накрывающего слоя — обычное правило CSS. Тот же
// приём, которым разворачивается простыня комментария, пришедшего по ссылке.

import (
	"strconv"

	"lovegw/internal/platform"
)

// shotView — иллюстрация в показе: сама картинка плюс адреса соседей по
// просмотрщику. Соседи считаются ЗДЕСЬ, а не в шаблоне, потому что считаются
// они по кругу, а остатка от деления шаблоны не знают.
type shotView struct {
	platform.Media
	// Anchor — id слоя просмотрщика: по нему же строится ссылка с картинки.
	Anchor string
	// Prev и Next — соседи по кругу. Пусты у единственной картинки: стрелка,
	// ведущая на саму себя, — это мёртвая кнопка, а таких площадка не печатает.
	Prev string
	Next string
}

// shotsView собирает иллюстрации заметки к показу.
//
// Строки без байтов выбрасываются здесь, а не в шаблоне: у них пуст URL,
// нарисовать их нечем, — а `len` списка решает, рисовать ли полосу и стрелки, и
// считать он обязан то, что читатель увидит. Такие строки бывают у зеркальной
// заметки, чью картинку мы видели ссылкой и не успели забрать.
func shotsView(noteID int64, imgs []platform.Media) []shotView {
	id := strconv.FormatInt(noteID, 10)
	out := make([]shotView, 0, len(imgs))
	for _, m := range imgs {
		if m.URL == "" {
			continue
		}
		out = append(out, shotView{
			Media:  m,
			Anchor: "shot" + id + "-" + strconv.Itoa(len(out)),
		})
	}
	if len(out) < 2 {
		return out
	}
	for i := range out {
		out[i].Prev = out[(i-1+len(out))%len(out)].Anchor
		out[i].Next = out[(i+1)%len(out)].Anchor
	}
	return out
}

// shotsAnchor — куда возвращает «закрыть». Не «наверх страницы» и не «#»:
// человек смотрел картинки и после закрытия должен оказаться там же, где их
// открыл, — иначе просмотрщик выбрасывал бы его в начало заметки.
func shotsAnchor(noteID int64) string {
	return "shots" + strconv.FormatInt(noteID, 10)
}
