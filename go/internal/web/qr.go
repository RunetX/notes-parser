package web

// QR-код личного контакта (справка, раздел «Как связаться»).
//
// Печатать личный адрес в MAX строкой нельзя по-человечески: это семьдесят
// шесть знаков токена, которые не прочесть глазом, не перепечатать и не
// запомнить, — а нужны они ровно затем, чтобы человек с телефоном попал в
// разговор. Поэтому на странице стои́т КОД, и рисуем мы его сами.
//
// Рисуем ИЗ НАСТРОЙКИ, а не кладём картинкой рядом: адрес живёт в
// platform.contacts.owner_max, и второе его написание — файл, нарисованный
// однажды, — разошлось бы с первым молча, ровно в тот день, когда владелец
// сменит ссылку. Из настройки же следует и место: картинка известна только при
// сборке сервера, а вшитые ресурсы (assets.go) считают свой хеш на старте
// процесса из встроенного каталога, — поэтому код едет в страницу ВНУТРИ
// разметки, отдельным файлом и маршрутом не заводится. Заодно это ни второго
// запроса, ни разговора с CSP: инлайновый <svg> — обычная разметка, а не
// inline-стиль и не скрипт.
//
// Уровень коррекции M (15 %), а не выше. Логотипа мы в код не врисовываем — то
// есть портить его нечем, кроме съёмки с экрана, — а каждый следующий уровень
// это ещё модулей: у нашего адреса M даёт 37 модулей в ряд, Q уже 45. Мелкий
// модуль хуже читается камерой с экрана, и «надёжнее» тут выходит наоборот.
//
// Чёрное по белому при ЛЮБОЙ теме, и подложка своя: инвертированный код (белые
// модули на тёмном) читают не все камеры, а тема у площадки бывает и тёмная.
// Тихое поле в четыре модуля — требование стандарта, без него часть читалок код
// не находит вовсе.

import (
	"fmt"
	"html/template"
	"strings"

	"rsc.io/qr"
)

const (
	// qrQuiet — тихое поле вокруг кода, в модулях. Четыре — как велит стандарт.
	qrQuiet = 4
	// qrSide — сторона картинки на странице. 168 точек — это чуть больше
	// четырёх точек на модуль у нашего адреса (37 модулей плюс поля): меньше —
	// и камера телефона начинает промахиваться, больше — код занимает половину
	// раздела, в котором он всего лишь одна строка из четырёх.
	qrSide = 168
)

// qrSVG — код для ссылки одной строкой разметки.
//
// Собирается ОДИН <path> с горизонтальными пробегами тёмных модулей, а не
// тысяча <rect>: у нашего адреса это 5 КБ против трёх десятков, а страница
// справки отдаётся каждому гостю и не кэшируется вовсе.
//
// shape-rendering="crispEdges" обязателен: со сглаживанием границы модулей
// размываются, и код перестаёт читаться при мелком показе — то есть ровно там,
// где он и стои́т.
//
// Пустая ссылка — пустой результат, а не пустая картинка: кода нет, и места он
// не занимает. Ошибку кодировщика (слишком длинная строка) возвращаем наверх —
// решать, ронять ли из-за неё страницу, не здесь.
func qrSVG(link string, side int) (template.HTML, error) {
	if link == "" {
		return "", nil
	}
	code, err := qr.Encode(link, qr.M)
	if err != nil {
		return "", fmt.Errorf("QR для %q: %w", link, err)
	}
	n := code.Size
	box := n + 2*qrQuiet
	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" `+
		`shape-rendering="crispEdges" role="img" aria-label="QR-код со ссылкой">`+
		`<rect width="%d" height="%d" fill="#fff"/><path fill="#000" d="`,
		box, box, side, side, box, box)
	for y := 0; y < n; y++ {
		for x := 0; x < n; {
			if !code.Black(x, y) {
				x++
				continue
			}
			run := 1
			for x+run < n && code.Black(x+run, y) {
				run++
			}
			fmt.Fprintf(&b, "M%d %dh%dv1h-%dz", x+qrQuiet, y+qrQuiet, run, run)
			x += run
		}
	}
	b.WriteString(`"/></svg>`)
	// template.HTML безопасен здесь по устройству: в разметку не попадает НИ
	// ОДНОГО знака из ссылки — только числа, посчитанные по её коду. Экранировать
	// нечего, а подставить чужой текст неоткуда.
	return template.HTML(b.String()), nil
}
