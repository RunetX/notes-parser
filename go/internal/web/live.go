package web

// Живая страница: сервер шлёт СИГНАЛ, страница идёт читать сама.
//
// На проводе — «в этом треде появилось новое» и «вам стало о чём сказать», и
// ничего больше: ни текста реплики, ни имени, ни готовой разметки. Отдавать
// собранный HTML соблазнительно (страница дописывалась бы сама), но это заводит
// ВТОРОЙ путь сборки текста, а вместе с ним второй источник экранирования — то
// есть возвращает поверхность XSS, которой у площадки нет структурно: весь текст
// хранится плоским и рисуется одним местом. Поэтому скрипт показывает полосу
// «новые ответы — показать», а нажатие на неё это обычный переход.
//
// Три вещи, без которых этот обработчик клал бы площадку, и каждая из них —
// прямое следствие того, что соединение живёт минутами, а не миллисекундами.
//
//  1. МИМО СЕМАФОРА. Общий потолок морды — двенадцать запросов в работе разом
//     при пуле в четыре соединения к Postgres (guard.go). Десяток открытых
//     вкладок занял бы его целиком, и площадка перестала бы отдавать страницы
//     вовсе. Поэтому /live идёт мимо семафора и мимо срока запроса, а взамен
//     имеет СВОИ потолки — общий и на человека.
//  2. БЕЗ БАЗЫ. Обработчик не делает ни одного запроса: он читает из хаба в
//     памяти (hub.go). Соединение, держащее строку пула, обнулило бы смысл
//     пункта первого.
//  3. ТОЛЬКО ВОШЕДШИМ. Это не про права — читать площадку может каждый, — а про
//     арифметику: так число долгоживущих соединений ограничено числом
//     участников, а не числом читателей. Гостю страница не дописывается, и это
//     ровно то, чем он теряет.
//
// Отдельная ловушка — WriteTimeout сервера (45 с). Он ставит дедлайн на ВЕСЬ
// ответ, то есть оборвал бы поток на середине минуты; снимается он только для
// этого соединения, через http.ResponseController.

import (
	"fmt"
	"net/http"
	"strconv"
	"time"
)

const (
	// maxLiveConns — сколько потоков держим всего. Шестьдесят четыре при
	// нынешних десятках участников — это «каждый с двумя вкладками», и упереться
	// в потолок раньше, чем в память, здесь дешевле, чем наоборот.
	maxLiveConns = 64
	// maxLivePerUser — сколько потоков одному человеку. Две вкладки: лента и
	// тред. Третья получит отказ и обойдётся обычной страницей.
	maxLivePerUser = 2
	// liveTTL — сколько живёт одно соединение. Пять минут, после чего сервер
	// прощается сам, а браузер переподключается (это встроено в EventSource).
	// Так соединения перетасовываются, и зависший клиент не занимает слот вечно.
	liveTTL = 5 * time.Minute
	// livePing — как часто шлём двоеточие-комментарий. Держит соединение живым
	// через прокси, которые рвут «молчащие» потоки, и первым узнаёт об уходе
	// клиента: запись в закрытый сокет — это и есть признак, что пора уходить.
	livePing = 20 * time.Second
	// liveGrace — на сколько поток укорачивается, если дедлайн записи снять не
	// удалось: он обязан закрыться САМ до общего WriteTimeout, а не быть
	// оборванным на середине сообщения.
	liveGrace = 5 * time.Second
)

// handleLive — поток событий. Отвечает text/event-stream и живёт до liveTTL,
// отмены запроса или отказа записи.
func (s *Server) handleLive(w http.ResponseWriter, r *http.Request) {
	u, ok := s.me(r)
	if !ok || s.hub == nil {
		// Гостю и при выключенном канале — «нет такой страницы»: обещать
		// возможность, которой у этого человека нет, незачем.
		s.fail(w, r, http.StatusNotFound, "Такой страницы нет.")
		return
	}
	rc := http.NewResponseController(w)
	// Снимаем дедлайн записи ИМЕННО У ЭТОГО соединения: общий WriteTimeout
	// оборвал бы поток на 45-й секунде.
	//
	// Не вышло — не отказ. Транспорт, не умеющий дедлайнов, встречается за
	// нестандартным сервером и в тестах, и правильный ответ тут «жить меньше»,
	// а не «не жить вовсе»: поток закрывается САМ, до общего срока, и браузер
	// переподключается ровно так же, как после обычного истечения liveTTL.
	// Отказать значило бы, что EventSource вечно долбится в 501.
	ttl := liveTTL
	if err := rc.SetWriteDeadline(time.Time{}); err != nil {
		ttl = writeTimeout - liveGrace
		s.log.Debug("живой канал: дедлайн записи не снимается", "err", err)
	}

	l := &listener{ch: make(chan liveMsg, listenerBuffer), topics: []string{userTopic(u.ID)}}
	q := r.URL.Query()
	if note := noteParam(q.Get("note")); note != 0 {
		l.topics = append(l.topics, noteTopic(note))
	}
	if q.Get("feed") != "" {
		l.topics = append(l.topics, feedTopic)
	}
	if !s.hub.subscribe(l, maxLiveConns, maxLivePerUser) {
		// Не поломка, а честная очередь — как «площадка сейчас занята» у
		// обычных страниц. Retry-After читают и браузер, и человек.
		retryLater(w, http.StatusServiceUnavailable, 60,
			"Слишком много открытых вкладок с живым обновлением.")
		return
	}
	defer s.hub.unsubscribe(l)

	h := w.Header()
	h.Set("Content-Type", "text/event-stream; charset=utf-8")
	h.Set("Cache-Control", "no-store")
	// Явно для прокси, которые буферизуют по умолчанию: без этого сигналы
	// копятся и приезжают пачкой, то есть страница «живой» не становится, а
	// соединение всё равно висит. У нашего Caddy это настроено отдельно.
	h.Set("X-Accel-Buffering", "no")
	w.WriteHeader(http.StatusOK)
	if err := rc.Flush(); err != nil {
		return
	}

	ping := time.NewTicker(livePing)
	defer ping.Stop()
	deadline := time.NewTimer(ttl)
	defer deadline.Stop()

	for {
		select {
		case <-r.Context().Done():
			return
		case <-deadline.C:
			return
		case <-ping.C:
			// Комментарий SSE: клиент его не видит, а сокет проверяется.
			if _, err := fmt.Fprint(w, ": ping\n\n"); err != nil {
				return
			}
		case m := <-l.ch:
			if _, err := fmt.Fprintf(w, "id: %d\ndata: %s\n\n", m.ID, liveData(m)); err != nil {
				return
			}
		}
		if err := rc.Flush(); err != nil {
			return
		}
	}
}

// liveData — тело сигнала. Собирается вручную, а не через encoding/json:
// полей три, все числа и наши же строки-константы, и городить кодировщик ради
// двадцати байт незачем.
func liveData(m liveMsg) string {
	if m.Note == 0 {
		return `{"kind":"` + m.Kind + `"}`
	}
	return `{"kind":"` + m.Kind + `","note":` + strconv.FormatInt(m.Note, 10) + `}`
}

// noteParam — какой тред слушать. Мусор читается как «никакой»: это не форма, а
// подсказка от собственной страницы, и отвечать на неё ошибкой незачем.
func noteParam(s string) int64 {
	id, err := strconv.ParseInt(s, 10, 64)
	if err != nil || id <= 0 {
		return 0
	}
	return id
}
