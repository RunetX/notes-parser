// Аватар по умолчанию: силуэт вместо буквы.
//
// Фото есть далеко не у всех — байты приезжали живым потоком зеркала, у теней
// из архива их не бывает вовсе, — и до 18.08.2026 на месте фото стояла БУКВА
// ника. Буква была нашей выдумкой: на НГС её нет нигде, там в этом месте стоит
// СИЛУЭТ, и стоит он по полу — /static/i/new/profile/male300px.png,
// female300px.png, anonymous300px.png (имена сняты с записанных страниц,
// notes_feed.html и comments_312696.html). Три файла скачаны с самого сайта
// 18.08.2026 и вшиты в бинарник, как смайлы: это часть ВИДА страницы, а не
// чьё-то вложение, и окно закрывается вместе с сайтом.
//
// Четвёртый файл (unknown.png) — НАШ, и на НГС такого нет: там пол известен
// всегда, его спрашивают при регистрации. У нас известен не всегда — он
// приезжает со страницы комментариев при обходе дерева (Ш6) и со входом,
// поэтому у теней его сплошь и рядом нет. Ставить в этом случае мужской силуэт
// значило бы назвать мужчинами половину площадки, а силуэт анонима означает
// «нарочно спрятался» — про безанкетного комментатора зеркала это неправда.
// Отсюда нейтральный: геометрия снята с male300px (голова x94..210, y34..190,
// срез бюста на y=239), серый — у anonymous300px (#d6d6d6 на светлом фоне).
//
// В хранилище медиа силуэт по-прежнему не кладётся (см. platsink: «аватар есть
// у всех» — это не аватар, а фон). Он рисуется отсюда, из статики, и не
// занимает ни строки в базе: 117 тыс. заметок и 10,7 млн реплик ссылаются на
// один и тот же файл с хешем в имени, то есть браузер берёт его один раз.

import "lovegw/internal/platform"

// silhouette — какой силуэт показать человеку без фото.
//
// Аноним идёт ПЕРВЫМ и без оглядки на пол: под анонимной публикацией не должно
// проступать ничего о её авторе, даже намёка «это была женщина». Ядро автора
// анонимки и так не отдаёт (в NoteView для него просто нет поля), но правило
// показа стоит и здесь — граница держится в двух местах, а не в одном.
func silhouette(g platform.Gender, anonymous bool) string {
	switch {
	case anonymous:
		return assetURL("profile/anonymous300px.png")
	case g == platform.GenderMale:
		return assetURL("profile/male300px.png")
	case g == platform.GenderFemale:
		return assetURL("profile/female300px.png")
	default:
		return assetURL("profile/unknown.png")
	}
}
