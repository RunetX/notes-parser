package web

// Откуда текст заметки: пришёл зеркалом с love.ngs.ru или написан здесь.
//
// Ш5з, просьба владельца 21.08.2026: в ленте вперемешку лежат заметки НГС,
// раскатанный архив и написанное на площадке, а различить их глазом нельзя.
// Различие при этом уже действует — у зеркальной нет правки, у неё пунктирная
// дата (точного времени сайт не отдаёт), в ней иначе разбирается разметка и не
// бывает карточек роликов, — но НИ ОДНО из этих отличий себя не называет.
//
// Разбор 21.08 предлагал метить не источник, а достижимость автора («автор
// здесь» / «автор на НГС»), чтобы не спорить с уже действующим правилом:
// различие показывается на АВТОРЕ, в форме ответа (platform.Author.Shadow,
// parts/reply.gohtml). Формулировка владельца 26.08.2026 этот замысел отменяет —
// «автор может быть один и тот же, но какая-то заметка опубликована только
// внутри, а какая-то могла прилететь с НГС»: у вошедшего участника обе заметки
// дали бы «автор здесь», то есть метка про человека не различает их вовсе.
//
// Двух меток об одном при этом не выходит, и держится это словами: та отвечает
// «дойдёт ли мой ответ» (про человека), эта — «откуда текст и почему его нельзя
// править» (про заметку).
//
// Источник различия — ПОЛОСА ИДЕНТИФИКАТОРОВ, никакой колонки source: у строки
// НГС id равен id на сайте, поэтому из него же строится и адрес оригинала.

import (
	"strconv"

	"lovegw/internal/platform"
)

// ngsBase — адрес love.ngs.ru для ссылки на оригинал.
//
// Пакетной переменной по тому же образцу и с той же оговоркой, что и
// setOwnLinkPrefix: сервер в процессе один, а шаблоны с их FuncMap разбираются
// один раз на процесс. Пусто — метка остаётся, ссылки нет: адрес чужого сайта
// мы не выдумываем.
var ngsBase string

func setNGSBase(base string) {
	ngsBase = trimSlash(base)
}

func trimSlash(s string) string {
	for len(s) > 0 && s[len(s)-1] == '/' {
		s = s[:len(s)-1]
	}
	return s
}

// noteOrigin — метка происхождения заметки.
//
// Метки этой на НГС не было — там и второго источника не было, — поэтому по
// правилу Ш5з она объясняет себя сама: заголовком при наведении и разделом в
// /help. Ровно как колокольчик и «исправлено».
// Показывается она ЗНАЧКОМ (решение владельца 26.08.2026): подпись словами
// печатала имя чужого сайта на каждой карточке ленты, а метка отвечает на
// вопрос, который задают редко, — спорить за внимание с датой ей незачем.
// Label от этого не исчезает: он уходит в .sr-only и остаётся именем ссылки для
// читалки, а объяснение для глаза даёт Title.
type noteOrigin struct {
	Label string // имя источника — для читалки, не для глаза
	Title string // что она означает, при наведении
	Icon  string // какой значок рисовать: own | mirror
	URL   string // адрес оригинала; пусто — вести некуда
}

// originOf — метка для заметки с этим номером.
//
// Значков ДВА, а не три: раскатанный архив и восстановленное из чужих зеркал
// читателю ничем не отличаются от свежего зеркала — это всё «пришло с НГС».
// Ссылка при этом ставится только строкам самого НГС: у восстановленной эпохи
// (полоса [2e11..3e11)) страницы на сайте нет и не было, и вести туда значило бы
// обещать несуществующее.
func originOf(id int64) noteOrigin {
	if platform.IsNative(id) {
		return noteOrigin{
			Label: SiteName,
			Title: "Заметка написана здесь, на площадке: у неё нет другого адреса, и правит её автор",
			Icon:  "own",
		}
	}
	o := noteOrigin{
		Label: "НГС",
		Title: "Заметка пришла с love.ngs.ru — здесь её копия, поэтому её текст не правится",
		Icon:  "mirror",
	}
	if platform.IsNGS(id) && ngsBase != "" {
		o.URL = ngsBase + "/notes/" + strconv.FormatInt(id, 10) + "/"
	}
	return o
}
