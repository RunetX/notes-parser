package web

// Мордолента — полоса лиц над содержимым страницы.
//
// Имя не выдумано: так её звали на НГС сами участники («а что там за
// проститутка в мордоленте?», «фоты мои по мордоленте не катаются», «мордолента
// уже третьи сутки не двигается» — всё это лежит в архиве комментариев). Там
// это была полоса фотографий на странице раздела, и попасть в неё было
// отдельным маленьким событием. У нас в ней живут ЖИТЕЛИ (эпик «народ»), и
// причина ровно та же, по которой у них вообще появилась своя страница: люди
// приходят в раздел к ЛЮДЯМ, а лента заголовков этого не показывает.
//
// Три решения, которые стоит назвать вслух, потому что каждое можно было
// принять иначе:
//
//   - только с ФОТО. Полоса силуэтов сообщает читателю ровно ничего, а
//     мордолента есть лента лиц — отбор делает сам запрос (JOIN к media);
//   - на всех страницах ЧТЕНИЯ, а не на одной ленте (просьба владельца
//     30.08.2026: «на странице заметки, профиля и справки тоже должна
//     отображаться»). Первая версия висела над первой страницей ленты, и довод
//     у неё был «шапка, которая едет за читателем»; на НГС же полоса — не
//     украшение ленты, а часть РАЗДЕЛА. Пишущие и служебные страницы (вход,
//     согласия, «моя страница», события, модерация, форма заметки, отказы) её не
//     получают: там человек ДЕЛАЕТ, а не читает, и лица соседей ему не помощь;
//   - порядок — по последнему сказанному слову (см. platform.personaFacesQuery).
//     Полоса с вечным порядком за неделю становится частью фона; на НГС
//     мордолента двигалась, и жаловались там как раз на то, что она стои́т.
//
// Наружу полоса не выдаёт ничего из песочницы: в ней имя, лицо и адрес
// страницы жителя — то же самое, что видно под любой его репликой.
//
// ВИД СНЯТ С ОРИГИНАЛА, а не придуман: в записанной ленте
// (love/testdata/notes_feed.html) это section.lv-top-tape ПЕРЕД блоком
// содержимого, внутри один ряд фотографий 100×100 («visible-part»), ни одной
// подписи — имя лежит в alt и всплывает при наведении — и тень со стрелкой у
// края (lv-top-tape__nav), которой ряд и двигают. У нас так же, только вместо
// тамошнего qtip обычный title: он работает без JS.
//
// Ряд ЛИСТАЕТСЯ, а полосы прокрутки не видно: она разрезала бы ряд лиц пополам,
// и на сайте её не было тоже. Пальцем и тачпадом это работает без скрипта,
// стрелки у краёв рисует app.js — мёртвых кнопок на странице не бывает.
//
// Что реплики жителей пишет машина, полоса НЕ объявляет (решение владельца
// 30.08.2026: подпись под ней ломала сходство с оригиналом). Правило Ш5з от
// этого не нарушено — метка не своя, а перенесённая, и объяснять себя обязана
// не она: про машину сказано значком песочницы у самой заметки, на странице
// жителя и в /help#narod.

import (
	"context"
	"net/http"
	"sync"
	"time"

	"lovegw/internal/platform"
)

// facesLimit — сколько лиц влезает в полосу.
//
// Потолок стоит не потому, что жителей много (их десятки), а потому, что число
// это ничем не ограничено СНАРУЖИ: `narod enroll` заводит их сколько угодно, а
// полоса едет теперь в каждую страницу чтения. Шестьдесят — заведомо больше
// нынешнего населения и заведомо меньше того, за что стоит платить разметкой:
// в ряд их влезает восемь, остальные ждут за краем (и не грузятся вовсе —
// картинки ленивые).
const facesLimit = 60

// facesTTL — сколько живёт прочитанная полоса.
//
// Кэш понадобился вместе с переездом полосы на все страницы чтения: запрос сам
// по себе дёшев (частичный индекс плюс по одному обращению на жителя), но
// платить за него КАЖДОЙ страницей заметки — это уже расход, а меняется полоса
// от силы раз в минуту, когда кто-то из жителей заговорил. Полминуты
// устаревания стоят ровно одного: порядок лиц на полминуты отстаёт от треда.
//
// Тот же приём и та же причина, что у счётчика длины ленты (feed.go), включая
// мьютекс вокруг похода в базу: он заодно схлопывает наплыв в один запрос.
const facesTTL = 30 * time.Second

// faceCache — прочитанная полоса и когда её читали. Живёт в памяти процесса:
// пережить рестарт ей незачем, а делить её с демоном нечем и не нужно.
type faceCache struct {
	mu sync.Mutex
	at time.Time
	v  []platform.PersonaFace
}

// faces — мордолента. Отказ чтения полосу гасит, но страницу не роняет: без лиц
// страница остаётся страницей, а без страницы лица не нужны — то же правило, что
// у иллюстраций ленты (thumbs). Отказ при этом НЕ запоминается: пустая полоса на
// полминуты из-за одной неудачной секунды была бы платой ни за что.
func (s *Server) faces(ctx context.Context) []platform.PersonaFace {
	s.band.mu.Lock()
	defer s.band.mu.Unlock()
	if time.Since(s.band.at) < facesTTL {
		return s.band.v
	}
	out, err := s.st.PersonaFaces(ctx, facesLimit)
	if err != nil {
		s.log.Error("мордолента", "err", err)
		return nil
	}
	s.band.v, s.band.at = out, time.Now()
	return out
}

// readingPage — общая часть СТРАНИЦЫ ЧТЕНИЯ: то же, что newPage, плюс полоса
// лиц над карточкой.
//
// Отдельным конструктором, а не полем внутри newPage, ровно затем, чтобы список
// таких страниц был виден по вызовам: лента, заметка, участник, справка. Положи
// мы полосу в newPage — она появилась бы и на входе, и в согласиях, и на
// странице отказа, то есть там, где человек занят делом, а не чтением.
func (s *Server) readingPage(r *http.Request, title string) page {
	p := s.newPage(r, title)
	p.Faces = s.faces(r.Context())
	return p
}
