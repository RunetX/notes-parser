package web

// Мордолента — полоса лиц над лентой заметок.
//
// Имя не выдумано: так её звали на НГС сами участники («а что там за
// проститутка в мордоленте?», «фоты мои по мордоленте не катаются», «мордолента
// уже третьи сутки не двигается» — всё это лежит в архиве комментариев). Там
// это была полоса фотографий на странице раздела, и попасть в неё было
// отдельным маленьким событием. У нас в ней живут ЖИТЕЛИ (эпик «народ»), и
// причина ровно та же, по которой у них вообще появилась своя страница: люди
// приходят в раздел к ЛЮДЯМ, а лента заголовков этого не показывает.
//
// Три решения, которые стоит назвать вслух, потому что каждое можно было
// принять иначе:
//
//   - только с ФОТО. Полоса силуэтов сообщает читателю ровно ничего, а
//     мордолента есть лента лиц — отбор делает сам запрос (JOIN к media);
//   - только ПЕРВАЯ страница ленты. На остальных полоса была бы шапкой, которая
//     едет за читателем, а листает он как раз затем, чтобы уйти от начала. Тот
//     же довод, что у закреплённых заметок, и та же выгода: на страницах
//     2…5933 лишнего запроса нет вовсе;
//   - порядок — по последнему сказанному слову (см. platform.personaFacesQuery).
//     Полоса с вечным порядком за неделю становится частью фона; на НГС
//     мордолента двигалась, и жаловались там как раз на то, что она стои́т.
//
// Наружу полоса не выдаёт ничего из песочницы: в ней имя, лицо и адрес
// страницы жителя — то же самое, что видно под любой его репликой.
//
// ВИД СНЯТ С ОРИГИНАЛА, а не придуман: в записанной ленте
// (love/testdata/notes_feed.html) это section.lv-top-tape ПЕРЕД блоком
// содержимого, внутри один ряд фотографий 100×100 («visible-part»), ни одной
// подписи — имя лежит в alt и всплывает при наведении — и тень со стрелкой у
// края (lv-top-tape__nav), которой ряд и двигают. У нас так же, только вместо
// тамошнего qtip обычный title: он работает без JS.
//
// Ряд ЛИСТАЕТСЯ, а полосы прокрутки не видно: она разрезала бы ряд лиц пополам,
// и на сайте её не было тоже. Пальцем и тачпадом это работает без скрипта,
// стрелки у краёв рисует app.js — мёртвых кнопок на странице не бывает.
//
// Что реплики жителей пишет машина, полоса НЕ объявляет (решение владельца
// 30.08.2026: подпись под ней ломала сходство с оригиналом). Правило Ш5з от
// этого не нарушено — метка не своя, а перенесённая, и объяснять себя обязана
// не она: про машину сказано значком песочницы у самой заметки, на странице
// жителя и в /help#narod.

import (
	"context"

	"lovegw/internal/platform"
)

// facesLimit — сколько лиц влезает в полосу.
//
// Потолок стоит не потому, что жителей много (их десятки), а потому, что число
// это ничем не ограничено СНАРУЖИ: `narod enroll` заводит их сколько угодно, а
// полоса едет в самый частый запрос площадки. Шестьдесят — заведомо больше
// нынешнего населения и заведомо меньше того, за что стоит платить запросом и
// разметкой: в ряд их всё равно влезает восемь, остальные обрезаны показом (и
// потому не грузятся вовсе — картинки ленивые).
const facesLimit = 60

// faces — мордолента. Отказ чтения полосу гасит, но ленту не роняет: без лиц
// лента остаётся лентой, а без ленты лица не нужны — то же правило, что у
// иллюстраций (thumbs).
func (s *Server) faces(ctx context.Context) []platform.PersonaFace {
	out, err := s.st.PersonaFaces(ctx, facesLimit)
	if err != nil {
		s.log.Error("мордолента", "err", err)
		return nil
	}
	return out
}
