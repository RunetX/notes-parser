package web

// «Проматывать к новым» — страница сама встаёт на пришедшую реплику.
//
// Просьба владельца 26.08.2026: «когда в заметке прилетают новые комментарии,
// непонятно где они». Это прямое следствие того, как устроен живой добор: в
// ЛИНЕЙНОМ виде новое встаёт сверху и потому заметно, а в ДЕРЕВЕ реплика
// садится в свою ветку — то есть где угодно, в том числе выше прочитанного и за
// пределами экрана. Подсветка у неё есть (.fresh, шесть секунд свечения), но
// подсветка отвечает на вопрос «которая из них новая», когда ты уже на неё
// смотришь, и молчит на вопрос «а где она».
//
// Почему КУКА, а не колонка в users. Предпочтений у площадки уже два — тема и
// вид треда, — и оба живут куками ровно потому, что описывают ПОВЕДЕНИЕ ЭКРАНА,
// а не человека: на телефоне, за которым следишь, прыжок к новому уместен, а во
// вкладке, открытой фоном на рабочей машине, он же — увод страницы из-под рук.
// Третий механизм ради третьего предпочтения пришлось бы оправдывать; повторение
// уже принятого — нет. Цена названа честно и в самой подписи на странице: выбор
// не переезжает на другое устройство и снимается вместе с данными сайта.
//
// Живёт настройка на /me, а не в меню участника рядом с темой (просьба владельца
// была «опция в профиле»), и это не спор с правилом «отдельной страницы настроек
// не заводим»: /me и есть та самая единственная страница про меня. Тема стоит в
// меню по своей причине — её переключают, глядя на страницу, которую она красит.
//
// Исполняет прыжок скрипт (assets/app.js), потому что исполнять его больше
// нечему: строка приезжает БЕЗ перезагрузки. Отсюда и граница ответственности
// сервера — он только передаёт флаг на страницу атрибутом, ровно как отдаёт
// data-fresh; без JS настройка не делает ничего и не притворяется, что делает.

import "net/http"

// jumpCookie — «проматывать к новым». Значение одно, «1»: отсутствие куки и есть
// «нет», а второго значения для «нет» заводить незачем — снятая галочка куку
// гасит.
const jumpCookie = "jump"

// jumpFresh — стоит ли у этого читателя прыжок к новой реплике.
func (s *Server) jumpFresh(r *http.Request) bool {
	c, err := r.Cookie(s.cookieName(jumpCookie))
	return err == nil && c.Value == "1"
}

// handleJump — переключатель со страницы «Моя страница».
//
// Форма с POST, а не ссылка, и по той же причине, что у темы и выхода: GET на
// смену состояния браузер нажимает сам в префетче. CSRF при этом НЕ спрашивается
// — как и у темы: подделанное нажатие меняет одну лишь прокрутку у самого
// пострадавшего, а sameOrigin отсекает чужую страницу и без него.
func (s *Server) handleJump(w http.ResponseWriter, r *http.Request) {
	if !sameOrigin(r) {
		s.fail(w, r, http.StatusForbidden, "Запрос пришёл не с нашей страницы.")
		return
	}
	if err := r.ParseForm(); err != nil {
		s.fail(w, r, http.StatusBadRequest, "Форма не разобралась.")
		return
	}
	if r.FormValue("on") == "1" {
		s.setCookie(w, jumpCookie, "1", prefTTL)
	} else {
		s.setCookie(w, jumpCookie, "", 0)
	}
	http.Redirect(w, r, "/me", http.StatusSeeOther)
}
