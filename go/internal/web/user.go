// profileView — то, что на странице человека ВИДНО: карточка, справочная
// колонка, альбом, рассказ и последние публикации.
//
// Структура ОДНА на две страницы — свою и чужую, — и это не экономия. С
// 12.09.2026 «Моя страница» показывает ровно тот же профиль, что видят другие
// (решение владельца: «к чему отдельно „Мой профиль" и „Моя страница"»), а
// собранный двумя разными кусками кода он разошёлся бы молча — и человек
// правил бы не то, что показывают. Рисует обе страницы один шаблон
// (parts/profile.gohtml) по тому же доводу, по которому у живого добора и
// страницы один рендер тела реплики.
type profileView struct {
	Member platform.Profile
	// Facts — справочная колонка слева, строками «что — какое». Собирается в
	// Go, а не перечисляется в шаблоне цепочкой {{if}}: пустое поле
	// пропускается поштучно (строка «Город: —» хуже отсутствующей — то же
	// правило, что у контактов в справке), и решить, осталось ли вообще что
	// показывать, можно только посчитав.
	Facts []userFact
	// Photos — альбом (эпик M). Пустой у всех, кто ничего не клал, и у ЖИТЕЛЯ
	// всегда: лицо ему рисует генератор по промпту, второго лица того же жителя
	// нарисовать нечем — три «его» фотографии оказались бы тремя разными
	// людьми.
	Photos []platform.Photo
	// HasSide — рисовать ли две колонки. Ответ обязан быть ОДИН на обе половины
	// сетки: нарисуй мы .ucols без .uside, грид положил бы записи в первую
	// колонку шириной 220px — страница схлопнулась бы в полосу, и ни один тест
	// поведения этого бы не увидел.
	HasSide bool
	// AboutHidden — карточку скрыл модератор, и смотрящий её всё же видит:
	// такое бывает у владельца и у модератора. Строка над ней объясняет, почему
	// другие этого не видят.
	AboutHidden bool
	Notes       []platform.PubNote
	Comments    []platform.PubComment
	// NotesTrimmed и ComsTrimmed — список показан не целиком. Счётчик у
	// заголовка называет ВСЁ написанное, а строк под ним два десятка, и без
	// этой оговорки заголовок «Заметки 412» над двадцатью строками врал бы
	// ровно так же, как прежняя строка «Заметок 5», под которой было три.
	NotesTrimmed bool
	ComsTrimmed  bool
	// Edit — правка прямо на странице, и непусто оно только у ХОЗЯИНА. Форма
	// живёт в том же шаблоне, что и показ, ровно затем, чтобы правили то, что
	// видят: до 12.09.2026 рассказ о себе правился на третьей странице, и
	// человек её не находил вовсе.
	Edit *profileEdit
}

// profileEdit — всё, что нужно формам своей страницы. Отдельной структурой, а
// не полями страницы: шаблон профиля один на свою и чужую, и «нет правки»
// обязано быть одним нулевым указателем, а не пятью условиями подряд.
type profileEdit struct {
	CSRF string
	// Signed — подписан ли profile.v1. Не подписан — форм нет вовсе, а есть
	// ссылка на экран документа: подпись, данная мимоходом под полем ввода,
	// подписью не является.
	Signed bool
	// Limit и Free — сколько фотографий бывает и сколько мест ещё свободно.
	// Числа приезжают ИЗ ЯДРА: потолок держит база (CHECK на позицию), и
	// написанная рядом тройка разошлась бы с ним молча.
	Limit int
	Free  int
	// MaxRunes — потолок длины рассказа, тоже из ядра: написанное в шаблоне
	// число разошлось бы с проверкой молча.
	MaxRunes int
	// Shots — перекодировщик поднят, файл принять есть чем. Не поднялся —
	// страница живёт дальше, просто без поля файла.
	Shots bool
	// Side — до какой длинной стороны фотография всё равно будет уменьшена на
	// сервере. Печатается в разметку затем, чтобы браузер уменьшил её ЗАРАНЕЕ
	// (assets/app.js): канал до площадки отдаёт десятки килобайт в секунду, и
	// девять десятых веса снимка едут к нам, чтобы быть выброшенными. Число
	// одно и живёт в Go — второе его написание в скрипте разошлось бы молча.
	Side int
	// About — что стои́т в полях формы. На отказе это НАБРАННОЕ человеком, а не
	// прочитанное из базы: перечитав, мы стёрли бы его работу.
	About platform.About
	Saved bool
	Bad   string
}

type userPage struct {
	page
	Prof   profileView
	Banned bool
	// CanModerate и CanAdmin — показывать ли решения. Два поля, а не одно:
	// запрет писать ставит модератор, роли раздаёт только администратор, и это
	// то самое различие «про слова / про людей», ради которого двери разведены.
	CanModerate bool
	CanAdmin    bool
	// Me — своя собственная страница. Нужно ровно затем, чтобы не предлагать
	// модератору забанить самого себя.
	Me bool
	// MailTo — куда ведёт кнопка «Написать»; пусто — кнопки нет. Адрес, а не
	// «можно ли»: у переписки три исхода (её ещё нет, она уже есть, документ не
	// подписан), и решать, в какой из них вести, обязано одно место.
	MailTo string
	// MailWhy — почему кнопки нет, когда сказать это надо вслух. Непусто только
	// у чёрного списка: закрытому говорят ПРЯМО (решение владельца 11.09.2026),
	// а видит эту строку один тот, кому она про него.
	MailWhy string
	// MailUnblock — закрыл переписку Я САМ, и снять запрет можно прямо здесь.
	// Кнопка стои́т РЯДОМ с причиной по одному доводу со страницей переписки:
	// текст, отсылающий человека на другую страницу за кнопкой, которую можно
	// поставить сюда, — это лишний переход и повод забыть, зачем шёл.
	MailUnblock bool
}

// userFact — строка справочной колонки.
//
// Значение — готовая разметка, а не строка, ровно ради дат: время у нас всегда
// <time> с новосибирским поясом и подписью у неточного (whenHTML), и второй
// способ напечатать дату завёл бы на площадке две разные даты. Поэтому
// собирается оно двумя конструкторами, и голой строки сюда не положить.
type userFact struct {
	K string
	V template.HTML
}

// plainExcerpt — выдержка для списка публикаций: знаки разметки и коды смайлов
// сняты, лишние пробелы схлопнуты.
//
// Ядро режет тело до двухсот рун ДО нас, поэтому на срезе может остаться
// половина тега («[colo») — её тоже убираем: незакрытая скобка в конце строки
// выглядит поломкой, а не текстом. Убираем только когда закрывающей скобки за
// ней нет вовсе, иначе пострадала бы честная квадратная скобка из текста.
func plainExcerpt(s string, e era) string {
	s = stripMarkup(s, e)
	if i := strings.LastIndexByte(s, '['); i >= 0 && !strings.ContainsRune(s[i:], ']') {
		s = s[:i]
	}
	return strings.TrimSpace(strings.Join(strings.Fields(s), " "))
}

func textFact(k, v string) userFact {
	return userFact{K: k, V: template.HTML(template.HTMLEscapeString(v))}
}

func dateFact(k string, t time.Time) userFact {
	return userFact{K: k, V: whenHTML(t, false)}
}

// mailButton — куда ведёт «Написать» и что сказать вместо кнопки.
//
// Вопрос к ядру ОДИН (CanWriteTo), и ответ его переводится здесь целиком:
// второго списка правил — «а не тень ли», «а не отозвал ли» — на морде не
// заводится, иначе кнопка однажды нарисуется там, где отправка откажет.
func (s *Server) mailButton(r *http.Request, me platform.User, peerID int64) (to, why string, unblock bool) {
	if s.mail == nil || me.ID == 0 || me.ID == peerID {
		return "", "", false
	}
	dialog, err := s.mail.CanWriteTo(r.Context(), me.ID, peerID)
	id := strconv.FormatInt(peerID, 10)
	switch {
	case errors.Is(err, platform.ErrNoTalkConsent):
		// Документ не подписан — ведём к нему, а не прячем кнопку.
		return "/mail/consent?to=" + id, "", false
	case errors.Is(err, platform.ErrBlockedByYou):
		// СВОЙ запрет снимается своей же рукой, и рука эта здесь.
		_, why := mailProblem(err)
		return "", why, true
	case errors.Is(err, platform.ErrBlockedByPeer):
		// А ЧУЖОЙ не снимается ничем, и кнопки тут быть не может: причина
		// названа, и это всё, что мы вправе сказать.
		_, why := mailProblem(err)
		return "", why, false
	case err != nil:
		// Сюда попадает и ErrNoRecipient, и всё, что случилось по дороге:
		// молчим. Про первое ядро молчит намеренно, а поломку счётчика писем
		// человеку на чужой странице объяснять нечем.
		return "", "", false
	case dialog != 0:
		return dialogPath(dialog), "", false
	}
	return "/mail/new?to=" + id, "", false
}

func (s *Server) handleUser(w http.ResponseWriter, r *http.Request) {
	me, signedIn := s.me(r)
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil || id <= 0 {
		s.fail(w, r, http.StatusNotFound, "Такого участника нет.")
		return
	}
	member, err := s.st.UserProfile(r.Context(), id)
	if err != nil && !errors.Is(err, platform.ErrNotFound) {
		s.oops(w, r, "страница участника", err)
		return
	}
	// Гостю открыты ЖИТЕЛИ и тот, кого площадка сама назвала в контактах, — и
	// «такого нет» отвечается ему ТАК ЖЕ, как «есть, но живой»: разведи мы эти
	// два ответа, перебор номеров сказал бы постороннему, какие анкеты на
	// площадке заведены. Вход, а не «нет такой страницы», потому что страница
	// ЕСТЬ и войдя человек её увидит.
	//
	// Владелец открыт по той же логике, по которой открыт житель: закрывали
	// страницу доводом «заметки и реплики открыты поиску по отдельности, а
	// профиль собирает их в одно место», — а тут человек сам поставил ссылку на
	// себя в контакты, то есть распорядился своими данными. Ссылка, отвечающая
	// гостю «войдите», не контакт, а тупик.
	if !signedIn && (err != nil || !member.Persona) && id != s.cfg.Contacts.ProfileID {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}
	if err != nil {
		s.fail(w, r, http.StatusNotFound, "Такого участника нет.")
		return
	}
	mailTo, mailWhy, mailUnblock := s.mailButton(r, me, member.ID)
	prof, ok := s.profileBody(w, r, me, member, nil)
	if !ok {
		return
	}
	s.render(w, r, http.StatusOK, "user.gohtml", userPage{
		page:        s.readingPage(r, userTitle(member)),
		Prof:        prof,
		Banned:      member.Banned(time.Now()),
		CanModerate: me.Role >= platform.RoleModerator && s.mod != nil,
		CanAdmin:    me.Role >= platform.RoleAdmin && s.mod != nil,
		Me:          me.ID == member.ID,
		MailTo:      mailTo,
		MailWhy:     mailWhy,
		MailUnblock: mailUnblock,
	})
}

// profileBody собирает то, что видно на странице человека, — для своей
// страницы и для чужой одинаково.
//
// Отдельной функцией, а не двумя сборками: до 12.09.2026 «Моя страница» и
// страница участника показывали РАЗНОЕ про одного и того же человека, и
// владелец справедливо спросил, к чему их две. Теперь показ один, а различает
// страницы только edit — правка, которой у чужой нет.
//
// Отказ пишет сама (ok=false): у всех трёх запросов свои слова, и собирать их
// в одну обёртку значило бы потерять, что именно не прочиталось.
func (s *Server) profileBody(w http.ResponseWriter, r *http.Request, me platform.User, member platform.Profile, edit *profileEdit) (profileView, bool) {
	notes, err := s.st.AuthorNotes(r.Context(), member.ID, 0)
	if err != nil {
		s.oops(w, r, "заметки участника", err)
		return profileView{}, false
	}
	comments, err := s.st.AuthorComments(r.Context(), member.ID, 0)
	if err != nil {
		s.oops(w, r, "реплики участника", err)
		return profileView{}, false
	}
	// Скрытую модератором карточку видят ДВОЕ — он сам и её владелец; для всех
	// остальных её нет вовсе, вместе с рассказом, городом, занятием и снимками.
	// Решается это ОДНИМ вопросом и здесь, а не тремя условиями в шаблоне:
	// разойдясь, они однажды показали бы половину скрытого.
	showAbout := member.AboutStatus == platform.StatusVisible ||
		me.ID == member.ID || me.Role >= platform.RoleModerator
	var photos []platform.Photo
	if showAbout {
		// Свой альбом и альбом глазами модератора идут целиком: скрытая
		// фотография, которой владелец у себя не видит, выглядит пропавшей.
		all := me.ID == member.ID || me.Role >= platform.RoleModerator
		photos, err = s.st.ProfilePhotos(r.Context(), member.ID, all)
		if err != nil {
			s.oops(w, r, "альбом участника", err)
			return profileView{}, false
		}
	}
	if !showAbout {
		member.Bio, member.City, member.Job = "", "", ""
	}
	// Выдержки идут через ТОТ ЖЕ снос знаков, что и заголовок вкладки: список
	// показывает ПЛОСКИЙ текст, а в базе лежит разметка НГС и коды смайлов — и
	// до 12.09.2026 они печатались как есть, «[color=red]UPD.» и «:::crazy2:::»
	// посреди строки (замечание владельца). Эпоха у каждой записи своя, как у
	// её тела: у заметки 2013 года скобки рисовал сайт, у сегодняшней — мы.
	for i, n := range notes {
		notes[i].Excerpt = plainExcerpt(n.Excerpt, eraOf(n.ID, n.At))
	}
	for i, c := range comments {
		e := eraOf(c.ID, c.At)
		comments[i].Excerpt, comments[i].Note = plainExcerpt(c.Excerpt, e), plainExcerpt(c.Note, e)
	}
	// Колонку держат ГОРОД, ЗАНЯТИЕ и АЛЬБОМ — то, что человек рассказал сам.
	// «Здесь с» уехало в служебную строку под именем и колонки собой больше не
	// оправдывает: у незаполненного профиля она выходила полосой в 220 точек с
	// единственной датой, и страница читалась перекошенной (замечание
	// владельца 12.09.2026). У ХОЗЯИНА колонка стои́т всегда: в ней живут формы
	// правки, и прятать их, пока не рассказано ничего, значило бы прятать
	// единственную дорогу что-нибудь рассказать.
	facts := userFacts(member)
	return profileView{
		Member:       member,
		Facts:        facts,
		Photos:       photos,
		HasSide:      len(facts) > 0 || len(photos) > 0 || edit != nil,
		AboutHidden:  showAbout && member.AboutStatus != platform.StatusVisible,
		Notes:        notes,
		Comments:     comments,
		NotesTrimmed: member.Notes > len(notes),
		ComsTrimmed:  member.Comments > len(comments),
		Edit:         edit,
	}, true
}

// userFacts — справочная колонка: что о человеке известно СТРОКАМИ, а не
// абзацем. Пустое не попадает сюда вовсе, поэтому шаблону остаётся один range,
// а не цепочка условий, каждое из которых однажды забудут.
//
// Чего здесь нет и не будет: последнего визита (огонёк «онлайн» эпик E не
// переносил сознательно) и полей анкеты НГС — обещание подписанных согласий
// прямо говорит, что кроме ника, фотографии и пола оттуда не показывается
// ничего.
func userFacts(m platform.Profile) []userFact {
	var out []userFact
	if m.City != "" {
		out = append(out, textFact("Город", m.City))
	}
	if m.Job != "" {
		out = append(out, textFact("Занятие", m.Job))
	}
	// «Здесь с» отсюда уехало в служебную строку под именем (12.09.2026): это
	// справка площадки о записи, а не то, что человек о себе рассказал, — и
	// колонку, где кроме него ничего нет, оно оправдывать не должно. Там же
	// стои́т и правило про обезличенных: время создания могилы огрублено до
	// суток НАМЕРЕННО, и печатать его рядом со словами «обезличенная запись»
	// значит рассказывать ровно то, что скрыто.
	return out
}

// userTitle — заголовок вкладки. Ник, а нет его (обезличенный, тень без имени)
// — номер: пустая вкладка в ряду из двадцати не отличима ни от чего.
func userTitle(m platform.Profile) string {
	if m.Nick != "" {
		return m.Nick
	}
	return "Участник №" + strconv.FormatInt(m.ID, 10)
}

// userDecisions — аргумент шаблона «moddec»: решения модератора и
// администратора об одном человеке.
//
// Собирается в Go по той же причине, что и modAct у полоски под репликой:
// «что кому показать» — решение, и приниматься оно обязано там же, где все
// остальные.
type userDecisions struct {
	ID          int64
	Nick        string
	Banned      bool
	BannedUntil *time.Time
	BanReason   string
	Role        platform.Role
	CanAdmin    bool
	CSRF        string
	Back        string
}

func userDecisionsOf(p userPage) userDecisions {
	return userDecisions{
		ID:          p.Prof.Member.ID,
		Nick:        p.Prof.Member.Nick,
		Banned:      p.Banned,
		BannedUntil: p.Prof.Member.BannedUntil,
		BanReason:   p.Prof.Member.BanReason,
		Role:        p.Prof.Member.Role,
		CanAdmin:    p.CanAdmin,
		CSRF:        p.CSRF,
		Back:        p.Back,
	}
}

// kindWord — чем человек здесь является, словами.
//
// Житель назван первым и вслух: читатель вправе знать, что реплики этого автора
// пишет машина, а справка (/help/narod) имён не называет намеренно — список из
// десяти ников устареет через неделю, признак у анкеты не устареет.
func kindWord(m platform.Profile) string {
	switch {
	case m.AnonymizedAt != nil:
		return "обезличенная запись"
	case m.Persona:
		return "житель площадки"
	case m.Kind == platform.KindShadow:
		return "ещё не переехал сюда с НГС"
	case m.Kind == platform.KindService:
		return "служебная анкета"
	default:
		return "участник"
	}
}
