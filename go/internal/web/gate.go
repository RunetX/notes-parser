package web

// Ворота: при MembersOnly площадку читают только вошедшие.
//
// Решение владельца 12.09.2026, и оно прямо обратно принятому 18.08.2026
// («чтение открыто всем»), поэтому важно, чем именно оно НЕ является. Это не
// возврат прежнего слоя внутри роутера: тот жил проверками в обработчиках, и
// список закрытого расходился со списком, который видел робот. Здесь список
// ОДИН — guestRoots, — и он отвечает на единственный вопрос, ради которого его
// читают: что видит посторонний, пришедший по ссылке из канала.
//
// Открытого ровно три рода, и каждый открыт по своей причине:
//
//	вход       — /login со всеми его дверями (код в анкете, приглашение, ключ
//	             из бота): запертая дверь без замочной скважины не дверь;
//	             /consent рядом с ним потому, что подпись согласий стоит МЕЖДУ
//	             входом и участием, и заперев её, мы заперли бы сам вход;
//	объяснение — /help: правила, которые видно только изнутри, — это не
//	             правила, а сюрприз (довод 18.08.2026, он решения не потерял);
//	бумаги     — /consents, /privacy, /disclaimer: политику обработки оператор
//	             обязан опубликовать так, чтобы её прочёл ЛЮБОЙ (ч. 2 ст. 18.1),
//	             то есть за вход её убирать НЕЛЬЗЯ. Это не наша щедрость, а
//	             закон, и потому строка в списке не обсуждается.
//
// Плюс /assets (без таблицы стилей форма входа — голый текст), /robots.txt и
// /healthz: первый обязан быть виден именно роботу, второго спрашивает
// оркестратор, у которого сессии нет и быть не может.
//
// МЕДИА ОСТАЮТСЯ ОТКРЫТЫМИ, и это решение, а не забывчивость. В бою файлы
// отдаёт Caddy, мимо Go, — то есть закрой мы /media здесь, в бою не изменилось
// бы ничего, а локальная разработка разошлась бы с боем молча. Вдобавок
// «Политика» прямо обещает обратное: картинка «отдаётся по собственному адресу
// вида t3h.ru/media/…, открытому без входа: у кого есть ссылка, тот файл и
// увидит». Обещание это остаётся правдой, и закрывать надо было бы Caddyfile, а
// не морду.
//
// КАРТА САЙТА, напротив, уходит за ворота: она печатает адрес и время последней
// реплики КАЖДОЙ из 117 тысяч заметок, то есть посторонний получал бы из неё
// ровно то, чего его лишили страницами. Роботу она после этого бесполезна, и
// robots.txt о ней больше не говорит (handleRobots).

import (
	"net/http"
	"strings"
)

// guestRoots — разделы, открытые не вошедшему при закрытой площадке. Совпадение
// считается по СЕГМЕНТАМ, а не по префиксу строки, — по той же причине, что и у
// privateRoots: «/consent» не должен открывать «/consentX», а «/help» обязан
// открывать «/help/login».
var guestRoots = []string{
	"/login", "/consent", "/consents", "/privacy", "/disclaimer",
	"/help", "/assets", "/media", "/robots.txt", "/healthz",
}

// openToGuests — этот адрес посторонний увидит и при закрытой площадке.
func openToGuests(p string) bool {
	if p == "/" {
		// Корень — это ЛЕНТА, а не визитка: пускать в неё гостя значит не
		// закрыть ничего. Названо явно, потому что иначе «/» совпало бы с
		// префиксом любого корня из списка.
		return false
	}
	for _, root := range guestRoots {
		if p == root || strings.HasPrefix(p, root+"/") {
			return true
		}
	}
	return false
}

// withGate отворачивает постороннего на страницу входа.
//
// Стоит слой ПОСЛЕ withViewer: ему надо знать, вошёл ли человек, а сессия
// читается один раз за запрос и лежит в контексте. И стоит он ДО mux, а не
// внутри обработчиков, — иначе каждый новый маршрут пришлось бы помнить
// закрыть, и первый же забытый открыл бы площадку целиком.
//
// Отвечает РЕДИРЕКТОМ, а не страницей входа по чужому адресу: адрес в строке
// браузера обязан совпадать с тем, что на экране, иначе человек, нажавший
// «обновить», второй раз получит не то, что видел. Возврата «куда он шёл» в
// редиректе нет намеренно — параметр с адресом пришлось бы проверять на чужой
// хост (открытый редирект), а платить этим риском за удобство одного перехода
// не стоит: после входа человек попадает в ленту, и заметка из канала лежит на
// расстоянии одного нажатия «назад».
func (s *Server) withGate(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if !s.cfg.MembersOnly || openToGuests(r.URL.Path) {
			next.ServeHTTP(w, r)
			return
		}
		if _, ok := s.me(r); ok {
			next.ServeHTTP(w, r)
			return
		}
		http.Redirect(w, r, "/login", http.StatusSeeOther)
	})
}
