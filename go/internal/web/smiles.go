// Смайлы НГС: :::popcorn:::, :::boogi:::, :::agree:::.
//
// Своя система знаков, дожившая до сентября 2017-го, и в архиве она заметнее
// BB-кодов: замер 18.08.2026 по 1 642 652 комментариям выгрузок досье — 6–11 %
// комментариев 2013–2017 годов несут хотя бы один смайл, у одного
// «:::popcorn:::» 9 581 вхождение. Без разбора это голые коды посреди фразы.
//
// ФОРМ У КОДА ДВЕ, и старшая — тильда: «~flowers~ ~boogi~». Замер 07.09.2026 по
// всему архиву (117 736 заметок, 10,8 млн реплик) говорит, что формы разошлись
// по МЕСТУ: в заметках писали тильдой (34 718 вхождений в 14 998 заметках, до
// четверти всех заметок 2010 года), в комментариях — двоеточиями (375 945
// реплик против 1 546 с тильдой). Прежний замер её не назвал потому, что искал
// ИЗВЕСТНЫЕ знаки — «:::» и скобки, — а вопроса «чем ещё писали смайл» никто не
// задал; отсюда правило: набор знаков спрашивают у КОРПУСА, а не у списка,
// который уже знаешь.
//
// Рубеж у обеих форм ОДИН, и в этом весь довод не заводить второй эпохи:
// тильда идёт сплошь до августа 2017-го, в сентябре одно вхождение, дальше НОЛЬ
// на 20 тысяч заметок 2018–2026 годов — то есть рисовал их один и тот же
// механизм сайта, и выключили его разом. Подтверждает это и чужая рука: зеркало
// заметок 2015 года (dump/lnParser) подменяло картинками ровно «~код~» и
// таблицу свою звало old_smiles.
//
// Картинки вшиты в бинарник (assets/smile), а не сложены в хранилище медиа:
// это часть вида страницы, а не чьё-то вложение. Скачаны они с самого сайта
// 18.08.2026 — и совпали БАЙТ В БАЙТ с копией 2015 года из старого парсера
// (dump/lnParser), то есть за одиннадцать лет ни один файл не поменялся.
// Восемь кодов, встреченных в архиве, сайт не отдаёт вовсе (baby2, bye,
// chereshnya, cofee, coo1, cpool1, eys1, yawn — от 1 до 4 вхождений каждый):
// это опечатки авторов, и на самом НГС они тоже остались текстом.
//
// Окно закрывается вместе с сайтом: пока love.ngs.ru отвечает, файлы можно
// забрать, потом — неоткуда. Поэтому взят ВЕСЬ набор, а не только встреченные
// в выгрузках коды: полный корпус вшестеро больше замера, и там наверняка есть
// коды, которых мы не видели. Восемь файлов (baby, cake, coffee, blush1, eek1,
// smile1, tongue1, yes) найдены перебором соседних имён — каталог сайта не
// листается, а страница-выбиралка смайлов с него давно снята.
//
// ЕЩЁ 23 ФАЙЛА добраны 07.09.2026, и назвал их полный замер: тильда открыла
// коды, которых в комментариях почти нет, а в заметках сотни — ~catwoman~ 469,
// ~airborne~ 331, ~givekiss~ 247, плюс новогодний набор (superng, dedmoroz,
// snegur, showng, santaclaus, snegurochka, decoratedtree, dedmoroz2,
// dedsnegurochka, dedsnegurochka2), biker, bounce1, inlove1, inlove3, wub1,
// affection, artist, climb, clone, airkiss. Настоящий код от опечатки отделяет
// САМ САЙТ, а не наше суждение о частоте: на эти 23 он отдал файл, на cofee,
// coffe, coffie, biker1, shuflle и прочие — отказ. Итого 87 файлов, 256 КБ.
// После добора без картинки остались ДВА вхождения на весь архив («~39~» и
// «~93~» — чей-то номер в тильдах).

import (
	"html"
	"html/template"
	"path"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// smileyRe — код смайла в тексте, в обеих формах сайта. Нижний регистр и цифры:
// так их писал сайт (`:::cool1:::`, `~heart2~`), а верхний регистр в архиве не
// встречается вовсе. Одно выражение на две формы, а не два прохода: второй
// смотрел бы на строку, в которую первый уже вписал НАШУ картинку с кодом в
// alt, — и порядок проходов решал бы, что из чего получилось.
var smileyRe = regexp.MustCompile(`:::([a-z0-9_]{1,20}):::|~([a-z0-9_]{1,20})~`)

// smileySunset — когда сайт перестал их показывать. Замер тот же, что у
// bbSunset: коды идут сплошь до 08.2017, в сентябре их 11, дальше НОЛЬ на
// 1,3 млн комментариев 2018–2026 годов; тильда в заметках кончается там же —
// август 2017-го, дальше одно вхождение в сентябре и ноль. Разметка и смайлы
// умерли порознь — отсюда и два рубежа вместо одного «раньше было лучше».
var smileySunset = time.Date(2017, 10, 1, 0, 0, 0, 0, time.UTC)

// smiley — картинка и её собственный размер. Размеры у набора разные (от 15×15
// до 100×20), поэтому они читаются из самого файла и ставятся атрибутами: без
// них строка дёргается, пока грузится картинка.
type smiley struct {
	url string
	w   int
	h   int
}

var smiles = map[string]smiley{}

// initSmiles вызывается из init статики, а не своим init: порядок здесь не
// вопрос вкуса — карта строится ИЗ уже собранных assetURLs, а порядок двух
// init в пакете задаётся именами файлов, то есть держится случайностью.
func initSmiles() {
	for name, url := range assetURLs {
		if !strings.HasPrefix(name, "smile/") || path.Ext(name) != ".gif" {
			continue
		}
		code := strings.TrimSuffix(path.Base(name), ".gif")
		s := smiley{url: url}
		if a, ok := assets[strings.TrimPrefix(url, "/assets/")]; ok {
			s.w, s.h = gifSize(a.data)
		}
		smiles[code] = s
	}
	if len(smiles) == 0 {
		panic("web: картинки смайлов не найдены")
	}
}

// gifSize достаёт размер из заголовка GIF: после «GIF89a» идут ширина и высота
// по два байта, младшим вперёд. Читать его самим дешевле, чем держать рядом
// таблицу размеров, которая разъедется с файлами при первой же замене.
func gifSize(b []byte) (int, int) {
	if len(b) < 10 || string(b[:3]) != "GIF" {
		return 0, 0
	}
	return int(b[6]) | int(b[7])<<8, int(b[8]) | int(b[9])<<8
}

// smileImg — картинка смайла по коду. Нужна не только тексту: теми же знаками
// подписаны кнопки реакций (react.go), и рисоваться они обязаны одинаково —
// иначе «:::agree:::» в реплике и «согласен» на кнопке выглядели бы разной
// мыслью. Неизвестный код даёт пустоту, а не битую картинку.
func smileImg(code string) template.HTML {
	s, ok := smiles[code]
	if !ok {
		return ""
	}
	var b strings.Builder
	writeSmileImg(&b, s, ":::"+code+":::")
	return template.HTML(b.String())
}

// writeSmileys пишет текст, подменяя известные коды картинками.
//
// Экранирование остаётся первичным: подставляем мы только СВОИ адреса из
// статики, а всё, что пришло из базы, уходит в html.EscapeString — в том числе
// сам код в alt. Неизвестный код не разметка и не ошибка: он остаётся текстом,
// ровно как оставался на сайте.
func writeSmileys(b *strings.Builder, line string) {
	idx := 0
	for _, m := range smileyRe.FindAllStringSubmatchIndex(line, -1) {
		s, ok := smiles[smileyCode(line, m)]
		if !ok {
			continue
		}
		b.WriteString(html.EscapeString(line[idx:m[0]]))
		writeSmileImg(b, s, line[m[0]:m[1]])
		idx = m[1]
	}
	b.WriteString(html.EscapeString(line[idx:]))
}

// smileyCode — сам код из совпадения. Групп две, по одной на форму, и
// незанятая приходит парой -1: у регулярки с развилкой другого способа сказать
// «совпало вот это» нет.
func smileyCode(line string, m []int) string {
	if m[2] >= 0 {
		return line[m[2]:m[3]]
	}
	return line[m[4]:m[5]]
}

// writeSmileImg — сама картинка. Размер ставится атрибутами: набор
// разнокалиберный, и без них строка дёргается, пока смайлы грузятся.
func writeSmileImg(b *strings.Builder, s smiley, alt string) {
	b.WriteString(`<img class="sm" src="`)
	b.WriteString(s.url)
	b.WriteString(`" alt="`)
	b.WriteString(html.EscapeString(alt))
	if s.w > 0 {
		b.WriteString(`" width="` + strconv.Itoa(s.w) + `" height="` + strconv.Itoa(s.h))
	}
	b.WriteString(`" loading="lazy">`)
}

// smileTop — порядок выбиралки: сперва то, чем пользуются, дальше по алфавиту.
//
// Числа те же, что у реакций (замер по боевому корпусу, 5 % от 10,77 млн
// комментариев): человеку, открывшему панель, нужен popcorn, а не baby2, и
// искать его глазами в алфавитном списке из шестидесяти четырёх картинок —
// работа, которой можно не быть.
var smileTop = []string{
	"crazy2", "agree", "popcorn", "flowers", "shuffle", "boogi",
	"sad2", "wow", "str", "live", "respect", "bottle",
	"tease", "eek", "susel", "umn", "mad2", "pester", "lick", "sorrow",
}

// smileList — все коды набора для выбиралки под формой.
func smileList() []string {
	out := make([]string, 0, len(smiles))
	seen := map[string]bool{}
	for _, code := range smileTop {
		if _, ok := smiles[code]; ok {
			out, seen[code] = append(out, code), true
		}
	}
	rest := make([]string, 0, len(smiles))
	for code := range smiles {
		if !seen[code] {
			rest = append(rest, code)
		}
	}
	sort.Strings(rest)
	return append(out, rest...)
}
