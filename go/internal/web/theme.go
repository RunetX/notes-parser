package web

// Темы. Механика ровно та же, что у токенов CSS: выбор человека живёт в куке и
// приезжает на страницу атрибутом data-theme. Не выбирал — атрибут всё равно
// стоит, и в нём тема по умолчанию (см. defaultTheme): состояния «темы нет» у
// страницы больше не бывает.
//
// Переключатель — форма с POST, а не ссылка: смена темы меняет состояние, а
// GET-ссылка на такое сама себя нажимает в любом префетче браузера. И не JS:
// страница обязана работать без него, а с ним ничего не улучшается.

import (
	"net/http"
	"time"
)

const (
	themeCookie = "theme"
	// prefTTL — срок жизни кук с предпочтениями (тема, вид треда). Год: это не
	// доступ и не личные данные, а выбор оформления, и переспрашивать его
	// каждую неделю незачем.
	prefTTL = 365 * 24 * time.Hour
)

// Theme — вариант оформления. Пустого идентификатора здесь не бывает: тема
// есть у КАЖДОЙ страницы, у невыбиравшего — defaultTheme. Отсюда следствие,
// ради которого это и стоит называть вслух: нажатую кнопку теперь называет
// разметка (класс on), а не CSS, — сервер больше не гадает, что у человека на
// экране, он это знает.
type Theme struct {
	ID   string
	Name string
}

// themes — весь набор. Первые две — палитра НГС, светлая и тёмная: их числа
// сняты с сайта и закреплены fidelity_test, потому что на них держится
// преемственность. Вторые две — свои, и заведены они по просьбе владельца
// (18.08.2026): переезд не обязывает жить в чужом оформлении вечно.
//
// Правило набора одно, и оно оплачено сокращением с четырёх тем до двух: кнопка
// обязана показывать то, чего не показывает другая. Прежние «Классика» и
// «Светлая» отдавали одну и ту же палитру НГС — два имени на одно оформление
// читаются как «есть что-то ещё», а нажатие это не подтверждало. Поэтому
// «Бумага» — не подкрашенная светлая (тёплый лист без синевы, тёмная шапка,
// другой акцент), а «Графит» — не осветлённая тёмная (нейтральный сланец
// вместо чёрного и графитовая шапка вместо синей шапки сайта). Стережёт это
// TestThemePalettesAreDistinct: он сравнивает не имена, а сами токены.
//
// ПЯТАЯ И ШЕСТАЯ — ПАРА (12.09.2026, дизайн «Гримуар»): одно оформление в двух
// яркостях, средневековый фасад на киберпанковом двигателе. Правило набора
// этим не нарушено, а прочитано точно: «тёмная с загадкой» и «светлая с
// загадкой» показывают разное — на светлом пергаменте витраж и латунь читаются
// иначе, чем на чёрном экране, и человек выбирает между ними, а не между
// «посветлее» и «потемнее».
//
// Порядок здесь — это порядок кнопок в меню (грид 1fr 1fr), поэтому светлая
// сестра идёт первой: левый столбец выходит целиком светлым, правый целиком
// тёмным, и шесть кнопок читаются как три пары, а не как список из шести.
//
// Идентификатор classic остался от прежнего набора — он уже лежит в куках
// людей; он же попадает в класс кнопки (.tbtn.t-<id>), поэтому идентификаторы
// только латиницей.
var themes = []Theme{
	{ID: "classic", Name: "Светлая"},
	{ID: "dark", Name: "Тёмная"},
	{ID: "paper", Name: "Бумага"},
	{ID: "graphite", Name: "Графит"},
	{ID: "stained", Name: "Витраж"},
	{ID: "grimoire", Name: "Гримуар"},
}

// defaultTheme — чем площадка встречает того, кто ещё не выбирал: «Витраж»
// (решение владельца 12.09.2026; до этого дня «Графит», а до 30.08.2026
// умолчания не было вовсе — атрибут не ставился, и палитру держал
// prefers-color-scheme, то есть вид площадки определяла настройка чужой
// операционной системы).
//
// Плата названа прямо, потому что она не нулевая, и с этого дня она
// РАЗВЕРНУЛАСЬ: «как в системе» по-прежнему не работает ни для кого, но теперь
// светлую страницу получает тот, у кого система тёмная. Вернуть себе тёмную он
// может только кнопкой в меню участника, то есть ВОЙДЯ — переключателя у гостя
// нет (он переехал в меню 23.08.2026). Взамен у площадки есть свой вид: один и
// тот же у гостя, у поисковика и на чужом экране, а не тот, что подвернулся
// настройкам.
//
// Умолчание — не «первая в списке» и не отдельная палитра: это ровно одна из
// шести кнопок, и человек, нажавший «Витраж» руками, и человек, не нажимавший
// ничего, видят одно и то же. Второй палитры «по умолчанию» здесь не заводится.
const defaultTheme = "stained"

// legacy — значения куки, которых в наборе больше нет. Уронить их в умолчание
// нельзя: у выбравшего светлую тему страница почернела бы сама.
var legacy = map[string]string{"light": "classic"}

func themeList() []Theme { return themes }

// defaultThemeName — как тема по умолчанию называется по-русски. Нужно справке:
// она обязана называть её вслух, а второе написание имени рядом с первым
// разошлось бы молча — ровно то, чем справка уже однажды соврала про потолок
// реплик в час.
func defaultThemeName() string {
	for _, t := range themes {
		if t.ID == defaultTheme {
			return t.Name
		}
	}
	return defaultTheme
}

func validTheme(id string) bool {
	for _, t := range themes {
		if t.ID == id {
			return true
		}
	}
	return false
}

// theme — тема этой страницы. Пустой ответ невозможен: не выбирал или прислал
// мусор — получает умолчание. Мусор здесь не ошибка, а рабочий случай: кука
// приходит от человека, и доверять ей нечего.
func (s *Server) theme(r *http.Request) string {
	c, err := r.Cookie(s.cookieName(themeCookie))
	if err != nil {
		return defaultTheme
	}
	if id, ok := legacy[c.Value]; ok {
		return id
	}
	if !validTheme(c.Value) {
		return defaultTheme
	}
	return c.Value
}

func (s *Server) handleTheme(w http.ResponseWriter, r *http.Request) {
	if !sameOrigin(r) {
		s.fail(w, r, http.StatusForbidden, "Запрос пришёл не с нашей страницы.")
		return
	}
	if err := r.ParseForm(); err != nil {
		s.fail(w, r, http.StatusBadRequest, "Форма не разобралась.")
		return
	}
	id := r.FormValue("theme")
	if !validTheme(id) {
		s.fail(w, r, http.StatusBadRequest, "Такой темы нет.")
		return
	}
	// Выбор всегда явный: пустое значение форма не отправляет вовсе, и validTheme
	// его больше не пропускает.
	s.setCookie(w, themeCookie, id, prefTTL)
	http.Redirect(w, r, localPath(r.FormValue("back")), http.StatusSeeOther)
}
