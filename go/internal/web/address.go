package web

// Обращение, которое УЖЕ есть в теле реплики.
//
// Устройство площадки такое: адресат живёт ребром `reply_to_id`, а «Ник, »
// дорисовывается показом из ТЕКУЩЕГО ника — только так переименование и
// обезличивание меняют подпись везде, включая чужие ответы. Чтобы обращение не
// вышло дважды, приём срезает его из тела (`platform.TrimAddress`), сверяя с
// ником адресата: без сверки «Кстати, я тоже» лишилось бы первого слова.
//
// Сверка промахивается ровно там, где человек ПЕРЕИМЕНОВАЛСЯ: в теле стоит ник
// на ту дату, а сверяем мы с нынешним. Тогда на странице выходит «Паноптикум,
// Рантье, привычное…» — один и тот же человек старым ником и новым.
//
// ЧЕМ ОТЛИЧИТЬ НИК ОТ ЗАЧИНА ФРАЗЫ. Первая попытка (18.08.2026) считала
// обращением всё, что стоит до первой запятой, и была откачена в тот же час:
// на живой странице из 227 обращений 62 оказались фразами — «Вы не
// представляете, как я люблю холодок», «пока писала, вспоминала подробности».
// Замер, которым я это себе разрешил, был неверен по методике: он считал
// совпадения со списком частых зачинов, а зачины — длинный хвост
// НЕПОВТОРЯЮЩИХСЯ фраз, и в такой список не попадают по определению.
//
// Отличает их повтор. Ник — это то, чем к человеку обращаются РАЗНЫЕ люди и
// не по одному разу; случайная фраза так не повторяется. Свидетельство берётся
// из самого треда, который и так весь лежит в памяти страницы: если токеном «X»
// в этой заметке обращались к ОДНОМУ И ТОМУ ЖЕ человеку дважды и больше — это
// его ник. Плюс дешёвая вторая примета: X совпадает с нынешним ником кого-то из
// участников заметки, то есть это заведомо ник, а не фраза.
//
// Чего этот способ НЕ ловит: одиночное обращение старым ником в маленьком
// треде. Там обращение по-прежнему выйдет дважды — и это честнее, чем резать
// чужой текст по догадке.

import (
	"strings"

	"lovegw/internal/platform"
)

// maxAddressRunes — потолок длины обращения. Ники бывают длинные («любовник
// мэри попинс», «Девочка с автоматом»), но не длиннее строки: всё, что больше,
// — это уже фраза с запятой, а не имя.
const maxAddressRunes = 40

// addressRepeats — сколько раз токен должен обратиться к одному человеку в
// пределах заметки, чтобы считаться его ником. Два: одиночное совпадение — это
// с тем же успехом начало фразы, а трёх в коротком треде может не набраться.
const addressRepeats = 2

// leadingAddress разбирает начало тела: «Ник, текст» → («Ник», «текст», true).
//
// Это ТОЛЬКО разбор формы, без ответа на вопрос «ник ли это»: отвечает на него
// addressBook, у которого есть свидетельство треда. Требования к форме взяты с
// самой площадки: обращение стоит до первой запятой, умещается в одну строку,
// не длиннее maxAddressRunes и не кончается знаком конца предложения. После
// запятой обязан остаться текст: «Ник,» и больше ничего — это реплика из одного
// обращения, и показывать её пустой хуже, чем с обращением.
func leadingAddress(body string) (nick, rest string, ok bool) {
	i := strings.IndexByte(body, ',')
	if i <= 0 {
		return "", "", false
	}
	nick = body[:i]
	if strings.ContainsAny(nick, "\n\r") || strings.ContainsAny(nick, ".!?;:…") {
		return "", "", false
	}
	if n := len([]rune(nick)); n > maxAddressRunes {
		return "", "", false
	}
	if strings.TrimSpace(nick) != nick || nick == "" {
		// Ведущий или висячий пробел — признак не обращения, а разорванной
		// фразы: сайт обращение таким не отдавал.
		return "", "", false
	}
	rest = strings.TrimLeft(body[i+1:], " \t")
	if rest == "" {
		return "", "", false
	}
	return nick, rest, true
}

// addrKey — «этим словом обращались вот к этому человеку».
type addrKey struct {
	user  int64
	token string
}

// addressBook — что известно про обращения В ПРЕДЕЛАХ ОДНОЙ ЗАМЕТКИ.
//
// Нулевое значение рабочее и отвечает «нет» на всё: страница без книги
// показывает обращения как раньше, а не падает.
type addressBook struct {
	nicks   map[string]bool // ники участников заметки, в нижнем регистре
	authors map[int64]int64 // id реплики → id её автора
	repeats map[addrKey]int // сколько раз токеном обращались к человеку
}

// newAddressBook собирает свидетельство по репликам страницы.
//
// Автор заметки идёт в участники наравне с комментаторами: к нему обращаются в
// треде чаще всех, а своей реплики у него может и не быть вовсе.
func newAddressBook(note platform.NoteView, comments []platform.CommentView) *addressBook {
	b := &addressBook{
		nicks:   make(map[string]bool, len(comments)+1),
		authors: make(map[int64]int64, len(comments)),
		repeats: make(map[addrKey]int),
	}
	if !note.Anonymous && note.Author.Nick != "" {
		b.nicks[strings.ToLower(note.Author.Nick)] = true
	}
	for _, c := range comments {
		if c.Author.ID != 0 {
			b.authors[c.ID] = c.Author.ID
		}
		if nick := c.Name(); nick != "" && !c.Anonymous {
			b.nicks[strings.ToLower(nick)] = true
		}
	}
	// Второй проход: считать повторы можно только когда известны все авторы —
	// адресат реплики бывает НИЖЕ по странице (в линейном виде новые сверху).
	for _, c := range comments {
		if c.ReplyTo == nil {
			continue
		}
		token, _, ok := leadingAddress(c.Body)
		if !ok {
			continue
		}
		if u, known := b.authors[c.ReplyTo.CommentID]; known {
			b.repeats[addrKey{u, strings.ToLower(token)}]++
		}
	}
	return b
}

// isAddress — считать ли токен обращением к адресату этой реплики.
func (b *addressBook) isAddress(c platform.CommentView, token string) bool {
	if b == nil || c.ReplyTo == nil || token == "" {
		return false
	}
	low := strings.ToLower(token)
	// Ник адресата прямо сейчас — случай, который приём почему-то не срезал.
	if c.ReplyTo.Nick != "" && strings.EqualFold(c.ReplyTo.Nick, token) {
		return true
	}
	// Ник кого-то из участников заметки: это заведомо ник, а не фраза.
	if b.nicks[low] {
		return true
	}
	// Свидетельство треда: этим словом обращались к тому же человеку не раз.
	if u, known := b.authors[c.ReplyTo.CommentID]; known {
		return b.repeats[addrKey{u, low}] >= addressRepeats
	}
	return false
}
