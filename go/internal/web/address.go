package web

// Обращение, которое УЖЕ есть в теле реплики.
//
// Устройство площадки такое: адресат живёт ребром `reply_to_id`, а «Ник, »
// дорисовывается показом из ТЕКУЩЕГО ника — только так переименование и
// обезличивание меняют подпись везде, включая чужие ответы. Чтобы обращение не
// вышло дважды, приём срезает его из тела (`platform.TrimAddress`), и срезает по
// нику адресата: без сверки «Кстати, я тоже» лишилось бы первого слова.
//
// Сверка эта промахивается ровно там, где человек ПЕРЕИМЕНОВАЛСЯ: в теле стоит
// ник на ту дату, а сверяем мы с нынешним. Тогда на странице выходит
// «Паноптикум, Рантье, привычное…» — оба обращения к одному и тому же человеку,
// старым ником и новым. Владелец увидел это 18.08.2026 на своих же репликах.
//
// Замер по боевой базе (выборка 289 776 реплик с ребром, id 10–11 млн):
//
//	172 991 (60 %) начинаются с «X, »;
//	 62 846 из них — ник, который и сейчас у кого-то на площадке;
//	  3 709 (2,1 % от токенов) — зачины вроде «Кстати», «Да», «Спасибо»;
//	     27 совпали с НЫНЕШНИМ ником адресата.
//
// То есть почти всё, что начинается с «X, », — это обращение, а сверка с
// нынешним ником не срабатывает почти никогда: люди на НГС переименовывались
// постоянно (в досье попадаются 12 и 19 ников на одной анкете).
//
// Отсюда правило показа: **если автор уже назвал адресата сам, второе обращение
// не дорисовывается** — вместо этого выделяется жирным то, что он написал.
// Ровно так это и выглядело на НГС: там префикс жирный и ссылкой не был.
// Своё обращение (со ссылкой на реплику и с нынешним ником) остаётся там, где в
// теле его нет, — а это большинство строк: у них приём обращение срезал.
//
// Что при этом теряется, надо назвать честно. Ребро точнее текста: мобильное
// дерево совпадает с настоящим адресатом в 92 % случаев, а написанное «Ник, » —
// в 48 %, потому что люди пишут обращение одному, отвечая кнопкой другому. В
// таких строках теперь виден адресат ИЗ ТЕКСТА, а настоящий остаётся ветвью
// дерева. Размен сделан в пользу написанного: показ не вправе прятать слова
// автора, а «оба сразу» — это и есть та поломка, с которой всё началось.

import "strings"

// maxAddressRunes — потолок длины обращения. Ники бывают длинные («любовник
// мэри попинс», «Девочка с автоматом»), но не длиннее строки: всё, что больше,
// — это уже фраза с запятой, а не имя.
const maxAddressRunes = 40

// openers — зачины, которые выглядят как обращение, но им не являются. Список
// короткий намеренно: по замеру это 2 % случаев, и каждый лишний пункт в нём —
// это чей-то ник, который перестанет опознаваться (ники бывают любые, включая
// «Ясно» и «Наверное»). Ошибка здесь дёшева в одну сторону: не узнав обращение,
// показ просто дорисует своё, как и раньше.
var openers = map[string]bool{
	"кстати": true, "да": true, "нет": true, "ну": true, "спасибо": true,
	"привет": true, "ой": true, "конечно": true, "согласна": true, "согласен": true,
	"извини": true, "извините": true, "вот": true, "ага": true, "понятно": true,
	"эх": true, "ох": true, "боже": true, "девочки": true, "мальчики": true,
	"люди": true, "народ": true, "ребят": true, "ребята": true, "всем": true,
	"короче": true, "слушай": true, "слушайте": true, "знаешь": true, "знаете": true,
	"наверное": true, "возможно": true, "по-моему": true, "кажется": true,
	"увы": true, "жаль": true, "блин": true,
}

// leadingAddress разбирает начало тела: «Ник, текст» → («Ник», «текст», true).
//
// Требования к нику взяты с самой площадки, а не выдуманы: он стоит ДО первой
// запятой, умещается в одну строку, не длиннее maxAddressRunes и не кончается
// знаком конца предложения (иначе это не имя, а фраза). После запятой обязан
// остаться текст: «Ник,» и больше ничего — это реплика из одного обращения, и
// показывать её пустой хуже, чем с обращением.
func leadingAddress(body string) (nick, rest string, ok bool) {
	i := strings.IndexByte(body, ',')
	if i <= 0 {
		return "", "", false
	}
	nick = body[:i]
	if strings.ContainsAny(nick, "\n\r") || strings.ContainsAny(nick, ".!?;:…") {
		return "", "", false
	}
	if n := len([]rune(nick)); n > maxAddressRunes {
		return "", "", false
	}
	if strings.TrimSpace(nick) != nick || nick == "" {
		// Ведущий или висячий пробел — признак не обращения, а разорванной
		// фразы: сайт обращение таким не отдавал.
		return "", "", false
	}
	if openers[strings.ToLower(nick)] {
		return "", "", false
	}
	rest = strings.TrimLeft(body[i+1:], " \t")
	if rest == "" {
		return "", "", false
	}
	return nick, rest, true
}
