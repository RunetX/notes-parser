type helpPage struct {
	page
	// Topics — оглавление. Стои́т на каждой странице справки, поэтому едет в
	// общей части, а не собирается в каждом обработчике заново.
	Topics []helpTopic
	// Current — открытая тема: в оглавлении она не ссылка, а метка «вы здесь».
	// Пусто на индексе.
	Current  string
	Operator string
	Contact  string
	// EditMinutes — окно правки своей заметки (platform.EditWindow).
	EditMinutes int
	// LoginDays — сколько живёт код входа (platform.ChallengeTTL), в сутках.
	// Из ядра, как и всё остальное на этой странице: 10.09.2026 выяснилось, что
	// экран входа три недели обещал «час» рядом с честным «правку одобряет
	// модератор», и разошлись эти фразы молча.
	LoginDays int
	// MaxPinned — сколько заметок можно закрепить наверху ленты.
	MaxPinned int
	// Пороги частоты — тоже из ядра (platform.NoteWindow и соседи).
	NoteMinutes     int
	NotesPerDay     int
	CommentSeconds  int
	CommentsPerHour int
	// Reactions — какие кнопки реакций предлагает ядро. Список приезжает
	// оттуда по тому же правилу, что окно правки и пороги частоты: набор задан
	// замером корпуса (platform.ReactionCodes), и второй такой же, набранный в
	// шаблоне руками, разошёлся бы с настоящим первой же правкой.
	Reactions []string
	// Contacts — живые контакты. Пустые поля шаблон пропускает: строка
	// «Telegram: —» хуже отсутствующей строки.
	Contacts Contacts
	// HasContacts — есть ли что показывать вообще. Считается здесь, а не тремя
	// {{if}} подряд в шаблоне: иначе у пустой настройки остался бы заголовок
	// раздела над пустотой — тот же дефект, что был у «ЧТО ТЕБЯ ЦЕПЛЯЕТ» в
	// брифе жителя.
	HasContacts bool
	// Demo — ЖИВОЙ СНИМОК карточки ленты: та же заметка, тем же шаблоном, что и
	// настоящая. Не картинка намеренно — см. demoNote ниже.
	Demo     feedPage
	DemoNote platform.NoteView
	// HasTelegram и HasMAX — про какой мессенджер площадка вправе рассказывать.
	// Признак один на две вещи (бот и группа): адрес хоть одного из них и
	// означает, что этот мессенджер у площадки есть.
	HasTelegram bool
	HasMAX      bool
	// Support — адрес сбора и цена месяца для темы «Поддержать площадку». Число
	// приезжает из настроек, а не написано в шаблоне словами, по тому же правилу,
	// что и пороги частоты выше: до 08.09.2026 в справке стояло «30 комментариев
	// в час» при настоящих девяноста, и разошлись они молча.
	Support Support
}

// helpTopics — темы, которые ЭТА площадка вправе показать.
//
// Отсеиваются две, и по одному доводу, тому же, что у раздела контактов: тема,
// зовущая нажать ссылку, которой нет, отправляет человека в никуда. «Telegram и
// MAX» рассказывает, куда идти и что там нажимать; «Поддержать площадку» —
// куда перевести деньги. Настроено — тема есть, и внутри показывается ровно
// настроенное.
//
// Проход ОДИН на оба гейта намеренно. Прежняя форма — «настроены мессенджеры →
// верни весь список целиком» — со вторым гейтом дала бы дефект молчаливый:
// площадка с настроенным Telegram, но без адреса сбора, показала бы карточку и
// открыла страницу с пустой ссылкой, а тесты с полным конфигом этого не увидели
// бы вовсе.
func (s *Server) helpTopics() []helpTopic {
	out := make([]helpTopic, 0, len(helpTopics))
	for _, t := range helpTopics {
		if t.Slug == "messengers" && !s.hasMessengers() {
			continue
		}
		if t.Slug == "support" && !s.hasSupport() {
			continue
		}
		out = append(out, t)
	}
	return out
}

func (s *Server) hasMessengers() bool {
	c := s.cfg.Contacts
	return c.Telegram != "" || c.MAX != "" || c.BotTelegram != "" || c.BotMAX != ""
}

// hasSupport — есть ли куда вести. Кривую ссылку гасит checkSupport при сборке
// сервера, и погашенная снимает тему так же, как незаполненная: показывать
// в обоих случаях нечего.
func (s *Server) hasSupport() bool { return s.cfg.Support.URL != "" }

// helpPaths — адреса справки для карты сайта: сам индекс и все его темы. Своим
// ходом робот дошёл бы до /help и остановился, а страницы под ним — это ровно те
// тексты, за которыми в поиск и приходят («правила», «как войти»).
func (s *Server) helpPaths() []string {
	topics := s.helpTopics()
	out := make([]string, 0, len(topics)+1)
	out = append(out, "/help")
	for _, t := range topics {
		out = append(out, "/help/"+t.Slug)
	}
	return out
}

// helpData — общая часть всех страниц справки. Одна на все темы намеренно:
// числа ядра нужны трём страницам, контакты двум, а второй способ их собрать
// однажды разошёлся бы с первым.
func (s *Server) helpData(r *http.Request, current, title string) helpPage {
	op := s.cfg.Operator.Public()
	c := s.cfg.Contacts
	return helpPage{
		page:            s.readingPage(r, title),
		Topics:          s.helpTopics(),
		Current:         current,
		Operator:        op.Name,
		Contact:         op.Contact,
		EditMinutes:     int(platform.EditWindow / time.Minute),
		LoginDays:       int(platform.ChallengeTTL / (24 * time.Hour)),
		MaxPinned:       platform.MaxPinned,
		NoteMinutes:     int(platform.NoteWindow / time.Minute),
		NotesPerDay:     platform.NotesPerDay,
		CommentSeconds:  int(platform.CommentWindow / time.Second),
		CommentsPerHour: platform.CommentsPerHour,
		Reactions:       platform.ReactionCodes,
		DemoNote:        demoNote(),
		Contacts:        c,
		HasContacts:     c.ProfileID != 0 || c.Telegram != "" || c.MAX != "",
		HasTelegram:     c.Telegram != "" || c.BotTelegram != "",
		HasMAX:          c.MAX != "" || c.BotMAX != "",
		Support:         s.cfg.Support,
	}
}

// demoNote — заметка, которой в базе нет: она нарисована в справке, чтобы
// показать карточку ленты.
//
// СНИМКОМ ЭКРАНА ЭТО НЕ ДЕЛАЕТСЯ, и довод не в лени. Картинка, во-первых,
// устаревает молча: вёрстку правят, а PNG остаётся прежним — и справка начинает
// учить искать то, чего на странице уже нет (ровно тот дефект, из-за которого
// числа приезжают из ядра). Во-вторых, тема: палитр четыре, и снимок, снятый в
// одной, в трёх других выглядит чужой заплатой. В-третьих, снимать пришлось бы
// с БОЕВОЙ страницы, то есть вшить в бинарник чужой ник, чужие слова и чужое
// лицо — навсегда и без спроса, включая того, кто завтра отзовёт согласие.
//
// Живой фрагмент всего этого лишён: он рисуется ТЕМ ЖЕ note_item, что и лента,
// значит не расходится с ней никогда, живёт во всех палитрах и не показывает ни
// одного настоящего человека. Текстом заметки служит объяснение того, на что
// смотреть, а автором — сама площадка (Author.System): в колонке автора у неё
// свой знак вместо лица, и вопрос «кто эта женщина на фотографии» не возникает
// вовсе.
//
// Ссылки внутри демо мертвы: контейнер помечен inert, а в CSS ему запрещены
// нажатия — иначе «Комментарии 12» вели бы в заметку, которой нет.
func demoNote() platform.NoteView {
	return platform.NoteView{
		// Номер — из НАТИВНОЙ полосы, и это не мелочь: значок происхождения
		// считается по полосе (platform.IsNative), и с нулём демо-карточка
		// объявляла себя копией с НГС, то есть врала ровно тем, что рядом
		// объясняет соседняя тема. Заметки с таким номером не существует, а
		// ссылка внутри снимка мертва (inert).
		ID:     platform.NativeIDBase,
		Author: platform.Author{Nick: SiteName, System: true},
		Body: "Так выглядит заметка в ленте. Слева — колонка автора: фото и ник " +
			"под ним, а у записей самой площадки вместо фото её знак. Справа от " +
			"даты стои́т значок происхождения, под текстом — сколько в заметке " +
			"комментариев.",
		CommentCount:   12,
		PublishedAt:    time.Date(2026, 9, 1, 9, 30, 0, 0, time.UTC),
		PublishedExact: true,
	}
}

// handleHelp — оглавление. Своего текста у него нет: карточки тем, контакты и
// строка про оператора.
func (s *Server) handleHelp(w http.ResponseWriter, r *http.Request) {
	s.render(w, r, http.StatusOK, "help.gohtml", s.helpData(r, "", "Справка"))
}

// handleHelpTopic — одна тема. Неизвестный адрес отвечает «нет такой страницы»,
// как всякий другой: справка не то место, где стоит гадать, что человек имел в
// виду.
func (s *Server) handleHelpTopic(w http.ResponseWriter, r *http.Request) {
	slug := r.PathValue("topic")
	for _, t := range s.helpTopics() {
		if t.Slug == slug {
			s.render(w, r, http.StatusOK, t.tmpl, s.helpData(r, t.Slug, t.Title))
			return
		}
	}
	s.handleNotFound(w, r)
}
