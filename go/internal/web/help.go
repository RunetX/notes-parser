package web

// Справка и правила — единственные страницы площадки, которые пишет человек, а
// не запрос к базе.
//
// Нужны они по двум причинам, и обе появились вместе с переездом. Первая: люди
// пришли с чужого сайта, где всё было устроено иначе, и половина вопросов
// («почему мой комментарий не правится», «куда делась заметка», «как войти без
// пароля») — это не поддержка, а отсутствующий текст. Вторая: правила раздела
// на НГС были, их читали и на них ссылались модераторы, — переехать без них
// значит начать с того, что правил нет вовсе.
//
// СТРАНИЦ ТЕПЕРЬ МНОГО, и это правка 08.09.2026 по жалобе владельца («справка
// стала сплошным полотном»). Одна страница на четыре с лишним сотни строк
// разметки отвечала на всякий вопрос и ни на один сразу: приходят сюда с
// конкретным («за что скрыли», «как войти», «почему реплика не правится»), а
// получали простыню, в которой нужный абзац искали прокруткой. Теперь тема —
// это страница: свой адрес, свой заголовок вкладки, своя строка в карте сайта и
// своя ссылка, которую можно дать человеку в ответ на вопрос.
//
// Оглавление стои́т на КАЖДОЙ странице, а не только на индексе: соседний раздел
// должен открываться одним нажатием, а не двумя (назад, потом в тему). Оно же и
// есть индекс — страница /help не пишет ничего сверх карточек и контактов,
// иначе через месяц у площадки было бы два разных текста про одно и то же.
//
// Числа приезжают ИЗ ЯДРА (окно правки, потолок закреплённых, пороги частоты), а
// не пишутся словами: справка, разошедшаяся с поведением кнопки, хуже
// отсутствующей. Правило это не теоретическое — до 08.09.2026 в справке стояло
// «30 комментариев в час» при настоящих девяноста, и разъехались они молча.
//
// Реквизиты оператора подставляются те же, что в тексты согласий, и берутся из
// конфига: разойдясь, они превратили бы справку в отдельный источник правды о
// том, кто обрабатывает данные.

import (
	"net/http"
	"time"

	"lovegw/internal/platform"
)

// helpTopic — одна тема справки.
//
// Заголовок живёт здесь, а не в шаблоне, потому что читают его трое: сама
// страница, карточка в оглавлении и заголовок вкладки. Три написания одного
// названия разошлись бы на первой же правке.
type helpTopic struct {
	// Slug — часть адреса. Меняться ему нельзя: /help/narod стоит ссылкой на
	// странице жителя, в форме ответа и в мордоленте.
	Slug string
	// Title — заголовок страницы и подпись карточки.
	Title string
	// Lead — строка под подписью в оглавлении: чем эта тема отличается от
	// соседней. Без неё список из одиннадцати названий не помогает выбрать.
	Lead string
	// tmpl — файл шаблона. Свой на тему: шаблоны страниц разбираются по одному,
	// и {{define "content"}} у них общий на всех.
	tmpl string
}

// helpTopics — порядок тем в оглавлении. Он не алфавитный и не случайный: сверху
