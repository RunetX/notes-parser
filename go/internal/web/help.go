package web

// Справка и правила — единственная страница площадки, которую пишет человек, а
// не запрос к базе.
//
// Нужна она по двум причинам, и обе появились вместе с переездом. Первая: люди
// пришли с чужого сайта, где всё было устроено иначе, и половина вопросов
// («почему мой комментарий не правится», «куда делась заметка», «как войти без
// пароля») — это не поддержка, а отсутствующий текст. Вторая: правила раздела
// на НГС были, их читали и на них ссылались модераторы, — переехать без них
// значит начать с того, что правил нет вовсе.
//
// Страница открыта ВСЕМ, включая не вошедших: правила, которые видно только
// изнутри, — это не правила, а сюрприз. Реквизиты оператора подставляются те
// же, что в тексты согласий, и берутся из конфига, а не из шаблона: разойдясь,
// они превратили бы справку в отдельный источник правды о том, кто обрабатывает
// данные.

import (
	"net/http"
	"time"

	"lovegw/internal/platform"
)

type helpPage struct {
	page
	Operator string
	Contact  string
	// EditMinutes — окно правки своей заметки. Число берётся из ядра
	// (platform.EditWindow), а не пишется в текст словами: справка, разошедшаяся
	// с поведением кнопки, хуже отсутствующей справки.
	EditMinutes int
	// MaxPinned — сколько заметок можно закрепить наверху. Здесь по той же
	// причине, что и окно правки.
	MaxPinned int
}

func (s *Server) handleHelp(w http.ResponseWriter, r *http.Request) {
	op := s.cfg.Operator.Public()
	s.render(w, r, http.StatusOK, "help.gohtml", helpPage{
		page:        s.newPage(r, "Справка и правила"),
		Operator:    op.Name,
		Contact:     op.Contact,
		EditMinutes: int(platform.EditWindow / time.Minute),
		MaxPinned:   platform.MaxPinned,
	})
}
